r"""
Extensions of modules over vertex algebras: projective covers, ``Ext^1``
up to a depth.

The category: positive energy ``V``-modules whose generalized ``L_0``
eigenvalues lie in ``h + Z_{>=0}`` (``L_0`` Jordan blocks allowed), the
degree of a vector its eigenvalue minus ``h``.  For a module ``N`` of it,
the degree-``n`` space ``N(n)`` is a module over the level-``n`` Zhu
algebra ``A_n(V)``, and ``Hom_V(\bar M_n(U), N) = Hom_{A_n}(U, N(n))``
(Dong--Li--Mason [DLM1998]_, in He's model [He2017]_).  Hence:

- if ``P`` is a projective ``A_n``-module (over a finite dimensional
  ``A_n``, e.g. a projective indecomposable module of
  ``Q.zhu_algebra_up_to(W, level=n)``, which is then projective over the
  true ``A_n(Q)`` too) and ``\bar M_n(P)(n) = P``, then ``\bar M_n(P)`` is
  projective: an extension ``E`` of ``\bar M_n(P)`` gives ``E(n) -> P``
  onto, a section ``P -> E(n)`` of ``A_n``-modules, and by the adjunction a
  section ``\bar M_n(P) -> E``;
- for ``π: P_0 -> M`` onto, ``P_0`` projective, ``K = ker π``: ``0 ->
  Hom(M, N) -> Hom(P_0, N) -> Hom(K, N) -> Ext^1(M, N) -> 0``, so
  ``Ext^1(M, N) = Hom(K, N) / {f|_K}``.

``L.projective_cover(max_weight, max_depth)`` (:func:`projective_cover`)
builds ``π: \bar M_n(A_n e) -> L`` for a simple ``L``, with the level ``n``
chosen so that the category contains every module of finite length whose
composition factors have their tops among the simple modules of ``A_0``.

``M.ext1_up_to(N, depth, cover)`` computes ``Ext^1`` with ``cover = π``
(from :func:`projective_cover`, or given by the user: its projectivity is
then the user's claim): generators of ``K``
degree by degree up to ``depth``; ``Hom(K, N)`` as the images of these
generators for which the map defined through certificates
(:meth:`~vertex_algebras.vertex_algebra_submodule.FinitelyGeneratedSubmodule.express`)
commutes with the modes of the strong generators on ``K`` in the degrees
``<= depth``; ``Hom(P_0, N)`` exactly (adjunction).  Up to ``depth``:
relations of ``K`` reached only through higher degrees are missed (the
space can only be too large), and so are generators of ``K`` above
``depth``.

For a cover ``P_0 = \bar M_n(U)`` over a quotient with a finite dimensional
``A_n`` the rest of ``Ext^1`` is computed too (proofs in the companion paper, in preparation):
the image of ``δ: Ext^1(M, N) -> Ext^1_{A_n}(U, N(n))``, the classes of the
top level that lift (:meth:`Ext1UpTo.delta_image`, :meth:`Ext1UpTo.top_extension`).

A cover that is not projective, ``P_0 = \bar M_n(U)`` with ``\bar M_n(U)(n)
= U``, gives a subspace in the first part: ``Hom(K, N) / {f|_K}`` is the kernel of
``Ext^1(M, N) -> Ext^1_{A_n}(U, N(n))`` (an extension of ``\bar M_n(U)``
whose degree-``n`` space splits over ``A_n`` splits by the adjunction): all
of ``Ext^1(M, N)`` when ``N(n) = 0``, e.g. ``Ext^1(W(0), W(1))`` of the
triplet algebra ``W(2)`` from ``\bar M(C) -> W(0)``
(``tests/smoke_module_ext.sage``).

EXAMPLES:

The Virasoro algebra at ``c = 3/7``: the Jordan block of ``[L_0]`` at
``h = 2`` over the Zhu algebra ``A_0 = C[x]/((x - 2)^2)`` is projective, and
so is the module it induces, an extension of the Verma module ``M(2)`` by
itself.  ``Ext^1(M(2), M(2))`` is one dimensional (that extension) in this
category (``[L_0]`` with ``(x - 2)^2 = 0``)::

    sage: import vertex_algebras as va
    sage: V = va.Virasoro(QQ, 3/7, conformal_vector='L')
    sage: Z = V.zhu_algebra().quotient([(V.zhu_algebra().gen(0) - 2)^2])
    sage: P = V.induced_module(Z.module({'L': matrix([[2, 1], [0, 2]])}))
    sage: M = V.verma_module(2); pi = P.hom([0, M.highest_weight_vector()], M)
    sage: E = M.ext1_up_to(M, 3, pi); E
    Ext^1 of Verma module ... by Verma module ... up to depth 3: dimension 1
    sage: E.kernel_generators()
    [u[0]]
    sage: E.basis()
    [(v,)]

AUTHORS:

- Christopher Raymond, Simon Wood (2026): initial version
"""

