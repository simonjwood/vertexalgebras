    @staticmethod
    def __classcall_private__(cls, M, gens, names=None):
        r"""
        Normalize the arguments: the generators as vectors of ``M`` (a tuple),
        the names as strings, one per generator.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=('w',))
            sage: N is M.submodule([L.mode(v, -1)], names=['w'])
            True
            sage: M.submodule([L.mode(v, -1)], names=['a', 'b'])
            Traceback (most recent call last):
            ...
            ValueError: 2 names for 1 generators
        """
        gens = tuple(M(x) for x in gens)
        if names is not None:
            names = tuple(str(t) for t in names)
            if len(names) != len(gens):
                raise ValueError('{} names for {} generators'.format(len(names), len(gens)))
        return VertexAlgebraModule.__classcall__(cls, M, gens, names)

    def __init__(self, M, gens, names=None):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1), M.zero()])
            sage: N._given_names, N._zero, N._whole, N.ambient() is M
            (['s0'], False, False, True)
            sage: Z = M.submodule([]); Z._zero, Z.weight_space(2).dimension()
            (True, 0)
        """
        R = M.base_ring()
        if not R.is_field():
            raise ValueError('submodules need a base field, not {}'.format(R))
        if names is None:
            names = ['s{}'.format(k) for k in range(len(gens))]
        self._given = [x for x in gens if not x.is_zero()]
        self._given_names = [t for t, x in zip(names, gens) if not x.is_zero()]
        self._whole = bool(self._given) and M._is_simple()
        self._zero = not self._given
        self._gens = []
        self._N = None          # the closure under non-raising modes
        self._S = {}            # degree -> (echelon, vecs, provenance)
        self._init_submodule(M)
        if self._whole or self._zero:
            return
        self._X = _strong_generator_modes(M)
        self._gens = self._split()
        self._graded_pieces = M._mgrading is not None and all(
            len({M._grade_key(m) for m in y}) == 1 for y, _, _ in self._gens)

    def _is_graded_submodule(self):
        r"""
        True if every generator is homogeneous for the grading (or the module
        is ungraded).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']); E, H, F = V.gens()
            sage: M = V.adjoint_module(); N = M.submodule([E.no(E)])
            sage: k = M(E.no(E)).leading_support()
            sage: N._is_graded_submodule(), M.submodule([E + F])._is_graded_submodule()
            (True, False)
        """
        if self._mgrading is None or self._whole or self._zero:
            return True
        M = self._ambient_module
        return all(len({M._grade_key(m) for m in y}) == 1 for y, _, _ in self._gens)

    def _repr_(self):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: N._repr_()
            "Submodule of Verma module of highest weight {'L': 0} over ... generated by [L_{-1} v]"
        """
        return 'Submodule of {} generated by {}'.format(self._ambient_module, list(self.gens()))

    def gens(self):
        r"""
        The generators (homogeneous components of the given vectors, if they
        were split), as vectors of ``self``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1) + L.mode(v, -2)]); N.gens()
            (L_{-1} v, L_{-2} v)
            sage: N.gens()[0].parent() is N
            True
        """
        if self._whole or self._zero:
            return tuple(self._el_from_dict(dict(x._monomial_coefficients)) for x in self._given)
        return tuple(self._el_from_dict(g[0]) for g in self._gens)

    def variable_names(self):
        r"""
        The names of :meth:`gens` (``s0, s1, ...`` by default; the
        homogeneous components of a split generator ``s`` are named
        ``s[w]``, ``w`` the weight).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: M.submodule([L.mode(v, -1)]).variable_names()
            ('s0',)
            sage: M.submodule([L.mode(v, -1) + L.mode(v, -2)], names=['u']).variable_names()
            ('u[1]', 'u[2]')
        """
        if self._whole or self._zero:
            return tuple(self._given_names)
        return tuple(g[2] for g in self._gens)

    def some_elements(self):
        r"""
        Some vectors of ``self``: the generators (the zero vector if there
        are none).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: M.submodule([L.mode(v, -1)]).some_elements()
            (L_{-1} v,)
            sage: M.submodule([]).some_elements()
            [0]
        """
        return self.gens() or [self.zero()]

    def _split(self):
        r"""
        The generators split into homogeneous components ``(raw dict, degree,
        name)`` (only when the weights are ``L_0``-eigenvalues; ``ValueError``
        otherwise).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: N._split() == [({k1: 1}, 1, 'w')]
            True
            sage: N2 = M.submodule([L.mode(v, -1) + L.mode(v, -2)], names=['u'])
            sage: [t[1:] for t in N2._split()]
            [(1, 'u[1]'), (2, 'u[2]')]
        """
        M = self._ambient_module
        out = []
        for x, name in zip(self._given, self._given_names):
            comps = {}
            for m, c in x._monomial_coefficients.items():
                if c:
                    comps.setdefault(self._degree_of_key(m), {})[m] = c
            if len(comps) > 1 and (not M._l0_grading() or M._mu is not None):
                raise ValueError(
                    'the generator {} of the submodule is not homogeneous for the '
                    'conformal weight (its components need not lie in the submodule '
                    'unless the weights are L_0-eigenvalues)'.format(x))
            for w in sorted(comps):
                wt = M._weight_key(next(iter(comps[w])))
                nm = name if len(comps) == 1 else '{}[{}]'.format(name, wt)
                out.append((comps[w], w, nm))
        return out

