    def __add__(self, other):
        r"""
        The sum of two submodules generated by vectors of the same module.

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: E.<L> = NormallyOrderedExpressions(QQ)
            sage: Vir = UniversalVertexAlgebra(QQ, E, {('L', 'L'): [L.derivative(), 2*L, 0, 1/4]},
            ....:                              conformal_vector=L)
            sage: M = Vir.verma_module(0); L = Vir.gen('L'); v = M.highest_weight_vector()
            sage: N1 = M.submodule([L.mode(v, -1)]); N2 = M.submodule([L.mode(v, -2)])
            sage: N1 <= N1 + N2, N2 <= N1, N1 <= N2
            (True, False, True)
        """
        if not getattr(other, '_is_fg_submodule', False) or other.ambient() is not self.ambient():
            return NotImplemented
        names = self._given_names + other._given_names
        if len(set(names)) != len(names):
            names = None
        return self.ambient().submodule(self._given + other._given, names)

    _is_fg_submodule = True

    def __le__(self, other):
        r"""
        Containment, by the generators of ``self``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: N2 = M.submodule([L.mode(v, -2)])
            sage: N <= N + N2, N2 <= N, N <= M.maximal_submodule()
            (True, False, True)
        """
        if not getattr(other, '_is_vertex_algebra_submodule', False):
            return NotImplemented
        if other is self:
            return True
        return all(other.contains(self.lift(g)) for g in self.gens())

    def __ge__(self, other):
        r"""
        Containment ``other <= self``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: N2 = M.submodule([L.mode(v, -2)])
            sage: N + N2 >= N, N >= N2
            (True, False)
        """
        if not getattr(other, '_is_vertex_algebra_submodule', False):
            return NotImplemented
        return other <= self

    def express(self, v):
        r"""
        ``v`` as an explicit descendant of the generators: a
        :class:`SubmoduleExpression`, a linear combination of terms ``x1_(n1)
        ... xk_(nk) s_j`` (modes of the strong generators of the vertex
        algebra); ``.element()`` evaluates it.  A certificate, not canonical.

        INPUT:

        - ``v`` -- a vector of the ambient module lying in ``self`` (else a
          ``ValueError``)

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: E.<L> = NormallyOrderedExpressions(QQ)
            sage: Vir = UniversalVertexAlgebra(QQ, E, {('L', 'L'): [L.derivative(), 2*L, 0, 1/4]},
            ....:                              conformal_vector=L)
            sage: M = Vir.verma_module(0); L = Vir.gen('L'); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: x = L.mode(L.mode(L.mode(v, -1), -1), -1) + L.mode(L.mode(v, -1), -2)
            sage: e = N.express(x); e
            L_(-1) w + L_(0) L_(0) w
            sage: e.element() == x
            True
        """
        d = self._to_dict(v)
        if d is None or not self._contains_dict(d):
            raise ValueError('{} is not in {}'.format(v, self))
        if self._whole:
            raise NotImplementedError('certificates for submodules of simple modules '
                                      'are not available')
        terms = []
        for p, comp in sorted(self._components(d).items(), key=lambda t: t[0][0]):
            ech, _, provs = self._space((QQ(p[0]), p[1]))
            co = ech.coordinates(comp)
            for lab in ech.labels():
                c = co.get(lab)
                if c:
                    terms.append((provs[lab], c))
        return SubmoduleExpression(self, terms)

    def _word_element(self, j, word):
        r"""
        The vector ``x1_(n1) ... xk_(nk) s_j`` (``word`` outermost mode first) of
        the ambient module.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: N._word_element(0, ((0, 0),))
            L_{-1} L_{-1} v
        """
        y = self._gens[j][0]
        for xi, n in reversed(word):
            y = self._act(xi, n, y)
        return self._el_from_dict(y)

    def _word_repr(self, j, word):
        r"""
        The string ``x1_(n1) ... xk_(nk) s_j`` of a provenance.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: N._word_repr(0, ((0, 0), (0, -1)))
            'L_(0) L_(-1) w'
        """
        V = self._V
        names = V.variable_names()
        if len(names) != len(self._X):
            names = ['x{}'.format(k) for k in range(len(self._X))]
        parts = ['{}_({})'.format(names[xi], n) for xi, n in word]
        return ' '.join(parts + [self._gens[j][2]])


