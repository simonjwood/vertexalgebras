    def _check_simple_top(self):
        r"""
        Check that the lowest weight space ``M_0`` is simple: one-dimensional,
        or the zero modes of the integer-weight strong generators generate
        ``End(M_0)`` (``ValueError`` otherwise).

        TESTS:

        The doublet top of affine ``sl_2`` passes (its zero modes generate
        ``End(C^2)``); a two-dimensional top with zero action is refused (when
        the maximal submodule is built)::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1, names=['E', 'H', 'F'],
            ....:                                  conformal_vector='sugawara')
            sage: A = V.zhu_algebra()
            sage: U2 = A.module({'E': matrix([[0, 1], [0, 0]]), 'H': matrix([[1, 0], [0, -1]]),
            ....:                'F': matrix([[0, 0], [1, 0]])})
            sage: J = V.induced_module(U2).maximal_submodule(); J._check_simple_top() is None
            True
            sage: Z = matrix(QQ, 2)
            sage: V.induced_module(A.module({'E': Z, 'H': Z, 'F': Z})).maximal_submodule()
            Traceback (most recent call last):
            ...
            ValueError: the lowest weight space of ... is not known to be simple ...
        """
        B0 = self._basis(QQ.zero())
        d = len(B0)
        if d == 0:
            raise ValueError('the lowest weight space of {} is zero'.format(self._ambient_module))
        if d == 1:
            return
        R = self.base_ring()
        E0 = KeyedSpan(R)
        for j, b in enumerate(B0):
            E0.insert(b, label=j)
        mats = []
        for xi, (_, _, h, _) in enumerate(self._X):
            if not (h - 1).is_integer():
                continue
            cols = []
            for b in B0:
                co = E0.coordinates(self._act(xi, int(h - 1), b))
                cols.append([co.get(j, R.zero()) for j in range(d)])
            mats.append(matrix(R, cols).transpose())
        span = [matrix.identity(R, d)]
        rank = 1
        frontier = list(span)
        while frontier and rank < d * d:
            new = []
            for P in frontier:
                for G in mats:
                    Q = G * P
                    rows = matrix(R, [list(X.list()) for X in span + [Q]])
                    r = rows.rank()
                    if r > rank:
                        span.append(Q)
                        new.append(Q)
                        rank = r
            frontier = new
        if rank < d * d:
            raise ValueError(
                'the lowest weight space of {} is not known to be simple (the zero modes '
                'of the strong generators do not generate its endomorphisms), so the '
                'largest submodule meeting it trivially need not be the maximal '
                'submodule'.format(self._ambient_module))

    def _act(self, xi, n, y):
        r"""
        The mode ``x_(n)`` of the strong generator ``xi`` on the raw vector ``y``
        of the ambient module (a raw dict without zeros).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: J = M.maximal_submodule()
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: J._act(0, 0, {k1: 1}) == {k11: 1}
            True
        """
        M = self._ambient_module
        return {k: c for k, c in M._action_raw(self._X[xi][1], n, y).items() if c}

    @_gc_paused
    def _space(self, p):
        r"""
        ``J`` in the piece ``p = (w, G)``: the vectors that every lowering
        mode maps into ``J``, refined to the largest subspace stable under the
        modes of twisted degree 0 (a reduced echelon form).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: J = M.maximal_submodule()
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: J._space((1, None)).rows() == [{k1: 1}]             # L_{-1} v is singular
            True
            sage: J._space((2, None)).rows() == [{k11: 1}], J._space((0, None)).rows()
            (True, [])
        """
        J = self._J.get(p)
        if J is not None:
            return J
        w, G = p
        R = self.base_ring()
        M = self._ambient_module
        ech = KeyedSpan(R, key_order=M._key_order)
        if w > 0:
            basis = M._piece_basis(w, G)
            images = []
            for b in basis:
                img = {}
                for xi, (_, _, h, sh) in enumerate(self._X):
                    # lowering: -w <= h - n - 1 < 0
                    for n in range(floor(h - 1) + 1, floor(h - 1 + w) + 1):
                        r = self._act(xi, n, b)
                        if r:
                            r = reduce_by_rows(
                                r, self._space((w + h - n - 1, self._shift(G, sh))).row_dict())
                            for k, c in r.items():
                                img[(xi, n, k)] = c
                images.append(img)
            kernel = []
            for rel in left_kernel(images, R):
                v = {}
                for j, c in rel.items():
                    for k, a in basis[j].items():
                        v[k] = v.get(k, 0) + c * a
                kernel.append({k: a for k, a in v.items() if a})
            zero_modes = [(xi, int(X[2] - 1)) for xi, X in enumerate(self._X)
                          if (X[2] - 1).is_integer()]
            while kernel and zero_modes:
                K = KeyedSpan(R, key_order=M._key_order)
                K.insert_many(kernel)
                rows = K.row_dict()
                imgs = []
                for v in kernel:
                    img = {}
                    for xi, n in zero_modes:
                        r = self._act(xi, n, v)
                        if r:
                            for k, c in reduce_by_rows(r, rows).items():
                                img[(xi, n, k)] = c
                    imgs.append(img)
                rels = left_kernel(imgs, R)
                if len(rels) == len(kernel):
                    break
                new = []
                for rel in rels:
                    v = {}
                    for j, c in rel.items():
                        for k, a in kernel[j].items():
                            v[k] = v.get(k, 0) + c * a
                    new.append({k: a for k, a in v.items() if a})
                kernel = new
            if kernel:
                ech.insert_many(kernel)
        self._J[p] = ech
        return ech

    def _echelon_piece(self, p):
        r"""
        The reduced echelon form of the piece ``p`` (from :meth:`_space`).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: J = M.maximal_submodule()
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: J._echelon_piece((1, None)).rows() == [{k1: 1}]
            True
        """
        return self._space((QQ(p[0]), p[1]))

    def some_elements(self):
        r"""
        Some vectors of ``self``: up to three canonical basis vectors of the
        lowest degree (at most 4) in which ``self`` is nonzero, else the zero
        vector.

        EXAMPLES:

        The singular vector of ``M(1/2, 1/2)`` at depth 2::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: V.verma_module(1/2).maximal_submodule().some_elements()
            [-4/3*L_{-2} v + L_{-1} L_{-1} v]
        """
        for k in range(1, 4 * self._D + 1):
            rows = self._rows_at_tdeg(QQ((k, self._D)))
            if rows:
                return [self._el_from_dict(r) for r in rows[:3]]
        return [self.zero()]


