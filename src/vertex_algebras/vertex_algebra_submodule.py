    def _new_space(self, ordered=False):
        r"""
        An empty space ``(echelon, vectors, provenances)``; with ``ordered``, the
        echelon form has the leading monomials of the ambient module's key order
        as pivots.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: ech, vecs, provs = N._new_space(ordered=True); vecs, provs
            ([], [])
        """
        R = self.base_ring()
        if ordered:
            return (KeyedSpan(R, key_order=self._ambient_module._key_order), [], [])
        return (KeyedSpan(R), [], [])

    @staticmethod
    def _add(space, z, prov):
        r"""
        Insert the raw vector ``z`` with provenance ``prov`` into ``space`` if it
        is independent; True if it was.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: sp = N._new_space()
            sage: N._add(sp, {k1: 1}, 'a'), N._add(sp, {k1: 2}, 'b'), N._add(sp, {}, 'c')
            (True, False, False)
            sage: sp[2]
            ['a']
        """
        if not z:
            return False
        ech, vecs, provs = space
        if ech.insert(z, label=len(vecs)):
            vecs.append(z)
            provs.append(prov)
            return True
        return False

    @staticmethod
    def _add_many(space, cands):
        r"""
        Insert the independent vectors of ``cands`` (pairs ``(raw vector,
        provenance)``) in one batch; the labels index the stored vectors.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: sp = N._new_space()
            sage: N._add_many(sp, [({k1: 1}, 'a'), ({k1: 2}, 'b'), ({k2: 1}, 'c'), ({}, 'd')])
            sage: sp[2], sp[0].labels()
            (['a', 'c'], [0, 1])
        """
        ech, vecs, provs = space
        cands = [(z, prov) for z, prov in cands if z]
        n0 = len(vecs)
        flags = ech.insert_many([z for z, _ in cands],
                                labels=list(range(n0, n0 + len(cands))))
        for (z, prov), ok in zip(cands, flags):
            if ok:
                vecs.append(z)
                provs.append(prov)
        ech._labels[n0:] = list(range(n0, len(vecs)))

    def _act(self, xi, n, y):
        r"""
        The mode ``x_(n)`` of the strong generator ``xi`` on the raw vector ``y``
        of the ambient module (a raw dict without zeros).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: N._act(0, 0, {k1: 1}) == {k11: 1}           # L_(0) = L_{-1}
            True
        """
        M = self._ambient_module
        return {k: c for k, c in M._action_raw(self._X[xi][1], n, y).items() if c}

    @_gc_paused
    def _closure(self):
        r"""
        The closure of the generators under the non-raising modes of the
        strong generators, by piece: ``{piece: (echelon, vectors,
        provenances)}``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: C = N._closure(); list(C)
            [(1, None)]
            sage: C[(1, None)][1:] == ([{k1: 1}], [(0, ())])
            True
        """
        if self._N is not None:
            return self._N
        store = {}
        queue = []
        for j, (y, w, _) in enumerate(self._gens):
            p = self._piece(next(iter(y)))
            sp = store.setdefault(p, self._new_space())
            if self._add(sp, y, (j, ())):
                queue.append((y, p, (j, ())))
        while queue:
            y, (w, G), (j, word) = queue.pop()
            for xi, (_, _, h, sh) in enumerate(self._X):
                for n in range(ceil(h - 1), floor(h - 1 + w) + 1):
                    z = self._act(xi, n, y)
                    if not z:
                        continue
                    p2 = (w + h - n - 1, self._shift(G, sh))
                    sp = store.setdefault(p2, self._new_space())
                    prov = (j, ((xi, n),) + word)
                    if self._add(sp, z, prov):
                        queue.append((z, p2, prov))
        self._N = store
        return store

    @_gc_paused
    def _space(self, p):
        r"""
        The piece ``p = (w, G)``: raising words applied to the closure, as
        ``(echelon, vectors, provenances)`` (a provenance ``(j, word)``: the word
        of modes applied to the generator ``j``).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: ech, vecs, provs = N._space((2, None))
            sage: vecs == [{k11: 1}], provs
            (True, [(0, ((0, 0),))])
        """
        sp = self._S.get(p)
        if sp is not None:
            return sp
        w, G = p
        sp = self._new_space(ordered=True)
        if w >= 0:
            cands = []
            n0 = self._closure().get(p)
            if n0 is not None:
                cands.extend(zip(n0[1], n0[2]))
            for xi, (_, _, h, sh) in enumerate(self._X):
                # raising: 0 < h - n - 1 <= w
                for n in range(ceil(h - 1 - w), ceil(h - 1)):
                    sub = self._space((w - (h - n - 1), self._shift(G, sh, -1)))
                    for y, (j, word) in zip(sub[1], sub[2]):
                        cands.append((self._act(xi, n, y), (j, ((xi, n),) + word)))
            self._add_many(sp, cands)
        self._S[p] = sp
        return sp

    def _echelon_piece(self, p):
        r"""
        The reduced echelon form of the piece ``p`` (from :meth:`_space`).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: k1, k2 = L.mode(v, -1).leading_support(), L.mode(v, -2).leading_support()
            sage: k11 = L.mode(L.mode(v, -1), -1).leading_support()
            sage: N._echelon_piece((2, None)).rows() == [{k11: 1}]
            True
        """
        return self._space((QQ(p[0]), p[1]))[0]

