def _strong_generator_modes(M):
    r"""
    The strong generators of the vertex algebra of ``M`` as ``(element, raw
    dict, h, sh)``: ``h`` their (twisted, if ``M`` has a twisted degree)
    conformal weight, positive and rational (``NotImplementedError``
    otherwise), ``sh`` the image of their grade in the grading group of ``M``
    (``None`` if ``M`` is not graded).

    Affine ``sl_2`` at level 1 acting on itself (graded by the root lattice)
    and the Virasoro algebra on a Verma module (ungraded):

    TESTS::

        sage: import vertex_algebras as va
        sage: V = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']); E, H, F = V.gens()
        sage: M = V.adjoint_module(); N = M.submodule([E.no(E)])
        sage: k = M(E.no(E)).leading_support()
        sage: from vertex_algebras.vertex_algebra_submodule import _strong_generator_modes
        sage: _strong_generator_modes(M)
        [(E, {((0, 0),): 1}, 1, (1,)), (H, {((1, 0),): 1}, 1, (0,)), (F, {((2, 0),): 1}, 1, (-1,))]
        sage: _strong_generator_modes(va.Virasoro(QQ, 1/2, conformal_vector='L').verma_module(0))
        [(L, {((0, 0),): 1}, 2, None)]
    """
    V = M.vertex_algebra()
    try:
        gens = V._strong_generators_for_ideals()
        data = V._weight_data()
    except (NotImplementedError, ValueError, AttributeError) as err:
        raise NotImplementedError('submodules need a finite set of strong generators '
                                  'of {} and its conformal weights: {}'.format(V, err))
    X = []
    for x in gens:
        ws = {V._weight_key(k, data) for k in x.support()}
        h = None
        if len(ws) == 1:
            try:
                h = QQ(ws.pop())
            except (TypeError, ValueError):
                h = None
        sh = None
        if h is not None and (M._mu is not None or M._mgrading is not None):
            gs = {V._grade_key(k) for k in x.support()}
            if len(gs) != 1:
                h = None
            else:
                g = gs.pop()
                h = h + M._mu_of(g)
                if M._mgrading is not None:
                    sh = M._mgrading(g)
        if h is None or h <= 0:
            raise NotImplementedError(
                'submodules need strong generators of positive rational (twisted) '
                'conformal weight, homogeneous for the grading; {} is not one'.format(x))
        X.append((x, dict(x._monomial_coefficients), h, sh))
    return X


class SubmoduleExpression:
    r"""
    A vector of a submodule written as a linear combination of descendants
    ``x1_(n1) ... xk_(nk) s_j`` of its generators (returned by
    :meth:`FinitelyGeneratedSubmodule.express`).  :meth:`terms` lists
    ``((j, word), coefficient)`` with ``word`` a tuple of ``(strong generator
    index, n)``, outermost mode first; :meth:`element` evaluates it.

    INPUT:

    - ``N`` -- a :class:`FinitelyGeneratedSubmodule`
    - ``terms`` -- an iterable of pairs ``((j, word), coefficient)`` as
      above

    EXAMPLES::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
        sage: M = V.verma_module(0); v = M.highest_weight_vector()
        sage: N = M.submodule([L.mode(v, -1)], names=['w'])
        sage: e = N.express(L.mode(L.mode(v, -1), -2)); e
        L_(-1) w
        sage: type(e)
        <class 'vertex_algebras.vertex_algebra_submodule.SubmoduleExpression'>
    """
    def __init__(self, N, terms):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra_submodule import SubmoduleExpression
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: e = SubmoduleExpression(N, [((0, ((0, -1),)), 2)]); e.terms()
            [((0, ((0, -1),)), 2)]
            sage: e.element() == 2*L.mode(L.mode(v, -1), -2)
            True
        """
        self._N = N
        self._terms = list(terms)

    def terms(self):
        r"""
        The list of ``((j, word), coefficient)``: ``word`` is a tuple of
        ``(strong generator index, n)``, outermost mode first, applied to the
        generator ``j`` of the submodule.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: x = L.mode(L.mode(L.mode(v, -1), -1), -1) + L.mode(L.mode(v, -1), -2)
            sage: N.express(x).terms()
            [((0, ((0, -1),)), 1), ((0, ((0, 0), (0, 0))), 1)]
        """
        return list(self._terms)

    def element(self):
        r"""
        The vector of the submodule this expression denotes.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: x = L.mode(L.mode(L.mode(v, -1), -1), -1) + L.mode(L.mode(v, -1), -2)
            sage: y = N.express(x).element(); y.parent() is N, y == x
            (True, True)
        """
        N = self._N
        return sum((c * N._word_element(*t) for t, c in self._terms), N.zero())

    def __repr__(self):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: N = M.submodule([L.mode(v, -1)], names=['w'])
            sage: repr(N.express(L.mode(L.mode(v, -1), -2)))
            'L_(-1) w'
        """
        from .vertex_algebra import _format_terms
        N = self._N
        return _format_terms(N._V, [(N._word_repr(*t), c) for t, c in self._terms])


