    def _install_conformal_vector(self, T, check=True):
        r"""
        The Virasoro vector of ``self`` (construction data: ``conformal_vector``
        of the constructor, ``with_conformal_vector``).  The conformal
        weights are those of the ambient algebra ``V``.  ``'coset'`` takes
        ``T_V - T_A`` with ``T_V``, ``T_A`` the Virasoro vectors of ``V`` and
        of :meth:`acting_subalgebra` (give ``A`` as a subalgebra constructed
        with its Virasoro vector; ``'coset'`` is resolved to that element at
        construction).  Otherwise ``T`` must lie in ``self``, have a
        Virasoro OPE, and ``T_V - T`` must lie in the acting subalgebra
        ``A``: then ``T_(n) v = (T_V)_(n) v`` for ``v`` in ``self`` and
        ``n >= 0``, so ``T`` induces the conformal weights of ``V``.
        ``check=False`` (constructor) skips the last two checks (and the
        central charge is then not computed).

        EXAMPLES:

        The Heisenberg coset of the βγ system (weights ``1/2``) is the
        simple ``W_3`` algebra at ``c = -2`` ([Wan1998]_; the universal one has
        dimension 8 at weight 6)::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<b, g> = NormallyOrderedExpressions(QQ)
            sage: B = UniversalVertexAlgebra(QQ, X, {('b', 'g'): [-1]},
            ....:     conformal_vector=(b.derivative()*g - b*g.derivative())/2)
            sage: b, g = B.gens()
            sage: Jbg = b.no(g); A = B.subalgebra([Jbg], conformal_vector=-Jbg.no(Jbg) / 2)
            sage: C = B.commutant(A, conformal_vector='coset'); C.central_charge()
            -2
            sage: [C.weight_space(n).dimension() for n in range(7)]
            [1, 0, 1, 2, 3, 4, 6]
            sage: C0 = B.commutant(A); C0.conformal_vector() is None
            True
            sage: C0.with_conformal_vector('coset') is C, C._spaces is C0._spaces
            (True, True)

        The acting subalgebra needs a Virasoro vector for ``'coset'`` (here
        the generator ``2 Jbg`` is new: ``B.commutant([Jbg], ...)`` would use
        ``A``, recorded by ``C0`` above)::

            sage: B.commutant([2*Jbg], conformal_vector='coset')
            Traceback (most recent call last):
            ...
            ValueError: the acting subalgebra has no Virasoro vector; give it as a subalgebra constructed with one

        TESTS:

        The GKO coset (Goddard-Kent-Olive) ``Com(L_2(sl_2), L_1(sl_2) ⊗
        L_1(sl_2))`` is the Ising model: central charge ``1/2``, the
        dimensions of the even part of a Majorana fermion, strongly generated
        by ``T`` alone; other candidates are refused::

            sage: from vertex_algebras.lattice_vertex_algebra import LatticeVertexAlgebra
            sage: L0 = LatticeVertexAlgebra(QQ, matrix([[2, 0], [0, 2]]))
            sage: a0, a1 = L0.heisenberg_currents()
            sage: L = L0.with_conformal_vector(a0.no(a0)/4 + a1.no(a1)/4)
            sage: e, f = L.e((1, 0)) + L.e((0, 1)), L.e((-1, 0)) + L.e((0, -1))
            sage: h = e.nproduct(f, 0)
            sage: A = L.subalgebra([e, f], conformal_vector=(h.no(h)/2 + e.no(f) + f.no(e))/8)
            sage: C = L.commutant(A, conformal_vector='coset')
            sage: C.central_charge(), L.commutant([e, f]).acting_subalgebra() is A
            (1/2, True)
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: F = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]}, degrees={'psi': 1/2})
            sage: ([C.weight_space(n).dimension() for n in range(9)]
            ....:  == [F.weight_space(n).dimension() for n in range(9)])
            True
            sage: T = C.conformal_vector(); gs = C.strong_generators_up_to(6)
            sage: len(gs), C(gs[0]).leading_coefficient() * T == gs[0] * T.leading_coefficient()
            (1, True)
            sage: C.with_conformal_vector(2*T)
            Traceback (most recent call last):
            ...
            ValueError: T is not a Virasoro field: ...
            sage: C.with_conformal_vector(L.conformal_vector())
            Traceback (most recent call last):
            ...
            ValueError: 1/4*:J0 J0: + 1/4*:J1 J1: is not an element of Commutant of ...
            sage: B.commutant([Jbg]).with_conformal_vector(B.conformal_vector())
            Traceback (most recent call last):
            ...
            ValueError: 1/2*:db g: - 1/2*:dg b: is not an element of Commutant of ...
        """
        V = self._ambient
        T = V._el_from_dict(dict(T))
        TV = V.conformal_vector()
        cv = V._conformal
        if cv is not None and cv['jordan']:
            raise NotImplementedError(
                'L_0 of the ambient algebra has Jordan blocks: Virasoro '
                'vectors of its commutants are not implemented')
        try:
            T = self(T)
        except ValueError:
            raise ValueError('{} is not an element of {}'.format(T, self))
        c = None
        if check:
            c = self._verify_virasoro(T)
            if TV is None:
                raise ValueError(
                    'the ambient algebra has no Virasoro vector, so it cannot '
                    'be checked that T induces its conformal weights on {}; '
                    'use check=False'.format(self))
            A = self.acting_subalgebra()
            if not A.contains(TV - V(self.lift(T))):
                raise ValueError(
                    'T_V - T is not in the acting subalgebra, so it cannot be '
                    'checked that T induces the conformal weights of the '
                    'ambient algebra on {}; use check=False'.format(self))
        self._conformal = {'T': T, 'c': c, 'data': self._weight_data(),
                           'jordan': {}}
