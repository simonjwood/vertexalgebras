    def acting_subalgebra(self):
        """
        The vertex subalgebra of the ambient algebra generated by
        :meth:`acting_generators` (the one passed to ``commutant``, or built
        here; its closure may fail with
        :class:`vertex_subalgebra.StrongGenerationError`).

        OUTPUT: a :class:`vertex_subalgebra.VertexSubalgebra`

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: A = H.subalgebra([J]); H.commutant(A).acting_subalgebra() is A
            True
            sage: H.commutant([J]).acting_subalgebra()
            Vertex subalgebra of Universal vertex algebra on generators ['J', 'K']
             over Rational Field strongly generated by ['S0']
        """
        if self._acting is None:
            self._acting = self._ambient.subalgebra(
                self._acting_gens,
                horizontal_grading='ambient' if self._cgrading is not None else None)
        return self._acting

