    def _grade_coords(self, horizontal_grade):
        """
        The coordinate tuple of a grade (``None`` stays ``None``; a grade
        needs ``horizontal_grading='ambient'``).

        TESTS::

            sage: from vertex_algebras.ghost_systems import BosonicGhosts
            sage: B = BosonicGhosts(QQ, beta_weight=1, horizontal_grading='charge')
            sage: b, g = B.gens()
            sage: CB = B.commutant([b.no(g)], horizontal_grading='ambient')
            sage: CB._grade_coords(-1), CB._grade_coords(None)
            ((-1,), None)
        """
        if horizontal_grade is None:
            return None
        return self._require_grading()['group'].coords(horizontal_grade)

    @_gc_paused
    def _space(self, W, G):
        """The weight space of weight ``W`` (and grade coordinates ``G``)
        in reduced echelon form (key order of the root algebra): the kernel
        of the acting generators on the ambient weight space (cached in
        ``_spaces``, shared with the copies with another Virasoro vector).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._space(2, None).rows()
            [{((1, 0), (1, 0)): 1}, {((1, 1),): 1}]
            sage: C._space(2, None) is C._spaces[(2, None)]
            True
        """
        key = (W, G)
        ech = self._spaces.get(key)
        if ech is not None:
            return ech
        A = self._ambient
        R = self.base_ring()
        B = A.weight_space(W, None if G is None else self._grade_out(G))
        if A._key_weight_spaces:
            # increasing key order: the relations found by left_kernel (in
            # reduced echelon form, pivots at the largest indices) are then
            # the canonical basis, whose entries are usually small (much
            # cheaper than other orders; see left_kernel)
            one = R.one()
            xs = [{k: one} for k in sorted(B.basis_keys(),
                                           key=self._key_order)]
        else:
            xs = [dict(b._monomial_coefficients) for b in B.basis()]
        ech = KeyedSpan(R, key_order=self._key_order)
        if xs:
            imgs = [{} for _ in xs]
            root = self._root
            for i, (a, _, _, _) in enumerate(self._act):
                if self._modes is None:
                    for img, poles in zip(imgs, root._ope_raw_many(a, xs)):
                        for n, p in enumerate(poles):
                            for m, c in p.items():
                                if c:
                                    img[(i, n, m)] = c
                    continue
                # only some modes (a kernel of zero modes): those products
                # alone, in one engine batch when there is one
                for n in self._modes:
                    tasks = [(0, n, j + 1) for j in range(len(xs))]
                    res = root._nprod_raw_batch([a] + xs, tasks)
                    if res is None:
                        res = [root._nprod_raw(a, n, x) for x in xs]
                    for img, p in zip(imgs, res):
                        for m, c in p.items():
                            if c:
                                img[(i, n, m)] = c
            vecs = []
            for r in left_kernel(imgs, R):
                v = {}
                for j, c in r.items():
                    _addmul(v, xs[j], c)
                vecs.append(v)
            del imgs
            ech.insert_many(vecs)
        self._spaces[key] = ech
        return ech

    def weight_space(self, weight, horizontal_grade=None):
        r"""
        The weight space of ``self`` of conformal weight ``weight`` (and,
        with ``horizontal_grading='ambient'``, of the given grade): a
        :class:`weight_spaces.SubspaceWeightSpace` whose basis is the reduced
        echelon basis for the key order of the ambient algebra (canonical;
        its leading monomials are :meth:`~weight_spaces.SubspaceWeightSpace.leading_monomials`).  Computed as
        the kernel of the acting generators on the weight space of the
        ambient algebra (which must be finite dimensional: give a grade
        otherwise).

        INPUT:

        - ``weight`` -- a conformal weight

        - ``horizontal_grade`` -- (default: ``None``) a grade (with
          ``horizontal_grading='ambient'``)

        OUTPUT: a :class:`weight_spaces.SubspaceWeightSpace`

        EXAMPLES:

        In the lattice vertex algebra of ``Z^2``, the commutant of the first
        free boson is the lattice vertex algebra of ``Z`` (two fermions)::

            sage: from vertex_algebras.lattice_vertex_algebra import LatticeVertexAlgebra
            sage: L0 = LatticeVertexAlgebra(QQ, matrix([[1, 0], [0, 1]]))
            sage: J0, J1 = L0.heisenberg_currents()
            sage: L = L0.with_conformal_vector(J0.no(J0) / 2 + J1.no(J1) / 2)
            sage: J0, J1 = L.heisenberg_currents()
            sage: C = L.commutant([J0])
            sage: [C.weight_space(n / 2).dimension() for n in range(9)]
            [1, 2, 1, 2, 4, 4, 5, 6, 9]
            sage: C.weight_space(1).basis()
            [J1]
            sage: C.strong_generators_up_to(4)
            [e^(0,1), e^(0,-1)]
        """
        from .weight_spaces import SubspaceWeightSpace, _to_rational
        self._weight_data()
        W = _to_rational(weight)
        G = self._grade_coords(horizontal_grade)
        ech = self._space(W, G)
        return SubspaceWeightSpace(
            self, self, W, None if G is None else self._grade_out(G), ech,
            self._root_dict)

