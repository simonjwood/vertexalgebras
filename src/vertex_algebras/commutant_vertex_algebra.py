    #  Strong generators                                                  #
    # ------------------------------------------------------------------ #

    def _weights_up_to(self, W, G):
        """The possible weights of keys of grade coordinates ``G`` (``None``:
        any) up to ``W``, increasing (from the root's weight bounds; a
        ``ValueError`` if those may be infinite).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._weights_up_to(3, None)
            [0, 1, 2, 3]
        """
        lb, D = self._root._weight_bounds(G, self._weight_data())
        if lb is None:
            raise ValueError(
                'the weight spaces{} of the ambient algebra may be infinite '
                'dimensional: give grades'.format(
                    '' if G is None else ' of grade {}'.format(
                        self._grade_out(G))))
        if lb > W:
            return []
        k = (QQ(lb) * D).ceil()
        out = []
        while QQ(k) / D <= W:
            out.append(QQ(k) / D)
            k += 1
        return out

    def _fresh_name(self, names):
        """
        The name of the next strong generator: from ``names`` if given that
        far, else the first unused ``C<k>``, ``k >=`` the number of
        generators.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J3', 'K3'],
            ....:     {('J3', 'J3'): [0, 1], ('K3', 'K3'): [0, 2]}, degrees={'J3': 1, 'K3': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._fresh_name(None), C._fresh_name(['a', 'b'])
            ('C0', 'a')
        """
        i = len(self._gens)
        if names is not None and i < len(names):
            return names[i]
        used = set(self.variable_names())
        k = i
        while 'C{}'.format(k) in used:
            k += 1
        return 'C{}'.format(k)

    @_gc_paused
    def strong_generators_up_to(self, max_weight, horizontal_grades=None, names=None):
        r"""
        Strong generators of ``self`` up to conformal weight ``max_weight``:
        for every weight ``w <= max_weight`` (and every grade in ``horizontal_grades``
        if given, else all of them), the weight space of weight ``w`` is
        spanned by the normally ordered monomials of the returned
        generators.  Nothing is claimed above ``max_weight``: a commutant
        need not be finitely strongly generated.

        The generators are found weight by weight: the canonical basis
        vectors of a weight space (see :meth:`weight_space`) that are not in
        the span of the normally ordered monomials of the generators found
        so far become new generators (homogeneous for weight, parity and
        grade).  The search is incremental (a larger ``max_weight``
        continues it); the generators are named ``C0, C1, ...`` unless
        ``names`` (a list, for the generators in order) says otherwise.
        They are also :meth:`~vertex_algebra.VertexAlgebra.gens` of ``self``, and :meth:`express`
        writes elements of weight ``<= max_weight`` in them.  With
        ``horizontal_grades`` only those grades are searched (needed when the weight
        spaces of the ambient algebra are infinite dimensional): products
        of generators of other grades may then appear as generators.

        INPUT:

        - ``max_weight`` -- the conformal weight up to which to search

        - ``horizontal_grades`` -- (default: ``None``) a list of grades to
          search (with ``horizontal_grading='ambient'``); ``None``: all

        - ``names`` -- (default: ``None``) names of the generators, in order
          (default ``C0, C1, ...``)

        OUTPUT: the generators of weight ``<= max_weight`` found so far

        EXAMPLES:

        The coset ``Com(L_2(sl_2), L_1(sl_2) ⊗ L_1(sl_2))`` (diagonal
        currents) in the lattice vertex algebra of ``A_1 ⊕ A_1`` is the
        Ising model ``L(1/2, 0)``, strongly generated by the coset Virasoro
        vector::

            sage: from vertex_algebras.lattice_vertex_algebra import LatticeVertexAlgebra
            sage: L0 = LatticeVertexAlgebra(QQ, matrix([[2, 0], [0, 2]]))
            sage: J0, J1 = L0.heisenberg_currents()
            sage: L = L0.with_conformal_vector(J0.no(J0) / 4 + J1.no(J1) / 4)
            sage: e, f = L.e((1, 0)) + L.e((0, 1)), L.e((-1, 0)) + L.e((0, -1))
            sage: C = L.commutant([e, f])          # e_(0) f = J0 + J1
            sage: [C.weight_space(n).dimension() for n in range(7)]
            [1, 0, 1, 1, 2, 2, 3]
            sage: T, = C.strong_generators_up_to(5); T.degree()
            2

        Searching only some grades (the ambient weight spaces are infinite
        dimensional here)::

            sage: from vertex_algebras.ghost_systems import BosonicGhosts
            sage: B = BosonicGhosts(QQ, beta_weight=1, horizontal_grading='charge')
            sage: b, g = B.gens()
            sage: CB = B.commutant([b.no(g)], horizontal_grading='ambient')
            sage: [x.degree() for x in CB.strong_generators_up_to(3, horizontal_grades=[0])]
            [2, 3]

        TESTS:

        Ctrl-C in the middle of the search (simulated: an elimination
        raising ``KeyboardInterrupt``): continued afterwards, it finds what
        an uninterrupted search finds::

            sage: from vertex_algebras._keyed_spans import KeyedSpan
            sage: def interrupted(f, k, cls=KeyedSpan, name='insert_many'):
            ....:     # f() with cls.name raising KeyboardInterrupt at its k-th call
            ....:     orig, calls = getattr(cls, name), [0]
            ....:     def patched(*args, **kwds):
            ....:         calls[0] += 1
            ....:         if calls[0] == k:
            ....:             raise KeyboardInterrupt
            ....:         return orig(*args, **kwds)
            ....:     setattr(cls, name, patched)
            ....:     try:
            ....:         f()
            ....:         return False
            ....:     except KeyboardInterrupt:
            ....:         return True
            ....:     finally:
            ....:         setattr(cls, name, orig)
            sage: def gko(names):
            ....:     # a fresh copy (algebras are unique by their data): other names
            ....:     L0 = LatticeVertexAlgebra(QQ, matrix([[2, 0], [0, 2]]), names=names)
            ....:     J0, J1 = L0.heisenberg_currents()
            ....:     L = L0.with_conformal_vector(J0.no(J0) / 4 + J1.no(J1) / 4)
            ....:     return L.commutant([L.e((1, 0)) + L.e((0, 1)), L.e((-1, 0)) + L.e((0, -1))])
            sage: def result(C):
            ....:     C.strong_generators_up_to(7)
            ....:     return ([C.weight_space(w).dimension() for w in range(8)],
            ....:             [(g['name'], g['h'], g['origin'], dict(g['el']._monomial_coefficients))
            ....:              for g in C._gens],
            ....:             [sorted(r.items()) for r in C._space(6, None).rows()])
            sage: ref = result(gko('K'))
            sage: for k in (1, 3, 6, 10):
            ....:     C = gko('K%s_' % k)
            ....:     assert interrupted(lambda: C.strong_generators_up_to(7), k)
            ....:     assert result(C) == ref
        """
        from .weight_spaces import _to_rational
        self._weight_data()
        W = _to_rational(max_weight)
        if names is not None:
            names = [str(s) for s in names]
            for i, g in enumerate(self._gens[:len(names)]):
                g['name'] = names[i]
        Gs = [None] if horizontal_grades is None else [
            self._grade_coords(g) for g in horizontal_grades]
        V = self._root
        vac = V._vacuum_key()
        graded = self._cgrading is not None
        for G in Gs:
            start = self._searched.get(G)
            if start is None and G is not None:
                start = self._searched.get(None)
            for w in self._weights_up_to(W, G):
                if start is not None and w <= start:
                    continue
                rows = self._space(w, G).rows()
                for r in rows:
                    if len(r) == 1 and vac in r:
                        continue                # the vacuum (word ())
                    if self._span(w, G).echelon.contains(r):
                        continue
                    x = V._el_from_dict(r)
                    if G is None and graded and w <= 0:
                        raise NotImplementedError(
                            'the commutant has a strong generator {} of '
                            'weight {} <= 0: search with grades'.format(x, w))
                    Gx = self._grade_of(x, 'the strong generator') \
                        if graded else None
                    self._add_gen(x, w, self._parity_of(x, 'the strong '
                                                       'generator'),
                                  self._fresh_name(names),
                                  'weight {}'.format(w), Gx)
            if start is None or W > start:
                self._searched[G] = W
        return [self.gen(i) for i, g in enumerate(self._gens)
                if g['h'] <= W]

    def _searched_weight(self, G):
        """The weight up to which grade ``G`` was searched (``None``:
        never), counting an ungraded search.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J4', 'K4'],
            ....:     {('J4', 'J4'): [0, 1], ('K4', 'K4'): [0, 2]}, degrees={'J4': 1, 'K4': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._searched_weight(None)
            sage: _ = C.strong_generators_up_to(2); C._searched_weight(None)
            2
        """
        ws = [w for w in (self._searched.get(None), self._searched.get(G))
              if w is not None]
        return max(ws) if ws else None

    def express(self, v):
        r"""
        ``v`` (an element of ``self``) as a linear combination of normally
        ordered monomials of the strong generators found by
        :meth:`strong_generators_up_to` (only for the weights and grades
        searched); see
        :meth:`vertex_subalgebra.NormalOrderedSpans.express`.

        INPUT:

        - ``v`` -- an element of ``self`` (or of the ambient algebra lying in
          ``self``) of weights at most the searched weight

        OUTPUT:

        An element of ``self.normally_ordered_expressions()`` (see
        :meth:`vertex_subalgebra.NormalOrderedSpans.express`).

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C.strong_generators_up_to(3, names=['K'])
            [K]
            sage: C.express(K.no(K.no(K)) + K.derivative(2))
            :K K K: + d^2K
            sage: C.express(K.no(K.no(K.no(K))))
            Traceback (most recent call last):
            ...
            ValueError: ... has weight 4, above the weight up to which strong generators were searched (3); use strong_generators_up_to(4)
        """
        d = self._root_dict(v)
        if d is None or not self._contains_dict(d):
            raise ValueError('{} is not an element of {}'.format(v, self))
        comps = self._components(d)
        for (w, G) in comps:
            s = self._searched_weight(G)
            if s is None or w > s:
                raise ValueError(
                    '{} has weight {}, above the weight up to which strong '
                    'generators were searched ({}); use '
                    'strong_generators_up_to({})'.format(v, w, s, w))
        return NormalOrderedSpans.express(self, v)

