    def _kills(self, d):
        """
        True if every acting generator kills the raw dict ``d`` (of the
        root algebra): all poles ``a_(n) d``, ``n >= 0`` (only ``n`` in
        ``_modes`` if set), vanish.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._kills({((1, 0),): 1}), C._kills({((0, 0),): 1}), C._kills({})
            (True, False, True)
        """
        if not d:
            return True
        modes = self._modes
        for a, _, _, _ in self._act:
            for n, p in enumerate(self._root._ope_raw(a, d)):
                if (modes is None or n in modes) and any(p.values()):
                    return False
        return True

    def _contains_dict(self, d):
        """
        Membership of the raw root dict ``d``: in the ambient algebra (if
        that is a subspace algebra) and killed by the acting generators.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._contains_dict({((1, 0), (1, 0)): 1}), C._contains_dict({((0, 1),): 1})
            (True, False)
        """
        self._weight_data()           # stale products / weights
        A = self._ambient
        if _is_subalgebra(A) and not A._contains_dict(d):
            return False
        return self._kills(d)

