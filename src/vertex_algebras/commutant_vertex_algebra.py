    _is_commutant = True
    #: the products tested: ``a_(n) x = 0`` for ``n`` in ``_modes`` (``None``:
    #: all ``n >= 0``, the commutant; subclasses: e.g. a kernel of a zero mode)
    _modes = None
    _spaces = _shared('spaces')          # shared with the copies with other T
    _searched = _shared('searched')

    @staticmethod
    def __classcall_private__(cls, ambient, gens, horizontal_grading=None,
                              conformal_vector=None, check=True):
        """
        Normalise the arguments to the unique-representation key
        ``(ambient, gens, horizontal_grading, T)``: generators converted into
        ``ambient``, zero and repeated ones dropped; ``'coset'`` resolved to
        the element ``T_V - T_A``; ``T`` canonical.  ``check`` reaches
        ``__init__`` through ``_PENDING_CHECKS`` (not part of the key).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: from vertex_algebras.commutant_vertex_algebra import CommutantVertexAlgebra
            sage: CommutantVertexAlgebra(H, [J, 0*J, J]) is C
            True
            sage: CommutantVertexAlgebra(H, [J], horizontal_grading='x')
            Traceback (most recent call last):
            ...
            ValueError: grading must be None or 'ambient'
        """
        if not isinstance(ambient, VertexAlgebra):
            raise TypeError('{!r} is not a vertex algebra'.format(ambient))
        if horizontal_grading not in (None, 'ambient'):
            raise ValueError("grading must be None or 'ambient'")
        uniq = []
        for x in (ambient(x) for x in gens):
            if not x.is_zero() and x not in uniq:
                uniq.append(x)
        T = conformal_vector
        if isinstance(T, str) and T == 'coset':
            # T_V - T_A, as an element (the key does not depend on which
            # copy of the acting subalgebra was given)
            C0 = cls(ambient, uniq, horizontal_grading)
            TV = ambient.conformal_vector()
            if TV is None:
                raise ValueError('the ambient algebra has no Virasoro vector')
            A = C0.acting_subalgebra()
            TA = A.conformal_vector()
            if TA is None:
                raise ValueError('the acting subalgebra has no Virasoro vector; '
                                 'give it as a subalgebra constructed with one')
            T = TV - ambient(A.lift(TA))
        T = _canonical_element(ambient, T)
        _PENDING_CHECKS.append(check)
        try:
            return VertexAlgebra.__classcall__(cls, ambient, tuple(uniq), horizontal_grading,
                                               T)
        finally:
            _PENDING_CHECKS.pop()

    def __init__(self, ambient, gens, horizontal_grading, conformal_vector=None):
        r"""
        TESTS:

        A commutant with a conformal vector shares the computed state of
        the one without::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H0 = UniversalVertexAlgebra(QQ, ['J', 'K'], {('J', 'J'): [0, 1], ('K', 'K'): [0, 1]})
            sage: J, K = H0.gens(); H = H0.with_conformal_vector((J.no(J) + K.no(K))/2)
            sage: J, K = H.gens(); C = H.commutant([J])
            sage: C1 = H.commutant([J], conformal_vector=K.no(K)/2)
            sage: C1 is C, C1._core is C._core, C1._acting_gens == (J,), C1.central_charge()
            (False, True, True, 1)
        """
        check = _PENDING_CHECKS[-1] if _PENDING_CHECKS else True
        C0 = None
        if conformal_vector is not None:
            # the same commutant without T: its spaces and generators are
            # shared
            C0 = VertexAlgebra.__classcall__(            # the key of T=None
                CommutantVertexAlgebra, ambient, gens, horizontal_grading, None)
        self._init_subspace(ambient, horizontal_grading, 'commutants',
                            conformal_vector is not None)
        self._pickle_args = (ambient, tuple(gens), horizontal_grading, conformal_vector)
        self._grading_option = horizontal_grading
        self._data = {'T': conformal_vector}
        self._init_spans(None if C0 is None else C0._core)
        V = self._root
        graded = self._cgrading is not None
        self._acting_gens = tuple(gens)
        #: the acting generators: (raw root dict, weight, parity, grade)
        self._act = []
        for a in gens:
            x = V._el_from_dict(dict(a._monomial_coefficients))
            self._act.append((
                dict(x._monomial_coefficients),
                self._weight_of(x, 'the generator'),
                self._parity_of(x, 'the generator'),
                self._grade_of(x, 'the generator') if graded else None))
        self._acting = None if C0 is None else C0._acting   # once known
        if C0 is None:
            self._spaces = {}     # (W, G or None) -> KeyedSpan
            self._searched = {}   # G or None -> weight searched up to
        if graded:
            self._grading = self._cgrading
        self._embed_into_ambient()
        if conformal_vector is not None:
            self._install_conformal_vector(conformal_vector, check)

    # conformal data as construction data (see VertexAlgebra._forgets)

    def _structure_key(self):
        """
        The construction data without the conformal ones (forgetful
        coercions, see ``VertexAlgebra._forgets``).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._structure_key()
            ('CommutantVertexAlgebra', Universal vertex algebra on generators ['J', 'K']
             over Rational Field, (J,), None)
        """
        return ('CommutantVertexAlgebra', self._ambient, self._acting_gens,
                self._grading_option)

    def _conformal_key(self):
        """
        The conformal construction data: the canonical Virasoro vector.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._conformal_key()
            {'T': None}
        """
        return {'T': self._data['T']}

    def _with(self, **changes):
        """
        The commutant with the same acting generators and other
        construction data (``conformal_vector``, ``horizontal_grading``);
        the hook of ``with_conformal_vector`` / ``with_horizontal_grading``.
        The conformal weights are always the ambient's.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'],
            ....:     {('J', 'J'): [0, 1], ('K', 'K'): [0, 2]}, degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: C._with(horizontal_grading=None) is C
            True
            sage: C._with(degrees={'K': 2})
            Traceback (most recent call last):
            ...
            ValueError: the conformal weights of a commutant are those of the ambient algebra
        """
        if changes.pop('horizontal_grading_group', None) is not None:
            raise ValueError("the grading of a commutant is 'ambient' (that of "
                             "the ambient algebra) or None")
        if 'degrees' in changes:
            raise ValueError('the conformal weights of a commutant are those of '
                             'the ambient algebra')
        args = {'conformal_vector': self._data['T'],
                'horizontal_grading': self._grading_option}
        args.update(changes)
        C0 = CommutantVertexAlgebra(self._ambient, self._acting_gens,
                                    args['horizontal_grading'])
        if C0._acting is None and self._acting is not None:
            C0._acting = self._acting
        if args['conformal_vector'] is None:
            return C0
        return CommutantVertexAlgebra(self._ambient, self._acting_gens,
                                      args['horizontal_grading'], args['conformal_vector'])

    def __reduce__(self):
        """
        Pickle by the arguments of the public constructor.

        Unpickling returns this commutant in the same session; in a new
        session the
        weight spaces and strong generators found so far are computed again
        on demand.

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'], {('J', 'J'): [0, 1], ('K', 'K'): [0, 1]},
            ....:                            degrees={'J': 1, 'K': 1})
            sage: J, K = H.gens()
            sage: C = H.commutant([J])
            sage: loads(dumps(C)) is C
            True
            sage: TestSuite(C).run()
        """
        return (CommutantVertexAlgebra, self._pickle_args)

