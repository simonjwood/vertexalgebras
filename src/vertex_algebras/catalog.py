def W3(base_ring, c, names=('L', 'W'), degrees=None, **options):
    r"""
    Zamolodchikov's universal ``W_3`` algebra [Zam1985]_ of central charge
    ``c``: the Virasoro field ``L`` and a primary ``W`` of degree 3 with::

        W(z) W(w) ~ (c/3)/(z-w)^6 + 2L/(z-w)^4 + ∂L/(z-w)^3
                    + (2βΛ + 3/10 ∂²L)/(z-w)^2 + (β∂Λ + 1/15 ∂³L)/(z-w),

    ``Λ = :LL: - 3/10 ∂²L``, ``β = 16/(22 + 5c)`` (``22 + 5c`` must be
    invertible).

    INPUT:

    - ``base_ring`` -- a commutative ring containing ``QQ``
    - ``c`` -- the central charge, an element of ``base_ring`` with
      ``22 + 5c`` invertible
    - ``names`` -- (default: ``('L', 'W')``) the names of the two generators
    - ``degrees`` -- (default: ``None``) ``None`` (2 and 3), ``False`` or a
      dict
    - ``**options`` -- further keywords as for
      :class:`universal_vertex_algebra.UniversalVertexAlgebra`;
      ``conformal_vector`` may be given by the name of the Virasoro field
      (``conformal_vector='L'``)

    OUTPUT:

    A :class:`universal_vertex_algebra.UniversalVertexAlgebra`.

    EXAMPLES::

        sage: from vertex_algebras.catalog import W3
        sage: K.<c> = Frac(QQ['c'])
        sage: V = W3(K, c, conformal_vector='L')
        sage: V.central_charge(), [V.weight_space(n).dimension() for n in range(7)]
        (c, [1, 0, 1, 2, 3, 4, 8])
        sage: V.jacobi_identity_failures()
        {}
        sage: W = V.gen('W'); W.ope(W)[1]
        (32/5/(c + 22/5))*:L L: + ((3/10*c - 3/5)/(c + 22/5))*d^2L
    """
    from .normally_ordered_expressions import NormallyOrderedExpressions
    from .universal_vertex_algebra import UniversalVertexAlgebra
    nL, nW = names
    R = base_ring
    c = R(c)
    E = NormallyOrderedExpressions(R, [nL, nW])
    L, W = E.gens()
    beta = 16 / R(22 + 5 * c)
    Lam = L * L - R(3) / 10 * L.derivative(2)
    opes = {(nL, nL): [L.derivative(), 2 * L, 0, c / 2],
            (nL, nW): [W.derivative(), 3 * W],
            (nW, nW): [L.derivative(3) / 15 + beta * Lam.derivative(),
                       R(3) / 10 * L.derivative(2) + 2 * beta * Lam,
                       L.derivative(), 2 * L, 0, c / 3]}
    if degrees is None:
        degrees = {nL: 2, nW: 3}
    elif degrees is False:
        degrees = None
    if isinstance(options.get('conformal_vector'), str):
        options['conformal_vector'] = E.gen(options['conformal_vector'])
    return UniversalVertexAlgebra(R, E, opes, degrees=degrees, **options)


def W(base_ring, g, f, level, **options):
    r"""
    The W-algebra ``W^k(g, f)`` by quantum Hamiltonian reduction:
    :func:`quantum_hamiltonian_reduction.WAlgebra`.

    INPUT:

    - ``base_ring`` -- a field containing ``QQ`` (and the level)
    - ``g`` -- a :class:`lie_superalgebras.LieSuperalgebra` (or what
      :func:`quantum_hamiltonian_reduction.WAlgebra` accepts)
    - ``f`` -- the nilpotent: ``'minimal'``, ``'principal'``, a Jordan type,
      a list of positive roots or an element of ``g``
    - ``level`` -- the level ``k``
    - ``**options`` -- further keywords (``conformal_vector='reduction'``,
      ``x``, ``names``, ...) as for
      :func:`quantum_hamiltonian_reduction.WAlgebra`

    OUTPUT:

    A :class:`universal_vertex_algebra.UniversalVertexAlgebra` on the generators ``J{v}``
    (see :func:`quantum_hamiltonian_reduction.WAlgebra`).

    EXAMPLES::

        sage: from vertex_algebras.catalog import W
        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: K.<k> = Frac(QQ['k'])
        sage: BP = W(K, LieSuperalgebra(QQ, CartanMatrix(['A', 2])), 'minimal', k,
        ....:        conformal_vector='reduction')
        sage: sorted(BP.degrees().values())
        [1, 3/2, 3/2, 2]
    """
    from .quantum_hamiltonian_reduction import WAlgebra
    return WAlgebra(base_ring, g, f, level, **options)
