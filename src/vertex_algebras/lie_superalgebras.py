def _ad_table(n, br):
    """
    The sparse adjoint maps of a bracket table ``br`` (``{(i, j): {k: c}}``
    on basis indices ``0, ..., n-1``): ``ad[i][j] = [e_i, e_j]``.

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import _ad_table
        sage: _ad_table(3, {(0, 1): {2: 1}, (1, 0): {2: -1}, (0, 2): {}})
        [{1: {2: 1}}, {0: {2: -1}}, {}]
    """
    ad = [{} for _ in range(n)]
    for (i, j), v in br.items():
        if v:
            ad[i][j] = v
    return ad


def _killing_entry(R, par, ad, i, j):
    """
    The (super) Killing form ``str(ad e_i ad e_j)`` over ``R`` from the
    sparse adjoint maps ``ad`` (:func:`_ad_table`) and the parities ``par``.

    TESTS:

    ``sl_2`` with basis ``e, h, f``: ``κ(e, f) = 4``, ``κ(h, h) = 8``::

        sage: from vertex_algebras.lie_superalgebras import _ad_table, _killing_entry
        sage: br = {(0, 1): {0: -2}, (1, 0): {0: 2}, (0, 2): {1: 1}, (2, 0): {1: -1},
        ....:       (1, 2): {2: -2}, (2, 1): {2: 2}}
        sage: ad = _ad_table(3, br)
        sage: [_killing_entry(QQ, [0, 0, 0], ad, i, j) for i, j in [(0, 2), (1, 1), (0, 0)]]
        [4, 8, 0]
    """
    if par[i] != par[j]:
        return R.zero()
    tot = R.zero()
    for s, col in ad[j].items():          # (ad_i ad_j)[s, s]
        for t, c in col.items():
            d = ad[i].get(t, {}).get(s)
            if d:
                tot += -c * d if par[s] else c * d
    return tot


def _killing_form(R, par, br):
    """The Gram matrix over ``R`` of the (super) Killing form ``str(ad a ad
    b)`` of the Lie superalgebra with parities ``par`` and brackets ``br``,
    by sparse traces over the bracket table (supersymmetric).

    TESTS:

    ``sl_2``: ``κ = 4`` times the normalised form (``2 h^∨ = 4``)::

        sage: from vertex_algebras.lie_superalgebras import _killing_form
        sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
        sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1); a = V._affine
        sage: _killing_form(QQ, a['par'], a['brackets']) == 4 * a['gram']
        True
    """
    return _killing_matrix(R, par, _ad_table(len(par), br))


def _killing_matrix(R, par, ad):
    """
    The Gram matrix over ``R`` of the (super) Killing form from the sparse
    adjoint maps ``ad`` (:func:`_ad_table`) and the parities ``par``.

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import _ad_table, _killing_matrix
        sage: br = {(0, 1): {0: -2}, (1, 0): {0: 2}, (0, 2): {1: 1}, (2, 0): {1: -1},
        ....:       (1, 2): {2: -2}, (2, 1): {2: 2}}
        sage: _killing_matrix(QQ, [0, 0, 0], _ad_table(3, br))
        [0 0 4]
        [0 8 0]
        [4 0 0]
    """
    n = len(par)
    K = matrix(R, n, n)
    for i in range(n):
        for j in range(i, n):
            tot = _killing_entry(R, par, ad, i, j)
            if tot:
                K[i, j] = tot
                K[j, i] = -tot if par[i] and par[j] else tot
    return K


class LieSuperalgebra(_ArtFromRepr, CombinatorialFreeModule):
    r"""
    The contragredient Lie superalgebra of a Cartan matrix with odd simple
    roots, or a named basic classical Lie superalgebra (see the module
    documentation).

    INPUT:

    - ``base_ring`` -- a field containing ``QQ``

    - ``cartan`` -- a name (``'sl(m|n)'``, ``'psl(m|m)'``, ``'osp(m|n)'``,
      ``'spo(n|m)'``, ``'D(2,1;a)'``, ``'F(4)'``, ``'G(3)'``), or a Cartan
      matrix (an indecomposable, symmetrizable square matrix: the rows of
      odd isotropic simple roots have a zero diagonal entry)

    - ``odd`` -- (default: ``None``) for a Cartan matrix: the odd simple
      roots, 1-based

    - ``theta`` -- (default: ``None``) the root ``θ`` with ``(θ|θ) = 2``,
      the highest root of a simple component of the even part: a tuple of
      simple-root coordinates, or for ``F(4)`` / ``G(3)`` ``'sl2'`` /
      ``'so7'`` / ``'G2'`` (required); ``None`` for a Cartan matrix of a
      Lie algebra and for ``D(2,1;a)``: the highest root

    - ``a`` -- (default: ``None``) the parameter of ``D(2,1;a)``
      (``a ≠ 0, -1``)

    EXAMPLES::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: g = LieSuperalgebra(QQ, 'spo(2|1)'); g          # osp(1|2)
        Lie superalgebra spo(2|1) over Rational Field
        sage: g.dimension(), g.dual_coxeter_number(), g.theta()
        (5, 3/2, (2,))
        sage: e = g.e(1); e.bracket(e)
        E[2*alpha[1]]
        sage: K.<a> = Frac(QQ['a'])
        sage: D = LieSuperalgebra(K, 'D(2,1;a)', a=a); D
        Lie superalgebra D(2,1;a) with a = a over Fraction Field of Univariate Polynomial Ring in a over Rational Field
        sage: D.dimension(), D.dual_coxeter_number(), D.theta()
        (17, 0, (2, 1, 1))
        sage: [ct for ct, theta, roots in D.even_part_components()]
        [['A', 1], ['A', 1], ['A', 1]]
        sage: F = LieSuperalgebra(QQ, 'F(4)', theta='so7')
        sage: [(ct, t, F.root_norm(t)) for ct, t, roots in F.even_part_components()]
        [(['B', 3], (0, 2, 2, 1), 2), (['A', 1], (2, 3, 2, 1), -3)]

    A Cartan matrix: ``sl(2|1)`` with both simple roots odd (another Borel),
    and a Lie algebra::

        sage: H = LieSuperalgebra(QQ, matrix([[0, 1], [1, 0]]), odd=[1, 2], theta=(1, 1))
        sage: H.dimension(), H.superdimension(), H.dual_coxeter_number()
        (8, 0, 1)
        sage: G2 = LieSuperalgebra(QQ, CartanMatrix(['G', 2]))
        sage: G2.dimension(), G2.dual_coxeter_number()
        (14, 4)

    TESTS::

        sage: g is LieSuperalgebra(QQ, 'spo(2|1)'), loads(dumps(g)) is g
        (True, True)
        sage: TestSuite(g).run(); TestSuite(D).run(); TestSuite(H).run()
        sage: LieSuperalgebra(QQ, 'F(4)')
        Traceback (most recent call last):
        ...
        ValueError: F(4) has two normalisations of the form: give theta='sl2' or theta='so7'
        sage: LieSuperalgebra(QQ, 'osp(3|2)')
        Traceback (most recent call last):
        ...
        ValueError: osp(m|n) has theta in so_m: m >= 4, n even (and so_4 is not simple); use spo(n|m) for theta in sp_n
        sage: LieSuperalgebra(QQ, matrix([[2, -1], [-1, 0]]), odd=[2])
        Traceback (most recent call last):
        ...
        ValueError: the highest root is odd: give theta (a highest root of a simple component of the even part)

    The super antisymmetry, parity, super Jacobi identity and invariance of
    the form for more algebras::

        sage: for n, kw in [('psl(2|2)', {}), ('spo(4|1)', {}), ('osp(5|2)', {}),
        ....:               ('F(4)', {'theta': 'so7'}), ('G(3)', {'theta': 'sl2'}),
        ....:               ('D(2,1;a)', {'a': 2})]:
        ....:     TestSuite(LieSuperalgebra(QQ, n, **kw)).run()

    Other Dynkin diagrams: ``osp(3|2)`` with the odd non-isotropic simple
    root ``δ`` (simple roots ``ε - δ``, ``δ``) is ``spo(2|3)``;
    ``D(2,1;1) = osp(4|2)``::

        sage: from vertex_algebras.lie_superalgebras import _from_simple_roots
        sage: A, odd = _from_simple_roots([[-1, 1], [1, 0]], [-1, 1])
        sage: O = LieSuperalgebra(QQ, A, odd=[i + 1 for i in odd], theta=(0, 2))
        sage: S = LieSuperalgebra(QQ, 'spo(2|3)')
        sage: O.odd_simple_roots(), [(G.dimension(), G.superdimension(), G.dual_coxeter_number(),
        ....:                         [ct for ct, _, _ in G.even_part_components()]) for G in (O, S)]
        ((1, 2), [(12, 0, 1/2, [['A', 1], ['A', 1]]), (12, 0, 1/2, [['A', 1], ['A', 1]])])
        sage: TestSuite(O).run()
        sage: D1, O42 = LieSuperalgebra(QQ, 'D(2,1;a)', a=1), LieSuperalgebra(QQ, 'osp(4|2)')
        sage: [(G.dimension(), G.dual_coxeter_number(), len(G.even_part_components()))
        ....:  for G in (D1, O42)]
        [(17, 0, 3), (17, 0, 3)]

    Lie algebras: dimensions and positive roots as Sage's::

        sage: all(LieSuperalgebra(QQ, CartanMatrix(ct)).dimension()
        ....:     == LieAlgebra(QQ, cartan_type=ct).dimension()
        ....:     and len(LieSuperalgebra(QQ, CartanMatrix(ct)).positive_roots())
        ....:     == len(list(RootSystem(ct).root_lattice().positive_roots()))
        ....:     for ct in (['A', 2], ['B', 3], ['C', 3], ['G', 2], ['D', 4]))
        True

    Refusals::

        sage: for args, kw in [(('G(3)',), {}), (('sl(1|2)',), {}), (('sl(2|2)',), {}),
        ....:                  (('psl(2|3)',), {}), (('D(2,1;a)',), {'a': -1}),
        ....:                  ((matrix([[2, -2], [-2, 2]]),), {}),
        ....:                  ((matrix([[2, 0], [0, 2]]),), {})]:
        ....:     try:
        ....:         LieSuperalgebra(QQ, *args, **kw)
        ....:     except ValueError as err:
        ....:         print(err)
        G(3) has two normalisations of the form: give theta='sl2' or theta='G2'
        sl(m|n) has theta in sl_m, so m >= 2 (write sl(2|1) for theta in sl_2)
        sl(m|m) is not simple: use psl(m|m)
        psl(m|m) needs m >= 2
        D(2,1;a) needs a != 0, -1
        the Lie superalgebra of this Cartan matrix is not finite dimensional (roots of height above 100)
        the invariant forms of this Lie superalgebra form a space of dimension 2 (expected 1: is the Cartan matrix indecomposable?)
    """

    _is_lie_superalgebra = True             # duck typing (doctests)

    @staticmethod
    def __classcall_private__(cls, base_ring, cartan, odd=None, theta=None, a=None):
        """
        Normalise the arguments (Cartan matrix over the base ring, 0-based
        odd simple roots, ``θ`` spec, canonical name) for the unique
        representation.

        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: LieSuperalgebra(QQ, ' sl(2 | 1)') is LieSuperalgebra(QQ, 'sl(2|1)')
            True
            sage: LieSuperalgebra(GF(3), 'sl(2|1)')
            Traceback (most recent call last):
            ...
            ValueError: the base ring must contain QQ
        """
        R = base_ring
        if R.characteristic() != 0:
            raise ValueError('the base ring must contain QQ')
        if isinstance(cartan, str):
            if odd is not None:
                raise ValueError('a named type has its own odd simple roots')
            A, oddt, th, name = _named(cartan, a)
            if name in ('F(4)', 'G(3)'):
                opts = ('sl2', 'so7') if name == 'F(4)' else ('sl2', 'G2')
                if theta not in opts and not isinstance(theta, tuple):
                    raise ValueError('{} has two normalisations of the form: give '
                                     "theta='{}' or theta='{}'".format(name, *opts))
                th = theta
            elif theta is not None:
                th = tuple(int(x) for x in theta) if not isinstance(theta, str) else theta
            if name == 'D(2,1;a)':
                a = R(a)
                if a == 0 or a == -1:
                    raise ValueError('D(2,1;a) needs a != 0, -1')
                name = ('D(2,1;a)', a)
            A = matrix(R, A)
        else:
            if a is not None:
                raise ValueError('a is the parameter of D(2,1;a)')
            A = matrix(R, cartan)
            if not A.is_square():
                raise ValueError('the Cartan matrix must be square')
            oddt = tuple(sorted(int(i) - 1 for i in (odd or ())))
            if any(not 0 <= i < A.nrows() for i in oddt):
                raise ValueError('odd simple roots are numbered 1, ..., {}'.format(A.nrows()))
            th = None if theta is None else tuple(int(x) for x in theta)
            name = None
        A.set_immutable()
        return super().__classcall__(cls, R, A, tuple(oddt), th, name)

    def __init__(self, R, A, odd, theta, name):
        r"""
        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g._A
            [ 2 -1]
            [-1  0]
            sage: g._odd, g._p, g._name
            ((1,), [0, 1], 'sl(2|1)')
            sage: g.dimension()
            8
            sage: LieSuperalgebra(QQ, [[0, 1], [-1, 2]])
            Traceback (most recent call last):
            ...
            ValueError: an even simple root needs a nonzero diagonal entry
        """
        n = A.nrows()
        self._theta_spec = theta
        self._R = R
        self._A = A
        self._odd = odd
        self._name = name
        p = [int(i in odd) for i in range(n)]
        self._p = p
        for i in range(n):
            if A[i, i] == 0 and not p[i]:
                raise ValueError('an even simple root needs a nonzero diagonal entry')
        ch = None if any(p) else _chevalley_structure(R, A)
        if ch is None:
            keys, deg, par, ad, adE, adF = _contragredient_structure(R, A, p)
        else:
            keys, deg, par, ad, adE, adF = ch
        d = len(keys)
        zero = (0,) * n
        self._keys = keys
        self._index = {k: t for t, k in enumerate(keys)}
        self._deg = deg
        self._par = par
        self._ad = ad
        self._adE, self._adF = adE, adF
        self._hbasis = [t for t in range(d) if deg[t] == zero]
        self._sc = {}
        for s in range(d):
            M = ad[s]
            for t in range(d):
                col = M.column(t)
                nz = {keys[u]: col[u] for u in col.nonzero_positions()}
                if nz:
                    self._sc[(keys[s], keys[t])] = nz
        self._form0 = self._solve_form()
        self._theta = self._resolve_theta(theta)
        tt = self._root_norm(self._theta, self._form0)
        if not tt:
            raise ValueError('theta = {} is isotropic'.format(self._theta))
        # (θ|θ) is computed through the inverse of the form on h: scaling the
        # form by λ divides it by λ
        self._form = (tt / 2) * self._form0
        CombinatorialFreeModule.__init__(
            self, R, keys, prefix='',
            category=LieSuperalgebras(R).WithBasis().FiniteDimensional())

