r"""
Basic classical Lie superalgebras.

The finite-dimensional contragredient Lie superalgebra ``g(A, τ)`` of a
Cartan matrix ``A`` with a set ``τ`` of odd simple roots (a super Dynkin
diagram; [Kac1977]_): generated by
``e_i, f_i, h_i`` (``e_i``, ``f_i`` odd for ``i ∈ τ``) with

    [e_i, f_j] = δ_ij h_i,  [h_i, e_j] = a_ij e_j,  [h_i, f_j] = -a_ij f_j,  [h_i, h_j] = 0,

modulo the largest ideal meeting the Cartan subalgebra trivially; for a
singular ``A`` (``psl(m|m)``) also modulo the centre.  It is built root
space by root space: for ``β > 0`` of height at least 2, ``g_β`` is
spanned by the ``[e_i, x]``, ``x ∈ g_{β - α_i}``, and such an element is
zero iff all ``[f_j, ·]`` kill it.  So no Serre relations are needed (the
extra relations at odd isotropic nodes come out by themselves).  The
basis: the root vectors (iterated brackets of the ``e_i``, ``f_i``) and
the ``h_i``, named as Sage prints its Chevalley bases (``E[alpha[1] +
alpha[2]]``, ``E[-alpha[1]]``, ``h1``; ``E[2*alpha[1]]`` for the root
``2α_1`` of an odd non-isotropic simple root).  The invariant form is
computed by solving the invariance equations (unique up to a scalar).

Sage has no Lie superalgebras (``LieAlgebras(R).Super()`` is the category
of super modules, and Sage's tests of Lie algebras assume
antisymmetry): :class:`LieSuperalgebras` is the category here.

**Named types** (:class:`LieSuperalgebra`), with the distinguished
Dynkin diagram (one odd simple root; [FSS1996]_) and the invariant form
normalised as in the tables of Kac--Wakimoto ([KW2004]_, Tables
I--III): ``(θ|θ) = 2`` for ``θ`` the highest
root of a chosen simple component of the even part, the choice being part
of the name:

=================  ==========================  ==================
name               ``θ`` in                    ``h^∨``
=================  ==========================  ==================
``sl(m|n)``        ``sl_m`` (``m >= 2``)       ``m - n``
``psl(m|m)``       ``sl_m`` (``m >= 2``)       ``0``
``osp(m|n)``       ``so_m`` (``m >= 4``)       ``m - n - 2``
``spo(n|m)``       ``sp_n`` (``n >= 2``)       ``(n - m)/2 + 1``
``D(2,1;a)``       one ``sl_2`` (``theta=``)   ``0``
``F(4)``           ``sl_2`` / ``so_7``         ``-2`` / ``3``
``G(3)``           ``sl_2`` / ``G_2``          ``-3/2`` / ``2``
=================  ==========================  ==================

(``osp(m|n) = spo(n|m)`` as Lie superalgebras; ``n`` even.)  Any other
diagram: a Cartan matrix and the odd simple roots, with ``theta=``.

EXAMPLES::

    sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
    sage: g = LieSuperalgebra(QQ, 'sl(2|1)'); g
    Lie superalgebra sl(2|1) over Rational Field
    sage: g.dimension(), g.superdimension(), g.dual_coxeter_number()
    (8, 0, 1)
    sage: g.cartan_matrix(), g.odd_simple_roots()
    (
    [ 2 -1]
    [-1  0], (2,)
    )
    sage: list(g.basis().keys())
    ['E[alpha[1]]', 'E[alpha[2]]', 'E[alpha[1] + alpha[2]]', 'h1', 'h2', 'E[-alpha[1]]', 'E[-alpha[2]]', 'E[-alpha[1] - alpha[2]]']
    sage: e2, f2 = g.e(2), g.f(2)
    sage: e2.bracket(f2), e2.bracket(e2), e2.is_even_odd()
    (h2, 0, 1)
    sage: [(G.dimension(), G.superdimension(), G.dual_coxeter_number())
    ....:  for G in [LieSuperalgebra(QQ, 'F(4)', theta='sl2'), LieSuperalgebra(QQ, 'G(3)', theta='G2')]]
    [(40, 8, -2), (31, 3, 2)]

AUTHORS:

- Christopher Raymond, Simon Wood (2026): initial version
"""

