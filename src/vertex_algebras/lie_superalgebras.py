class LieSuperalgebras(Category_over_base_ring):
    r"""
    The category of Lie superalgebras over ``R``: super modules with an
    even bilinear bracket satisfying::

        [x, y] = -(-1)^{|x||y|} [y, x],
        [x, [y, z]] = [[x, y], z] + (-1)^{|x||y|} [y, [x, z]].

    Sage has no such category (``LieAlgebras(R).Super()`` is the category of
    super modules, and the tests of ``LieAlgebras`` assume antisymmetry);
    this one sits over Sage's super modules.

    INPUT:

    - ``R`` -- the base ring

    EXAMPLES::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebras
        sage: C = LieSuperalgebras(QQ); C
        Category of Lie superalgebras over Rational Field
        sage: C.WithBasis().FiniteDimensional()
        Category of finite dimensional Lie superalgebras with basis over Rational Field
        sage: C.is_subcategory(Modules(QQ).Super())
        True
    """

    @cached_method
    def super_categories(self):
        """
        The super categories: super modules over the base ring.

        EXAMPLES::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebras
            sage: LieSuperalgebras(QQ).super_categories()
            [Category of super modules over Rational Field]
        """
        return [Modules(self.base_ring()).Super()]

    class ParentMethods:
        """
        Methods of Lie superalgebras.

        EXAMPLES::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g.bracket(g.e(2), g.f(2))
            h2
        """

        def bracket(self, x, y):
            """
            The bracket ``[x, y]`` (both converted into ``self`` first).

            INPUT:

            - ``x``, ``y`` -- elements of ``self`` (or convertible into it)

            EXAMPLES::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                sage: g.bracket(g.e(1), g.e(2)), g.bracket(g.e(2), g.e(2))
                (-E[alpha[1] + alpha[2]], 0)
            """
            return self(x).bracket(self(y))

        def _homogeneous_some_elements(self, tester):
            """
            The super-homogeneous elements among ``tester.some_elements()``
            (the elements the ``_test_*`` methods use).

            TESTS::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                sage: S = g._homogeneous_some_elements(g._tester())
                sage: len(S), all(x.is_super_homogeneous() for x in S)
                (8, True)
            """
            return [x for x in tester.some_elements() if x.is_super_homogeneous()]

        def _test_super_antisymmetry(self, **options):
            """
            ``[x, y] = -(-1)^{|x||y|} [y, x]`` on homogeneous elements.

            TESTS::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: LieSuperalgebra(QQ, 'sl(2|1)')._test_super_antisymmetry()
            """
            tester = self._tester(**options)
            S = self._homogeneous_some_elements(tester)
            for x in S:
                for y in S:
                    s = (-1) ** (x.is_even_odd() * y.is_even_odd())
                    tester.assertEqual(x.bracket(y), -s * y.bracket(x))

        def _test_super_jacobi_identity(self, **options):
            """
            The super Jacobi identity on homogeneous elements.

            TESTS::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: LieSuperalgebra(QQ, 'spo(2|1)')._test_super_jacobi_identity()
            """
            tester = self._tester(**options)
            S = self._homogeneous_some_elements(tester)
            for x in S:
                for y in S:
                    s = (-1) ** (x.is_even_odd() * y.is_even_odd())
                    for z in S:
                        tester.assertEqual(x.bracket(y.bracket(z)),
                                           x.bracket(y).bracket(z)
                                           + s * y.bracket(x.bracket(z)))

        def _test_bracket_parity(self, **options):
            """
            ``|[x, y]| = |x| + |y|``.

            TESTS::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: LieSuperalgebra(QQ, 'sl(2|1)')._test_bracket_parity()
            """
            tester = self._tester(**options)
            S = self._homogeneous_some_elements(tester)
            for x in S:
                for y in S:
                    b = x.bracket(y)
                    if b:
                        tester.assertEqual(b.is_even_odd(),
                                           (x.is_even_odd() + y.is_even_odd()) % 2)

    class ElementMethods:
        """
        Methods of elements of Lie superalgebras.

        EXAMPLES::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g.e(1).bracket(g.f(1))
            h1
        """

        def bracket(self, y):
            """
            The bracket ``[self, y]`` (``y`` converted into the parent first).

            INPUT:

            - ``y`` -- an element of the parent (or convertible into it)

            EXAMPLES::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                sage: e2, f2 = g.e(2), g.f(2)
                sage: e2.bracket(f2), f2.bracket(e2), g.h(1).bracket(e2)
                (h2, h2, -E[alpha[2]])
            """
            P = self.parent()
            return self._bracket_(P(y))

    class WithBasis(CategoryWithAxiom_over_base_ring):
        """
        Lie superalgebras with a distinguished basis.

        EXAMPLES::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebras
            sage: LieSuperalgebras(QQ).WithBasis()
            Category of Lie superalgebras with basis over Rational Field
        """

        def extra_super_categories(self):
            """
            Super modules with basis (so that elements have
            ``is_even_odd`` and ``is_super_homogeneous``).

            EXAMPLES::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebras
                sage: LieSuperalgebras(QQ).WithBasis().extra_super_categories()
                [Category of super modules with basis over Rational Field]
            """
            from sage.categories.modules_with_basis import ModulesWithBasis
            return [ModulesWithBasis(self.base_ring()).Super()]

        class ParentMethods:
            """
            Methods of Lie superalgebras with basis.

            EXAMPLES::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                sage: g.bracket_on_basis('E[alpha[2]]', 'E[-alpha[2]]')
                h2
            """

            @abstract_method
            def bracket_on_basis(self, a, b):
                """
                The bracket of the basis elements indexed by ``a`` and ``b``.

                INPUT:

                - ``a``, ``b`` -- basis keys

                EXAMPLES::

                    sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                    sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                    sage: g.bracket_on_basis('E[alpha[1]]', 'E[alpha[2]]')
                    -E[alpha[1] + alpha[2]]
                """

        class ElementMethods:
            """
            Methods of elements of Lie superalgebras with basis: the
            bracket, bilinear from :meth:`bracket_on_basis`.

            EXAMPLES::

                sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                sage: (g.e(1) + g.e(2)).bracket(g.f(1) + g.f(2))
                h1 + h2
            """

            def _bracket_(self, y):
                """
                The bracket with ``y`` (an element of the same parent),
                bilinear from ``bracket_on_basis``.

                EXAMPLES::

                    sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
                    sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
                    sage: g.e(1)._bracket_(g.f(1)), (g.e(1) + g.e(2))._bracket_(g.e(2))
                    (h1, -E[alpha[1] + alpha[2]])
                """
                P = self.parent()
                out = P.zero()
                for a, c in self._monomial_coefficients.items():
                    for b, d in y._monomial_coefficients.items():
                        out += (c * d) * P.bracket_on_basis(a, b)
                return out


