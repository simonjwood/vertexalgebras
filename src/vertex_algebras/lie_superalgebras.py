    def _solve_form(self):
        """
        The invariant supersymmetric form, up to a scalar: solved from
        ``B([a, u], v) = -(-1)^{|a||u|} B(u, [a, v])`` for ``a = e_i, f_i``
        (Gram matrix on the basis); refused unless unique up to scalars and
        non-degenerate.

        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: G = g._solve_form(); G.det() != 0
            True
            sage: G.rank(), (G / G[0, 5]) == (g._form / g._form[0, 5])
            (8, True)
        """
        R = self._R
        d = len(self._keys)
        deg, par = self._deg, self._par
        var = {}
        bydeg = {}
        for t in range(d):
            bydeg.setdefault(deg[t], []).append(t)

        def canon(x, y):
            """(variable index, sign) of B(x, y), or None if zero."""
            if any(a + b for a, b in zip(deg[x], deg[y])):
                return None
            key, sgn = (x, y), 1
            if x > y:
                key, sgn = (y, x), (-1) ** (par[x] * par[y])
            if key not in var:
                var[key] = len(var)
            return var[key], sgn
        for x in range(d):
            for y in bydeg.get(tuple(-a for a in deg[x]), []):
                canon(x, y)
        rows = []
        n = self._A.nrows()
        for gens, sign in ((self._adE, 1), (self._adF, -1)):
            for i in range(n):
                M = gens[i]
                da = tuple(sign * int(t == i) for t in range(n))
                for u in range(d):
                    au = M.column(u)
                    s = (-1) ** (self._p[i] * par[u])
                    # the v with deg a + deg u + deg v = 0
                    for v in bydeg.get(tuple(-x - y for x, y in zip(da, deg[u])), []):
                        av = M.column(v)
                        row = {}
                        for w in au.nonzero_positions():
                            cv = canon(w, v)
                            if cv is not None:
                                row[cv[0]] = row.get(cv[0], 0) + au[w] * cv[1]
                        for w in av.nonzero_positions():
                            cv = canon(u, w)
                            if cv is not None:
                                row[cv[0]] = row.get(cv[0], 0) + s * av[w] * cv[1]
                        row = {k: c for k, c in row.items() if c}
                        if row:
                            rows.append(row)
        nv = len(var)
        M = matrix(R, len(rows), nv, sparse=True)
        for r, row in enumerate(rows):
            for k, c in row.items():
                M[r, k] = c
        K = M.right_kernel_matrix()
        if K.nrows() != 1:
            raise ValueError('the invariant forms of this Lie superalgebra form a '
                             'space of dimension {} (expected 1: is the Cartan '
                             'matrix indecomposable?)'.format(K.nrows()))
        sol = K.row(0)
        G = matrix(R, d, d)
        for (x, y), k in var.items():
            G[x, y] = sol[k]
            G[y, x] = (-1) ** (par[x] * par[y]) * sol[k]
        if G.det() == 0:
            raise ValueError('the invariant form is degenerate')
        return G

    def _root_value(self, beta):
        """
        ``β(h)`` on the basis of the Cartan subalgebra (``β`` in simple-root
        coordinates).

        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g._root_value((1, 0)), g._root_value((0, 1))
            ((2, -1), (-1, 0))
        """
        A = self._A
        n = A.nrows()
        out = []
        for t in self._hbasis:
            k = int(self._keys[t][1:]) - 1
            out.append(sum((beta[l] * A[k, l] for l in range(n)), self._R.zero()))
        return vector(self._R, out)

    def _root_norm(self, beta, G, gamma=None):
        """
        ``(β|γ)`` (default ``γ = β``) for the form with Gram matrix ``G``,
        through the inverse of ``G`` on the Cartan subalgebra.

        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g._root_norm((1, 0), g._form), g._root_norm((0, 1), g._form)
            (2, 0)
            sage: g._root_norm((1, 0), g._form, (0, 1))
            -1
        """
        H = G.matrix_from_rows_and_columns(self._hbasis, self._hbasis)
        t = self._root_value(beta)
        u = t if gamma is None else self._root_value(gamma)
        return t * H.solve_right(u)

    def _resolve_theta(self, theta):
        """
        The root ``θ`` (simple-root coordinates) from its spec: a tuple (an
        even root), a type name of a simple component of the even part
        (``'sl2'``, ``'so7'``, ``'G2'``), or ``None`` (the highest root,
        refused if odd).

        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g._resolve_theta((1, 0))
            (1, 0)
            sage: g._resolve_theta(None)
            Traceback (most recent call last):
            ...
            ValueError: the highest root is odd: give theta (a highest root of a simple component of the even part)
            sage: LieSuperalgebra(QQ, CartanMatrix(['A', 2]))._resolve_theta(None)
            (1, 1)
        """
        if isinstance(theta, tuple):
            if theta not in self._deg or self._par[self._deg.index(theta)]:
                raise ValueError('theta = {} is not an even root'.format(theta))
            return theta
        comps = self._components(self._form0)
        if isinstance(theta, str):
            want = _THETA_TYPES[theta]
            hits = [t for ct, t, _ in comps if (ct.type(), ct.rank()) == want]
            if len(hits) != 1:
                raise ValueError('no unique simple component of type {} in the even '
                                 'part'.format(theta))
            return hits[0]
        top = max(self.positive_roots(), key=lambda b: (sum(b), b))
        if self._par[self._deg.index(top)]:
            raise ValueError('the highest root is odd: give theta (a highest root '
                             'of a simple component of the even part)')
        return top

    def _components(self, G):
        """
        ``[(Cartan type, highest root, positive roots)]`` of the simple
        components of the even part, root norms from the Gram matrix ``G``;
        largest components first.

        TESTS::

            sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
            sage: g = LieSuperalgebra(QQ, 'sl(2|1)')
            sage: g._components(g._form)
            [(['A', 1], (1, 0), [(1, 0)])]
            sage: g = LieSuperalgebra(QQ, 'osp(4|2)')
            sage: [(ct, t) for ct, t, _ in g._components(g._form)]
            [(['A', 1], (0, 0, 1)), (['A', 1], (0, 1, 0)), (['A', 1], (2, 1, 1))]
        """
        from sage.combinat.root_system.cartan_matrix import CartanMatrix
        from sage.combinat.root_system.cartan_type import CartanType
        even = [b for b in self.positive_roots() if not self._par[self._deg.index(b)]]
        # linked by EVEN roots only: [g_0, g_0] lies in g_0, so an odd root
        # β ± γ does not join two simple components of the even part
        roots = set(self.even_roots())
        parent = {b: b for b in even}

        def find(b):
            while parent[b] != b:
                parent[b] = parent[parent[b]]
                b = parent[b]
            return b
        for b in even:
            for c in even:
                if _add(b, c) in roots or _add(b, c, -1) in roots:
                    parent[find(b)] = find(c)
        groups = {}
        for b in even:
            groups.setdefault(find(b), []).append(b)
        out = []
        for grp in groups.values():
            gs = set(grp)
            simple = [b for b in grp
                      if not any(_add(b, c, -1) in gs for c in grp if c != b)]
            simple.sort(key=lambda b: (sum(b), b))
            M = matrix(QQ, [[2 * self._root_norm(b, G, c) / self._root_norm(b, G)
                             for c in simple] for b in simple])
            ct = CartanMatrix(M).cartan_type()
            ct = CartanType([ct.type(), ct.rank()])
            top = max(grp, key=lambda b: (sum(b), b))
            out.append((ct, top, sorted(grp, key=lambda b: (sum(b), b))))
        out.sort(key=lambda x: (-len(x[2]), x[1]))
        return out

