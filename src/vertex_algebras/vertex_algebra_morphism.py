    #  Tensor product domains                                          #
    # -------------------------------------------------------------- #

    def _init_tensor(self, im_gens, check, check_weight):
        r"""
        The factor morphisms, from a list of them or from images of all
        generators.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); T = V.tensor(V)
            sage: phi = End(T).identity(); len(phi._factors)
            2

        The map ``V_Z ⊗ V_Z -> V_{Z^2}`` from two lattice embeddings: the
        Koszul sign of the tensor product matches the cocycle, so all
        products of basis vectors of weight at most `3/2` are respected;
        two copies of one embedding do not commute::

            sage: J = va.Lattice(QQ, matrix([[1]])).gen(0)
            sage: VZ = va.Lattice(QQ, matrix([[1]]), conformal_vector=J.no(J)/2)
            sage: T = VZ.tensor(VZ, conformal_vector='factors')
            sage: L0 = va.Lattice(QQ, matrix.identity(2)); J0, J1 = L0.J(0), L0.J(1)
            sage: L2 = va.Lattice(QQ, matrix.identity(2), conformal_vector=(J0.no(J0) + J1.no(J1))/2)
            sage: f0 = VZ.hom([L2.e((1, 0)), L2.e((-1, 0))], L2)
            sage: f1 = VZ.hom([L2.e((0, 1)), L2.e((0, -1))], L2)
            sage: tp = T.hom([f0, f1], L2); tp.is_conformal()
            True
            sage: keys = [k for w in srange(0, 2, 1/2) for k in T.weight_space(w).basis_keys()]
            sage: all(tp(T.monomial(a).nproduct(T.monomial(b), n))
            ....:     == tp(T.monomial(a)).nproduct(tp(T.monomial(b)), n)
            ....:     for a in keys for b in keys for n in range(-2, 4))
            True
            sage: tp(T.pure_tensor(VZ.e((1,)), VZ.e((-1,))))
            e^(1,-1)
            sage: T.hom([f0, f0], L2)
            Traceback (most recent call last):
            ...
            ValueError: the images of the factors 0 and 1 do not commute: e^(1) and e^(-1)
        """
        T, Y = self.domain(), self.codomain()
        F = T.factors()
        if isinstance(im_gens, (list, tuple)) and len(im_gens) == len(F) and all(isinstance(m, Morphism) for m in im_gens):
            self._factors = [Hom(F[i], Y)(m) if m.parent() is Hom(F[i], Y) else Hom(F[i], Y)(m.im_gens_dict(), check=check, check_weight=check_weight)
                             for i, m in enumerate(im_gens)]
        else:
            names = tuple(T.variable_names())
            if isinstance(im_gens, dict):
                d = dict(im_gens)
            else:
                im_gens = list(im_gens)
                if len(im_gens) != len(names):
                    raise ValueError('expected {} images, got {}'.format(len(names), len(im_gens)))
                d = dict(zip(names, im_gens))
            self._factors = []
            pos = 0
            for Fi in F:
                fnames = Fi.variable_names()
                tnames = names[pos:pos + len(fnames)]
                pos += len(fnames)
                imgs = {fn: d[tn] for fn, tn in zip(fnames, tnames) if tn in d}
                self._factors.append(Hom(Fi, Y)(imgs, check=check, check_weight=check_weight))
        names = tuple(T.variable_names())
        self._im = {}
        pos = 0
        for Fi, m in zip(F, self._factors):
            for fn, g in zip(Fi.variable_names(), Fi.gens()):
                self._im[names[pos]] = m(g)
                pos += 1
            if m._checked is not None:
                self._checked = m._checked if self._checked is None else min(self._checked, m._checked)
        if check:
            self._check_commuting()

    def _check_commuting(self):
        r"""
        The images of different factors super-commute.

        TESTS::

            sage: import vertex_algebras as va
            sage: H = va.FreeBosons(QQ); T = H.tensor(H); J = H.gen(0)
            sage: T.hom([J, J], H)
            Traceback (most recent call last):
            ...
            ValueError: the images of the factors 0 and 1 do not commute: alpha and alpha
        """
        F = self.domain().factors()
        imgs = []
        for Fi, m in zip(F, self._factors):
            gens = dict(zip(Fi.variable_names(), Fi.gens()))
            imgs.append([(n, m(gens[n])) for n in _defining_names(Fi)])
        for i in range(len(F)):
            for j in range(i + 1, len(F)):
                for na, a in imgs[i]:
                    for nb, b in imgs[j]:
                        if any(not p.is_zero() for p in a.ope(b)):
                            raise ValueError('the images of the factors {} and {} do not commute: {} and {}'.format(i, j, na, nb))

    def _tensor_key(self, k):
        r"""
        ``φ(m_1 ⊗ m_2 ⊗ ...) = φ_1(m_1)_(-1) φ(1 ⊗ m_2 ⊗ ...)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.FermionicGhosts(QQ); T = V.tensor(V); phi = End(T).identity()
            sage: x = T.pure_tensor(V.gen(0), V.gen(1))
            sage: phi(x) == x
            True
        """
        F = self.domain().factors()
        out = self.codomain().one()
        for i in reversed(range(len(F))):
            if k[i] == F[i].one().leading_support():
                continue
            out = self._factors[i]._key_image(k[i]).nproduct(out, -1)
        return out

