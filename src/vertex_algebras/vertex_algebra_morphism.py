def _make_morphism(X, Y, images, checked):
    r"""
    Unpickling: the morphism with these images, not checked again.

    TESTS::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2); phi = End(V).identity()
        sage: loads(dumps(phi)) == phi
        True
    """
    phi = Hom(X, Y)(dict(images), check=False)
    phi._checked = checked
    return phi


class VertexAlgebraMorphism(Morphism):
    r"""
    A morphism of vertex algebras, given by the images of generators (see
    the module documentation for what is checked).

    Built by ``V.hom(im_gens, W)`` or ``Hom(V, W)(im_gens)``.

    INPUT:

    - ``parent`` -- a :class:`VertexAlgebraHomset`
    - ``im_gens`` -- the images of the defining generators of the domain
      (the ``e^{±x_i}`` for lattice vertex algebras, else all generators):
      a list in the order of the defining generators or of ``X.gens()``,
      or a dict by generator name (or generator); for tensor products
      also a list of factor morphisms
    - ``check`` -- boolean (default: ``True``); whether to check the
      relations of the domain (``ValueError`` if they fail)
    - ``check_weight`` -- (default: ``None``) a weight; relations known
      only weight by weight (presentations, vertex subalgebras) are
      checked up to this weight

    EXAMPLES:

    The Virasoro algebra in the Heisenberg algebra with a background
    charge::

        sage: import vertex_algebras as va
        sage: a = QQ(3)
        sage: c = 1 - 12*a^2
        sage: Vir = va.Virasoro(QQ, c); H = va.FreeBosons(QQ); J = H.gen(0)
        sage: phi = Vir.hom([J.no(J)/2 + a*J.derivative()], H)
        sage: phi.is_weight_preserving()
        True
        sage: Vir.hom([J.no(J)/2 + 2*a*J.derivative()], H)
        Traceback (most recent call last):
        ...
        ValueError: the images do not satisfy the OPE of L and L: pole 3 is -431/2 instead of -107/2

    TESTS:

    The lattice criterion against brute force.  Of the 16 sign lifts of
    the swap of the basis of ``A_2`` and of the odd ``ZZ^2``, exactly four
    are accepted, and each maps every product of basis vectors of low
    weight to the product of the images::

        sage: import itertools
        sage: def respects_products(phi, X, wmax):
        ....:     keys = [k for w in srange(0, wmax + 1/2, 1/2) for k in X.weight_space(w).basis_keys()]
        ....:     return all(phi(X.monomial(a).nproduct(X.monomial(b), n))
        ....:                == phi(X.monomial(a)).nproduct(phi(X.monomial(b)), n)
        ....:                for a in keys for b in keys for n in range(-2, 4))
        sage: def lattice(B):
        ....:     L0 = va.Lattice(QQ, B); Bi = B.inverse(); r = B.nrows()
        ....:     T = sum(Bi[i, j] * L0.J(i).no(L0.J(j)) for i in range(r) for j in range(r)) / 2
        ....:     return va.Lattice(QQ, B, conformal_vector=T)
        sage: for B in [matrix([[2, -1], [-1, 2]]), matrix([[1, 0], [0, 1]])]:  # long time
        ....:     L = lattice(B); e = L.e; accepted = []
        ....:     for s in itertools.product([1, -1], repeat=4):
        ....:         im = {'e^(1,0)': s[0]*e((0, 1)), 'e^(-1,0)': s[1]*e((0, -1)),
        ....:               'e^(0,1)': s[2]*e((1, 0)), 'e^(0,-1)': s[3]*e((-1, 0))}
        ....:         try:
        ....:             phi = L.hom(im, L)
        ....:         except ValueError:
        ....:             continue
        ....:         accepted.append((s, respects_products(phi, L, 2 if B[0, 0] == 2 else 3/2)))
        ....:     print(accepted)
        [((1, 1, 1, 1), True), ((1, 1, -1, -1), True), ((-1, -1, 1, 1), True), ((-1, -1, -1, -1), True)]
        [((1, 1, 1, 1), True), ((1, 1, -1, -1), True), ((-1, -1, 1, 1), True), ((-1, -1, -1, -1), True)]

    The map ``V_{2Z} -> V_Z``, ``e^{±x} -> e^{±2y}``, respects products and
    sends ``J`` to ``2J``::

        sage: L4, L1 = lattice(matrix([[4]])), lattice(matrix([[1]]))
        sage: phi = L4.hom([L1.e((2,)), L1.e((-2,))], L1)
        sage: respects_products(phi, L4, 4), phi(L4.J(0)) == 2*L1.J(0)  # long time
        (True, True)
    """

    def __init__(self, parent, im_gens, check=True, check_weight=None):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2)
            sage: V.hom([V.gen(0), V.gen(0)], V)
            Traceback (most recent call last):
            ...
            ValueError: expected 1 images, got 2
        """
        Morphism.__init__(self, parent)
        X, Y = parent.domain(), parent.codomain()
        self._kind = _kind(X)
        self._memo = {}
        self._checked = None                 # None = exact, else checked up to this weight
        if self._kind == 'tensor':
            self._init_tensor(im_gens, check, check_weight)
        else:
            self._im = self._normalize(im_gens)
            if self._kind == 'quotient':
                V = X.ambient()
                self._cover = Hom(V, Y)({n: self._im[n] for n in _defining_names(V)}, check=False)
            elif self._kind == 'lattice':
                self._init_lattice()
            if check:
                self._check(check_weight)

    # -------------------------------------------------------------- #
    #  Input                                                           #
    # -------------------------------------------------------------- #

    def _presentation_morphism(self):
        r"""
        For a vertex subalgebra ``S`` as domain: the morphism with the same
        images out of its presentation (built on first use).

        TESTS::

            sage: import vertex_algebras as va
            sage: H = va.FreeBosons(QQ); J = H.gen(0); H = H.with_conformal_vector(J.no(J)/2)
            sage: S = H.subalgebra([H.conformal_vector()], names=['L'])
            sage: f = S.hom([H.conformal_vector()], H, check_weight=4)
            sage: f._presentation_morphism().domain() is S.presentation()
            True

        The Ising model ``<T>`` in the free fermion maps to the quotient of
        the Virasoro algebra by its weight-6 singular vector (checked up to
        weight 8, refused without ``check_weight``); the inclusion agrees
        with ``lift``::

            sage: Maj = va.FreeFermions(QQ); p = Maj.gen(0)
            sage: Maj = Maj.with_conformal_vector(p.derivative().no(p)/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['T'])
            sage: Vir = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: Ising = Vir.quotient([Vir.find_singular(6)[0]])
            sage: f = S.hom([Ising.gen(0)], Ising, check_weight=8); f.checked_up_to_weight()
            8
            sage: f(S.gen(0).no(S.gen(0))) == Ising.gen(0).no(Ising.gen(0))
            True
            sage: S.hom([Ising.gen(0)], Ising)
            Traceback (most recent call last):
            ...
            ValueError: the relations of Presentation of ... are known weight by weight only: give check_weight
            sage: g = S.hom([Maj.conformal_vector()], Maj, check_weight=8)
            sage: all(g(x) == S.lift(x) for x in S.weight_space(6).basis())
            True
        """
        try:
            return self._pres
        except AttributeError:
            P = self.domain().presentation()
            self._pres = Hom(P, self.codomain())(self._im, check=False)
            return self._pres

    def _normalize(self, im_gens):
        r"""
        The images as a dict ``{name: element of the codomain}`` of the
        defining generators (lattice: images of the ``J_i`` given too are
        kept for the check).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); phi = End(V).identity()
            sage: phi._normalize([V.gen(0)])
            {'L': L}
        """
        X, Y = self.domain(), self.codomain()
        names = _defining_names(X)
        allnames = tuple(X.variable_names())
        if isinstance(im_gens, dict):
            d = {}
            for k, v in im_gens.items():
                if not isinstance(k, str):
                    k = allnames[list(X.gens()).index(X(k))]
                d[k] = v
        else:
            im_gens = list(im_gens)
            if len(im_gens) == len(names):
                d = dict(zip(names, im_gens))
            elif len(im_gens) == len(allnames):
                d = dict(zip(allnames, im_gens))
            else:
                raise ValueError('expected {} images, got {}'.format(len(names), len(im_gens)))
        missing = [n for n in names if n not in d]
        if missing:
            raise ValueError('no images of {}'.format(missing))
        unknown = [n for n in d if n not in allnames]
        if unknown:
            raise ValueError('{} are not generators of {}'.format(unknown, X))
        return {n: Y(d[n]) for n in allnames if n in d}

    # -------------------------------------------------------------- #
    #  Evaluation                                                      #
    # -------------------------------------------------------------- #

    def _call_(self, x):
        r"""
        The image of ``x``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.FermionicGhosts(QQ); b, c = V.gens()
            sage: phi = V.hom([c, b], V)
            sage: phi(b.no(c.derivative()))
            -:db c:
        """
        if self._kind == 'subalgebra':
            P = self.domain().presentation()
            return self._presentation_morphism()(P(x))
        if self._kind == 'quotient':
            return self._cover._eval_dict(x.monomial_coefficients())
        return self._eval_dict(x.monomial_coefficients())

    def _eval_dict(self, d):
        r"""
        The image of the element with the coefficients ``d`` (over the
        domain's keys; quotients: the cover's).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); phi = End(V).identity()
            sage: phi._eval_dict({((0, 1), (0, 0)): 2})
            2*:dL L:
        """
        Y = self.codomain()
        out = Y.zero()
        for k, c in d.items():
            out += c * self._key_image(k)
        return out

    def _key_image(self, k):
        r"""
        The image of the basis key ``k`` of the domain (memoised).

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); phi = End(L).identity()
            sage: phi._key_image((((0, 1),), (2,)))
            :dJ0 e^(2):
        """
        try:
            return self._memo[k]
        except KeyError:
            pass
        if self._kind == 'universal':
            img = self._universal_key(k)
        elif self._kind == 'lattice':
            img = self._lattice_key(k)
        elif self._kind == 'tensor':
            img = self._tensor_key(k)
        elif self._kind == 'quotient':
            return self._cover._key_image(k)
        else:
            raise NotImplementedError
        self._memo[k] = img
        return img

    def _letter(self, name, n):
        r"""
        ``∂^n`` of the image of the generator ``name`` (memoised).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); End(V).identity()._letter('L', 2)
            d^2L
        """
        key = ('letter', name, n)
        try:
            return self._memo[key]
        except KeyError:
            pass
        img = self._im[name] if n == 0 else self._letter(name, n - 1).derivative()
        self._memo[key] = img
        return img

    def _universal_key(self, k):
        r"""
        ``φ(:∂^{n_1} g_1 :∂^{n_2} g_2 ...::) = φ(∂^{n_1} g_1)_(-1) φ(rest)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); End(V).identity()._universal_key(((0, 1), (0, 0)))
            :dL L:
        """
        if not k:
            return self.codomain().one()
        names = self.domain().variable_names()
        i, n = k[0]
        a = self._letter(names[i], n)
        return a.nproduct(self._key_image(k[1:]), -1)

    # -------------------------------------------------------------- #
    #  Lattice domains                                                 #
    # -------------------------------------------------------------- #

    def _init_lattice(self):
        r"""
        The images ``a[(i, ±1)]`` of the ``e^{±x_i}`` and ``j[i]`` of the
        ``J_i`` (computed; given images of the ``J_i`` are checked by
        :meth:`_check`).

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); phi = End(L).identity()
            sage: phi._lat_j
            {0: J0}
        """
        L = self.domain()
        es, js = _lattice_generators(L)
        B = L.gram_matrix()
        r = L.rank()
        self._lat_a = {key: self._im[name] for key, name in es.items()}
        self._lat_j = {}
        for i in range(r):
            x = tuple(1 if k == i else 0 for k in range(r))
            mx = tuple(-c for c in x)
            eps = L.cocycle(x, mx)
            self._lat_j[i] = self._lat_a[(i, 1)].nproduct(self._lat_a[(i, -1)], B[i, i] - 2) / eps
        self._lat_jnames = js

    def _lattice_e(self, q):
        r"""
        ``φ(e^q)``: ``e^{s x_i}_(N) e^p = ε(s x_i, p) e^{s x_i + p}`` with ``N =
        -B(s x_i, p) - 1``, ``i`` the first nonzero coordinate of ``q``.

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2, -1], [-1, 2]])); phi = End(L).identity()
            sage: all(phi._lattice_e(q) == L.e(q) for q in [(1, 1), (-2, 1), (0, -3)])
            True
        """
        key = ('e', q)
        try:
            return self._memo[key]
        except KeyError:
            pass
        L = self.domain()
        r = len(q)
        if not any(q):
            img = self.codomain().one()
        else:
            i = next(k for k, c in enumerate(q) if c)
            s = 1 if q[i] > 0 else -1
            a = tuple(s if k == i else 0 for k in range(r))
            p = tuple(q[k] - a[k] for k in range(r))
            N = -L._form(a, p) - 1
            img = self._lat_a[(i, s)].nproduct(self._lattice_e(p), N) / L.cocycle(a, p)
        self._memo[key] = img
        return img

    def _lattice_key(self, k):
        r"""
        ``φ(:∂^{n_1} J_{i_1} ... e^q:)``, right nested.

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); phi = End(L).identity()
            sage: x = L.J(0).no(L.J(0).derivative().no(L.e((1,))))
            sage: phi(x) == x
            True
        """
        letters, q = k
        if not letters:
            return self._lattice_e(tuple(q))
        i, n = letters[0]
        a = self._letter_j(i, n)
        return a.nproduct(self._key_image((letters[1:], q)), -1)

    def _letter_j(self, i, n):
        r"""
        ``∂^n j_i`` (memoised).

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); End(L).identity()._letter_j(0, 1)
            dJ0
        """
        key = ('j', i, n)
        try:
            return self._memo[key]
        except KeyError:
            pass
        img = self._lat_j[i] if n == 0 else self._letter_j(i, n - 1).derivative()
        self._memo[key] = img
        return img

