def _kind(V):
    r"""
    How morphisms out of ``V`` are given and checked.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_morphism import _kind
        sage: V = va.Virasoro(QQ, 1/2)
        sage: _kind(V), _kind(va.Lattice(QQ, matrix([[2]]))), _kind(V.tensor(V))
        ('universal', 'lattice', 'tensor')
    """
    if getattr(V, '_is_quotient_vertex_algebra', False):
        return 'quotient'
    if getattr(V, '_is_lattice_vertex_algebra', False):
        return 'lattice'
    if getattr(V, '_is_tensor_product', False):
        return 'tensor'
    if getattr(V, '_is_commutant', False):
        raise NotImplementedError('morphisms out of commutants (use V.subalgebra(C.strong_generators_up_to(W)))')
    if getattr(V, '_is_vertex_subalgebra', False):
        return 'subalgebra'
    if getattr(V, '_is_universal_vertex_algebra', False):
        return 'universal'
    raise NotImplementedError('morphisms out of {}'.format(V))


def _lattice_generators(L):
    r"""
    The names of the generators of the lattice vertex algebra ``L``:
    ``{(i, s): name}`` for ``e^{s x_i}`` (``s = ±1``) and ``{i: name}`` for
    ``J_i``.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_morphism import _lattice_generators
        sage: _lattice_generators(va.Lattice(QQ, matrix([[2]])))
        ({(0, -1): 'e^(-1)', (0, 1): 'e^(1)'}, {0: 'J0'})
    """
    es, js = {}, {}
    for name, g in zip(L.variable_names(), L.gens()):
        (key, c), = g.monomial_coefficients().items()
        letters, q = key
        if letters:
            js[letters[0][0]] = name
        else:
            i = next(k for k, x in enumerate(q) if x)
            es[(i, q[i])] = name
    return dict(sorted(es.items())), js


def _defining_names(V):
    r"""
    The names of the generators whose images define a morphism out of
    ``V`` (lattice algebras: the ``e^{±x_i}``).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_morphism import _defining_names
        sage: _defining_names(va.Lattice(QQ, matrix([[2]]))), _defining_names(va.N2(QQ, 1))
        (('e^(1)', 'e^(-1)'), ('L', 'J', 'G1', 'G2'))
    """
    try:
        kind = _kind(V)
    except NotImplementedError:
        kind = None
    if kind == 'lattice':
        es, js = _lattice_generators(V)
        return tuple(es[(i, s)] for i in range(V.rank()) for s in (1, -1))
    return tuple(V.variable_names())


def _hom_category(X, Y):
    r"""
    The category of the homset: vertex algebras, or proto vertex algebras
    if one of the two is proto.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_morphism import _hom_category
        sage: V = va.Virasoro(QQ, 1/2); _hom_category(V, V)
        Category of vertex algebras over Rational Field
    """
    from .vertex_algebra_categories import (
        ProtoVertexAlgebras,
        VertexAlgebras,
        _is_proto,
    )
    R = X.base_ring()
    if _is_proto(X) or _is_proto(Y):
        return ProtoVertexAlgebras(R)
    return VertexAlgebras(R)


def _weights(V, upto):
    r"""
    The weights of ``V`` from its lowest weight up to ``upto``, in steps of
    ``1/D`` (``D`` the common denominator of the weights).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_morphism import _weights
        sage: _weights(va.Virasoro(QQ, 1/2, conformal_vector='L'), 3)
        [0, 1, 2, 3]
    """
    data = V._weight_data()
    lb, D = V._weight_bounds(None, data)
    if lb is None:
        raise ValueError('the weight spaces of {} are not certified finite'.format(V))
    D = ZZ(D)
    w = (QQ(lb) * D).floor() / D
    out = []
    while w <= upto:
        out.append(w)
        w += 1 / D
    return out


