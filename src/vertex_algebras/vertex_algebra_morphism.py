    def _check(self, check_weight):
        r"""
        Check that the images define a morphism (see the module
        documentation); raise ``ValueError`` otherwise.

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); J, ep, em = L.gens()
            sage: L.hom([ep, 2*em], L)
            Traceback (most recent call last):
            ...
            ValueError: the images of e^(1) and e^(-1) do not satisfy e^(1)_(1) e^(-1) = 1: got 2
        """
        if self._kind == 'universal':
            self._check_universal()
        elif self._kind == 'quotient':
            self._cover._check(check_weight)
            self._check_ideal(check_weight)
        elif self._kind == 'lattice':
            self._check_lattice()
        elif self._kind == 'subalgebra':
            m = self._presentation_morphism()
            m._check(check_weight)
            self._checked = m._checked

    def _check_parity(self, name, g, img):
        r"""
        ``img`` is zero or homogeneous of the parity of ``g``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.FermionicGhosts(QQ); b, c = V.gens()
            sage: V.hom([b, b.no(c)], V)
            Traceback (most recent call last):
            ...
            ValueError: the image of c is not of the parity 1 of c
        """
        from .vertex_algebra_categories import _parity
        if img.is_zero():
            return
        if _parity(img) != _parity(g):
            raise ValueError('the image of {} is not of the parity {} of {}'.format(name, _parity(g), name))

    def _check_universal(self):
        r"""
        Parities and the declared OPEs of all pairs of generators.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, 'A1', 1); E, H, F = V.gens()
            sage: phi = V.hom([-F, -H, -E], V); phi(E.no(F)) == F.no(E)
            True
        """
        X = self.domain()
        names = X.variable_names()
        gens = X.gens()
        for name, g in zip(names, gens):
            self._check_parity(name, g, self._im[name])
        for i in range(len(gens)):
            for j in range(i, len(gens)):
                self._compare_ope(names[i], gens[i], names[j], gens[j])

    def _compare_ope(self, na, a, nb, b):
        r"""
        ``φ(a)_(n) φ(b) = φ(a_(n) b)`` for all ``n >= 0``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen(0)
            sage: End(V).identity()._compare_ope('L', L, 'L', L)
        """
        X = a.ope(b)
        Yp = self(a).ope(self(b))
        for n in range(max(len(X), len(Yp))):
            lhs = Yp[n] if n < len(Yp) else self.codomain().zero()
            rhs = self(X[n]) if n < len(X) else self.codomain().zero()
            if lhs != rhs:
                raise ValueError('the images do not satisfy the OPE of {} and {}: pole {} is {} instead of {}'.format(na, nb, n, lhs, rhs))

    def _check_ideal(self, check_weight):
        r"""
        The cover morphism kills the ideal: its given generators (exact),
        or its weight spaces up to ``check_weight`` (kernels of
        realizations, e.g. presentations).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, 'A1', 1); E, H, F = V.gens()
            sage: Q = V.quotient([E.no(E)]); L = va.Lattice(QQ, matrix([[2]]))
            sage: J, ep, em = L.gens()
            sage: Q.hom([ep, J, em], L)(Q(E.no(F)))
            1/2*:J0 J0: + 1/2*dJ0
        """
        X = self.domain()
        I = X._I
        if hasattr(I, '_given'):
            for s in I._given:
                if not self._cover(s).is_zero():
                    raise ValueError('the images do not kill the generator {} of the ideal'.format(s))
            return
        if check_weight is None:
            raise ValueError('the relations of {} are known weight by weight only: give check_weight'.format(X))
        V = X.ambient()
        for w in _weights(V, check_weight):
            for r in self._ideal_basis(I, w):
                if not self._cover(r).is_zero():
                    raise ValueError('the images do not kill the relation {} of weight {}'.format(r, w))
        self._checked = QQ(check_weight) if self._checked is None else min(self._checked, QQ(check_weight))

    @staticmethod
    def _ideal_basis(I, w):
        r"""
        A basis of the weight-``w`` space of the ideal ``I`` (all grades),
        as elements of its ambient.

        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra_morphism import VertexAlgebraMorphism
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen(0)
            sage: I = V.ideal([V.find_singular(4)[0]])
            sage: len(VertexAlgebraMorphism._ideal_basis(I, 4))
            1
        """
        V = I.ambient()
        try:
            return list(I.weight_space(w).basis())
        except (ValueError, TypeError):
            pass
        grades = {V._grade_key(k) for k in V.weight_space(w).basis_keys()}
        out = []
        for G in grades:
            out.extend(I.weight_space(w, V.horizontal_grading_group()(G)).basis())
        return out

    def _check_lattice(self):
        r"""
        The checks of the lattice criterion (module documentation).

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); J, ep, em = L.gens()
            sage: L.hom([em, ep], L)(J) == -J
            True
            sage: L.hom({'e^(1)': ep, 'e^(-1)': em, 'J0': 2*J}, L)
            Traceback (most recent call last):
            ...
            ValueError: the given image of J0 is not the image 2*J0 of e^(1)_(0) e^(-1) ... got J0

        Wrong charges, inhomogeneous images and missing images are refused;
        scaling ``e^{±x}`` by ``3^{±1}`` scales ``e^{2x}`` by 9::

            sage: L.hom([ep, ep], L)
            Traceback (most recent call last):
            ...
            ValueError: the images of e^(1) and e^(-1) do not satisfy e^(1)_(1) e^(-1) = 1: got 0
            sage: L.hom([ep + em, em], L)
            Traceback (most recent call last):
            ...
            ValueError: the image of J0 does not act on the image of e^(1) by the charge 2
            sage: L.hom([ep], L)
            Traceback (most recent call last):
            ...
            ValueError: expected 2 images, got 1
            sage: L.hom([3*ep, em/3], L)(L.e((2,))) == 9*L.e((2,))
            True
        """
        L, Y = self.domain(), self.codomain()
        B = L.gram_matrix()
        r = L.rank()
        es, js = _lattice_generators(L)
        a, j = self._lat_a, self._lat_j
        for (i, s), name in es.items():
            if a[(i, s)].is_zero() or {self._parity_or_none(a[(i, s)])} != {B[i, i] % 2}:
                raise ValueError('the image of {} is not homogeneous of parity {}'.format(name, B[i, i] % 2))
        for i, name in js.items():
            if name in self._im and self._im[name] != j[i]:
                raise ValueError('the given image of {} is not the image {} of {}_({}) {} (divided by the cocycle): got {}'.format(
                    name, self._im[name], es[(i, 1)], B[i, i] - 2, es[(i, -1)], j[i]))
        unit = lambda i, s: tuple(s if k == i else 0 for k in range(r))
        one = Y.one()
        for i in range(r):
            x, mx = unit(i, 1), unit(i, -1)
            p, m = a[(i, 1)], a[(i, -1)]
            eps = L.cocycle(x, mx)
            got = p.nproduct(m, B[i, i] - 1)
            if got != eps * one:
                raise ValueError('the images of {} and {} do not satisfy {}_({}) {} = {}: got {}'.format(
                    es[(i, 1)], es[(i, -1)], es[(i, 1)], B[i, i] - 1, es[(i, -1)], eps, got))
            self._vanish(p, m, B[i, i], es[(i, 1)], es[(i, -1)])
        for i in range(r):
            for k in range(r):
                poles = j[i].ope(j[k])
                want = [Y.zero(), B[i, k] * one]
                poles = poles + [Y.zero()] * (2 - len(poles))
                if poles[:2] != want or any(not x.is_zero() for x in poles[2:]):
                    raise ValueError('the images J{} and J{} do not satisfy the Heisenberg OPE'.format(i, k))
                for s in (1, -1):
                    poles = j[i].ope(a[(k, s)])
                    want = s * B[i, k] * a[(k, s)]
                    if (poles[0] if poles else Y.zero()) != want or any(not x.is_zero() for x in poles[1:]):
                        raise ValueError('the image of J{} does not act on the image of {} by the charge {}'.format(i, es[(k, s)], s * B[i, k]))
        for (k, s), name in es.items():
            if a[(k, s)].derivative() != s * j[k].nproduct(a[(k, s)], -1):
                raise ValueError('the image of {} does not satisfy the translation identity of e^q'.format(name))
        for (i, s), na in es.items():
            for (k, t), nb in es.items():
                if (i, s) < (k, t) and not (i == k and s == -t):
                    self._vanish(a[(i, s)], a[(k, t)], -s * t * B[i, k], na, nb)

    @staticmethod
    def _parity_or_none(x):
        r"""
        The parity of ``x``, ``None`` if inhomogeneous.

        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra_morphism import VertexAlgebraMorphism
            sage: VertexAlgebraMorphism._parity_or_none(va.FreeFermions(QQ).gen(0))
            1
        """
        from .vertex_algebra_categories import _parity
        return _parity(x)

    @staticmethod
    def _vanish(x, y, bound, nx, ny):
        r"""
        ``x_(n) y = 0`` for all ``n >= bound``.

        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra_morphism import VertexAlgebraMorphism
            sage: L = va.Lattice(QQ, matrix([[2]])); J, ep, em = L.gens()
            sage: VertexAlgebraMorphism._vanish(ep, em, 1, 'a', 'b')
            Traceback (most recent call last):
            ...
            ValueError: a_(1) b is not zero
        """
        for n in range(bound, 0):
            if not x.nproduct(y, n).is_zero():
                raise ValueError('{}_({}) {} is not zero'.format(nx, n, ny))
        poles = x.ope(y)
        for n in range(max(bound, 0), len(poles)):
            if not poles[n].is_zero():
                raise ValueError('{}_({}) {} is not zero'.format(nx, n, ny))

