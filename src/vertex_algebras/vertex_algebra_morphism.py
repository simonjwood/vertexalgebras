r"""
Morphisms of vertex algebras.

A morphism ``φ: V -> W`` is determined by the images of generators of
``V``; it exists iff these images satisfy the relations of ``V``.  Which
relations, and whether they can be checked exactly, depends on how ``V``
is given:

- **universal** (also proto) ``V``: the images of the strong generators
  must have their parities and satisfy the declared OPEs, ``φ(a)_(n) φ(b) =
  φ(a_(n) b)`` for all pairs of generators and ``n >= 0`` (the universal
  algebra is presented by its generator OPEs: rewriting a product into
  normally ordered monomials uses only these OPEs and the Borcherds
  identities, which hold in ``W``).  Exact.
- **quotient** ``V / I``: a morphism from ``V`` killing the given generators
  of ``I`` (the kernel of a morphism is an ideal).  Exact.  A presentation
  (the kernel of a realization, known weight by weight) is checked up to a
  weight ``check_weight``.
- **lattice** ``V_L``: weakly generated by the ``e^{±x_i}`` (``x_i`` the
  basis of ``L``); only their images ``a_i^±`` are needed.  With ``j_i =
  ε(x_i, -x_i)^{-1} (a_i^+)_(B_ii - 2) a_i^-`` (the image of ``J_i``) the
  checks are: parities ``B_ii mod 2``; ``(a_i^+)_(n) a_i^- = 0`` for ``n >=
  B_ii`` and ``(a_i^+)_(B_ii - 1) a_i^- = ε(x_i, -x_i)``; the Heisenberg OPEs
  of the ``j_i``; ``(j_i)_(0) a_k^± = ±B_ik a_k^±`` and ``(j_i)_(n) a_k^± =
  0`` for ``n >= 1``; ``∂ a_k^± = ±(j_k)_(-1) a_k^±``; ``(a_i^s)_(n) a_k^t =
  0`` for ``n >= -st B_ik``.  Then ``φ(e^q)`` is the ordered product of the
  generator images (with the cocycle), and the conditions make it a
  homomorphism ([LL2004]_ §6.5; H. Li, arXiv:2008.05982, Prop. 4.3).
- **tensor product**: morphisms of the factors whose images super-commute
  (all ``n >= 0`` products of images of generators of different factors
  vanish); ``φ(a ⊗ b) = φ_1(a)_(-1) φ_2(b)``.
- **vertex subalgebra**: through its presentation (checked up to a weight).

Morphisms are Sage morphisms: ``V.hom(images, W)``, ``Hom(V, W)``,
composition ``ψ * φ``, ``φ(x)``.

EXAMPLES:

The Frenkel–Kac map from the universal affine ``sl_2`` at level 1 to the
lattice vertex algebra of the root lattice::

    sage: import vertex_algebras as va
    sage: V = va.Affine(QQ, 'A1', 1); V.variable_names()
    ('alpha[1]', 'alphacheck[1]', '-alpha[1]')
    sage: L = va.Lattice(QQ, matrix([[2]]))
    sage: J, ep, em = L.gens()
    sage: phi = V.hom([ep, J, em], L); phi
    Vertex algebra morphism:
      From: Universal affine vertex algebra of type ['A', 1] at level 1 over Rational Field
      To:   Lattice vertex algebra of rank 1 with Gram matrix [2] over Rational Field
      Defn: alpha[1] |--> e^(1)
            alphacheck[1] |--> J0
            -alpha[1] |--> e^(-1)
    sage: E = V.gen(0); phi(E.no(E))
    0

A wrong sign is refused::

    sage: V.hom([ep, J, -em], L)
    Traceback (most recent call last):
    ...
    ValueError: the images do not satisfy the OPE of alpha[1] and -alpha[1]: pole 0 is -J0 instead of J0

The boson-fermion correspondence: the lattice vertex algebra of ``ZZ`` is
the ``bc`` system, both ways, and the maps are conformal::

    sage: bc = va.FermionicGhosts(QQ, conformal_vector='symmetric'); b, c = bc.gens()
    sage: J = va.Lattice(QQ, matrix([[1]])).gen(0)
    sage: VZ = va.Lattice(QQ, matrix([[1]]), conformal_vector=J.no(J)/2); J, ep, em = VZ.gens()
    sage: to_bc = VZ.hom([c, b], bc); to_VZ = bc.hom([em, ep], VZ)
    sage: to_bc(J), to_bc(VZ.e((2,))), to_VZ(c.no(b))
    (-:b c:, :dc c:, J0)
    sage: to_bc.inverse(to_VZ) is to_VZ, to_bc * to_VZ == End(bc).identity()
    (True, True)
    sage: to_bc.is_conformal(), to_VZ.is_conformal()
    (True, True)

AUTHORS:

- Christopher Raymond, Simon Wood (2026): initial version
"""

