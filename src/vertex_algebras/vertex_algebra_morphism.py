    def _repr_defn(self):
        r"""
        The images of the defining generators (and how far the
        morphism property was checked, if not exactly).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); print(End(V).identity()._repr_defn())
            L |--> L
        """
        lines = ['{} |--> {}'.format(n, x) for n, x in self.im_gens_dict().items()]
        if self._checked is not None:
            lines.append('(checked up to weight {})'.format(self._checked))
        return '\n'.join(lines)

    def im_gens_dict(self):
        r"""
        The images of the generators, a dict by name.

        OUTPUT:

        A dictionary ``{name: image}`` over the defining generators (all
        generators for tensor products).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.FermionicGhosts(QQ); b, c = V.gens()
            sage: V.hom([c, b], V).im_gens_dict()
            {'b': c, 'c': b}
        """
        X = self.domain()
        names = _defining_names(X) if self._kind != 'tensor' else tuple(X.variable_names())
        return {n: self._im[n] for n in names}

    def im_gens(self):
        r"""
        The images of the defining generators, a tuple (lattice algebras:
        of the ``e^{±x_i}``).

        OUTPUT:

        A tuple of elements of the codomain.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); End(L).identity().im_gens()
            (e^(1), e^(-1))
        """
        return tuple(self.im_gens_dict().values())

    def checked_up_to_weight(self):
        r"""
        ``None`` if the morphism property is certified exactly, else the
        weight up to which the relations were checked.

        OUTPUT:

        ``None`` or a weight.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); End(V).identity().checked_up_to_weight() is None
            True
        """
        return self._checked

    def _richcmp_(self, other, op):
        r"""
        Morphisms are equal iff their images are.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.FermionicGhosts(QQ); b, c = V.gens()
            sage: phi = V.hom([c, b], V); phi * phi == End(V).identity(), phi == End(V).identity()
            (True, False)
        """
        a, b = self.im_gens(), other.im_gens()
        if a == b:
            return rich_to_bool(op, 0)
        if op in (op_EQ, op_NE):
            return op == op_NE
        return NotImplemented

