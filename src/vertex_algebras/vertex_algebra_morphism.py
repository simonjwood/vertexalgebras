class VertexAlgebraHomset(Homset):
    r"""
    The set of morphisms of vertex algebras ``X -> Y``.

    Built by ``Hom(X, Y)`` (one homset per codomain, cached on ``X``).

    INPUT:

    - ``X`` -- a vertex algebra, the domain
    - ``Y`` -- a vertex algebra, the codomain
    - ``category`` -- (default: ``None``) a category; ``None`` gives the
      vertex algebras over the base ring of ``X``, or the proto vertex
      algebras if ``X`` or ``Y`` is proto

    EXAMPLES::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2); H = Hom(V, V); H
        Set of Morphisms from Universal vertex algebra on generators ['L'] over Rational Field to Universal vertex algebra on generators ['L'] over Rational Field in Category of vertex algebras over Rational Field
        sage: H.identity()(V.gen(0).no(V.gen(0)))
        :L L:
        sage: End(V) is H
        True
    """

    def __init__(self, X, Y, category=None):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); H = Hom(V, V)
            sage: H.domain() is V and H.codomain() is V
            True
        """
        if category is None:
            category = _hom_category(X, Y)
        Homset.__init__(self, X, Y, category=category, base=X.base_ring(), check=False)

    def __call__(self, x, check=True, check_weight=None):
        r"""
        The morphism with the images ``x`` (a list in the order of
        ``_defining_names(X)`` or of ``X.gens()``, or a dict by generator
        name; tensor products also take a list of factor morphisms).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L')
            sage: Hom(V, V)({'L': L})(L.no(L))
            :L L:
        """
        if isinstance(x, VertexAlgebraMorphism) and x.parent() is self:
            return x
        return self.element_class(self, x, check=check, check_weight=check_weight)

    def identity(self):
        r"""
        The identity morphism (``X`` and ``Y`` must be the same).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); i = End(L).identity()
            sage: i(L.e((2,))) == L.e((2,))
            True
        """
        X = self.domain()
        if X is not self.codomain():
            raise TypeError('identity morphism only for End(X)')
        names = _defining_names(X)
        gens = dict(zip(X.variable_names(), X.gens()))
        return self.element_class(self, {n: gens[n] for n in names}, check=False)

    def _an_element_(self):
        r"""
        The identity of ``End(X)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); End(V).an_element() == End(V).identity()
            True
        """
        return self.identity()


