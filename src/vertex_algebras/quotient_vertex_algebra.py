    def _install_conformal_vector(self, T):
        r"""
        The Virasoro vector ``T`` of ``self`` (construction data, see
        ``conformal_vector`` of the constructor): ``'ambient'`` takes the
        image of that of the ambient algebra; otherwise ``T`` (canonical
        data of an element) is any element whose OPE is Virasoro and which
        induces the conformal weights of the ambient algebra: on the image
        ``g`` of every strong generator of the ambient algebra, of weight
        ``h``, ``T_(0) g = ∂g`` and ``T_(1) g - h g`` has weight ``h`` and
        is nilpotent under ``T_(1) - h`` (Jordan blocks give a
        :class:`LogarithmicWarning`).

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<L> = NormallyOrderedExpressions(QQ)
            sage: Vir = UniversalVertexAlgebra(QQ, X, {('L', 'L'): [L.derivative(), 2*L, 0, -11/5]},
            ....:                              degrees={'L': 2})
            sage: L = Vir.gen('L')
            sage: Q = Vir.quotient([L.no(L) - 3/10 * L.derivative(2)])
            sage: Q.with_conformal_vector('ambient')
            Traceback (most recent call last):
            ...
            ValueError: the ambient algebra has no Virasoro vector
            sage: Q.with_conformal_vector(Q.gen('L')).central_charge()
            -22/5
            sage: Q.with_conformal_vector(2 * Q.gen('L'))
            Traceback (most recent call last):
            ...
            ValueError: T is not a Virasoro field: ...
        """
        V = self._ambient
        c = None
        check = True
        if not isinstance(T, str):
            T = self._el_from_dict(dict(T))
        else:
            T0 = V.conformal_vector()
            if T0 is None:
                raise ValueError('the ambient algebra has no Virasoro vector')
            T = self(T0)
            if T.is_zero():
                raise ValueError('the Virasoro vector {} of the ambient '
                                 'algebra lies in the ideal'.format(T0))
            c = V.central_charge()
            check = False
        xs = V._strong_generators_for_ideals()
        labels = V.variable_names()
        if len(labels) != len(xs):
            labels = [repr(x) for x in xs]
        gens = []
        for label, x in zip(labels, xs):
            y = self(x)
            if not y.is_zero():
                gens.append((label, y, V.degree(x)))
        self._set_virasoro_inherited(T, check, c, gens)

    def _weight_space_enumeration(self, W, G, data):
        """
        The keys of weight ``W`` (grade coordinates ``G``) of ``self``: the
        ambient's (a finite enumeration is required) filtered by
        :meth:`_is_standard`.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: list(Q._weight_space_enumeration(4, None, Q._weight_data()).factory())
            [((0, 2),)]
        """
        from .weight_spaces import _KeyEnumeration
        V = self._ambient
        w = self._I._wdata
        if w is not None and data is not w and data != w:
            raise ValueError('the weight data differ from the conformal '
                             'weights of {}'.format(self))
        base = V._weight_space_enumeration(W, G, data)
        if not base.finite:
            if G is None:
                raise ValueError(
                    'the weight space of weight {} of the ambient algebra is '
                    'infinite dimensional; that of the quotient may be '
                    'finite: give a grade'.format(W))
            raise NotImplementedError(
                'the weight space of weight {} and grade {} of the ambient '
                'algebra has no finiteness certificate; the dimension of that '
                'of the quotient is not decided'.format(W, G))
        std = self._is_standard
        return _KeyEnumeration(True, factory=lambda: (
            k for k in base.factory() if std(k)))

    def _weight_bounds(self, G, data):
        """
        The ambient's weight bounds, refused when those have no finiteness certificate.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: Q._weight_bounds(None, Q._weight_data())
            (0, 1)
        """
        lb, D = self._ambient._weight_bounds(G, data)
        if lb is None:
            raise NotImplementedError(
                'the weight spaces of grade {} of the ambient algebra have no '
                'finiteness certificate; those of the quotient are not '
                'decided'.format(G))
        return lb, D

    @_gc_paused
    def weight_space(self, weight, horizontal_grade=None):
        r"""
        The weight space of ``self`` of conformal weight ``weight`` (and,
        for a graded quotient, of the given grade).  If the weight spaces
        of the ambient algebra are spanned by basis monomials, a
        :class:`weight_spaces.WeightSpace` whose basis keys are the
        standard monomials (those that are not leading monomials of the
        ideal); for a quotient of a vertex subalgebra, a
        :class:`weight_spaces.SubspaceWeightSpace` whose basis consists of
        images of normally ordered monomials of its strong generators
        (``basis_words()``).

        INPUT:

        - ``weight`` -- a conformal weight

        - ``horizontal_grade`` -- (default: ``None``) a grade (graded
          quotients)

        OUTPUT:

        A :class:`weight_spaces.WeightSpace` or a
        :class:`weight_spaces.SubspaceWeightSpace` (see above).

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<L> = NormallyOrderedExpressions(QQ)
            sage: Vir = UniversalVertexAlgebra(QQ, X, {('L', 'L'): [L.derivative(), 2*L, 0, -11/5]},
            ....:                              degrees={'L': 2})
            sage: L = Vir.gen('L')
            sage: Q = Vir.quotient([L.no(L) - 3/10 * L.derivative(2)])
            sage: B = Q.weight_space(8); B
            Weight space of conformal weight 8 of Quotient of ... (dimension 3)
            sage: B.basis()
            [:d^2L d^2L:, :d^3L dL:, d^6L]
            sage: Vir.weight_space(8).dimension()
            7

        TESTS:

        Ctrl-C in the middle of the spaces (simulated: an elimination
        raising ``KeyboardInterrupt``) leaves nothing half-built::

            sage: from vertex_algebras._keyed_spans import KeyedSpan
            sage: def interrupted(f, k, cls=KeyedSpan, name='insert_many'):
            ....:     # f() with cls.name raising KeyboardInterrupt at its k-th call
            ....:     orig, calls = getattr(cls, name), [0]
            ....:     def patched(*args, **kwds):
            ....:         calls[0] += 1
            ....:         if calls[0] == k:
            ....:             raise KeyboardInterrupt
            ....:         return orig(*args, **kwds)
            ....:     setattr(cls, name, patched)
            ....:     try:
            ....:         f()
            ....:         return False
            ....:     except KeyboardInterrupt:
            ....:         return True
            ....:     finally:
            ....:         setattr(cls, name, orig)
            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: def lee_yang(n):
            ....:     # a fresh copy (algebras are unique by their data): other names
            ....:     V = UniversalVertexAlgebra(QQ, [n], {(n, n): [{((n, 1),): 1}, {((n, 0),): 2}, 0, -11/5]},
            ....:                                degrees={n: 2})
            ....:     T = V.gen(0)
            ....:     return V.ideal([T.no(T) - 3/10*T.derivative(2)])
            sage: I = lee_yang('T')
            sage: Q = I.ambient().quotient(I)
            sage: ref = [Q.weight_space(w).dimension() for w in range(17)]; ref
            [1, 0, 1, 1, 1, 1, 2, 2, 3, 3, 4, 4, 6, 6, 8, 9, 11]
            sage: for k in (1, 5, 20):
            ....:     I = lee_yang('T%s' % k)
            ....:     Q = I.ambient().quotient(I)
            ....:     assert interrupted(lambda: [Q.weight_space(w).dimension() for w in range(17)], k)
            ....:     assert [Q.weight_space(w).dimension() for w in range(17)] == ref
        """
        if self._key_weight_spaces:
            from .vertex_algebra_categories import ProtoVertexAlgebras
            return ProtoVertexAlgebras.Graded.ParentMethods.weight_space(
                self, weight, horizontal_grade)
        from .weight_spaces import SubspaceWeightSpace, _to_rational
        self._weight_data()
        W = _to_rational(weight)
        G = None
        if horizontal_grade is not None:
            G = self._require_grading()['group'].coords(horizontal_grade)
            horizontal_grade = self._grade_out(G)
        key = (W, G)
        sp = self._subspaces.get(key)
        if sp is None:
            B = self._ambient.weight_space(W, horizontal_grade)
            words = B.basis_words()
            nfs = [self._nf(dict(x._monomial_coefficients))
                   for x in B.basis()]
            ech = KeyedSpan(self.base_ring(), key_order=self._key_order)
            flags = ech.insert_many(nfs, labels=words)
            sp = (ech, {w: d for w, d, ok in zip(words, nfs, flags) if ok})
            self._subspaces[key] = sp
        ech, elts = sp
        return SubspaceWeightSpace(
            self, self, W, horizontal_grade, ech, self._to_dict,
            element=lambda w: self._el_from_dict(elts[w]))
