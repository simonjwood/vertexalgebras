    def zhu_algebra_up_to(self, max_weight, twist=None, degree_bound=None, algorithm=None,
                          level=0):
        r"""
        Zhu's algebra of the universal vertex algebra ``V`` under this
        quotient modulo the images of the weight spaces ``I_w``, ``w <=
        max_weight``, of the ideal: an algebra mapping onto the Zhu algebra of
        ``self``, equal to it for ``max_weight`` large enough (which this cannot
        detect); see :mod:`zhu_algebra`.

        INPUT:

        - ``max_weight`` -- the largest weight of the ideal's weight spaces
          whose images are imposed

        - ``twist`` -- (default: ``None``) ``'H'`` (or ``'ramond'``): the same
          for the H-twisted Zhu algebras

        - ``degree_bound`` -- (default: ``None``) the degree bound of the
          Letterplace Gröbner basis (default: twice the top relation degree;
          ``'letterplace'`` only)

        - ``algorithm`` -- (default: ``None``) ``'plural'`` (two-sided
          Gröbner bases of Singular Plural in the PBW algebra) or
          ``'letterplace'`` (Gröbner bases in the free algebra); ``None``:
          ``'letterplace'`` iff the universal vertex algebra is proto

        - ``level`` -- (default: ``0``) ``n >= 1``: the level ``n`` Zhu
          algebra of [DLM1998]_ up to the weight, a
          :class:`higher_zhu_algebra.HigherZhuAlgebraQuotient`
          (``degree_bound``: the filtration of the words computed with)

        OUTPUT:

        A quotient of a Zhu algebra: a
        :class:`zhu_algebra.ZhuAlgebraQuotient` (Plural), a
        ``ZhuAlgebraFreeQuotient`` (Letterplace), or a
        :class:`higher_zhu_algebra.HigherZhuAlgebraQuotient` for
        ``level >= 1``.

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: E.<L> = NormallyOrderedExpressions(QQ)
            sage: V = UniversalVertexAlgebra(QQ, E, {('L', 'L'): [L.derivative(), 2*L, 0, -11/5]},
            ....:                            degrees={'L': 2})
            sage: L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: [Q.zhu_algebra_up_to(W).dimension() for W in (3, 4, 6)]
            [+Infinity, 2, 2]
            sage: Q.zhu_algebra_up_to(4, algorithm='letterplace').dimension()
            2
            sage: Q.zhu_algebra_up_to(6, level=1).dimension()
            3
        """
        from .zhu_algebra import _zhu_algebra_up_to
        return _zhu_algebra_up_to(self, max_weight, twist, degree_bound, algorithm, level)

    def simple_modules_up_to(self, max_weight, max_depth, degree_bound=None):
        r"""
        The simple positive energy modules whose tops are the simple modules
        of the Zhu algebra computed with the relations of weight ``<=
        max_weight``, computed to ``max_depth``; see
        :func:`~vertex_algebras.vertex_algebra_module_ext.simple_modules_up_to`.

        INPUT:

        - ``max_weight`` -- a rational number; the relations of ``self`` of
          weight ``<= max_weight`` are used

        - ``max_depth`` -- a rational number; each module is computed in the
          degrees ``<= max_depth``

        - ``degree_bound`` -- (default: ``None``) the degree bound of the
          Zhu algebra (``None``: raised until its dimension is determined)

        OUTPUT:

        A list of simple quotients of induced modules up to a depth, sorted
        by lowest weight.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: [S._weight_base() for S in Q.simple_modules_up_to(6, 2)]
            [-1/5, 0]
        """
        from .vertex_algebra_module_ext import simple_modules_up_to
        return simple_modules_up_to(self, max_weight, max_depth, degree_bound)

    def induced_module_up_to(self, U, max_weight, max_depth, commutators=True, implementation=None):
        r"""
        The universal module ``\bar M(U)`` of [DLM1998]_ with top level ``U``
        (a finite-dimensional module over a Zhu algebra of ``self``, e.g.
        from :meth:`zhu_algebra_up_to`), computed in the depths ``<= max_depth``
        from the relations of weight ``<= max_weight``: the module induced over
        the universal vertex algebra under ``self``, modulo what these
        relations generate.  It maps onto ``\bar M(U)`` in these depths and
        equals it once stable in ``max_weight`` and ``max_depth`` (not detected); a
        :class:`quotient_induced_module.InducedModuleUpTo`, see
        :mod:`quotient_induced_module`.

        INPUT:

        - ``U`` -- a finite-dimensional module over a Zhu algebra of ``self``

        - ``max_weight`` -- the relations of weight ``<= max_weight`` are used

        - ``max_depth`` -- the module is computed in the depths
          ``<= max_depth``

        - ``commutators`` -- (default: ``True``) also impose the commutator
          formula of the generators (needed when the universal vertex
          algebra does not satisfy the Jacobi identity, e.g. for
          presentations)

        - ``implementation`` -- (default: ``None``) ``None`` (the C++ engine
          of induced modules when available), ``'engine'`` or ``'python'``
          (see :class:`vertex_algebra_module.InducedModule`)

        OUTPUT: a :class:`quotient_induced_module.InducedModuleUpTo`

        EXAMPLES:

        The Lee--Yang model: the module induced from the top ``h = -1/5`` is
        ``L(-22/5, -1/5)``, with the second Rogers--Ramanujan character::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: E.<L> = NormallyOrderedExpressions(QQ)
            sage: V = UniversalVertexAlgebra(QQ, E, {('L', 'L'): [L.derivative(), 2*L, 0, -11/5]},
            ....:                            conformal_vector=L)
            sage: L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: U = Q.zhu_algebra_up_to(4).module({'L': -1/5})
            sage: M = Q.induced_module_up_to(U, 4, 9)
            sage: [M.weight_space(-1/5 + d).dimension() for d in range(10)]
            [1, 1, 1, 1, 2, 2, 3, 3, 4, 5]
        """
        from .quotient_induced_module import InducedModuleUpTo
        return InducedModuleUpTo(self, U, max_weight, max_depth, commutators, implementation)

