    _is_quotient_vertex_algebra = True      # duck typing (doctests)

    @staticmethod
    def __classcall_private__(cls, ambient, ideal, horizontal_grading=None, names=None,
                              conformal_vector=None):
        """
        Normalise the arguments to the unique-representation key ``(ambient,
        spec, horizontal_grading, T)``: ``spec`` is ``('generators', gens,
        grading option, names)`` (zero generators dropped; also for a given
        finitely generated ideal) or ``('ideal', I)``; a given ideal object reaches
        ``__init__`` through ``_PENDING_IDEALS`` (its weight spaces are reused); an
        element ``T`` is canonicalised by its normal form in the quotient without
        ``T``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: from vertex_algebras.quotient_vertex_algebra import QuotientVertexAlgebra
            sage: QuotientVertexAlgebra(V, [L.no(L) - 3/10*L.derivative(2)]) is Q
            True
            sage: QuotientVertexAlgebra(V, Q.defining_ideal()) is Q
            True
            sage: QuotientVertexAlgebra(V, Q.defining_ideal(), names=['a'])
            Traceback (most recent call last):
            ...
            ValueError: names are an option for the generators of an ideal, not for an ideal
            sage: QuotientVertexAlgebra(V, 3)
            Traceback (most recent call last):
            ...
            TypeError: 3 is neither an ideal nor a list of generators
        """
        if not isinstance(ambient, VertexAlgebra):
            raise TypeError('{!r} is not a vertex algebra'.format(ambient))
        V = ambient
        given = None
        if _is_ideal(ideal):
            if ideal.ambient() is not V:
                raise ValueError('{} is not an ideal of {}'.format(ideal, V))
            if names is not None:
                raise ValueError('names are an option for the generators of '
                                 'an ideal, not for an ideal')
            if horizontal_grading not in (None, 'ambient'):
                raise ValueError("grading must be None or 'ambient'")
            if horizontal_grading is None and ideal._grading is not None:
                horizontal_grading = 'ambient'     # graded by the ideal's grading
            given = ideal
            if hasattr(ideal, '_given'):    # finitely generated: by its data
                spec = ('generators', tuple(ideal._given),
                        None if ideal._grading is None else 'ambient',
                        tuple(ideal._given_names))
            else:
                spec = ('ideal', ideal)
        else:
            if isinstance(ideal, VertexAlgebraElement):
                ideal = [ideal]
            if not isinstance(ideal, (list, tuple)):
                raise TypeError('{!r} is neither an ideal nor a list of '
                                'generators'.format(ideal))
            if horizontal_grading not in (None, 'ambient'):
                raise ValueError("grading must be None or 'ambient'")
            gens = [V(x) for x in ideal]
            if names is None:
                names = ['s{}'.format(k) for k in range(len(gens))]
            else:
                names = [str(t) for t in names]
                if len(names) != len(gens):
                    raise ValueError('{} names for {} generators'.format(
                        len(names), len(gens)))
            keep = [(x, t) for x, t in zip(gens, names) if not x.is_zero()]
            spec = ('generators', tuple(x for x, _ in keep), horizontal_grading,
                    tuple(t for _, t in keep))
        T = conformal_vector
        if T is not None and not isinstance(T, (str, tuple)):
            # its normal form in the quotient without T
            Q0 = cls(V, given if given is not None else ideal,
                     horizontal_grading if given is not None else spec[2],
                     None if given is not None else names)
            T = _canonical_element(Q0, T)
        T = _canonical_element(V, T, ('ambient',))
        _PENDING_IDEALS.append(given)
        try:
            return VertexAlgebra.__classcall__(
                cls, V, spec, horizontal_grading, T)
        finally:
            _PENDING_IDEALS.pop()

    def __init__(self, ambient, spec, horizontal_grading=None, conformal_vector=None):
        r"""
        TESTS:

        A quotient with a conformal vector shares the ideal of the one
        without::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: v = L.no(L) - 3/10*L.derivative(2)
            sage: Q0 = V.quotient([v]); Q = V.quotient([v], conformal_vector='ambient')
            sage: Q is not Q0, Q._I is Q0._I, Q.ambient() is V, Q._spec[0]
            (True, True, True, 'generators')
            sage: Q.central_charge()
            -22/5
        """
        I = _PENDING_IDEALS[-1] if _PENDING_IDEALS else None
        if _PENDING_IDEALS:
            _PENDING_IDEALS[-1] = None      # nested constructions get none
        V = ambient
        Q0 = None
        if conformal_vector is not None:
            # the same quotient without T: its ideal and caches are shared
            _PENDING_IDEALS.append(I)
            try:
                Q0 = VertexAlgebra.__classcall__(     # the key of T=None
                    QuotientVertexAlgebra, V, spec, horizontal_grading, None)
            finally:
                _PENDING_IDEALS.pop()
            I = Q0._I
        if I is None:
            if spec[0] == 'ideal':
                I = spec[1]
            else:
                _, gens, horizontal_grading, names = spec
                I = V.ideal(list(gens), horizontal_grading=horizontal_grading, names=list(names))
        if I._whole or V.one() in I:
            raise ValueError('the ideal {} contains the vacuum: the quotient '
                             'is zero'.format(I))
        self._ambient = V
        self._I = I
        # the arguments of the public constructor giving the same spec
        self._pickle_args = ((V, spec[1], horizontal_grading, None, conformal_vector)
                             if spec[0] == 'ideal' else
                             (V, list(spec[1]), spec[2], list(spec[3]),
                              conformal_vector))
        self._spec = spec
        self._grading_option = horizontal_grading
        self._data = {'T': conformal_vector}
        try:
            V._weight_data()
            graded = True
        except ValueError:
            graded = False
        from .vertex_algebra_categories import (
            _is_finitely_strongly_generated,
            _is_proto,
        )
        VertexAlgebra.__init__(self, V.base_ring(), V._indices,
                               category=self._category_for(
                                   V.base_ring(), V._has_odd(), graded,
                                   conformal_vector is not None,
                                   fsg=_is_finitely_strongly_generated(V),
                                   proto=_is_proto(V) and not getattr(
                                       I, '_quotient_is_vertex_algebra', False)))
        if Q0 is not None:
            self._nf_rows = Q0._nf_rows
            self._subspaces = Q0._subspaces
        self._grading = None
        if horizontal_grading == 'ambient':
            gd = V._require_grading()
            if I._grading is None:
                gens = getattr(I, 'gens', None)
                if gens is None:
                    raise NotImplementedError(
                        'cannot check that {} is graded'.format(I))
                for g in gens():
                    if len({V._grade_key(m) for m in g.support()}) > 1:
                        raise ValueError(
                            'the generator {} of the ideal is not homogeneous '
                            'for the grading of {}'.format(g, V))
            self._grading = gd
        if conformal_vector is not None:
            self._install_conformal_vector(conformal_vector)

    def _has_odd(self):
        """
        Whether the ambient algebra has odd basis vectors (the category).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: Q._has_odd()
            False
        """
        return self._ambient._has_odd()

