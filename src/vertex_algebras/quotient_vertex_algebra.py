def _is_ideal(x):
    """True if ``x`` is an ideal (duck typing: modules under doctest are
    loaded twice, so ``isinstance`` is unreliable).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.quotient_vertex_algebra import _is_ideal
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: _is_ideal(V.ideal([L.no(L)])), _is_ideal([L]), _is_ideal(V)
        (True, False, False)
    """
    return hasattr(x, '_normal_form_rows')


def _quotient_cover(Q):
    r"""
    ``Q.cover()`` (unpickling).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.quotient_vertex_algebra import _quotient_cover
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]; _quotient_cover(Q) == Q.cover()
        True
    """
    return Q.cover()


