    def _monomial(self, index):
        """
        The basis vector of the key ``index``, in normal form.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: Q._monomial(((0, 0), (0, 0)))
            3/10*d^2L
            sage: Q.monomial(((0, 1),))
            dL
        """
        return self._el_from_dict(self._nf({index: self._one_R}))

    def _element_constructor_(self, x):
        """
        Convert ``x``: an element of ``self`` (or of a quotient forgetting or
        adding conformal data) is copied, a basis key or a scalar gives its
        vector, the ideal's ``_preimage`` is tried (presentations), anything else
        goes through the ambient algebra; the result is in normal form.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: Q(L.no(L)), Q(((0, 0), (0, 0))), Q(2)
            (3/10*d^2L, 3/10*d^2L, 2)
            sage: Q(Q(L)) == Q(L)
            True
        """
        if isinstance(x, VertexAlgebraElement) and x.parent() is self:
            return self._el_from_dict(dict(x._monomial_coefficients))
        P = getattr(x, 'parent', lambda: None)()
        if (P is not None and getattr(P, '_forgets', None) is not None
                and (self._forgets(P) or P._forgets(self))):
            return self._el_from_dict(dict(x._monomial_coefficients))
        if isinstance(x, tuple) and x in self._indices:
            return self._monomial(x)
        if not isinstance(x, VertexAlgebraElement):
            R = self.base_ring()
            try:
                c = R(x)
            except (TypeError, ValueError, ArithmeticError):
                c = None
            if c is not None:
                return self.one() * c
        pre = getattr(self._I, '_preimage', None)
        if pre is not None:             # e.g. the realization of a presentation
            d = pre(x)
            if d is not None:
                return self._el_from_dict(self._nf(d))
        try:
            v = self._ambient(x)
        except TypeError:
            raise TypeError('cannot convert {!r} into {}'.format(x, self))
        return self._el_from_dict(self._nf(dict(v._monomial_coefficients)))

    def _coerce_map_from_(self, R):
        # the projection: whatever coerces into the ambient algebra
        """
        The projection: whatever coerces into the ambient algebra coerces into ``self``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: Q.has_coerce_map_from(V), Q.has_coerce_map_from(QQ), V.has_coerce_map_from(Q)
            (True, True, False)
            sage: (Q(L) + L).parent() is Q
            True
        """
        V = self._ambient
        if R is V or V.has_coerce_map_from(R):
            return True
        return super()._coerce_map_from_(R)

    def lift(self, x):
        """
        The canonical representative of ``x`` (an element of ``self``) in
        the ambient algebra: its normal form, supported on the monomials
        that are not leading monomials of the ideal.

        INPUT:

        - ``x`` -- an element of ``self``

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: v = Q.lift(Q(L.no(L))); v
            3/10*d^2L
            sage: v.parent() is V
            True
        """
        x = self(x)
        return self._ambient._el_from_dict(dict(x._monomial_coefficients))

    def retract(self, v):
        """
        The image of the element ``v`` of the ambient algebra.

        INPUT:

        - ``v`` -- an element of the ambient algebra

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: x = Q.retract(L.no(L) + L); x
            L + 3/10*d^2L
            sage: x.parent() is Q, Q.retract(L.no(L) - 3/10*L.derivative(2)).is_zero()
            (True, True)
        """
        return self(v)

