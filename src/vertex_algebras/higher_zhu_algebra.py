def _word_of(A, k):
    """
    The generator word named by ``k``: a word (tuple of modes), its string
    (as printed), or a monomial of ``A`` with coefficient 1.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.higher_zhu_algebra import _word_of
        sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
        sage: _word_of(A, 'L_{-1} L_1'), _word_of(A, A.gen(0)), _word_of(A, ((0, 0),))
        (((0, -1), (0, 1)), ((0, 0),), ((0, 0),))
        sage: _word_of(A, 'L_7')
        Traceback (most recent call last):
        ...
        ValueError: 'L_7' is not a generator word (the generators are ['L_0', 'L_{-1} L_1'])
    """
    words = A._generator_words()
    if isinstance(k, tuple) and k in words:
        return k
    names = {A._repr_term(w): w for w in words}
    if isinstance(k, str) and k in names:
        return names[k]
    if _parent(k) is A:
        d = k.monomial_coefficients()
        if len(d) == 1:
            (w, c), = d.items()
            if c == 1 and w in words:
                return w
    raise ValueError('{!r} is not a generator word (the generators are {})'.format(
        k, sorted(names, key=lambda s: words.index(names[s]))))


def _word_matrix(A, gmat, cache, w, d):
    """
    The matrix of the word ``w`` of a level ``n`` Zhu algebra ``A`` (degree
    0, positive part ``<= n``) in the representation given by the matrices
    ``gmat`` (generator word ``->`` ``d x d`` matrix), by the filtration
    recursion of :class:`HigherZhuAlgebraModule`; memoised in ``cache``.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.higher_zhu_algebra import _word_matrix
        sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
        sage: g = {((0, 0),): matrix([[3]]), ((0, -1), (0, 1)): matrix([[4]])}
        sage: _word_matrix(A, g, {}, ((0, -1), (0, 0), (0, 1)), 1)       # y x - y
        [8]
    """
    r = cache.get(w)
    if r is not None:
        return r
    from sage.matrix.constructor import matrix
    R = A.base_ring()
    cre = tuple(x for x in w if x[1] < 0)
    zer = tuple(x for x in w if x[1] == 0)
    low = tuple(x for x in w if x[1] > 0)
    if not cre and not low:
        M = matrix.identity(R, d)
        for x in zer:
            M = M * gmat[(x,)]
    elif not zer:
        M = gmat[w]
    else:
        rl = cre + low
        prod = dict(A._P.apply_word(rl, {zer: R.one()}))
        c0 = prod.pop(w)
        M = gmat[rl] * _word_matrix(A, gmat, cache, zer, d)
        for k, c in prod.items():
            M = M - c * _word_matrix(A, gmat, cache, k, d)
        M = M / c0
    M.set_immutable()
    cache[w] = M
    return M


def _word_grading_spec(A, d, horizontal_grades, horizontal_grading_group, embedding):
    r"""
    The grading datum ``(B, grades, M)`` of a module of dimension ``d``
    over a level ``n`` Zhu algebra ``A`` (or ``None`` without grades), as
    :func:`zhu_algebra_module._grading_spec` for given grades: ``B`` the
    group (default: that of the vertex algebra if the grades lie in it,
    else ``R^k``; for affine algebras the weights ``P ⊗ R``), ``M`` the
    matrix of the embedding (default: the identity, or the affine one).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.higher_zhu_algebra import _word_grading_spec
        sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
        sage: C = UniversalVertexAlgebra(QQ, ['a', 'b'], {('a', 'b'): [0, 1]}, degrees={'a': 1, 'b': 1},
        ....:                            horizontal_grading={'a': 1, 'b': -1})
        sage: A = C.zhu_algebra(level=1)
        sage: _word_grading_spec(A, 2, [(0,), (1,)], None, None)
        (Vector space of dimension 1 over Rational Field, ((0), (1)), [1])
        sage: _word_grading_spec(A, 1, [(1/2,)], None, None)[0]
        Vector space of dimension 1 over Rational Field
        sage: _word_grading_spec(A, 1, None, None, None) is None
        True
    """
    from sage.matrix.constructor import matrix
    from sage.modules.free_module import FreeModule

    from ._grading_groups import module_grading_group
    if horizontal_grades is None:
        if horizontal_grading_group is not None or embedding is not None:
            raise ValueError('give the grades of the basis vectors')
        return None
    V = A._V
    gd = V._grading
    if gd is None:
        raise ValueError('grades need a vertex algebra graded by an abelian group')
    R = V.base_ring()
    AG = gd['group']
    horizontal_grades = list(horizontal_grades)
    if len(horizontal_grades) != d:
        raise ValueError('{} grades expected (one per basis vector)'.format(d))
    auto = getattr(V, '_cartan_weight_grading', None)
    auto = auto() if auto is not None else None
    if horizontal_grading_group is None and embedding is None and auto is not None:
        horizontal_grading_group = FreeModule(R, len(auto[0]))         # weights: P ⊗ R
        embedding = auto[1]
    if horizontal_grading_group is None:
        try:
            [AG.coords(g) for g in horizontal_grades]
            horizontal_grading_group = AG.group
        except (ValueError, TypeError):
            horizontal_grading_group = FreeModule(R, AG.k)
    BG = module_grading_group(horizontal_grading_group)
    if embedding is None:
        if BG.k != AG.k:
            raise ValueError('give the embedding of the grading group {} of the vertex '
                             'algebra into {}'.format(AG.group, BG.group))
        embedding = matrix.identity(BG.R if BG.kind == 'vector' else ZZ, BG.k)
    M = matrix(BG.R if BG.kind == 'vector' else ZZ, BG.k, AG.k, embedding)
    M.set_immutable()
    return (BG.group, tuple(BG.element(BG.coords(g)) for g in horizontal_grades), M)


