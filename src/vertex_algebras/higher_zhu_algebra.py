    def product_on_basis(self, w1, w2):
        """
        The product of standard words: ``w1`` on ``w2 v`` in normal form if
        their filtrations add up to at most the degree bound; otherwise,
        when the dimension is determined (:meth:`dimension`), through the
        left regular representation (the generators' matrices on the
        standard words and the filtration recursion of
        :class:`HigherZhuAlgebraModule`); else ``ValueError``.

        INPUT:

        - ``w1``, ``w2`` -- standard words (basis keys)

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: y = ((0, -1), (0, 1)); Z.product_on_basis(y, y), Z.product_on_basis(((0, 0),), y)
            (-2/5*L_{-1} L_1, 4/5*L_{-1} L_1)

        TESTS:

        Beyond the degree bound (the triplet algebra ``W(2)``: standard words
        of filtration 9, degree bound 16), see the class documentation and
        ``tests/smoke_higher_zhu.sage``.

        ::

            sage: Z.product_on_basis((), y)
            L_{-1} L_1
        """
        if self._filt(w1) + self._filt(w2) <= self._N:
            z = self._P.apply_word(w1, {w2: self.base_ring().one()})
            return self._from_dict(self._nf(z), coerce=False, remove_zeros=True)
        words, pos, gmat, cache = self._regular()
        col = _word_matrix(self, gmat, cache, w1, len(words)).column(pos[w2])
        return self._from_dict({words[i]: c for i, c in col.dict().items()},
                               coerce=False, remove_zeros=True)

    def _regular(self):
        """
        The left regular representation: ``(words, positions, generator
        matrices, cache of word matrices)`` on the standard words (needs the
        dimension, :meth:`dimension`).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: words, pos, gmat, cache = Z._regular(); gmat[((0, 0),)]
            [   0    0    0]
            [   1 -1/5    0]
            [   0   -2  4/5]
        """
        try:
            return self._reg
        except AttributeError:
            pass
        from sage.matrix.constructor import matrix
        words = self._basis_words()
        pos = {w: i for i, w in enumerate(words)}
        R = self.base_ring()
        d = len(words)
        irr = _irreducible_generator_words(self._odd, self._level)
        nf = self.__dict__.setdefault('_gen_nf', {})
        todo = [(g, s) for g in irr for s in words if (g, s) not in nf]
        nf.update(zip(todo, self._nf_many([self._P.apply_word(g, {s: R.one()})
                                           for g, s in todo])))
        gmat, cache = {}, {}
        for g in irr:
            M = matrix(R, d, d)
            for j, s in enumerate(words):
                for k, c in nf[g, s].items():
                    M[pos[k], j] = c
            M.set_immutable()
            gmat[g] = M
        # the others are products of two of lower filtration modulo lower
        # filtration (their products with standard words may exceed N)
        for g in sorted(self._generator_words(), key=self._filt):
            if g not in gmat:
                gmat[g] = self._decomposed_matrix(g, gmat, cache, d)
        self._reg = (words, pos, gmat, cache)
        return self._reg

    def _decomposed_matrix(self, g, gmat, cache, d):
        """
        The matrix of the generator word ``g`` in a representation given by
        the matrices ``gmat`` of the generator words of lower filtration:
        ``g = (g_1 g_2 - Σ c_k k) / c`` for generator words ``g_1, g_2``
        whose product ``c g + Σ c_k k`` has no other word of filtration
        ``filt(g)`` (:func:`_is_decomposable`).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(8, level=2)
            sage: words, pos, gmat, cache = Z._regular()
            sage: g = ((0, -1), (0, -1), (0, 1), (0, 1)); g in gmat
            True
            sage: d = len(words); A = dict(gmat); del A[g]
            sage: Z._decomposed_matrix(g, A, {}, d) == gmat[g]
            True
        """
        R = self.base_ring()
        fg = self._filt(g)
        for g1 in list(gmat):
            for g2 in list(gmat):
                if self._filt(g1) + self._filt(g2) != fg:
                    continue
                z = dict(self._P.apply_word(g1, {g2: R.one()}))
                c0 = z.pop(g, 0)
                if not c0 or any(self._filt(k) >= fg for k, c in z.items() if c):
                    continue
                M = gmat[g1] * gmat[g2]
                for k, c in z.items():
                    if c:
                        M = M - c * _word_matrix(self, gmat, cache, k, d)
                M = M / c0
                M.set_immutable()
                return M
        raise ValueError('the generator word {} is not a product of two of lower '
                         'filtration'.format(g))

