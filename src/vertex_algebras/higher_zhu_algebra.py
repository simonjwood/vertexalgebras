    def _depth(self, key):
        """
        The degree of a key: the creation degree plus that of ``l u``.

        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.higher_zhu_algebra import HigherInducedModule
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: U = V.zhu_algebra(level=1).module({'L_0': 3, 'L_{-1} L_1': 4})
            sage: M = HigherInducedModule(V, U)
            sage: M._depth((((0, -2),), (((0, 1),), 0))), M._depth(((), ((), 0)))
            (2, 1)
        """
        modes, u = key
        return -sum((QQ(m) for _, m in modes), QQ.zero()) + self._U._tdeg(u)

