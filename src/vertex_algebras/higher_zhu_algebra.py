    def gen(self, i):
        """
        The ``i``-th algebra generator.

        INPUT:

        - ``i`` -- an integer: an index into :meth:`algebra_generators`

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1).gen(1)
            L_{-1} L_1
        """
        return self._generators()[i]

    def some_elements(self):
        """
        The unit, up to three generators and a product (``TestSuite``).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1).some_elements()
            [1, L_0, L_{-1} L_1, L_{-1} L_0 L_1 + L_{-1} L_1 + 2*L_0]
        """
        gens = list(self._generators()[:3])
        out = [self.one()] + gens
        if gens:
            out.append(gens[0] * gens[-1] + 2 * gens[0])
        return out

    def module(self, action, parities=None, **grading):
        """
        The finite-dimensional module given by the matrices of the generator
        words (a :class:`HigherZhuAlgebraModule`; grades of the basis by the
        keywords ``horizontal_grades``, ``horizontal_grading_group``,
        ``embedding``).

        INPUT:

        - ``action`` -- the matrices of the generator words, as for
          :class:`HigherZhuAlgebraModule`
        - ``parities`` -- (default: ``None``, all even) the parities of the
          basis vectors
        - ``**grading`` -- the keywords ``horizontal_grades``,
          ``horizontal_grading_group``, ``embedding`` of
          :class:`HigherZhuAlgebraModule`

        OUTPUT:

        A :class:`HigherZhuAlgebraModule`.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A.module({'L_0': 2, 'L_{-1} L_1': 2}).dimension()
            1
        """
        return HigherZhuAlgebraModule(self, action, parities, **grading)

    # ------------------------------------------------------------------ #
    #  The Zhu map, lower levels                                           #
    # ------------------------------------------------------------------ #

    def _zeta_dict(self, d):
        """
        ``Σ c o(a) v`` for a dict ``{basis monomial a of V: c}``.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A._zeta_dict({((0, 1),): 1, (): 2})              # ∂L + 2
            {(): 2, ((0, 0),): -2}
        """
        P, V = self._P, self._V
        out = {}
        for a, c in d.items():
            w = V._weight_key(a, P._data)
            _add_scaled(out, P._action_mono(a, int(w - 1), ()), c)
        return out

    def retract(self, v):
        r"""
        The image ``[v] = o(v) v_0`` of the element ``v`` of the vertex
        algebra (also ``A(v)``; a conversion, not a coercion).

        INPUT:

        - ``v`` -- an element of the vertex algebra (or anything it
          converts)

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: A = V.zhu_algebra(level=1)
            sage: A.retract(L.derivative(2)), A(L.no(L.derivative()))
            (6*L_0, -4*L_{-1} L_1 - 6*L_0 - 2*L_0^2)
        """
        v = self._V(v)
        return self._from_dict(self._zeta_dict(dict(v._monomial_coefficients)),
                               coerce=False, remove_zeros=True)

    def _project_dict(self, d, level):
        """
        The image in level ``level <= n``: drop the words lowering by more
        than ``level``.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=2)
            sage: A._project_dict({((0, -2), (0, 2)): 1, ((0, 0),): 3}, 1)
            {((0, 0),): 3}
        """
        return {w: c for w, c in d.items() if sum(max(m, 0) for _, m in w) <= level}

    def _coerce_map_from_(self, P):
        """
        The projections ``A_m(V) -> A_n(V)``, ``m >= n``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: A1, A2 = V.zhu_algebra(level=1), V.zhu_algebra(level=2)
            sage: A1.has_coerce_map_from(A2), A2.has_coerce_map_from(A1)
            (True, False)
            sage: x = A2.gen(3); x, A1(x)
            (L_{-2} L_2, 0)
        """
        if (isinstance(P, HigherZhuAlgebra) and P._V is self._V
                and P._level >= self._level):
            return True
        return super()._coerce_map_from_(P)

    def _element_constructor_(self, x):
        """
        ``A(v)`` for ``v`` in the vertex algebra (the Zhu map); elements of
        higher levels (projected); otherwise as any
        ``CombinatorialFreeModule``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: A = V.zhu_algebra(level=1); A(V.gen('L')), A(3), A(V.zhu_algebra(level=2)(V.gen('L')))
            (L_0, 3, L_0)
        """
        P = _parent(x)
        if isinstance(P, HigherZhuAlgebra) and P is not self and P._V is self._V:
            if P._level < self._level:
                raise TypeError('no map from level {} to level {}'.format(
                    P._level, self._level))
            return self._from_dict(self._project_dict(x.monomial_coefficients(), self._level),
                                   coerce=False, remove_zeros=True)
        if P is not self and _of_vertex_algebra(self._V, P):
            return self.retract(x)
        return super()._element_constructor_(x)


