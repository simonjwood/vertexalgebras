class HigherZhuAlgebraModule(ZhuAlgebraModule):
    r"""
    A finite-dimensional module over a level ``n`` Zhu algebra
    (``Z.module(action)``, ``Z`` a :class:`HigherZhuAlgebra` or
    :class:`HigherZhuAlgebraQuotient`), given by the matrices of the
    generator words (:meth:`HigherZhuAlgebra.algebra_generators`: the zero
    modes ``g_0`` and the words ``r l``).

    The matrix ``ρ(w)`` of any word follows by the filtration: ``ρ(z_1 ...
    z_k) = ρ(z_1) ... ρ(z_k)`` for zero modes, and for a word ``r z l``
    (``z`` the zero modes, ``r``, ``l`` not both empty) ``(r l) z = r z l +
    (lower words)`` in ``A_n``, so ``ρ(r z l) = ρ(r l) ρ(z) - ρ(lower)``.
    Checked: the parities; ``ρ(x y) = ρ(x) ρ(y)`` for all words ``x``, ``y``
    of filtration at most that of the generators (the universal algebra:
    a check on these words only) or, for a quotient of known dimension,
    for all pairs of standard words, and ``ρ`` kills every relation
    computed.

    INPUT:

    - ``A`` -- a level ``n`` Zhu algebra
    - ``action`` -- a dict (or list of pairs): generator (word, its string
      as printed, or the generator itself) ``->`` matrix (columns: images
      of the basis); or the matrices in the order of the generators
    - ``parities`` -- (default: ``None``, all even) the parities of the
      basis vectors
    - ``horizontal_grades`` -- (default: ``None``) the grades of the basis
      vectors (the vertex algebra graded by a group ``A``); a generator
      word of grade ``a`` must map grade ``b`` to ``b + ι(a)``
    - ``horizontal_grading_group`` -- (default: ``None``) the group ``B``
      of the grades: ``A`` if they lie in it, else ``A ⊗ R``; affine
      algebras: the weights; as for modules over
      :class:`zhu_algebra.ZhuAlgebra`
    - ``embedding`` -- (default: ``None``) the matrix of ``ι: A -> B``, as
      for modules over :class:`zhu_algebra.ZhuAlgebra`
    - ``horizontal_grading`` -- (default: ``None``) the normalised grading
      datum; internal (used by unpickling), not to be given by users

    EXAMPLES:

    The universal Virasoro algebra, ``A_1 = C[x, y] / (y (y - 2x + 2))``:
    the one-dimensional modules lie on the two lines::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
        sage: A = V.zhu_algebra(level=1)
        sage: U = A.module({'L_0': 3, 'L_{-1} L_1': 4}); U
        Module of dimension 1 over Level 1 Zhu algebra of Universal vertex algebra on generators ['L'] over Rational Field
        sage: U.representation_matrix(L.no(L))         # x^2 + 2x + 2y
        [23]
        sage: A.module({'L_0': 3, 'L_{-1} L_1': 1})
        Traceback (most recent call last):
        ...
        ValueError: the matrices are not a representation: rho(x) rho(y) != rho(x y) for x = L_{-1} L_1, y = L_{-1} L_1

    The Lee--Yang model at level 1: the modules of its three blocks::

        sage: Q = V.with_conformal_vector(None).with_degrees({'L': 2})
        sage: VL = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = VL.gen('L')
        sage: Z = (VL / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
        sage: [Z.module({'L_0': x, 'L_{-1} L_1': y}).dimension() for x, y in [(0, 0), (-1/5, 0), (4/5, -2/5)]]
        [1, 1, 1]
        sage: Z.module({'L_0': 4/5, 'L_{-1} L_1': 0})
        Traceback (most recent call last):
        ...
        ValueError: the matrices do not satisfy the relation ... = 0 of the level 1 Zhu algebra

    TESTS::

        sage: loads(dumps(U)) is U, U.algebra() is A
        (True, True)
        sage: TestSuite(U).run()
        sage: A.module({'L_0': 3})
        Traceback (most recent call last):
        ...
        ValueError: give the matrices of all generators ['L_0', 'L_{-1} L_1']
    """

    _is_higher_zhu_algebra_module = True      # duck typing (doctests)

    @staticmethod
    def __classcall_private__(cls, A, action, parities=None, horizontal_grades=None,
                              horizontal_grading_group=None, embedding=None,
                              horizontal_grading=None):
        """
        Normalise: immutable matrices in the order of the generator words,
        the parities as a tuple, the grading datum (:func:`_word_grading_spec`,
        passed by keyword).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A.module({'L_0': 0, 'L_{-1} L_1': 0}) is A.module({((0, 0),): 0, A.gen(1): 0})
            True
        """
        from sage.matrix.constructor import matrix
        R = A.base_ring()
        words = A._generator_words()
        given = {}
        if isinstance(action, dict):
            items = list(action.items())
        else:
            items = list(action)
            if len(items) == len(words) and all(hasattr(v, 'nrows') for v in items):
                items = list(zip(words, items))       # matrices in generator order
        for k, v in items:
            given[_word_of(A, k)] = v
        if len(given) != len(words):
            raise ValueError('give the matrices of all generators {}'.format(
                [A._repr_term(w) for w in words]))
        mats = []
        for w in words:
            v = given[w]
            M = matrix(R, v) if (isinstance(v, (list, tuple)) or hasattr(v, 'nrows')) \
                else matrix(R, [[v]])
            M.set_immutable()
            mats.append(M)
        d = mats[0].nrows()
        parities = tuple(int(p) % 2 for p in (parities if parities is not None else [0] * d))
        if horizontal_grading is None:     # (given: the normalised datum, from unpickling)
            horizontal_grading = _word_grading_spec(A, d, horizontal_grades,
                                                    horizontal_grading_group, embedding)
        return CombinatorialFreeModule.__classcall__(cls, A, tuple(mats), parities,
                                                     horizontal_grading=horizontal_grading)

    def __init__(self, A, mats, parities, horizontal_grading=None):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: U = A.module({'L_0': 3, 'L_{-1} L_1': 4}); U.dimension(), U._par
            (1, (0,))
            sage: sorted(U._gmat.items())
            [(((0, -1), (0, 1)), [4]), (((0, 0),), [3])]
        """
        from sage.categories.modules import Modules
        R = A.base_ring()
        d = len(parities)
        words = A._generator_words()
        for w, M in zip(words, mats):
            if M.nrows() != d or M.ncols() != d:
                raise ValueError('the matrix of {} is not {} x {}'.format(A._repr_term(w), d, d))
        self._A = A
        self._cover = A
        self._mats = mats
        self._par = parities
        self._gmat = dict(zip(words, mats))
        self._rho = {}
        self._grading = None
        self._check()
        if horizontal_grading is not None:
            self._install_grading(*horizontal_grading)
        cat = Modules(R).WithBasis().FiniteDimensional()
        if any(parities):
            cat = cat.Super()
        CombinatorialFreeModule.__init__(self, R, list(range(d)), prefix='u', category=cat)

    def _rho_word(self, w):
        """
        The matrix of the word ``w`` (degree 0, positive part ``<= n``), by
        the filtration recursion of the class documentation (cached).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: U = A.module({'L_0': 3, 'L_{-1} L_1': 4})
            sage: U._rho_word(((0, -1), (0, 0), (0, 1)))         # y x - y
            [8]
        """
        return _word_matrix(self._A, self._gmat, self._rho, w, len(self._par))

    def _evaluate(self, dct):
        """
        ``Σ c ρ(w)`` for a dict ``{word: c}``.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A.module({'L_0': 3, 'L_{-1} L_1': 4})._evaluate({(): 1, ((0, 0),): 2})
            [7]
        """
        from sage.matrix.constructor import matrix
        R = self._A.base_ring()
        d = len(self._par)
        out = matrix(R, d, d)
        for w, c in dct.items():
            out += c * self._rho_word(w)
        return out

    def _check(self):
        """
        The parities, multiplicativity on the words of small filtration (all
        standard words for quotients of known dimension) and, for
        quotients, the relations; a ``ValueError`` naming a failure.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: SF = UniversalVertexAlgebra(QQ, ['chp', 'chm'], {('chp', 'chm'): [0, 1]},
            ....:     parities={'chp': 1, 'chm': 1}, degrees={'chp': 1, 'chm': 1})
            sage: A = SF.zhu_algebra(level=1); [A._repr_term(w) for w in A._generator_words()]
            ['chp_0', 'chm_0', 'chp_{-1} chp_1', 'chp_{-1} chm_1', 'chm_{-1} chp_1', 'chm_{-1} chm_1']
            sage: z = matrix(QQ, 2, 2)
            sage: A.module([(w, z) for w in A._generator_words()], parities=[0, 1]).dimension()
            2
            sage: A.module([(w, matrix([[1, 0], [0, 0]]) if i == 0 else z)
            ....:           for i, w in enumerate(A._generator_words())], parities=[0, 1])
            Traceback (most recent call last):
            ...
            ValueError: the matrix of the odd generator chp_0 does not change the parity
        """
        A = self._A
        par = self._par
        for w, M in self._gmat.items():
            odd = sum(1 for i, _ in w if A._odd[i]) % 2
            for r in range(M.nrows()):
                for c in range(M.ncols()):
                    if M[r, c] and (par[r] + par[c]) % 2 != odd:
                        raise ValueError('the matrix of the {} generator {} does not {} '
                                         'the parity'.format('odd' if odd else 'even',
                                                             A._repr_term(w),
                                                             'change' if odd else 'preserve'))
        R = A.base_ring()
        quotient = isinstance(A, HigherZhuAlgebraQuotient)
        if quotient:
            e = A._store.get(A._level)
            if e is not None:
                for row in e.rows():
                    if self._evaluate(row):
                        raise ValueError('the matrices do not satisfy the relation {} = 0 of '
                                         'the level {} Zhu algebra'.format(
                                             ' + '.join('({})*{}'.format(c, A._repr_term(k))
                                                        for k, c in row.items()), A._level))
            try:
                A.dimension()
                words = A._standard_up_to(A._N // 2)
            except ValueError:
                words = A._standard_up_to(A._N // 2)
        else:
            D = max(sum(A._h[i] for i, _ in w) for w in A._generator_words())
            words = _words_of_degree(A._h, A._odd, A._level, A._level, D)
        for x in words:
            for y in words:
                prod = A._P.apply_word(x, {y: R.one()})
                if self._rho_word(x) * self._rho_word(y) != self._evaluate(prod):
                    raise ValueError('the matrices are not a representation: rho(x) rho(y) != '
                                     'rho(x y) for x = {}, y = {}'.format(A._repr_term(x),
                                                                      A._repr_term(y)))

    def _install_grading(self, B, horizontal_grades, M):
        """
        Install the grading datum (``B``, the grades of the basis vectors,
        the matrix ``M`` of ``ι``), checking that each generator word of
        grade ``a`` (the sum of its generators' grades) maps grade ``b`` to
        ``b + ι(a)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F'], conformal_vector='sugawara')
            sage: A = V.zhu_algebra(level=1)
            sage: e, h, f = matrix([[0, 1], [0, 0]]), matrix([[1, 0], [0, -1]]), matrix([[0, 0], [1, 0]])
            sage: z = matrix(QQ, 2, 2)
            sage: act = {'E_0': e, 'H_0': h, 'F_0': f}
            sage: act.update({w: z for w in map(A._repr_term, A._generator_words()) if w not in act})
            sage: U = A.module(act, horizontal_grades=[(1,), (-1,)]); U.horizontal_grades()
            [(1), (-1)]
            sage: A.module(act, horizontal_grades=[(1,), (1,)])
            Traceback (most recent call last):
            ...
            ValueError: the matrix of E_0 maps a vector of grade (1) to one of grade (1), not (1) + iota(grade of E_0) = (3)
        """
        from ._grading_groups import GradingEmbedding, module_grading_group
        A = self._A
        gd = A._V._grading
        BG = module_grading_group(B)
        iota = GradingEmbedding(gd['group'], BG, M)
        coords = [BG.coords(g) for g in horizontal_grades]
        for w, X in self._gmat.items():
            shift = BG.zero
            for i, _ in w:
                shift = BG.add(shift, iota(gd['g'][i]))
            for r in range(X.nrows()):
                for c in range(X.ncols()):
                    if X[r, c] and coords[r] != BG.add(coords[c], shift):
                        raise ValueError(
                            'the matrix of {} maps a vector of grade {} to one of grade {}, '
                            'not {} + iota(grade of {}) = {}'.format(
                                A._repr_term(w), BG.element(coords[c]), BG.element(coords[r]),
                                BG.element(coords[c]), A._repr_term(w),
                                BG.element(BG.add(coords[c], shift))))
        self._grading = (iota, coords)

    def _repr_(self):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A.module({'L_0': 3, 'L_{-1} L_1': 4})
            Module of dimension 1 over Level 1 Zhu algebra of Universal vertex algebra on generators ['L'] over Rational Field
        """
        return 'Module of dimension {} over {}'.format(len(self._par), self._A)

    def generator_matrices(self):
        """
        The matrices of the generator words, a dict by their strings.

        OUTPUT:

        A dictionary ``{string: matrix}``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A.module({'L_0': 3, 'L_{-1} L_1': 4}).generator_matrices()
            {'L_0': [3], 'L_{-1} L_1': [4]}
        """
        return {self._A._repr_term(w): M for w, M in self._gmat.items()}

    def _gen_action_key(self, z, u):
        """
        The zero mode of the ``z``-th generator of the vertex algebra on
        ``u``, as a dict.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, 1/2, conformal_vector='L').zhu_algebra(level=1)
            sage: A.module({'L_0': 3, 'L_{-1} L_1': 4})._gen_action_key(0, 0)
            {0: 3}
        """
        M = self._gmat[((z, 0),)]
        return {r: M[r, u] for r in range(M.nrows()) if M[r, u]}

    def representation_matrix(self, x):
        """
        The matrix of ``x`` (an element of the Zhu algebra, or of the vertex
        algebra: then its image).

        INPUT:

        - ``x`` -- an element of the Zhu algebra, or of the vertex algebra
          (then its image ``A(x)``)

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: A = V.zhu_algebra(level=1); U = A.module({'L_0': 3, 'L_{-1} L_1': 4})
            sage: U.representation_matrix(L.derivative()), U.representation_matrix(A.gen(1)^2)
            ([-6], [16])
        """
        A = self._A
        if _parent(x) is not A:
            x = A(x)
        return self._evaluate(dict(x.monomial_coefficients()))


