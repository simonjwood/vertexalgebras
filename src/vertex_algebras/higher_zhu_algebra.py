    def top_weight(self):
        """
        The weight of degree 0: ``h - n``, ``h`` the eigenvalue of ``[T]``
        on ``U`` (if it has only one; else ``-n``).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.higher_zhu_algebra import HigherInducedModule
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: U = V.zhu_algebra(level=1).module({'L_0': 3, 'L_{-1} L_1': 4})
            sage: HigherInducedModule(V, U).top_weight()
            2
        """
        return -self._n if self._top is None else self._top

