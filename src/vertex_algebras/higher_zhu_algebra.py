class _StandardModeWords:
    """
    The basis keys of a :class:`HigherZhuAlgebraQuotient`: the words of
    degree 0 of filtration at most the degree bound that are not leading
    words of the relations (not iterable).

    TESTS::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
        sage: from vertex_algebras.higher_zhu_algebra import _StandardModeWords
        sage: S = _StandardModeWords(Z); () in S, ((0, -1), (0, 1)) in S, ((0, 0), (0, 0)) in S
        (True, True, False)
        sage: S.an_element(), S.cardinality()
        ((), 3)
    """
    def __init__(self, Z):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: from vertex_algebras.higher_zhu_algebra import _StandardModeWords
            sage: _StandardModeWords(Z)._Z is Z
            True
        """
        self._Z = Z

    def __contains__(self, w):
        """
        Whether ``w`` is a standard word: of degree 0, within the degree
        bound, not a leading word of the relations.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: from vertex_algebras.higher_zhu_algebra import _StandardModeWords
            sage: S = _StandardModeWords(Z); ((0, 0),) in S, ((0, 0), (0, 0)) in S, ((0, 1),) in S
            (True, False, False)
        """
        Z = self._Z
        return (w in Z._words and Z._filt(w) <= Z._N and w not in Z._pivots)

    def an_element(self):
        """
        The empty word (the unit).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: from vertex_algebras.higher_zhu_algebra import _StandardModeWords
            sage: _StandardModeWords(Z).an_element()
            ()
        """
        return ()

    def cardinality(self):
        """
        The dimension of the algebra, ``+Infinity`` if it is not determined.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: from vertex_algebras.higher_zhu_algebra import _StandardModeWords
            sage: _StandardModeWords(Z).cardinality()
            3
        """
        try:
            return self._Z.dimension()
        except ValueError:
            return Infinity


class HigherZhuAlgebraQuotient(_ZhuGrading, CombinatorialFreeModule):
    r"""
    The level ``n`` Zhu algebra of a quotient ``Q = V/I`` of a universal
    vertex algebra (also a presentation: ``V`` proto) up to a weight
    (``Q.zhu_algebra_up_to(max_weight, level=n, degree_bound=N)``), an
    algebra mapping onto ``A_n(Q)``.

    By He's theorem (module documentation) ``A_n(Q)`` is the degree-``n``
    part of ``P / K``, ``P`` the module of mode words of ``V`` (degree ``n``
    vector ``v``) and ``K`` the ``U``-submodule generated by the ``r_(k) v``,
    ``r ∈ I``, and, when ``V`` is proto, the defects of the commutator
    formula of the generator modes (the Jacobi identity holds in ``Q``, not
    in ``V``).  Computed: the closure of the ``r_(k) v`` for ``r`` in the
    weight spaces ``I_w``, ``w <= max_weight``, under the generator modes,
    and the defects, inside the degrees ``0, ..., n`` and the words of
    filtration (sum of the generators' weights) ``<= N``.  That is a
    subspace of ``K``, so ``P_n^{<= N} / K_n`` maps onto the part of
    ``A_n(Q)`` of filtration ``<= N``; the elements are normal forms
    (standard words: no leading word of the relations, leading = highest
    filtration).  The standard words of filtration ``<= f_0`` span an
    algebra mapping onto ``A_n(Q)`` once their span is checked to be
    closed under multiplication by the irreducible generator words of
    ``A_n(V)`` within the degree bound (:meth:`dimension`, which
    determines ``f_0``).

    INPUT:

    - ``Q`` -- a quotient of a universal vertex algebra with positive integer
      conformal weights
    - ``level`` -- ``n >= 0`` (``n = 0``: the Zhu algebra ``A(Q)`` in He's
      model, with the structure methods below; ``Q.zhu_algebra_up_to(W)``
      itself gives the Plural or free algebra quotient)
    - ``max_weight`` -- the ideal's weight spaces ``I_w``, ``w <=
      max_weight``, give the relations
    - ``degree_bound`` -- (default: ``None``, ``max_weight`` plus the
      largest filtration of an algebra generator) the filtration ``N`` of
      the words computed with

    EXAMPLES:

    The Lee--Yang model: ``A_n`` is ``⊕ End(M(d))`` over the simple modules
    ``M = L(0), L(-1/5)`` and their degrees ``d <= n`` (``L(0)`` has nothing
    in degree 1): dimensions 2, 3, 5::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
        sage: Z = Q.zhu_algebra_up_to(6, level=1); Z
        Level 1 Zhu algebra of Quotient of Universal vertex algebra on generators ['L'] over Rational Field by the ideal generated by [:L L: - 3/10*d^2L] up to weight 6 (words of filtration <= 10)
        sage: Z.dimension(), Q.zhu_algebra_up_to(6, level=2).dimension()
        (3, 5)
        sage: Z.basis().list()
        [1, L_0, L_{-1} L_1]

    ``[L]`` has the eigenvalues ``0``, ``-1/5`` (degree 0) and ``4/5`` (degree
    1 of ``L(-1/5)``)::

        sage: x = Z(L); x*(x + 1/5)*(x - 4/5), x*(x + 1/5) == 0
        (0, False)

    At level 3 the dimension is 7 (``L(0)`` adds degree 2, ``L(-1/5)``
    has one vector in each degree)::

        sage: Q.zhu_algebra_up_to(8, level=3).dimension()
        7

    The triplet algebra ``W(2)`` from its presentation (no modules): ``A_1``
    is 24-dimensional, ``A_0`` 11-dimensional::

        sage: from vertex_algebras import UniversalVertexAlgebra, NormallyOrderedExpressions
        sage: Y.<cp, cm> = NormallyOrderedExpressions(QQ, parities={'cp': 1, 'cm': 1})
        sage: SF = UniversalVertexAlgebra(QQ, Y, {('cp', 'cm'): [0, 1]}, conformal_vector=cm*cp,
        ....:                             horizontal_grading={'cp': 1, 'cm': -1})
        sage: a, b = SF.gens()
        sage: W2 = SF.subalgebra([SF.conformal_vector(), a.no(a.derivative()),
        ....:     a.no(b.derivative()) + b.no(a.derivative()), b.no(b.derivative())],
        ....:     names=['T', 'Wp', 'W0', 'Wm'], horizontal_grading='ambient', conformal_vector='ambient')
        sage: P = W2.presentation()
        sage: Z1 = P.zhu_algebra_up_to(8, level=1, degree_bound=16)   # long time
        sage: Z1.dimension(), P.zhu_algebra_up_to(8).dimension()        # long time
        (24, 11)

    Products of standard words beyond the degree bound go through the left
    regular representation::

        sage: B = Z1.basis().list(); max(Z1._filt(x.leading_support()) for x in B)   # long time
        9
        sage: x = B[-1]; (x * x) * B[-2] == x * (x * B[-2])                          # long time
        True

    The default degree bound (``8 + 6``) does not determine it: a standard
    word of filtration 9 times a generator of filtration 6 is beyond it::

        sage: P.zhu_algebra_up_to(8, level=1).dimension()
        Traceback (most recent call last):
        ...
        ValueError: standard words of filtration up to the degree bound 14: the dimension is not determined (increase max_weight or degree_bound)
    """

    Element = ZhuAlgebraElement

    @staticmethod
    def __classcall_private__(cls, Q, level, max_weight, degree_bound=None):
        """
        Normalise: the key is ``(Q, level, max_weight, degree_bound)`` with
        the default degree bound resolved.

        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.higher_zhu_algebra import HigherZhuAlgebraQuotient
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V / [L.no(L) - 3/10*L.derivative(2)]
            sage: HigherZhuAlgebraQuotient(Q, 1, 6) is HigherZhuAlgebraQuotient(Q, 1, 6, 10)
            True
        """
        if not (level in ZZ and level >= 0):
            raise ValueError('the level must be a nonnegative integer, not {}'.format(level))
        level, W = ZZ(level), ZZ(max_weight)
        if degree_bound is None:
            V, _ = _cover(Q)
            h = _cover_weights(V)
            degree_bound = W + max(2 * level * max(h), *h)
        return CombinatorialFreeModule.__classcall__(cls, Q, level, W, ZZ(degree_bound))

    def __init__(self, Q, level, max_weight, degree_bound):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._level, Z._W, Z._N, Z._names
            (1, 6, 10, ('L',))
        """
        from .vertex_algebra_categories import _is_proto
        V, chain = _cover(Q)
        self._Q = Q
        self._V = V
        self._level = level
        self._W = max_weight
        self._N = degree_bound
        self._h = _cover_weights(V)
        self._odd = tuple(bool(V._parities.get(i, 0)) for i in range(len(self._h)))
        self._names = tuple(V._gens)
        self._P = _FreeModeModule(V, level, self._h, self._odd)
        self._words = _ModeWords(level, len(self._h),
                                 [i for i, o in enumerate(self._odd) if o])
        self._proto = _is_proto(V)
        self._compute()
        R = V.base_ring()
        cat = Algebras(R).WithBasis()
        cat = cat.Super() if any(self._odd) else cat.Filtered()
        CombinatorialFreeModule.__init__(self, R, _StandardModeWords(self),
                                         prefix='', category=cat)

    # the relations

    def _filt(self, w):
        """
        The filtration of a word: the sum of the weights of its generators.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._filt(((0, -1), (0, 0), (0, 1)))
            6
        """
        c = self.__dict__.setdefault('_filt_cache', {})
        f = c.get(w)
        if f is None:
            f = c[w] = sum((self._h[i] for i, _ in w), ZZ.zero())
        return f

    def _word_order(self, w):
        """
        The order of words (the leading word of a relation is the largest):
        by filtration, length, then the word.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._word_order(((0, 0), (0, 0))) > Z._word_order(((0, -1), (0, 1)))
            True
        """
        return (self._filt(w), len(w), w)

    def _window_keys(self, d, budget):
        """
        The words of degree ``d`` (``Σ m = n - d``) of filtration ``<=
        budget``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._window_keys(1, 4), Z._window_keys(0, 4)
            ([(), ((0, 0),), ((0, 0), (0, 0)), ((0, -1), (0, 1))], [((0, 1),), ((0, 0), (0, 1))])
        """
        return _words_of_degree(self._h, self._odd, self._level, d, budget)

    def _act(self, i, m, z):
        """
        The mode ``g_{i,m}`` on the dict ``z``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._act(0, 1, {((0, -1),): 2})
            {((0, -1), (0, 1)): 2, ((0, 0),): 4}
        """
        return self._P.act_many([(i, m, z)])[0]

    def _compute(self):
        """
        The relations: per degree ``d`` a ``KeyedSpan`` (``_store``),
        the leading words of degree ``n`` (``_pivots``), the number of new
        relations from commutator defects (``_ndefects``).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: sorted(Z._store), Z._ndefects
            ([0, 1], 0)
        """
        from ._keyed_spans import KeyedSpan
        from .zhu_algebra import _ideal_elements
        V, P, n, N = self._V, self._P, self._level, self._N
        R = V.base_ring()
        data = V._weight_data()
        store = {}
        queue = []

        def insert(cands):
            by = {}
            for z in cands:
                z = {k: c for k, c in z.items() if c}
                if not z:
                    continue
                d = P._deg(next(iter(z)))
                if 0 <= d <= n and max(self._filt(k) for k in z) <= N:
                    by.setdefault(d, []).append(z)
            new = 0
            for d, zs in by.items():
                e = store.get(d)
                if e is None:
                    e = store[d] = KeyedSpan(R, key_order=self._word_order)
                # only the span matters: any certified basis (greedy=False)
                for z, ok in zip(zs, e.insert_many(zs, greedy=False)):
                    if ok:
                        queue.append((z, d))
                        new += 1
            return new

        def close():
            while queue:
                todo = list(queue)
                queue.clear()
                tasks = []
                for z, d in todo:
                    f = max(self._filt(k) for k in z)
                    for i, hi in enumerate(self._h):
                        if f + hi <= N:
                            tasks.extend((i, m, z) for m in range(d - n, d + 1))
                insert(P.act_many(tasks))           # one engine call per round

        # the sources r_(k) v, degrees n + w - k - 1 in [0, n]
        cands = []
        for x in _ideal_elements(self._Q, self._W)[1]:
            d = dict(x.monomial_coefficients())
            if not d:
                continue
            w = ZZ(V._weight_key(next(iter(d)), data))
            if w > N:
                continue
            for k in range(w - 1, w + n):
                z = {}
                for a, c in d.items():
                    _add_scaled(z, P._action_mono(a, k, ()), c)
                cands.append(z)
        insert(cands)
        close()
        self._ndefects = 0
        while self._proto:
            new = insert(self._defects(store))
            self._ndefects += new
            if not new:
                break
            close()
        self._store = store
        e = store.get(n)
        self._pivots = frozenset(e.pivots()) if e is not None else frozenset()

    def _defects(self, store):
        r"""
        The defects ``g_m h_{m'} t - s h_{m'} g_m t - [g_m, h_{m'}] t`` of
        the commutator formula on the standard words ``t`` of the window,
        intermediate degrees in ``[0, n]``.

        TESTS:

        The universal Virasoro algebra satisfies the Jacobi identity: no
        defects::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._defects(Z._store)
            []
        """
        P, n, N = self._P, self._level, self._N
        out = []
        for d in range(n + 1):
            e = store.get(d)
            piv = set(e.pivots()) if e is not None else set()
            for t in self._window_keys(d, N):
                if t in piv:
                    continue
                ft = self._filt(t)
                for i, hi in enumerate(self._h):
                    for j, hj in enumerate(self._h):
                        if ft + hi + hj > N:
                            continue
                        s = -1 if (self._odd[i] and self._odd[j]) else 1
                        for mj in range(d - n, d + 1):
                            for mi in range(d - mj - n, d - mj + 1):
                                if not 0 <= d - mi <= n:
                                    continue
                                z = self._act(i, mi, P._gen_act(j, mj, t))
                                _add_scaled(z, self._act(j, mj, P._gen_act(i, mi, t)), -s)
                                _add_scaled(z, P._commutator_on(i, mi, (j, mj), t), -1)
                                if z:
                                    out.append(z)
        return out

    def _nf(self, z):
        """
        The normal form of a dict of words of degree ``n`` (filtration
        ``<= N``, else ``ValueError``).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: Z._nf({((0, 0), (0, 0)): 1})
            {((0, -1), (0, 1)): -2, ((0, 0),): -1/5}
            sage: Z._nf({((0, 0),) * 6: 1})
            Traceback (most recent call last):
            ...
            ValueError: a word of filtration 12 > the degree bound 10: increase degree_bound
        """
        z = {k: c for k, c in z.items() if c}
        if not z:
            return {}
        f = max(self._filt(k) for k in z)
        if f > self._N:
            raise ValueError('a word of filtration {} > the degree bound {}: increase '
                             'degree_bound'.format(f, self._N))
        e = self._store.get(self._level)
        return dict(e.normal_form(z)) if e is not None else z

    def _nf_many(self, zs):
        """
        ``[self._nf(z) for z in zs]``, reduced in one batch
        (:meth:`~vertex_algebras._keyed_spans.KeyedSpan.reduce_many`).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Z = (V / [L.no(L) - 3/10*L.derivative(2)]).zhu_algebra_up_to(6, level=1)
            sage: zs = [{((0, 0), (0, 0)): 1}, {((0, 0),): 2}, {}]
            sage: Z._nf_many(zs) == [Z._nf(z) for z in zs]
            True
        """
        zs = [{k: c for k, c in z.items() if c} for z in zs]
        for z in zs:
            f = max((self._filt(k) for k in z), default=-1)
            if f > self._N:
                raise ValueError('a word of filtration {} > the degree bound {}: increase '
                                 'degree_bound'.format(f, self._N))
        e = self._store.get(self._level)
        return [dict(r) for r in e.reduce_many(zs)] if e is not None else zs

