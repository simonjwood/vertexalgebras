        from .vertex_algebra_categories import _is_proto
        if not getattr(V, '_is_universal_vertex_algebra', False):
            raise NotImplementedError(
                'higher level Zhu algebras are implemented for universal '
                'vertex algebras, not for {}'.format(V))
