def _w_algebra(g, f, x, R, k, names, implementation, algorithm, store=None):
    """The W-algebra (degrees, no conformal vector); see :func:`WAlgebra`.
    With ``algorithm='miura'`` and a dict ``store``, ``store['miura']`` is
    set to ``(M, images)``: the free field algebra and the images of the
    generators (a dict by name).

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _prepare, _w_algebra
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
        sage: f, x, R, k = _prepare(QQ, g, 'principal', 1/3, None)
        sage: W = _w_algebra(g, f, x, R, k, ['L'], None, 'miura'); W.degrees()
        {'L': 2}
        sage: W.gen('L').ope(W.gen('L'))
        [-7/3*dL, -14/3*L, 0, -175/18]
        sage: _w_algebra(g, f, x, R, k, ['L'], None, 'complex') is W
        True
    """
    C, d, gens, Jname, low, Sh = _complex(g, f, x, R, k, implementation)
    S = C.subalgebra(gens)                                  # C^-_0 (closure)
    Ker = ZeroModeKernel(S, [d])
    gr = g.ad_eigenvalues(x)
    cent = g.centralizer_basis(f, x)
    wt = [1 - gr[v.leading_support()] for v in cent]
    found = [Ker.lift(G) for G in Ker.strong_generators_up_to(max(wt))]
    if sorted(Ker._weight_of(G, 'a generator') for G in found) != sorted(wt):
        raise RuntimeError('the strong generators found, of weights {}, do not '
                           'match the centraliser'.format(
                               [Ker._weight_of(G, '') for G in found]))
    # the generators matched to the centraliser basis: linear part v modulo
    # im(ad e) (the Dynkin grading: g = g^f ⊕ [e, g])
    e = g.sl2_triple(f)[0]
    Bg = g.basis()
    Cn = C.variable_names()
    current = {Cn.index(Jname[a]): a for a in Bg.keys()}

    position = {a: i for i, a in enumerate(Bg.keys())}

    def linear(G):
        """The coordinates (over ``R``) of the currents ``J^a`` in ``G``."""
        v = [R.zero()] * len(position)
        for m, c in G.monomial_coefficients().items():
            if len(m) == 1 and m[0][1] == 0 and m[0][0] in current:
                v[position[current[m[0][0]]]] += c
        return vector(R, v)
    ordered, gnames, gweights = [], [], []
    for h in sorted(set(wt)):
        Gs = [G for G in found if Ker._weight_of(G, '') == h]
        vs = [v for v, w in zip(cent, wt) if w == h]
        lowk = [b for b in Bg.keys() if gr[b] == 1 - h - 1]
        comp = [e.bracket(Bg[b]) for b in lowk]
        basis = matrix(R, [u.to_vector() for u in vs + comp])
        try:
            P = matrix(R, [basis.solve_left(linear(G))[:len(vs)] for G in Gs])
            Q = P.inverse()
        except (ValueError, ZeroDivisionError):
            Q = None
        if Q is None:
            ordered += Gs
            gnames += ['W%d' % (len(gnames) + i) for i in range(len(Gs))]
        else:
            ordered += [sum((Q[r, i] * G for i, G in enumerate(Gs)), C.zero())
                        for r in range(len(vs))]
            gnames += ['J{%s}' % v for v in vs]
        gweights += [h] * len(Gs)
    if names is not None:
        names = [str(s) for s in names]
        if len(names) != len(gnames):
            raise ValueError('{} names expected'.format(len(gnames)))
        gnames = names
    if algorithm == 'miura':
        M, pi = _miura(g, gr, R, S, gens, low, Sh, implementation)
        ordered = [pi(G) for G in ordered]
        SW = M.subalgebra(ordered)
    else:
        SW = C.subalgebra(ordered)
    if len(SW.strong_generators()) != len(ordered):
        raise RuntimeError('the generators of W are not closed under OPEs')

    def expr(v):
        out = {}
        for word, c in SW.express(v).monomial_coefficients().items():
            out[tuple((gnames[i], n) for i, n in word)] = c
        return out
    opes = {}
    for i, G in enumerate(ordered):
        for j in range(i, len(ordered)):
            poles = [expr(p) for p in G.ope(ordered[j])]
            if poles:
                opes[(gnames[i], gnames[j])] = poles
    parities = {s: G.parity() for s, G in zip(gnames, ordered)}
    weights = dict(zip(gnames, gweights))
    if store is not None and algorithm == 'miura':
        store['miura'] = (M, dict(zip(gnames, ordered)))
    return UniversalVertexAlgebra(R, gnames, opes, parities=parities,
                                  degrees=weights, implementation=implementation)
