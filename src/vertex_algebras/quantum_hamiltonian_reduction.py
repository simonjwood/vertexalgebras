r"""
Quantum Hamiltonian reduction: W-algebras.

The W-algebra ``W^k(g, f)`` of a basic Lie superalgebra ``g`` (a
:class:`lie_superalgebras.LieSuperalgebra`, with its normalised form) at
level ``k``, for an even nilpotent ``f`` and a good grading ``x``, as
defined by Kac--Roan--Wakimoto [KRW2003]_ and Kac--Wakimoto [KW2004]_
(with its corrigendum, Adv. Math. 193 (2005)):
``W^k(g, f) = H(C, d_0)`` for the complex ``C = V^k(g) ⊗ F(A_ch) ⊗
F(A_ne)``, a universal vertex algebra here:

- the currents ``J^a`` (``a`` in the basis of ``g``), ``[J^a λ J^b] =
  J^{[a,b]} + λ k (a|b)``;
- the charged ghosts ``φ_α``, ``φ^α`` (``u_α`` the basis vectors of ``g_+ =
  ⊕_{j>0} g_j``) of the opposite parity, ``[φ_α λ φ^β] = δ_{αβ}``;
- the neutral free superfermions ``Φ_α`` (``u_α ∈ g_{1/2}``), ``[Φ_α λ
  Φ_β] = (f|[u_α, u_β])``;
- the conformal weights ``1 - j`` (``J^a``, ``φ_α`` for ``a``, ``u_α ∈
  g_j``), ``j`` (``φ^α``), ``1/2`` (``Φ_α``);
- ``d_0 = d_(0)`` with ``d = Σ_α (-1)^{p(α)} :J^{u_α} φ^α: - 1/2
  Σ_{α,β,γ} (-1)^{p(α)p(γ)} c^γ_{αβ} :φ_γ φ^α φ^β: + Σ_α (f|u_α) φ^α +
  Σ_{α ∈ S_{1/2}} :φ^α Φ_α:`` (``[u_α, u_β] = Σ_γ c^γ_{αβ} u_γ``).

By [KRW2003]_, Theorem 4.1 (proof corrected in the corrigendum) the cohomology
is that of ``C^-``, generated by the dressed currents ``J^{(a)} = J^a +
Σ_{α,β} (-1)^{p(α)} c^α_{aβ} :φ_α φ^β:`` (``a ∈ g_{<=0}``, ``c^α_{aβ}`` the
coefficient of ``u_α`` in ``[a, u_β]``), the ``φ^α`` and the ``Φ_α``.  It
has no negative charge, so ``W`` consists of the ``d_0``-closed elements
of charge 0 (as Kac--Wakimoto remark in the corrigendum): the kernel of
``d_0`` on the subalgebra ``C^-_0`` generated by the ``J^{(a)}`` and the
``Φ_α``, whose generators all have positive weight.  So ``W`` is computed
weight space by weight space (:class:`ZeroModeKernel`).  It is freely
generated by fields ``J^{(v)}``, ``v`` in a basis of the centraliser ``g^f``,
``J^{(v)}`` of weight ``1 + j`` for ``v ∈ g_{-j}`` ([DSK2006]_); their
OPEs, written in them, give ``W`` as a
:class:`universal_vertex_algebra.UniversalVertexAlgebra`, with the
conformal vector of weight 2 acting as ``∂`` and as the weights on the
generators.

EXAMPLES:

The Virasoro algebra from ``sl_2``::

    sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
    sage: from vertex_algebras.quantum_hamiltonian_reduction import WAlgebra
    sage: K.<k> = Frac(QQ['k'])
    sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
    sage: W = WAlgebra(K, g, 'principal', k, conformal_vector='reduction'); W
    Universal vertex algebra on generators ['J{E[-alpha[1]]}'] over Fraction Field of Univariate Polynomial Ring in k over Rational Field
    sage: W.central_charge() == 1 - 6*(k + 1)^2/(k + 2)
    True

The ``N = 2`` superconformal algebra from ``sl(2|1)``::

    sage: N2 = WAlgebra(K, LieSuperalgebra(QQ, 'sl(2|1)'), 'minimal', k, conformal_vector='reduction')
    sage: N2.degrees()
    {'J{E[-alpha[1] - alpha[2]]}': 3/2,
     'J{E[-alpha[1]]}': 2,
     'J{E[alpha[2]]}': 3/2,
     'J{h1 + 2*h2}': 1}
    sage: N2.central_charge() == -3*(2*k + 1)
    True

AUTHORS:

- Christopher Raymond, Simon Wood (2026): initial version
"""

