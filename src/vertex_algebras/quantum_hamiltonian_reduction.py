class ZeroModeKernel(CommutantVertexAlgebra):
    r"""
    The kernel of the zero modes ``d_(0)`` of elements ``d`` of the root
    algebra on a vertex (sub)algebra ``ambient``: a vertex subalgebra, since
    ``d_(0)`` is a derivation of all products.  Weight spaces, strong
    generators (:meth:`strong_generators_up_to`) and ``express`` work as for
    commutants (it is one, of the zero modes only).

    INPUT:

    - ``ambient`` -- a vertex algebra with conformal weights, or a vertex
      subalgebra of one (e.g. ``C^-_0``)

    - ``gens`` -- elements ``d`` of the root algebra of ``ambient`` whose
      zero modes ``d_(0)`` are taken (zero and repeated ones dropped)

    - ``horizontal_grading`` -- (default: ``None``) ``None`` or
      ``'ambient'``, as for :class:`~commutant_vertex_algebra.CommutantVertexAlgebra`

    EXAMPLES::

        sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
        sage: H = UniversalVertexAlgebra(QQ, ['J', 'K'], {('J', 'J'): [0, 1], ('K', 'K'): [0, 1]},
        ....:                            degrees={'J': 1, 'K': 1})
        sage: J, K = H.gens()
        sage: Z = ZeroModeKernel(H, [J]); Z
        Kernel of the zero modes of [J] on Universal vertex algebra on generators ['J', 'K'] over Rational Field
        sage: [Z.weight_space(n).dimension() for n in range(5)]
        [1, 2, 5, 10, 20]
        sage: J in Z, J.no(J) in Z
        (True, True)
        sage: loads(dumps(Z)) is Z
        True
    """
    _modes = (0,)

    @staticmethod
    def __classcall_private__(cls, ambient, gens, horizontal_grading=None):
        """
        The key: the ambient, the nonzero distinct ``gens`` (as elements of
        the root), the grading option.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: ZeroModeKernel(H, [H.gen('J'), 0, H.gen('J')]) is Z
            True
            sage: ZeroModeKernel(H, [], horizontal_grading='x')
            Traceback (most recent call last):
            ...
            ValueError: grading must be None or 'ambient'
        """
        if not isinstance(ambient, VertexAlgebra):
            raise TypeError('{!r} is not a vertex algebra'.format(ambient))
        if horizontal_grading not in (None, 'ambient'):
            raise ValueError("grading must be None or 'ambient'")
        root = getattr(ambient, '_root', ambient)
        uniq = []
        for x in (root(x) for x in gens):
            if not x.is_zero() and x not in uniq:
                uniq.append(x)
        return VertexAlgebra.__classcall__(cls, ambient, tuple(uniq), horizontal_grading, None)

    def __reduce__(self):
        """
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: loads(dumps(Z)) is Z
            True
        """
        return (ZeroModeKernel, (self._ambient, self._acting_gens, self._grading_option))

    def _repr_(self):
        """
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: Z
            Kernel of the zero modes of [J] on Universal vertex algebra on generators ['J']
             over Rational Field
            sage: _ = Z.strong_generators_up_to(2); Z
            Kernel of the zero modes of [J] on Universal vertex algebra on generators ['J']
             over Rational Field; strong generators up to weight 2: ('C0',)
        """
        s = 'Kernel of the zero modes of {} on {}'.format(list(self._acting_gens),
                                                        self._ambient)
        if self._searched:
            s += '; strong generators up to weight {}: {}'.format(
                self._searched_repr(), self.variable_names())
        return s

    def _structure_key(self):
        """
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: Z._structure_key() == ('ZeroModeKernel', H, (H.gen('J'),), None)
            True
        """
        return ('ZeroModeKernel', self._ambient, self._acting_gens, self._grading_option)

    def _state_fingerprint(self):
        """
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: fp = Z._state_fingerprint(); fp[0], fp[1] == H._state_fingerprint()
            ('ZeroModeKernel', True)
        """
        return ('ZeroModeKernel', self._root._state_fingerprint(),
                tuple(a for a, _, _, _ in self._act))

    def _with(self, **changes):
        """
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: Z._with(degrees=None)
            Traceback (most recent call last):
            ...
            NotImplementedError: a kernel of zero modes has no conformal data of its own
        """
        raise NotImplementedError('a kernel of zero modes has no conformal data of '
                                  'its own')

    def _weights_up_to(self, W, G):
        """As for commutants; on a subalgebra whose strong generators all have
        positive weight (the root's weights may be unbounded below) the
        weights ``0, 1/D, ..., W``.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: Z = ZeroModeKernel(H, H.gens())
            sage: Z._weights_up_to(2, None)
            [0, 1, 2]
        """
        try:
            return CommutantVertexAlgebra._weights_up_to(self, W, G)
        except ValueError:
            A = self._ambient
            if G is not None or not hasattr(A, 'strong_generators'):
                raise
            hs = [QQ(x.degree()) for x in A.strong_generators()]
            if not hs or any(h <= 0 for h in hs):
                raise
        from sage.arith.functions import lcm
        D = lcm([h.denominator() for h in hs])
        return [QQ(n) / D for n in range((QQ(W) * D).floor() + 1)]

    def acting_subalgebra(self):
        """
        Not available: the zero modes of the acting elements do not act as
        a subalgebra (unlike for commutants).

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ZeroModeKernel
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: ZeroModeKernel(H, H.gens()).acting_subalgebra()
            Traceback (most recent call last):
            ...
            NotImplementedError: the zero modes of the acting elements do not act as a subalgebra
        """
        raise NotImplementedError('the zero modes of the acting elements do not act '
                                  'as a subalgebra')


def _is_partition(p):
    """
    Whether ``p`` is a Sage partition or a nonempty list or tuple of
    positive integers (a Jordan type); a false value otherwise.

    TESTS::

        sage: from vertex_algebras.quantum_hamiltonian_reduction import _is_partition
        sage: [bool(_is_partition(p)) for p in [[2, 1], Partition([2]), [], 'minimal', [0]]]
        [True, True, False, False, False]
    """
    from sage.combinat.partition import Partition
    return isinstance(p, Partition) or (
        isinstance(p, (list, tuple)) and p and all(x in ZZ and x > 0 for x in p))


def _nilpotent(g, f):
    """``f`` given as ``'minimal'``, ``'principal'``, a Jordan type (a
    partition, or a pair of partitions whose sizes are the numbers in the
    name of ``g``), a list of positive roots (``f`` the sum of their
    negative root vectors) or an element; returns the element of ``g``.

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _nilpotent
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 2]))
        sage: [_nilpotent(g, f) for f in ['minimal', 'principal', [2, 1], [(1, 0)]]]
        [E[-alpha[1] - alpha[2]], E[-alpha[1]] + E[-alpha[2]], E[-alpha[1]], E[-alpha[1]]]
        sage: _nilpotent(g, 'regular')
        Traceback (most recent call last):
        ...
        ValueError: f: 'minimal', 'principal', a partition, a list of roots or an element
    """
    if isinstance(f, str):
        if f == 'minimal':
            return g.minimal_nilpotent()
        if f == 'principal':
            return g.principal_nilpotent()
        raise ValueError("f: 'minimal', 'principal', a partition, a list of roots or "
                         "an element")
    if _is_partition(f):
        return g.nilpotent_of_jordan_type(f)
    if isinstance(f, (list, tuple)):
        data = g._natural_data()
        if (len(f) == 2 and all(_is_partition(p) for p in f) and data is not None
                and [sum(p) for p in f] == [size for _, _, size in data[2]]):
            return g.nilpotent_of_jordan_type(*f)
        return sum((g.root_vector(tuple(b), -1) for b in f), g.zero())
    return g(f)


def _complex(g, f, x, R, k, implementation):
    r"""
    The complex: ``(C, d, generators of C^-_0, names)`` with ``C`` the
    universal vertex algebra of the currents ``J{a}``, the charged ghosts
    ``phi{a}``, ``phi*{a}`` (``a ∈ g_+``) and the neutral fermions
    ``Phi{a}`` (``a ∈ g_{1/2}``); also returned: ``J`` (``a -> J{a}``),
    the basis keys ``low`` of ``g_{<=0}`` (the dressed currents among the
    generators) and ``Sh`` those of ``g_{1/2}``.

    TESTS:

    ``sl_2``, principal: the complex of the Virasoro algebra::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _prepare, _complex
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
        sage: f, x, R, k = _prepare(QQ, g, 'principal', 1/3, None)
        sage: C, d, gens, J, low, Sh = _complex(g, f, x, R, k, None)
        sage: C.variable_names()
        ('J{E[alpha[1]]}', 'J{h1}', 'J{E[-alpha[1]]}', 'phi{E[alpha[1]]}', 'phi*{E[alpha[1]]}')
        sage: d, d.nproduct(d, 0)
        (:J{E[alpha[1]]} phi*{E[alpha[1]]}: + phi*{E[alpha[1]]}, 0)
        sage: gens, low, Sh
        ([J{h1} + 2*:phi{E[alpha[1]]} phi*{E[alpha[1]]}:, J{E[-alpha[1]]}], ['h1', 'E[-alpha[1]]'], [])
    """
    gr = g.ad_eigenvalues(x)
    B = g.basis()
    keys = list(B.keys())
    par = {a: B[a].is_even_odd() for a in keys}
    sc = g.structure_coefficients()
    half = QQ((1, 2))
    Sp = [a for a in keys if gr[a] > 0]
    Sh = [a for a in keys if gr[a] == half]
    J = {a: 'J{%s}' % a for a in keys}
    ph = {a: 'phi{%s}' % a for a in Sp}
    phs = {a: 'phi*{%s}' % a for a in Sp}
    Ph = {a: 'Phi{%s}' % a for a in Sh}
    names = ([J[a] for a in keys] + [ph[a] for a in Sp] + [phs[a] for a in Sp]
             + [Ph[a] for a in Sh])
    parity = {J[a]: par[a] for a in keys}
    parity.update({ph[a]: 1 - par[a] for a in Sp})
    parity.update({phs[a]: 1 - par[a] for a in Sp})
    parity.update({Ph[a]: par[a] for a in Sh})
    E = NormallyOrderedExpressions(R, names, {s: p for s, p in parity.items() if p})
    gen = dict(zip(names, E.gens()))
    opes = {}
    for i, a in enumerate(keys):
        for b in keys[i:]:
            br = sum((R(c) * gen[J[cc]] for cc, c in sc.get((a, b), {}).items()), E.zero())
            poles = [br, k * R(g.invariant_form(B[a], B[b]))]
            while poles and not poles[-1]:
                poles.pop()
            if poles:
                opes[(J[a], J[b])] = poles
    for a in Sp:
        opes[(ph[a], phs[a])] = [1]
    for i, a in enumerate(Sh):
        for b in Sh[i:]:
            v = R(g.invariant_form(f, B[a].bracket(B[b])))
            if v:
                opes[(Ph[a], Ph[b])] = [v]
    w = {J[a]: 1 - gr[a] for a in keys}
    w.update({ph[a]: 1 - gr[a] for a in Sp})
    w.update({phs[a]: gr[a] for a in Sp})
    w.update({Ph[a]: half for a in Sh})
    C = UniversalVertexAlgebra(R, E, opes, degrees=w,
                               implementation=implementation)
    d = E.zero()
    for a in Sp:
        d += (-1) ** par[a] * gen[J[a]] * gen[phs[a]]
    for al in Sp:
        for be in Sp:
            for ga, c in sc.get((al, be), {}).items():
                if ga in ph:
                    d -= (R(c) / 2 * (-1) ** (par[al] * par[ga])
                          * gen[ph[ga]] * gen[phs[al]] * gen[phs[be]])
    for a in Sp:
        v = R(g.invariant_form(f, B[a]))
        if v:
            d += v * gen[phs[a]]
    for a in Sh:
        d += gen[phs[a]] * gen[Ph[a]]

    def dressed(a):
        out = gen[J[a]]
        for be in Sp:
            for al, c in sc.get((a, be), {}).items():
                if al in ph:
                    out += (-1) ** par[al] * R(c) * gen[ph[al]] * gen[phs[be]]
        return out
    low = [a for a in keys if gr[a] <= 0]
    gens = [C(dressed(a)) for a in low] + [C(gen[Ph[a]]) for a in Sh]
    return C, C(d), gens, J, low, Sh


def _miura(g, gr, R, S, gens, low, Sh, implementation):
    r"""
    The free field algebra ``M = V^τ(g_0) ⊗ F(g_{1/2})`` and the Miura map
    ``π: C^-_0 -> M`` ([KW2004]_): on the normally ordered monomials of
    the generators of ``C^-_0`` (``S``), ``J^{(a)} ↦ J{a}`` for ``a ∈ g_0``,
    ``J^{(a)} ↦ 0`` for ``a ∈ g_{<0}``, ``Φ_a ↦ Phi{a}``; restricted to
    ``W`` an injective vertex algebra homomorphism, so the OPEs of the
    generators of ``W`` can be computed in ``M``.  The OPEs of ``M`` are the
    images of those of the generators in ``C``.  Returns ``(M, π)`` with
    ``π`` mapping an element of ``C^-_0`` (given in ``C``) to ``M``.

    TESTS:

    ``sl_2``: ``M`` is the Heisenberg algebra of ``J{h1}``, the dressed
    ``J^{(f)}`` goes to 0::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _prepare, _complex
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
        sage: f, x, R, k = _prepare(QQ, g, 'principal', 1/3, None)
        sage: C, d, gens, J, low, Sh = _complex(g, f, x, R, k, None)
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _miura
        sage: S = C.subalgebra(gens)
        sage: M, pi = _miura(g, g.ad_eigenvalues(x), R, S, gens, low, Sh, None)
        sage: M, M.gen(0).ope(M.gen(0))
        (Universal vertex algebra on generators ['J{h1}'] over Rational Field, [0, 14/3])
        sage: pi(gens[0]), pi(gens[1])
        (J{h1}, 0)
    """
    if len(S.strong_generators()) != len(gens):
        raise RuntimeError('C^-_0 is not generated by the dressed currents and '
                           'the neutral fermions')
    B = g.basis()
    given = []                          # given generator -> name in M or None
    for a in low:
        given.append('J{%s}' % a if gr[a] == 0 else None)
    given += ['Phi{%s}' % a for a in Sh]
    # S keeps its strong generators in its own order (by weight)
    target = []                         # strong generator of S -> name in M or None
    for sg in S.strong_generators():
        hits = [i for i, G in enumerate(gens) if S.lift(sg) == G]
        if len(hits) != 1:
            raise RuntimeError('a strong generator of C^-_0 is not a given one')
        target.append(given[hits[0]])
    # M's generators: the lowering currents of g_0, the Cartan ones, the
    # raising ones (simple-root coordinates), then the neutral fermions; so
    # the ordered monomials of M's Zhu algebra read lowering · Cartan ·
    # raising (see ``_top_values``)
    side = {}
    for a in low:
        if gr[a] == 0:
            beta = g.root_on_basis(a)
            side['J{%s}' % a] = (1 if not any(beta) else
                                 0 if all(c <= 0 for c in beta) else 2)
    names = sorted((t for t in given if t is not None), key=lambda t: side.get(t, 3))
    par = {}
    for a in low:
        if gr[a] == 0:
            par['J{%s}' % a] = B[a].is_even_odd()
    for a in Sh:
        par['Phi{%s}' % a] = B[a].is_even_odd()
    E = NormallyOrderedExpressions(R, names, {t: p for t, p in par.items() if p})
    letter = dict(zip(names, E.gens()))

    def image(x):
        """π(x) as an expression of ``E``."""
        out = E.zero()
        for word, c in S.express(x).monomial_coefficients().items():
            factors = []
            for i, n in word:
                t = target[i]
                if t is None:               # J^{(a)}, a ∈ g_{<0}: killed
                    break
                factors.append(letter[t].derivative(n) if n else letter[t])
            else:
                out += c * _product(factors) if factors else E.term((), c)
        return out
    idx = [i for i, t in enumerate(given) if t is not None]
    opes = {}
    for a, i in enumerate(idx):
        for j in idx[a:]:
            poles = [image(p) for p in gens[i].ope(gens[j])]
            while poles and poles[-1].is_zero():
                poles.pop()
            if poles:
                opes[(given[i], given[j])] = poles
    w = {t: (QQ(1) if t.startswith('J{') else QQ((1, 2))) for t in names}
    M = UniversalVertexAlgebra(R, E, opes, degrees=w,
                               implementation=implementation)
    return M, (lambda x: M(image(x)))


def _product(factors):
    """The right-nested normally ordered product of expressions (a
    nonempty list).

    TESTS::

        sage: from vertex_algebras.quantum_hamiltonian_reduction import _product
        sage: from vertex_algebras import NormallyOrderedExpressions
        sage: E.<a, b> = NormallyOrderedExpressions(QQ)
        sage: _product([a, b, a]), _product([b])
        (:a b a:, b)
    """
    out = factors[-1]
    for y in reversed(factors[:-1]):
        out = y * out
    return out


def _conformal_vector(W, gens, weights):
    """The element ``T`` of weight 2 with ``T_(0) G = ∂G`` and ``T_(1) G =
    h_G G`` for the generators ``G`` (``None`` if there is none;
    ``NotImplementedError`` if it is not unique).

    TESTS:

    The Virasoro algebra of the ``sl_2`` reduction, and a Heisenberg algebra
    (``T = 1/2 :JJ: + a ∂J`` for every ``a``)::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import WAlgebra, _conformal_vector
        sage: W = WAlgebra(QQ, LieSuperalgebra(QQ, CartanMatrix(['A', 1])), 'principal', 1/3,
        ....:              names=['L'])
        sage: T = _conformal_vector(W, W.gens(), [2]); T, T.ope(T)
        (-3/7*L, [-3/7*dL, -6/7*L, 0, -25/14])
        sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
        sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
        sage: _conformal_vector(H, H.gens(), [1])
        Traceback (most recent call last):
        ...
        NotImplementedError: the conformal vector of the reduction is not determined by its
        action on the generators of ...
    """
    R = W.base_ring()
    try:
        keys = list(W.weight_space(2).basis_keys())
    except (ValueError, NotImplementedError):
        return None
    if not keys:
        return None
    rows, rhs = [], []
    for G, h in zip(gens, weights):
        for n, target in ((0, G.derivative()), (1, h * G)):
            acts = [W.monomial(m).nproduct(G, n).monomial_coefficients() for m in keys]
            tgt = target.monomial_coefficients()
            for kk in sorted(set(tgt).union(*[set(a) for a in acts]), key=str):
                rows.append([a.get(kk, 0) for a in acts])
                rhs.append(tgt.get(kk, 0))
    A = matrix(R, rows)
    try:
        t = A.solve_right(matrix(R, len(rhs), 1, rhs)).column(0)
    except ValueError:
        return None
    if A.right_nullity():
        raise NotImplementedError('the conformal vector of the reduction is not '
                                  'determined by its action on the generators of {}'.format(W))
    return sum((c * W.monomial(m) for c, m in zip(t, keys) if c), W.zero())


_CACHE = {}

_MIURA = {}         # key of the W-algebra (without algorithm) -> (M, images)


def _miura_data(g, f, x, R, k, names=None, implementation=None):
    r"""
    The W-algebra ``W`` (without conformal vector), the free field algebra
    ``M = V^τ(g_0) ⊗ F(g_{1/2})`` of the Miura map and the images
    ``π(G)`` of the generators of ``W`` in ``M`` (a dict by name), for the
    data normalised by ``_prepare``.

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _prepare, _miura_data
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
        sage: f, x, R, k = _prepare(QQ, g, 'principal', 1/3, None)
        sage: W, M, images = _miura_data(g, f, x, R, k)
        sage: images
        {'J{E[-alpha[1]]}': -1/4*:J{h1} J{h1}: - 2/3*dJ{h1}}
        sage: _miura_data(g, f, x, R, k)[0] is W
        True
    """
    key = (g, tuple(sorted(f.monomial_coefficients().items())),
           tuple(sorted(x.monomial_coefficients().items())), R, k,
           None if names is None else tuple(names), implementation)
    data = _MIURA.get(key)
    if data is None:
        store = {}
        W = _w_algebra(g, f, x, R, k, names, implementation, 'miura', store)
        _CACHE.setdefault(key + ('miura',), W)
        data = _MIURA[key] = (W,) + store['miura']
    return data


def _prepare(base_ring, g, f, level, x):
    """``(f, x, R, k)``, checked: the nilpotent (:func:`_nilpotent`), the
    good grading in the Cartan subalgebra (default the Dynkin grading), the
    base ring and the level in it.

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _prepare
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
        sage: _prepare(QQ, g, 'principal', 1/3, None)
        (E[-alpha[1]], 1/2*h1, Rational Field, 1/3)
        sage: _prepare(QQ, g, 'principal', 1/3, g.h(1))
        Traceback (most recent call last):
        ...
        ValueError: h1 is not a good grading for E[-alpha[1]]
    """
    R = base_ring
    k = R(level)
    f = _nilpotent(g, f)
    g._check_even_nilpotent(f)
    x = g.dynkin_grading(f) if x is None else g(x)
    if not g.is_in_cartan(x):
        raise NotImplementedError('the grading x must lie in the Cartan subalgebra: '
                                  'give f as a sum of root vectors, or x')
    if not g.is_good_grading(x, f):
        raise ValueError('{} is not a good grading for {}'.format(x, f))
    return f, x, R, k


class ReductionComplex:
    r"""
    The complex of the quantum Hamiltonian reduction of ``V^k(g)`` by ``f``
    ([KRW2003]_; the ``C^-_0`` of [KW2004]_), returned by
    :meth:`affine_vertex_algebra.UniversalAffineVertexAlgebra.quantum_hamiltonian_reduction_complex`:

    - :meth:`vertex_algebra` -- ``C = V^k(g) ⊗ F^ch ⊗ F^ne`` as one universal
      vertex algebra on ``J{a}``, ``phi{a}``, ``phi*{a}``, ``Phi{a}``
    - :meth:`differential` -- ``d`` (``d_(0)`` is the differential)
    - :meth:`subalgebra` -- ``C^-_0``, generated by the dressed currents
      ``J^{(a)}``, ``a ∈ g_{<=0}``, and the ``Φ``'s
    - :meth:`kernel` -- the kernel of ``d_(0)`` on ``C^-_0``, which is the
      W-algebra ([KW2004]_), as a vertex algebra inside ``C``

    INPUT:

    - ``V`` -- the universal affine vertex algebra ``V^k(g)``

    - ``f`` -- the nilpotent element of ``g``

    - ``C`` -- the vertex algebra of the complex

    - ``d`` -- the element of ``C`` whose zero mode is the differential

    - ``S`` -- the subalgebra ``C^-_0`` of ``C``

    - ``K`` -- the kernel of ``d_(0)`` on ``S`` (a :class:`ZeroModeKernel`)

    The arguments are stored as given (they are computed by
    :meth:`~affine_vertex_algebra.UniversalAffineVertexAlgebra.quantum_hamiltonian_reduction_complex`).

    EXAMPLES::

        sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
        sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
        sage: Q = V.quantum_hamiltonian_reduction_complex('principal'); Q
        Complex of the quantum Hamiltonian reduction of Universal affine vertex algebra of type ['A', 1] at level 1/3 over Rational Field by E[-alpha[1]]
        sage: Q.vertex_algebra().variable_names()
        ('J{E[alpha[1]]}',
         'J{h1}',
         'J{E[-alpha[1]]}',
         'phi{E[alpha[1]]}',
         'phi*{E[alpha[1]]}')
        sage: d = Q.differential(); d, d.nproduct(d, 0)
        (:J{E[alpha[1]]} phi*{E[alpha[1]]}: + phi*{E[alpha[1]]}, 0)
        sage: [Q.kernel().weight_space(n).dimension() for n in range(6)]       # Virasoro
        [1, 0, 1, 1, 2, 2]
        sage: Q.subalgebra() is Q.kernel().ambient()
        True
    """

    def __init__(self, V, f, C, d, S, K):
        """
        TESTS::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: from vertex_algebras.quantum_hamiltonian_reduction import ReductionComplex
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: R = ReductionComplex(V, Q.nilpotent(), Q.vertex_algebra(), Q.differential(),
            ....:                      Q.subalgebra(), Q.kernel())
            sage: R.affine_vertex_algebra() is V, R.kernel() is Q.kernel(), R.differential() == Q.differential()
            (True, True, True)
        """
        self._V, self._f = V, f
        self._C, self._d, self._S, self._K = C, d, S, K

    def __repr__(self):
        """
        TESTS::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: repr(V.quantum_hamiltonian_reduction_complex('principal'))
            "Complex of the quantum Hamiltonian reduction of Universal affine vertex algebra
             of type ['A', 1] at level 1/3 over Rational Field by E[-alpha[1]]"
        """
        return 'Complex of the quantum Hamiltonian reduction of {} by {}'.format(
            self._V, self._f)

    def affine_vertex_algebra(self):
        """
        The affine vertex algebra ``V^k(g)`` reduced.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: Q.affine_vertex_algebra() is V
            True
        """
        return self._V

    def nilpotent(self):
        """
        The nilpotent element ``f``.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: Q.nilpotent()
            E[-alpha[1]]
        """
        return self._f

    def vertex_algebra(self):
        """
        The vertex algebra ``C`` of the complex.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: C = Q.vertex_algebra(); C.degrees()
            {'J{E[-alpha[1]]}': 2,
             'J{E[alpha[1]]}': 0,
             'J{h1}': 1,
             'phi*{E[alpha[1]]}': 1,
             'phi{E[alpha[1]]}': 0}
        """
        return self._C

    def differential(self):
        """
        The element ``d`` of ``C`` whose zero mode is the differential.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: d = Q.differential(); d
            :J{E[alpha[1]]} phi*{E[alpha[1]]}: + phi*{E[alpha[1]]}
            sage: d.nproduct(d, 0)
            0
        """
        return self._d

    def subalgebra(self):
        """
        The subalgebra ``C^-_0`` of ``C`` (generated by the dressed currents
        ``J^{(a)}``, ``a ∈ g_{<=0}``, and the ``Φ``'s).

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: S = Q.subalgebra(); S.ambient() is Q.vertex_algebra()
            True
            sage: len(S.strong_generators())
            2
        """
        return self._S

    def kernel(self):
        """
        The kernel of ``d_(0)`` on ``C^-_0`` (the W-algebra, inside ``C``): a
        :class:`ZeroModeKernel`.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1/3)
            sage: Q = V.quantum_hamiltonian_reduction_complex('principal')
            sage: Z = Q.kernel(); Z.ambient() is Q.subalgebra()
            True
            sage: [Z.weight_space(n).dimension() for n in range(6)]       # Virasoro
            [1, 0, 1, 1, 2, 2]
        """
        return self._K


def _reduction_complex(base_ring, g, f, level, x=None, implementation=None):
    """``(f, C, d, C^-_0, kernel)``: see :class:`ReductionComplex`.

    TESTS::

        sage: from vertex_algebras.lie_superalgebras import LieSuperalgebra
        sage: from vertex_algebras.quantum_hamiltonian_reduction import _reduction_complex
        sage: g = LieSuperalgebra(QQ, CartanMatrix(['A', 1]))
        sage: f, C, d, S, K = _reduction_complex(QQ, g, 'principal', 1/3)
        sage: f, K.ambient() is S, [K.weight_space(n).dimension() for n in range(4)]
        (E[-alpha[1]], True, [1, 0, 1, 1])
    """
    f, x, R, k = _prepare(base_ring, g, f, level, x)
    C, d, gens, _, _, _ = _complex(g, f, x, R, k, implementation)
    S = C.subalgebra(gens)
    return f, C, d, S, ZeroModeKernel(S, [d])


