    def _evaluate_expression(self, e):
        """The element denoted by ``e`` (in :meth:`normally_ordered_expressions`,
        or in normally ordered expressions in some of the strong
        generators' names).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: X = S.normally_ordered_expressions(); x = X.gen(0)
            sage: S._evaluate_expression(x*x - x.derivative(2)) == L.no(L) - L.derivative(2)
            True
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: S._evaluate_expression(NormallyOrderedExpressions(QQ, ['M']).gen(0))
            Traceback (most recent call last):
            ...
            TypeError: M is not an expression in the strong generators of ...
        """
        names = self.variable_names()
        E = e.parent()
        try:
            idx = [names.index(n) for n in E.variable_names()]
        except ValueError:
            raise TypeError('{} is not an expression in the strong generators of {}'
                            .format(e, self))
        out = {}
        for w, c in e.monomial_coefficients().items():
            word = tuple((idx[i], n) for i, n in w)
            for k, a in self._vec(word).items():
                out[k] = out.get(k, 0) + c * a
        return self._el_from_dict({k: a for k, a in out.items() if a})

