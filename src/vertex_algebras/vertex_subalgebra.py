    def _fresh_name(self):
        """
        The first ``S<k>`` not among the strong generators' and the given names.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._fresh_name()
            'S0'
        """
        used = set(self.variable_names()) | set(self._given_names or ())
        k = 0
        while 'S{}'.format(k) in used:
            k += 1
        return 'S{}'.format(k)

    @_gc_paused
    def _close(self, gens, names):
        """
        The closure (in ``__init__``): the given generators (by weight,
        redundant ones dropped), then rounds of OPEs of pairs involving a new
        strong generator; a product outside the span of the normally ordered
        monomials becomes a strong generator. :class:`StrongGenerationError`
        after ``max_closure_steps`` rounds that still added generators.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S.strong_generator_info()
            [('L', 2, 0, 'given')]
            sage: H.subalgebra([J.no(J)], max_closure_steps=0)
            Traceback (most recent call last):
            ...
            StrongGenerationError: no strong generating set found within 0 closure round(s) ...
        """
        V = self._root
        self._given_names = names
        graded = self._cgrading is not None
        items = []
        for k, a in enumerate(gens):
            x = V._el_from_dict(dict(a._monomial_coefficients))
            if x.is_zero():
                continue
            name = names[k] if names is not None else None
            h = self._weight_of(x, 'the generator')
            odd = self._parity_of(x, 'the generator')
            G = self._grade_of(x, 'the generator') if graded else None
            items.append((h, k, x, odd, name, G))
        items.sort(key=lambda t: (t[0], t[1]))
        for h, k, x, odd, name, G in items:
            if self._span(h, G).echelon.contains(
                    dict(x._monomial_coefficients)):
                continue                           # redundant (or vacuum)
            self._add_gen(x, h, odd, name or self._fresh_name(), 'given', G)
        new = set(range(len(self._gens)))
        for step in range(self._max_steps):
            if not new:
                return
            n0 = len(self._gens)
            prods = []
            for i in range(n0):
                for j in range(i, n0):
                    if i not in new and j not in new:
                        continue
                    gi, gj = self._gens[i], self._gens[j]
                    G = (self._cgrading['group'].add(self._gen_grades[i],
                                                     self._gen_grades[j])
                         if graded else None)
                    for n, y in enumerate(gi['el'].ope(gj['el'])):
                        if not y.is_zero():
                            prods.append((gi['h'] + gj['h'] - n - 1, i, j, n,
                                          y, G))
            prods.sort(key=lambda t: t[:4])
            new = set()
            for w, i, j, n, y, G in prods:
                if self._span(w, G).echelon.contains(
                        dict(y._monomial_coefficients)):
                    continue
                odd = (self._gens[i]['odd'] + self._gens[j]['odd']) % 2
                new.add(len(self._gens))
                self._add_gen(y, w, odd, self._fresh_name(), '{}_({}) {}'.format(
                    self._gens[i]['name'], n, self._gens[j]['name']), G)
        if not new:
            return
        n0 = len(self._gens)
        untested = sum(1 for i in range(n0) for j in range(i, n0)
                       if i in new or j in new)
        info = self.strong_generator_info()
        raise StrongGenerationError(
            'no strong generating set found within {} closure round(s) '
            '(the subalgebra may not be finitely strongly generated); '
            'strong generators so far: {}; {} pair(s) of generators untested; '
            'use a larger max_closure_steps'.format(
                self._max_steps,
                ', '.join('{} (weight {})'.format(s, h)
                          for s, h, _, _ in info), untested),
            info, untested)

