    _is_subspace_algebra = True

    def _init_subspace(self, ambient, horizontal_grading, what, conformal=False,
                       fsg=False):
        """Set up the ambient and root algebras, the weight data (those of
        the ambient algebra) and the grading option (``None`` or ``'ambient'``); ``what`` names
        the construction in error messages (e.g. ``'vertex
        subalgebras'``).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._ambient is H, S._root is H, S._wdata, S._cgrading
            (True, True, {'h': [1]}, None)
            sage: S.subalgebra([L.no(L)])._root is H
            True
        """
        self._ambient = ambient
        self._root = ambient._root if _is_subalgebra(ambient) else ambient
        V = self._root
        R = V.base_ring()
        if not R.is_field():
            raise ValueError('{} need a base field, not {}'.format(what, R))
        from .vertex_algebra_categories import _is_proto
        VertexAlgebra.__init__(self, R, V._indices,
                               category=self._category_for(
                                   R, V._has_odd(), True, conformal, fsg,
                                   proto=_is_proto(V)))
        try:
            self._wdata = ambient._weight_data()
        except ValueError as err:
            raise ValueError('{} need the conformal weights of the ambient '
                             'algebra: {}'.format(what, err))
        #: grading data used by the construction (``horizontal_grading='ambient'``)
        self._cgrading = None
        if horizontal_grading == 'ambient':
            try:
                self._cgrading = ambient._require_grading()
            except ValueError as err:
                raise ValueError("grading='ambient' needs a grading of the "
                                 'ambient algebra: {}'.format(err))

    def _has_odd(self):
        """
        Whether the root algebra has odd basis vectors (the category).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._has_odd()
            False
        """
        return self._root._has_odd()

    def _embed_into_ambient(self):
        """Register the inclusion into the ambient algebra as a coercion.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: H.has_coerce_map_from(S), (L + J).parent() is H
            (True, True)
            sage: H.coerce_map_from(S)
            Vertex algebra morphism:
              From: Vertex subalgebra of Universal vertex algebra on generators ['J'] over Rational Field strongly generated by ['L']
              To:   Universal vertex algebra on generators ['J'] over Rational Field
              Defn: L |--> 1/2*:J J:
        """
        from .vertex_algebra_morphism import _function_morphism
        A = self._ambient
        self.register_embedding(_function_morphism(
            self, A, lambda x: A.linear_combination((A.monomial(k), c) for k, c in x.monomial_coefficients().items()),
            reduction=(_ambient_embedding, (self,))))

