    def _saved_state(self):
        """The computed state (strong generators, spans, vectors), raw data
        independent of the class layout; see :meth:`save`.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: _ = S.weight_space(4); st = S._saved_state()
            sage: st['kind'], st['given_names'], [g['name'] for g in st['gens']]
            ('VertexSubalgebra', ('L',), ['L'])
            sage: (4, None) in st['spans']
            True
        """
        cg = self._cgrading
        spans, labels = {}, set()
        for key, sp in self._spans.items():
            if cg is None and key[1] is not None:
                continue
            spans[key] = {'ngens': sp.ngens, 'inserted': sp.inserted,
                          'echelon': sp.echelon._export()}
            labels.update(sp.echelon._labels)
        st = {
            'kind': 'VertexSubalgebra',
            'format': STATE_FORMAT,
            'fingerprint': self._root._state_fingerprint(),
            'wdata': self._wdata,
            'grading': None if cg is None else self._grading_fingerprint(cg),
            'given': [dict(x._monomial_coefficients) for x in self._given],
            'given_names': self._given_names,
            'gens': [{'el': dict(g['el']._monomial_coefficients),
                      'h': g['h'], 'odd': g['odd'], 'name': g['name'],
                      'origin': g['origin']} for g in self._gens],
            'gen_grades': self._gen_grades if cg is not None else None,
            'vecs': {w: dict(self._vec(w)._monomial_coefficients)
                     for w in labels},
            'spans': spans,
        }
        return st

    def _restore(self, st, gens, names):
        """Set up the strong generators and spans from a saved state (see
        :meth:`save`; instead of :meth:`_close`).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J2'], {('J2', 'J2'): [0, 1]}, degrees={'J2': 1})
            sage: J = H.gen('J2'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: _ = S.weight_space(6); st = S._saved_state(); args = S._pickle_args
            sage: from vertex_algebras.vertex_subalgebra import _load_saved_subalgebra
            sage: del S, L; import gc; _ = gc.collect()
            sage: S = _load_saved_subalgebra(args, st)       # restored, not closed
            sage: S.variable_names(), sorted(S._spans) == sorted(st['spans'])
            (('L',), True)
        """
        self._check_saved(st, gens, names)
        V = self._root
        self._given_names = names
        cg = self._cgrading
        graded = cg is not None
        for k, g in enumerate(st['gens']):
            x = V._el_from_dict(g['el'])
            what = 'the strong generator {}'.format(g['name'])
            if (self._weight_of(x, what) != g['h']
                    or self._parity_of(x, what) != g['odd']
                    or (graded and self._grade_of(x, what)
                        != tuple(st['gen_grades'][k]))):
                raise ValueError('{} has another weight, parity or grade '
                                 'than when it was saved'.format(what))
            self._gens.append({'el': x, 'h': g['h'], 'odd': bool(g['odd']),
                               'name': g['name'], 'origin': g['origin']})
        if graded:
            self._gen_grades = [tuple(G) for G in st['gen_grades']]
        self._import_spans(st, st['spans'])

    def _merge_saved(self, st):
        """Take over the spans of the saved state ``st`` that ``self`` has not
        computed (same construction and strong generators; else nothing).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: _ = S.weight_space(7); st = S._saved_state()
            sage: del S._spans[(7, None)]; S._merge_saved(st)
            sage: (7, None) in S._spans, S.weight_space(7).dimension()
            (True, 4)
        """
        self._check_saved(st, self._given, self._given_names)
        if st['gens'] != [{'el': dict(g['el']._monomial_coefficients), 'h': g['h'],
                           'odd': g['odd'], 'name': g['name'], 'origin': g['origin']}
                          for g in self._gens]:
            return
        new = {key: sp for key, sp in st['spans'].items() if key not in self._spans}
        if new:
            self._import_spans(st, new)

    def _import_spans(self, st, spans):
        """
        Import the saved spans ``spans`` (from the state ``st``) into
        ``_spans``, with the vectors of their labels.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: _ = S.weight_space(5); st = S._saved_state()
            sage: del S._spans[(5, None)]; S._import_spans(st, {(5, None): st['spans'][(5, None)]})
            sage: S._spans[(5, None)].echelon.rank()
            2
        """
        V = self._root
        K = self._engine_span_kernel()
        vecs = st['vecs']
        for key, s in spans.items():
            sp = _Span(self, K)
            sp.ngens = s['ngens']
            sp.inserted = set(s['inserted'])
            sp.echelon._import(s['echelon'])
            for w in sp.echelon._labels:
                if w not in self._vecs and w in vecs:
                    self._vecs[w] = V._el_from_dict(vecs[w])
            self._spans[key] = sp

