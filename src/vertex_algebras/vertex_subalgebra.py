        self._print_options['generators'] = 'ambient'
        if core is not None:        # the state of an algebra with other T
            self._core = core
            return
        self._core = _SpanState()
        self._given_names = None
        self._gens = []           # dicts: el (root element), h, odd, name, origin
        self._spans = {}          # (W, G or None) -> _Span
        self._vecs = {(): self._root.one()}
        # vectors computed by the root's engine, in its own form: word ->
        # (kernel, engine-form vector); root elements made on demand (_vec)
        self._evecs = {}
        self._derivs = {}
        #: grade coordinates of the strong generators (when graded)
        self._gen_grades = [] if self._cgrading is not None else None

