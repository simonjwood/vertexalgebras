    #  Strong generators                                                  #
    # ------------------------------------------------------------------ #

    def variable_names(self):
        """
        The names of the strong generators.

        Strong generators found by the closure are called ``S0, S1, ...``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: S = A.subalgebra([E, F], names=['e', 'f'])
            sage: S.variable_names()
            ('e', 'f', 'S0')
        """
        return tuple(g['name'] for g in self._gens)

    def gen(self, name_or_index):
        """
        The strong generator with the given name or index.

        INPUT:

        - ``name_or_index`` -- a name in :meth:`variable_names` or an index

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: S = A.subalgebra([E, F], names=['e', 'f'])
            sage: S.gen('e'), S.gen(2)
            (alpha[1], alphacheck[1])
            sage: S.gen('h')
            Traceback (most recent call last):
            ...
            ValueError: no strong generator named 'h'
        """
        if _is_int_like(name_or_index):
            g = self._gens[int(name_or_index)]
        else:
            names = self.variable_names()
            if name_or_index not in names:
                raise ValueError('no strong generator named {!r}'.format(
                    name_or_index))
            g = self._gens[names.index(name_or_index)]
        return self._el(g['el'])

    def strong_generator_info(self):
        """
        ``(name, conformal weight, parity, origin)`` for every strong
        generator; the origin is ``'given'`` or the product it came from.

        OUTPUT: a list of tuples ``(name, weight, parity, origin)``

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: S = A.subalgebra([E, F], names=['e', 'f'])
            sage: S.strong_generator_info()
            [('e', 1, 0, 'given'), ('f', 1, 0, 'given'), ('S0', 1, 0, 'e_(0) f')]
        """
        return [(g['name'], g['h'], int(g['odd']), g['origin'])
                for g in self._gens]

    def degrees(self):
        """
        The conformal weights of the strong generators, by name.

        OUTPUT: a dictionary ``{name: weight}``

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: S = A.subalgebra([E, F], names=['e', 'f'])
            sage: S.degrees()
            {'S0': 1, 'e': 1, 'f': 1}
        """
        self._weight_data()
        return {g['name']: g['h'] for g in self._gens}

    def _add_gen(self, x, h, odd, name, origin, G=None):
        """
        Append the strong generator ``x`` (root element) of weight ``h``, parity
        ``odd``, name and origin (and grade coordinates ``G`` when graded),
        checking positivity: ``h > 0`` ungraded, else some ``μ`` with ``h +
        μ·grade > 0`` on all strong generators (``NotImplementedError``
        otherwise).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: B = UniversalVertexAlgebra(QQ, ['b', 'g'], {('b', 'g'): [-1]},
            ....:     degrees={'b': 1, 'g': 0}, horizontal_grading={'b': 1, 'g': -1})
            sage: b, g = B.gens()
            sage: G = B.subalgebra([g], names=['g'], horizontal_grading='ambient')
            sage: S._add_gen(J, 0, 0, 'x', 'test')
            Traceback (most recent call last):
            ...
            NotImplementedError: the strong generator x = J has conformal weight 0 <= 0; ...
            sage: G._add_gen(g, 0, 0, 'x', 'test', (1,))
            Traceback (most recent call last):
            ...
            NotImplementedError: no μ with h + μ·grade > 0 on all strong generators ...
        """
        from .weight_spaces import _positive_functional
        hs = [g['h'] for g in self._gens] + [h]
        if self._cgrading is None:
            if h <= 0:
                raise NotImplementedError(
                    'the strong generator {} = {} has conformal weight {} <= 0; '
                    "strong generators of non-positive weight need a grading: "
                    "set one on the ambient algebra and use grading='ambient'"
                    .format(name, x, h))
        else:
            free = self._cgrading['group'].free
            gfree = [tuple(t[j] for j in free)
                     for t in self._gen_grades + [G]]
            if _positive_functional(hs, gfree, list(range(len(hs)))) is None:
                raise NotImplementedError(
                    'no μ with h + μ·grade > 0 on all strong generators '
                    '(those so far: {}; new: {} = {} of weight {} and grade '
                    '{}): not supported'.format(self.variable_names(), name, x, h,
                                       self._cgrading['group'].element(G)))
        g = {'el': x, 'h': h, 'odd': bool(odd), 'name': name, 'origin': origin}
        if self._cgrading is None:
            self._gens = self._gens + [g]
        else:       # one statement: the two lists never disagree (Ctrl-C)
            self._gen_grades, self._gens = self._gen_grades + [G], self._gens + [g]

