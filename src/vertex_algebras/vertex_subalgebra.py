    @staticmethod
    def __classcall_private__(cls, ambient, gens, names=None,
                              max_closure_steps=5, horizontal_grading=None, _state=None,
                              conformal_vector=None):
        """
        Normalise the arguments to the unique-representation key ``(ambient,
        gens, names, max_closure_steps, horizontal_grading, T)``; ``_state`` (a
        saved state, or strong generators to adopt) reaches ``__init__`` through
        ``_PENDING_STATES`` and is not part of the key.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: from vertex_algebras.vertex_subalgebra import VertexSubalgebra
            sage: VertexSubalgebra(H, [J.no(J)/2], ['L']) is S
            True
            sage: VertexSubalgebra(H, [J], ['a', 'b'])
            Traceback (most recent call last):
            ...
            ValueError: 2 names for 1 generators
        """
        if not isinstance(ambient, VertexAlgebra):
            raise TypeError('{!r} is not a vertex algebra'.format(ambient))
        gens = [ambient(x) for x in gens]
        if names is not None:
            names = tuple(str(s) for s in names)
            if len(names) != len(gens):
                raise ValueError('{} names for {} generators'.format(
                    len(names), len(gens)))
        if horizontal_grading not in (None, 'ambient'):
            raise ValueError("grading must be None or 'ambient'")
        T = _canonical_element(ambient, conformal_vector, ('ambient',))
        # a saved state (from load, or an in-memory dict of strong
        # generators to adopt, see _with) is not part of the key (the
        # subalgebra is the same): it is handed to __init__ out of band, and
        # unused if the subalgebra already exists
        _PENDING_STATES.append(_state)
        try:
            return VertexAlgebra.__classcall__(cls, ambient, tuple(gens), names,
                                               int(max_closure_steps), horizontal_grading,
                                               T)
        finally:
            _PENDING_STATES.pop()

    def __init__(self, ambient, gens, names, max_closure_steps, horizontal_grading,
                 conformal_vector=None):
        """
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['T'])
            sage: S.ambient() is H, S._max_steps, S._grading_option
            (True, 5, None)
            sage: S.variable_names(), S._given == (J.no(J)/2,)
            (('T',), True)
            sage: T = S.gen('T'); S2 = H.subalgebra([J.no(J)/2], names=['T'], conformal_vector=T)
            sage: S2._core is S._core, S2.central_charge()
            (True, 1)
        """
        state = _PENDING_STATES[-1] if _PENDING_STATES else None
        if _PENDING_STATES:
            _PENDING_STATES[-1] = None      # nested subalgebras get none
        core = None
        if conformal_vector is not None:
            # the same subalgebra without T computes (or has) the state
            _PENDING_STATES.append(state)
            try:
                S0 = VertexAlgebra.__classcall__(     # the key of T=None
                    VertexSubalgebra, ambient, gens, names, max_closure_steps,
                    horizontal_grading, None)
            finally:
                _PENDING_STATES.pop()
            core = S0._core
        self._init_subspace(ambient, horizontal_grading, 'vertex subalgebras',
                            conformal_vector is not None, fsg=True)
        self._pickle_args = (ambient, tuple(gens), names, max_closure_steps,
                             horizontal_grading, None, conformal_vector)
        self._given = tuple(gens)
        self._max_steps = max_closure_steps
        self._grading_option = horizontal_grading
        self._data = {'T': conformal_vector}
        self._init_spans(core)
        if core is None:
            if state is None:
                self._close(gens, names)
            elif state.get('adopt'):
                self._adopt(state, names)
            else:
                self._restore(state, gens, names)
        if self._cgrading is not None:
            self._grading = self._cgrading
        self._embed_into_ambient()
        if conformal_vector is not None:
            self._install_conformal_vector(conformal_vector)

    # conformal data as construction data (see VertexAlgebra._forgets)

    def _structure_key(self):
        """
        The construction data without the conformal ones (forgetful coercions).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._structure_key()[2:]
            ((1/2*:J J:,), ('L',), 5, None)
        """
        return ('VertexSubalgebra', self._ambient, self._given,
                self._given_names, self._max_steps, self._grading_option)

    def _conformal_key(self):
        """
        The conformal construction data: the canonical Virasoro vector.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._conformal_key(), S.with_conformal_vector(L)._conformal_key()['T'] is not None
            ({'T': None}, True)
        """
        return {'T': self._data['T']}

    def _with(self, **changes):
        """
        The subalgebra with the same generators and other construction data
        (``with_conformal_vector``, ``with_horizontal_grading``); another
        grading option adopts the strong generators instead of closing again.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._with(conformal_vector=L) is S.with_conformal_vector(L)
            True
            sage: S._with(degrees={'L': 1})
            Traceback (most recent call last):
            ...
            ValueError: the conformal weights of a vertex subalgebra are those of the ambient algebra
        """
        if changes.pop('horizontal_grading_group', None) is not None:
            raise ValueError("the grading of a vertex subalgebra is 'ambient' "
                             "(that of the ambient algebra) or None")
        if 'degrees' in changes:
            raise ValueError('the conformal weights of a vertex subalgebra are '
                             'those of the ambient algebra')
        args = {'conformal_vector': self._data['T'],
                'horizontal_grading': self._grading_option}
        args.update(changes)
        state = None
        if args['horizontal_grading'] != self._grading_option:
            # another grading: the strong generators stay strong generators
            state = {'adopt': True,
                     'gens': [dict(g) for g in self._gens]}
        return VertexSubalgebra(self._ambient, self._given, self._given_names,
                                self._max_steps, args['horizontal_grading'], state,
                                args['conformal_vector'])

    def _adopt(self, st, names):
        """Take over the strong generators of the same subalgebra with
        another grading option (they generate it strongly whatever the
        grading); grades are recomputed (a ``ValueError`` if one is not
        homogeneous), positivity checked as by the closure.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: B = UniversalVertexAlgebra(QQ, ['b', 'g'], {('b', 'g'): [-1]},
            ....:     degrees={'b': 1, 'g': 0}, horizontal_grading={'b': 1, 'g': -1})
            sage: b, g = B.gens()
            sage: G = B.subalgebra([g], names=['g'], horizontal_grading='ambient')
            sage: G0 = G.with_horizontal_grading(None)
            Traceback (most recent call last):
            ...
            NotImplementedError: the strong generator g = g has conformal weight 0 <= 0; ...
            sage: S2 = B.subalgebra([b.no(g)], names=['J'])
            sage: S2g = S2.with_horizontal_grading('ambient'); S2g._gen_grades, S2g.variable_names()
            ([(0,)], ('J',))
        """
        self._given_names = names
        graded = self._cgrading is not None
        for g in st['gens']:
            x = g['el']
            G = (self._grade_of(x, 'the strong generator {} ='.format(g['name']))
                 if graded else None)
            self._add_gen(x, g['h'], g['odd'], g['name'], g['origin'], G)

    def _install_conformal_vector(self, T):
        r"""
        The Virasoro vector ``T`` (``'ambient'`` or the canonical dict data
        of an element): ``'ambient'`` takes that of the ambient algebra,
        which must lie in ``self``; otherwise ``T`` must be an element of
        ``self`` whose OPE is Virasoro and which induces the conformal
        weights of the ambient algebra on ``self``: on every strong
        generator ``g`` of weight ``h``, ``T_(0) g = ∂g`` and ``T_(1) g -
        h g`` has weight ``h`` and is nilpotent under ``T_(1) - h``
        (Jordan blocks give a :class:`LogarithmicWarning`).

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]},
            ....:                            conformal_vector={(('J', 0), ('J', 0)): 1/2})
            sage: J = H.gen('J')
            sage: S = H.subalgebra([J.no(J)])
            sage: S.conformal_vector() is None
            True
            sage: St = S.with_conformal_vector('ambient'); St.conformal_vector(), St.central_charge()
            (1/2*:J J:, 1)
            sage: St._core is S._core, St is H.subalgebra([J.no(J)], conformal_vector='ambient')
            (True, True)
            sage: S.with_conformal_vector(J.no(J))
            Traceback (most recent call last):
            ...
            ValueError: T is not a Virasoro field: ...
            sage: H.subalgebra([J.derivative()], conformal_vector='ambient')
            Traceback (most recent call last):
            ...
            ValueError: the Virasoro vector 1/2*:J J: of the ambient algebra is not in ...

        TESTS:

        The ``c = -2`` singlet algebra ``<T_s, W>`` in the βγ system: the
        Virasoro vector of βγ is not in it, ``T_s`` is (central charge
        ``-2``), and the closure is shared::

            sage: V = UniversalVertexAlgebra(QQ, ['b', 'g'], {('b', 'g'): [-1]},
            ....:                            conformal_vector={(('b', 0), ('g', 1)): -1})
            sage: b, g = V.gens()
            sage: Ts = g.no(g.no(b.no(b))) / 2 + b.derivative().no(g) - b.no(g.derivative())
            sage: W = (g.no(g.no(g.no(b.no(b.no(b))))) / 9 - g.no(g.derivative().no(b.no(b))) / 2
            ....:      + g.no(g.no(b.no(b.derivative()))) / 2 + g.derivative(2).no(b) / 6
            ....:      - 2 * g.derivative().no(b.derivative()) / 3 + g.no(b.derivative(2)) / 6)
            sage: S = V.subalgebra([Ts, W], names=['T', 'W'], max_closure_steps=1)
            sage: S.with_conformal_vector('ambient')
            Traceback (most recent call last):
            ...
            ValueError: the Virasoro vector ... of the ambient algebra is not in ...
            sage: St = S.with_conformal_vector(Ts)
            sage: St.central_charge(), St._core is S._core, S.conformal_vector() is None
            (-2, True, True)
        """
        c = None
        check = True
        if isinstance(T, str) and T == 'ambient':
            T0 = self._ambient.conformal_vector()
            if T0 is None:
                raise ValueError('the ambient algebra has no Virasoro vector')
            if not self.contains(T0):
                raise ValueError('the Virasoro vector {} of the ambient '
                                 'algebra is not in {}'.format(T0, self))
            T = T0
            c = self._ambient.central_charge()
            check = False
        else:
            T = self._root._el_from_dict(dict(T))
        gens = [(g['name'], self.gen(i), g['h'])
                for i, g in enumerate(self._gens)]
        self._set_virasoro_inherited(T, check, c, gens)

