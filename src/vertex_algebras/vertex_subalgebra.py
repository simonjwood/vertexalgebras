    def weight_space(self, weight, horizontal_grade=None):
        r"""
        The weight space of ``self`` of conformal weight ``weight`` (and,
        with ``horizontal_grading='ambient'``, of the given grade): a
        :class:`weight_spaces.SubspaceWeightSpace`, whose basis consists of
        normally ordered monomials of the strong generators.

        INPUT:

        - ``weight`` -- a conformal weight

        - ``horizontal_grade`` -- (default: ``None``) a grade (with
          ``horizontal_grading='ambient'``; required when the weight space
          may be infinite dimensional)

        OUTPUT: a :class:`weight_spaces.SubspaceWeightSpace`

        EXAMPLES:

        ``e^α`` generates the principal subspace of ``V_{A_1}``, with
        character ``Σ_n q^{n^2} / (q)_n``; the ``e^{nα}`` part is graded by
        the partitions into at most ``n`` parts::

            sage: from vertex_algebras.lattice_vertex_algebra import LatticeVertexAlgebra
            sage: L0 = LatticeVertexAlgebra(QQ, matrix([[2]]))
            sage: J = L0.J(0)
            sage: L = L0.with_conformal_vector(J.no(J) / 4)
            sage: S = L.subalgebra([L.e((1,))], names=['e'])
            sage: [S.weight_space(n).dimension() for n in range(9)]
            [1, 1, 1, 1, 2, 2, 3, 3, 4]
            sage: Lg = L.with_horizontal_grading('lattice')
            sage: Sg = Lg.subalgebra([Lg.e((1,))], names=['e'], horizontal_grading='ambient')
            sage: [Sg.weight_space(n, horizontal_grade=2).dimension() for n in range(4, 9)]
            [1, 1, 2, 2, 3]
            sage: B = S.weight_space(5); B
            Weight space of conformal weight 5 of Vertex subalgebra of ... (dimension 2)
            sage: B.basis_words()
            [((0, 4),), ((0, 3), (0, 0))]
            sage: B.basis()[1]          # :∂³e^α e^α:
            6*:J0 e^(2):

        TESTS:

        The whole Rogers-Ramanujan character, and the partitions into at
        most ``n`` parts in every grade ``n`` (Feigin-Stoyanovsky)::

            sage: q = PowerSeriesRing(QQ, 'q', default_prec=12).gen()
            sage: ch = sum(q^(n*n) / prod(1 - q^k for k in range(1, n + 1)) for n in range(4))
            sage: [S.weight_space(n).dimension() for n in range(11)] == ch.list()[:11]
            True
            sage: all(Sg.weight_space(W, horizontal_grade=n).dimension()
            ....:     == (Partitions(W - n*n, max_length=n).cardinality() if W >= n*n else 0)
            ....:     for n in range(4) for W in range(11))
            True
        """
        from .weight_spaces import SubspaceWeightSpace, _to_rational
        self._weight_data()
        W = _to_rational(weight)
        G = None
        if horizontal_grade is not None:
            G = self._require_grading()['group'].coords(horizontal_grade)
        if G is None and self._cgrading is not None:
            if not self._words(W, None).finite:
                raise ValueError(
                    'the weight space of weight {} may be infinite dimensional '
                    '(strong generators of non-positive weight): give a '
                    'grade'.format(W))
        sp = self._span(W, G)
        return SubspaceWeightSpace(
            self, self, W, None if G is None else self._grade_out(G),
            sp.echelon, self._root_dict,
            element=lambda w: self._el(self._vec(w)))
