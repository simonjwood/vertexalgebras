    def _weight_of(self, x, what):
        """The conformal weight (rational) of the homogeneous root element
        ``x``.

        A ``ValueError`` naming ``what`` if ``x`` is not homogeneous.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._weight_of(J.no(J), 'the generator')
            2
            sage: S._weight_of(J + J.no(J), 'the generator')
            Traceback (most recent call last):
            ...
            ValueError: the generator J + :J J: is not homogeneous for the conformal weight; ...
        """
        from .weight_spaces import _to_rational
        V = self._root
        data = self._wdata
        ws = {V._weight_key(m, data) for m in x.support()}
        if len(ws) != 1:
            raise ValueError(
                '{} {} is not homogeneous for the conformal weight; '
                '(its homogeneous components may generate a larger '
                'subalgebra, so they are not used instead)'.format(what, x))
        return _to_rational(ws.pop())

    def _parity_of(self, x, what):
        """
        The parity of the homogeneous root element ``x`` (a ``ValueError``
        naming ``what`` otherwise).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._parity_of(J, 'the generator')
            0
        """
        pars = {self._root._parity_key(m) for m in x.support()}
