    def _root_dict(self, v):
        """``v`` as a raw dict over the root keys, or ``None`` if ``v`` is
        not an element of the root algebra (or of one of its
        subalgebras).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._root_dict(J), S._root_dict(L), S._root_dict(matrix([[1, 2]]))
            ({((0, 0),): 1}, {((0, 0), (0, 0)): 1/2}, None)
        """
        V = self._root
        if isinstance(v, VertexAlgebraElement):
            P = v.parent()
            if P is V or (_is_subalgebra(P) and P._root is V):
                return dict(v._monomial_coefficients)
        try:
            return dict(V(v)._monomial_coefficients)
        except (TypeError, ValueError, ArithmeticError):
            return None

    def _components(self, d):
        """The homogeneous components ``{(W, G): dict}`` of a raw dict (by
        weight, and by grade when the closure is graded), sorted; ``None``
        if a weight is not rational (such keys are not in ``self``).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S._components({((0, 0), (0, 0)): 1, ((0, 0),): 1})
            {(1, None): {((0, 0),): 1}, (2, None): {((0, 0), (0, 0)): 1}}
        """
        V = self._root
        data = self._weight_data()
        graded = self._cgrading is not None
        comps = {}
        for m, c in d.items():
            if c:
                key = (V._weight_key(m, data),
                       self._amb_grade(m) if graded else None)
                comps.setdefault(key, {})[m] = c
        out = {}
        for (w, G), comp in comps.items():
            try:
                w = QQ(w)
            except (TypeError, ValueError):
                return None
            out[(w, G)] = comp
        return dict(sorted(out.items(),
                           key=lambda t: (t[0][0], t[0][1] or ())))

