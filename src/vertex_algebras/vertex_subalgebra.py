    def _contains_dict(self, d):
        """
        Membership of a raw root dict: each homogeneous component lies in the
        span of its weight (and grade).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: LL, J1 = ((0, 0), (0, 0)), ((0, 0),)
            sage: S._contains_dict({LL: 1}), S._contains_dict({J1: 1}), S._contains_dict({})
            (True, False, True)
        """
        comps = self._components(d)
        return comps is not None and all(
            self._span(w, G).echelon.contains(comp)
            for (w, G), comp in comps.items())

