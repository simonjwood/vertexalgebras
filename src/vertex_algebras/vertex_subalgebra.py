    def _element_constructor_(self, x):
        """
        Convert ``x``: an element of ``self``, a basis key, a normally ordered
        expression in the strong generators, a scalar (times the vacuum), an
        element of a presentation of ``self``, or anything converting into the
        root algebra that lies in ``self`` (``ValueError`` otherwise).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
            sage: J = H.gen('J'); S = H.subalgebra([J.no(J)/2], names=['L']); L = S.gen('L')
            sage: S(J.no(J)) == 2*L, S(((0, 0), (0, 0))), S(3)
            (True, :J J:, 3)
            sage: X = S.normally_ordered_expressions(); S(X.gen(0)) == L
            True
            sage: S(J)
            Traceback (most recent call last):
            ...
            ValueError: J is not an element of ...
        """
        if isinstance(x, VertexAlgebraElement) and x.parent() is self:
            return self._el_from_dict(dict(x._monomial_coefficients))
        if isinstance(x, tuple) and x in self._indices:
            d = {x: self.base_ring().one()}
        else:
            P = getattr(x, 'parent', lambda: None)()
            if (getattr(P, '_is_normally_ordered_expressions', False)
                    and hasattr(self, '_evaluate_expression')):
                return self._evaluate_expression(x)
            if not isinstance(x, VertexAlgebraElement):
                # (not for elements: a failed conversion of one into the base
                # ring formats its repr, which is slow for long elements)
                R = self.base_ring()
                try:
                    c = R(x)
                except (TypeError, ValueError, ArithmeticError):
                    c = None
                if c is not None:
                    return self.one() * c
            if getattr(P, '_presentation_of', None) is self:
                return P._realize(x)         # the realization of a presentation
            d = self._root_dict(x)
            if d is None:
                raise TypeError('cannot convert {!r} into {}'.format(x, self))
        if not self._contains_dict(d):
            raise ValueError('{} is not an element of {}'.format(x, self))
        return self._el_from_dict(d)

