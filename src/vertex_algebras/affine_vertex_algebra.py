    def _cartan_weight_grading(self):
        r"""
        ``(cartan, M)`` for the grading of modules by weights: ``cartan`` the
        indices of the generators of grade 0 (the Cartan subalgebra ``h`` for
        the root lattice grading), ``M`` the matrix (rows: ``cartan``,
        columns: the coordinates of the grading group ``A``) of the embedding
        ``A -> h^* = P ⊗ R``, ``M a`` the eigenvalues of the zero modes of
        the Cartan currents on the generators of grade ``a`` (read off from
        the generators of the unit grades and checked on all generators).
        ``None`` if there is no such description (no grading, a grading
        that is not by a free group, Cartan currents that do not act
        diagonally by a function of the grade, or a non-injective map, e.g.
        ``psl(2|2)``).  Cached.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 2], level=1)
            sage: cartan, M = V._cartan_weight_grading(); [V.variable_names()[i] for i in cartan]
            ['alphacheck[1]', 'alphacheck[2]']
            sage: M                    # the simple roots in fundamental weight coordinates
            [ 2 -1]
            [-1  2]
        """
        if hasattr(self, '_cwg'):
            return self._cwg
        self._cwg = out = self._compute_cartan_weight_grading()
        return out

    def _compute_cartan_weight_grading(self):
        """
        The body of :meth:`_cartan_weight_grading` (uncached): the zero-mode
        eigenvalues of the Cartan currents (grade 0) on the generators of the
        unit grades, or ``None`` (no free grading, not diagonal, not
        injective).

        TESTS::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 2], level=1)
            sage: V._compute_cartan_weight_grading() == V._cartan_weight_grading()
            True
            sage: S = UniversalAffineVertexAlgebra(QQ, {('h', 'e'): {'e': 2}, ('h', 'f'): {'f': -2},
            ....:     ('e', 'f'): {'h': 1}}, form={('h', 'h'): 2, ('e', 'f'): 1})
            sage: S._compute_cartan_weight_grading() is None     # no grading
            True
        """
        gd = self._grading
        if gd is None:
            return None
        A = gd['group']
        if A.kind not in ('ZZ', 'free'):
            return None
        g = gd['g']
        n = len(self._gens)
        cartan = [i for i in range(n) if A.is_zero(g[i])]
        R = self.base_ring()

        def zero_mode(h, y):
            poles = self._ope_mono(((h, 0),), ((y, 0),))
            p0 = poles[0] if poles else {}
            if set(p0) - {((y, 0),)}:
                return None
            return R(p0.get(((y, 0),), 0))
        cols = []
        for j in range(A.k):
            e = tuple(int(t == j) for t in range(A.k))
            xs = [i for i in range(n) if tuple(g[i]) == e]
            if not xs:
                return None
            col = [zero_mode(h, xs[0]) for h in cartan]
            if any(c is None for c in col):
                return None
            cols.append(col)
        M = matrix(R, A.k, len(cartan), cols).transpose()
        if M.rank() < A.k:
            return None
        for y in range(n):
            for r, h in enumerate(cartan):
                if zero_mode(h, y) != sum(M[r, j] * g[y][j] for j in range(A.k)):
                    return None
        M.set_immutable()
        return tuple(cartan), M

