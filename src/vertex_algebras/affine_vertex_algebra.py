    def __init__(self, base_ring, kind, obj, names, par, brk, gram, level,
                 horizontal_grading, conformal_vector, implementation):
        r"""
        Initialize ``self``.

        TESTS::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1, conformal_vector='sugawara')
            sage: V._affine['kind'], V._affine['level'], V.variable_names()
            ('cartan', 1, ('alpha[1]', 'alphacheck[1]', '-alpha[1]'))
            sage: V.central_charge(), V.degrees()
            (1, {'-alpha[1]': 1, 'alpha[1]': 1, 'alphacheck[1]': 1})
        """
        self._pickle_args = (base_ring, kind, obj, names, par, brk, gram,
                             level, horizontal_grading, conformal_vector, implementation)
        parities = tuple((s, 1) for s, p in zip(names, par) if p)
        # the OPEs in the canonical form of the universal constructor
        # (pairs i <= j, single letters are basis monomials, zeros dropped)
        E = NormallyOrderedExpressions(base_ring, names, dict(parities))
        J = E.gens()
        br = {ij: dict(v) for ij, v in brk}
        opes = []
        for i in range(len(names)):
            for j in range(i, len(names)):
                poles = [E.sum(c * J[k] for k, c in br.get((i, j), {}).items()),
                         E(gram[i, j])]
                while poles and poles[-1].is_zero():
                    poles.pop()
                if poles:
                    opes.append(((names[i], names[j]), tuple(poles)))
        weights = tuple((s, base_ring.one()) for s in names)
        horizontal_grading, group = _canonical_grading(names, horizontal_grading, None)
        self._affine = {'kind': kind, 'obj': obj, 'par': par,
                        'brackets': br, 'gram': gram, 'level': level}
        T = checked = None
        if conformal_vector == 'sugawara':
            # computed and checked first, so that the category is known
            T, checked = _sugawara(base_ring, names, tuple(opes), parities,
                                   weights, gram, par, br, implementation)
        UniversalVertexAlgebra.__init__(self, base_ring, names, tuple(opes),
                                        parities, weights, T, horizontal_grading, group,
                                        implementation=implementation,
                                        _checked_virasoro=checked)

