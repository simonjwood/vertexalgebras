class _ScalarAction(Action):
    r"""
    Scalars acting on morphisms: ``c * f``.

    TESTS::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
        sage: f = End(M).identity(); g = 3 * f; g(M.highest_weight_vector())
        3*v
    """

    def __init__(self, R, H, self_on_left):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra_module_morphism import _ScalarAction
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: A = _ScalarAction(QQ, End(M), True); A.actor() is QQ, A.is_left()
            (True, False)
        """
        Action.__init__(self, R, H, not self_on_left)

    def _act_(self, c, f):
        r"""
        The morphism ``c f``.

        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra_module_morphism import _ScalarAction
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: A = _ScalarAction(QQ, End(M), True)
            sage: A._act_(5, End(M).identity())(M.highest_weight_vector())
            5*v
        """
        return f._scaled(c)


class ModuleHomset(Homset):
    r"""
    The space of morphisms ``X -> Y`` of modules over a vertex algebra.

    Built by ``Hom(X, Y)`` (one homset per codomain, cached on ``X``).

    INPUT:

    - ``X`` -- a module over a vertex algebra, the domain
    - ``Y`` -- a module over the same vertex algebra, the codomain
    - ``category`` -- (default: ``None``) a category; ``None`` gives the
      category of ``X``

    EXAMPLES::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
        sage: H = End(M); H
        Set of Morphisms from Verma module of highest weight {'L': 0} over ... in Category of conformally graded modules with basis over ...
        sage: H.dimension(), H.basis() == [H.identity()]
        (1, True)

    TESTS:

    Morphisms out of the adjoint module of the Heisenberg algebra are the
    vacuum-like vectors: one in the Fock module of charge 0, none in that
    of charge 3; the map onto the charge-0 Fock module is ``a -> a_(-1) v``
    and an isomorphism; the flow of the charge-0 Fock module by ``3 J`` is
    the charge-3 one::

        sage: import vertex_algebras as va
        sage: Hb = va.FreeBosons(QQ); J = Hb.gen(0)
        sage: Hb = Hb.with_conformal_vector(J.no(J) / 2); J = Hb.gen(0)
        sage: A = Hb.zhu_algebra()
        sage: F0 = Hb.induced_module(A.module({'alpha': 0}))
        sage: F3 = Hb.induced_module(A.module({'alpha': 3}))
        sage: Ad = Hb.adjoint_module()
        sage: Hom(Ad, F0).dimension(), Hom(Ad, F3).dimension(), End(Ad).dimension()
        (1, 0, 1)
        sage: phi, = Hom(Ad, F0).basis(); x = J.no(J.derivative())
        sage: phi(Ad(x)) == x.nproduct(F0.highest_weight_vector(), -1)
        True
        sage: phi.is_isomorphism_up_to(5)
        True
        sage: Hom(F0.spectral_flow(3 * J), F3).dimension()
        1
    """

    def __init__(self, X, Y, category=None):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: H = Hom(M, M); H.domain() is M and H.codomain() is M
            True
        """
        if category is None:
            category = X.category()
        Homset.__init__(self, X, Y, category=category, base=X.base_ring(), check=False)
        self._bases = {}

    def __call__(self, x, check=True, check_depth=None):
        r"""
        The morphism with the images ``x`` of the generators of the domain
        (a list in the order of :meth:`generating_vectors`, a dict by
        generating vector, a single vector, or a morphism with the same
        images, e.g. out of the cover of a quotient).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: v = M.highest_weight_vector(); f = End(M)([2*v]); f(v)
            2*v
        """
        if isinstance(x, ModuleMorphism) and x.parent() is self:
            return x
        if x == 0 and not isinstance(x, (list, tuple, dict, ModuleMorphism)):
            return self.zero()
        return self.element_class(self, x, check=check, check_depth=check_depth)

    def generating_vectors(self):
        r"""
        The vectors of the domain whose images define a morphism (the top
        level of an induced module, the vacuum of the adjoint module).

        OUTPUT:

        A list of vectors of the domain.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, 'A1', 1, names=['E', 'H', 'F'], conformal_vector='sugawara')
            sage: A = V.zhu_algebra()
            sage: U = A.module({'E': matrix([[0, 1], [0, 0]]), 'H': matrix([[1, 0], [0, -1]]),
            ....:               'F': matrix([[0, 0], [1, 0]])})
            sage: M = V.induced_module(U); End(M).generating_vectors()
            [u[0], u[1]]
        """
        X = self.domain()
        return [X.monomial(k) for k in _generating_keys(X)]

    def identity(self):
        r"""
        The identity of ``End(X)``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0).simple_quotient()
            sage: L = V.gen('L'); x = L.mode(L.mode(M.highest_weight_vector(), -2), -2)
            sage: End(M).identity()(x) == x
            True
        """
        X = self.domain()
        if X is not self.codomain():
            raise TypeError('identity morphism only for End(X)')
        return self.element_class(self, self.generating_vectors(), check=False)

    def zero(self):
        r"""
        The zero morphism.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: z = Hom(M, M).zero(); z(M.highest_weight_vector())
            0
        """
        Y = self.codomain()
        return self.element_class(self, [Y.zero()] * len(self.generating_vectors()), check=False)

    def _an_element_(self):
        r"""
        The zero morphism.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: End(M).an_element() == End(M).zero()
            True
        """
        return self.zero()

    def _get_action_(self, S, op, self_on_left):
        r"""
        Scalars of the base ring act (``c * f``, ``f * c``).

        TESTS::

            sage: import vertex_algebras as va
            sage: import operator
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); H = End(V.verma_module(0))
            sage: H._get_action_(QQ, operator.mul, False) is not None
            True
        """
        import operator
        R = self.base_ring()
        if op is operator.mul and S is not self and R.has_coerce_map_from(S):
            return _ScalarAction(S, self, self_on_left)
        return None

    def basis(self, weight=None, horizontal_grade=None, check_depth=None):
        r"""
        A basis of ``Hom(X, Y)``: the solutions of the conditions of the
        domain (see the module documentation) as linear equations on the
        images of the generating vectors in the weight space of ``Y`` of
        their weight.

        INPUT:

        - ``weight`` -- (default: the weight of the generating vectors) the
          weight of their images (needed when ``V`` has no conformal vector
          and the morphism shifts weights)

        - ``horizontal_grade`` -- (default: ``None``) the grade in ``Y`` of the
          image of the first generating vector (the others follow by the
          differences of their grades): the graded piece of ``Hom`` shifting
          grades by that amount.  By default the whole weight space of ``Y``
          if it is finite dimensional, else the grade-preserving morphisms

        - ``check_depth`` -- (default: ``None``) the depth up to which
          relations known only degree by degree are imposed (the maximal
          submodule of a simple quotient domain, when ``Y`` is not known to be
          simple)

        OUTPUT:

        A list of morphisms ``X -> Y``.

        EXAMPLES:

        Schur's lemma for the Ising modules::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: L0, L1 = (V.verma_module(h).simple_quotient() for h in (0, 1/16))
            sage: End(L0).dimension(), Hom(L0, L1).dimension(), Hom(L1, L1).dimension()
            (1, 0, 1)

        The Verma module ``M(1/2, 1/16)`` maps to its simple quotient (the
        cover); the simple quotient does not map back::

            sage: M = V.verma_module(1/16)
            sage: Hom(M, L1).dimension(), Hom(L1, M).dimension(check_depth=4)
            (1, 0)

        TESTS:

        The Verma module is not simple, so the basis of ``Hom(L1, M)``
        needs ``check_depth``::

            sage: Hom(L1, M).basis()
            Traceback (most recent call last):
            ...
            ValueError: the maximal submodule of Verma module of highest weight {'L': 1/16} over ... is known only degree by degree and ... is not known to be simple: give check_depth

        Schur's lemma for the two simple modules of affine ``sl_2`` at
        level 1::

            sage: W = va.Affine(QQ, 'A1', 1, names=['E', 'H', 'F'], conformal_vector='sugawara')
            sage: A = W.zhu_algebra()
            sage: S0 = W.induced_module(A.module({'E': 0, 'H': 0, 'F': 0})).simple_quotient()
            sage: U = A.module({'E': matrix([[0, 1], [0, 0]]), 'H': matrix([[1, 0], [0, -1]]),
            ....:               'F': matrix([[0, 0], [1, 0]])})
            sage: S1 = W.induced_module(U).simple_quotient()
            sage: End(S0).dimension(), End(S1).dimension(), Hom(S0, S1).dimension(), Hom(S1, S0).dimension()
            (1, 1, 0, 0)

        Direct sums: ``End(M(0) + M(1))`` is ``End(M(0)) + End(M(1)) +
        Hom(M(1), M(0))``, and the projection after the embedding is the
        identity::

            sage: M0, M1 = V.verma_module(0), V.verma_module(1)
            sage: D = M0.direct_sum(M1)
            sage: End(D).dimension(), Hom(D, M0).dimension(), Hom(M1, D).dimension()
            (3, 2, 2)
            sage: D.projection(0) * D.embedding(0) == End(M0).identity()
            True

        Hom spaces out of a submodule are not implemented::

            sage: L = V.gen('L'); N = M0.submodule([L.mode(M0.highest_weight_vector(), -1)])
            sage: Hom(N, M0).basis()
            Traceback (most recent call last):
            ...
            NotImplementedError: Hom spaces out of Submodule of ... are not implemented yet
        """
        key = (weight, None if horizontal_grade is None else tuple(horizontal_grade), check_depth)
        try:
            return list(self._bases[key])
        except KeyError:
            pass
        X, Y = self.domain(), self.codomain()
        k = _kind(X)
        if k in ('twist', 'flow'):
            P = X.underlying_module()
            Hp = Hom(P, _underlying_codomain(X, Y))
            out = [self.element_class(self, [Y._from_dict(dict(x._monomial_coefficients))
                                             for x in f.im_gens()],
                                      check=False, _checked=f._checked)
                   for f in Hp.basis(weight, horizontal_grade, check_depth)]
        elif k == 'quotient':
            Hc = Hom(X.ambient(), Y)
            cover = Hc.basis(weight, horizontal_grade, check_depth)
            checked, conds = None, []
            for f in cover:
                g = self.element_class(self, f.im_gens(), check=False)
                c, checked = g._quotient_defect(check_depth)
                conds.append(c)
            checked = _combine(checked, *[f._checked for f in cover])
            out = []
            for rel in left_kernel(conds, self.base_ring()):
                imgs = [sum((c * cover[j].im_gens()[i] for j, c in rel.items()), Y.zero())
                        for i in range(len(self.generating_vectors()))]
                out.append(self.element_class(self, imgs, check=False, _checked=checked))
        elif k in ('induced', 'adjoint', 'lattice', 'higher'):
            out = self._elementary_basis(weight, horizontal_grade, check_depth)
        elif k == 'sum':
            gens = _generating_keys(X)
            out = []
            for i, N in enumerate(X.summands()):
                for f in Hom(N, Y).basis(weight, horizontal_grade, check_depth):
                    imgs = dict(zip(_generating_keys(N), f.im_gens()))
                    out.append(self.element_class(
                        self, [imgs[g] if j == i else Y.zero() for j, g in gens],
                        check=False, _checked=f._checked))
        else:
            raise NotImplementedError('Hom spaces out of {} are not implemented yet'.format(X))
        self._bases[key] = tuple(out)
        return list(out)

    def _elementary_basis(self, weight, horizontal_grade, check_depth=None):
        r"""
        :meth:`basis` for induced, adjoint and lattice domains: unknown images in a
        weight space of the codomain, the conditions of
        :meth:`ModuleMorphism._defect` as linear equations.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: Hom(V.verma_module(5/2), V.verma_module(1/2))._elementary_basis(None, None)
            [Vertex algebra module morphism:
              From: Verma module of highest weight {'L': 5/2} over ...
              To:   Verma module of highest weight {'L': 1/2} over ...
              Defn: v |--> -4/3*L_{-2} v + L_{-1} L_{-1} v]

        Lattice modules (exact: Schur)::

            sage: L0 = va.Lattice(QQ, matrix([[2]])); J = L0.J(0)
            sage: L = va.Lattice(QQ, matrix([[2]]), conformal_vector=J.no(J)/4)
            sage: M, N = L.simple_module([0]), L.simple_module([1/2])
            sage: Hom(M, M)._elementary_basis(None, None), Hom(M, N)._elementary_basis(None, None)
            ([Vertex algebra module endomorphism of Module V_(lambda+L), lambda = (0), over ...
                Defn: |0> |--> |0>],
             [])
        """
        X, Y = self.domain(), self.codomain()
        R = self.base_ring()
        gens = _generating_keys(X)
        if weight is None:
            weight = X.top_weight() if _kind(X) == 'induced' else X._weight_key(gens[0])
        if X.vertex_algebra().conformal_vector() is not None:
            # morphisms commute with L_0: no weight of Y differs from the
            # base weight of Y by a non-rational amount (symbolic weights)
            try:
                base = Y._weight_base()
            except (NotImplementedError, ValueError, AttributeError):
                base = None
            if base is not None:
                try:
                    QQ(weight - base)
                except (TypeError, ValueError, ArithmeticError):
                    return []
        spaces = None
        if _kind(X) == 'lattice':
            # the image of e^λ lies in the grade of e^λ when both modules are
            # graded by the same group (the only place to look; ungraded
            # weight spaces of indefinite lattices are infinite)
            try:
                spaces = self._graded_spaces(gens, weight, horizontal_grade)
            except (ValueError, NotImplementedError, AttributeError):
                spaces = None
        if spaces is None and horizontal_grade is None:
            try:
                S = Y.weight_space(weight)
                if S.is_finite_dimensional():
                    spaces = [S] * len(gens)
            except (ValueError, NotImplementedError, TypeError):
                pass
        if spaces is None:
            spaces = self._graded_spaces(gens, weight, horizontal_grade)
        bases = [[dict(b._monomial_coefficients) for b in S.basis()] for S in spaces]
        units, conds = [], []
        for gi in range(len(gens)):
            for b in bases[gi]:
                imgs = [Y.zero()] * len(gens)
                imgs[gi] = Y._from_dict(b)
                f = self.element_class(self, imgs, check=False)
                units.append(imgs)
                conds.append(f._defect(check_depth))
        out = []
        for rel in left_kernel(conds, R):
            imgs = [sum((c * units[j][i] for j, c in rel.items()), Y.zero())
                    for i in range(len(gens))]
            checked = None
            if _kind(X) == 'lattice' and not _known_semisimple(Y, X.vertex_algebra()):
                checked = check_depth
            out.append(self.element_class(self, imgs, check=False, _checked=checked))
        return out

    def _graded_spaces(self, gens, weight, horizontal_grade):
        r"""
        The weight spaces of the codomain for the images of the generating
        keys ``gens``, by grade: the image of the first one in the grade
        ``horizontal_grade`` (default: its own grade), the others shifted by
        the differences of the grades in the domain (both modules graded by
        the same group).

        TESTS:

        The spectral flow of the vacuum module of affine ``sl_2`` at level 1
        by ``H/2`` keeps the grades of the vacuum module; the doublet ``L(1)``
        maps onto it with the grades shifted by ``-1``::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, 'A1', 1, names=['E', 'H', 'F'], conformal_vector='sugawara')
            sage: A = V.zhu_algebra(); H = V.gen('H')
            sage: L0 = V.induced_module(A.module({'E': 0, 'H': 0, 'F': 0})).simple_quotient()
            sage: U = A.module({'E': matrix([[0, 1], [0, 0]]), 'H': matrix([[1, 0], [0, -1]]),
            ....:               'F': matrix([[0, 0], [1, 0]])})
            sage: L1 = V.induced_module(U).simple_quotient(); S = L0.spectral_flow(H/2)
            sage: G = S.horizontal_grading_group()
            sage: Hom(L1, S).dimension(), Hom(L1, S).dimension(horizontal_grade=G([0]))
            (0, 1)
        """
        X, Y = self.domain(), self.codomain()
        try:
            BX, BY = X.horizontal_grading_group(), Y.horizontal_grading_group()
        except (ValueError, AttributeError, NotImplementedError):
            BX = BY = None
        if BX is None or BX is not BY:
            raise ValueError('the weight space of {} of weight {} is infinite or depends '
                             'on the grade, and the modules are not graded by the same '
                             'group'.format(Y, weight))
        grades = [X.horizontal_grade(X.monomial(k)) for k in gens]
        G0 = grades[0] if horizontal_grade is None else BY(horizontal_grade)
        spaces = []
        for g in grades:
            S = Y.weight_space(weight, G0 + (g - grades[0]))
            if not S.is_finite_dimensional():
                raise ValueError('the weight space of {} of weight {} and grade {} is '
                                 'infinite'.format(Y, weight, G0 + (g - grades[0])))
            spaces.append(S)
        return spaces

    def dimension(self, weight=None, horizontal_grade=None, check_depth=None):
        r"""
        The dimension of ``Hom(X, Y)`` (see :meth:`basis`).

        INPUT:

        - ``weight`` -- (default: ``None``) as in :meth:`basis`
        - ``horizontal_grade`` -- (default: ``None``) as in :meth:`basis`
        - ``check_depth`` -- (default: ``None``) as in :meth:`basis`

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: Hom(V.verma_module(5/2), V.verma_module(1/2)).dimension()
            1
            sage: Hom(V.verma_module(2), V.verma_module(0)).dimension()
            0

        TESTS:

        At a generic point ``(c, h)`` the Verma modules have no singular
        vectors (Kac determinant), so there are no maps between them::

            sage: K.<c, h> = Frac(QQ['c', 'h'])
            sage: VK = va.Virasoro(K, c, conformal_vector='L')
            sage: [Hom(VK.verma_module(h + n), VK.verma_module(h)).dimension() for n in (1, 2, 3)]
            [0, 0, 0]
        """
        return len(self.basis(weight, horizontal_grade, check_depth))

    def checked_up_to_depth(self, weight=None, horizontal_grade=None, check_depth=None):
        r"""
        ``None`` if :meth:`basis` is exact, else the depth up to which the
        relations of the domain were imposed.

        INPUT:

        - ``weight`` -- (default: ``None``) as in :meth:`basis`
        - ``horizontal_grade`` -- (default: ``None``) as in :meth:`basis`
        - ``check_depth`` -- (default: ``None``) as in :meth:`basis`

        OUTPUT:

        ``None`` or a depth.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: M, L = V.verma_module(1/16), V.verma_module(1/16).simple_quotient()
            sage: Hom(M, L).checked_up_to_depth(), Hom(L, M).checked_up_to_depth(check_depth=3)
            (None, 3)

        TESTS:

        The triplet algebra ``W(2)`` from its presentation: ``P(0)``,
        induced from the Jordan block of ``[T]``, has a two-dimensional
        endomorphism space in the window (the identity and the nilpotent
        part of ``L_0``, which squares to zero), and maps to and from the
        module induced from the trivial top::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: Y.<cp, cm> = NormallyOrderedExpressions(QQ, parities={'cp': 1, 'cm': 1})
            sage: SF = UniversalVertexAlgebra(QQ, Y, {('cp', 'cm'): [0, 1]}, conformal_vector=cm * cp,
            ....:                             horizontal_grading={'cp': 1, 'cm': -1})
            sage: a, b = SF.gens()
            sage: S = SF.subalgebra([SF.conformal_vector(), a.no(a.derivative()),
            ....:                    a.no(b.derivative()) + b.no(a.derivative()), b.no(b.derivative())],
            ....:                   names=['T', 'Wp', 'W0', 'Wm'], horizontal_grading='ambient',
            ....:                   conformal_vector='ambient')
            sage: P = S.presentation(); Z = P.zhu_algebra_up_to(8); O = matrix(QQ, 2, 2)
            sage: Uj = Z.module({'T': matrix([[0, 1], [0, 0]]), 'Wp': O, 'W0': O, 'Wm': O},
            ....:               horizontal_grades=[0, 0])
            sage: Ut = Z.module({'T': 0, 'Wp': 0, 'W0': 0, 'Wm': 0}, horizontal_grades=[0])
            sage: Pj, Mt = P.induced_module_up_to(Uj, 8, 4), P.induced_module_up_to(Ut, 8, 4)
            sage: E = End(Pj); len(E.basis()), E.checked_up_to_depth()
            (2, 4)
            sage: u0, u1 = E.generating_vectors(); T = P.gen('T')
            sage: nil = Pj.hom([Pj.zero(), u0]); nil.checked_up_to_depth()
            4
            sage: nil.is_zero(), nil == E.identity(), (nil * nil).is_zero()
            (False, False, True)
            sage: nil(T.mode(u1, -2)) == T.mode(u0, -2)
            True
            sage: Hom(Mt, Pj).dimension(), Hom(Pj, Mt).dimension()
            (1, 1)
        """
        B = self.basis(weight, horizontal_grade, check_depth)
        if B:
            return _combine(*[f._checked for f in B])
        if _kind(self.domain()) == 'quotient' and not self._quotient_exact():
            return check_depth if check_depth is not None else self._window()
        return None

    def _quotient_exact(self):
        r"""
        Whether the relations of a quotient domain are imposed exactly.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: End(M.simple_quotient())._quotient_exact()
            True
        """
        X, Y = self.domain(), self.codomain()
        K = X.defining_submodule()
        if getattr(K, '_is_maximal_submodule', False):
            T = X.vertex_algebra().conformal_vector()
            return bool(Y._is_simple() and T is not None and X.ambient()._l0_grading())
        from .vertex_algebra_submodule import FinitelyGeneratedSubmodule
        return isinstance(K, FinitelyGeneratedSubmodule)

    def _window(self):
        r"""
        The depth of a windowed quotient domain (``None`` otherwise).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: End(M.simple_quotient())._window() is None
            True
        """
        return getattr(self.domain().defining_submodule(), '_depth', None)


def _combine(*checked):
    r"""
    The depth up to which a combination of morphisms is checked: ``None``
    (exact) if all are, else the smallest depth.

    TESTS::

        sage: from vertex_algebras.vertex_algebra_module_morphism import _combine
        sage: _combine(None, 3, 5), _combine(None, None), _combine()
        (3, None, None)
    """
    c = [x for x in checked if x is not None]
    return min(c) if c else None


