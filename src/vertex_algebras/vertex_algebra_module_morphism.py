    def _lattice_key(self, k):
        r"""
        The image of the key ``k = (letters, p)`` of a lattice module:
        ``:∂^n J_i rest: = n! J_i_(-1-n) rest``, and ``e^p = ε(a, p' -
        λ)^{-1} e^a_(N) e^{p'}`` (``a = ±x_i`` towards the generating vector
        ``e^λ``, ``p' = p - a``, ``N = -B(a, p') - 1``).

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); M = L.simple_module([1/2])
            sage: f = End(M).identity(); f._lattice_key(((), (5/2,)))
            {((), (5/2,)): 1}
        """
        from sage.arith.misc import factorial
        X, Y = self.domain(), self.codomain()
        V = X.vertex_algebra()
        letters, p = k
        if letters:
            i, n = letters[0]
            v = self._key_image((letters[1:], p))
            return _clean({y: factorial(n) * c for y, c in
                           Y._action_raw(self._jd[i], -1 - n, v).items()}) if v else {}
        mu = self._gens[0][1]
        d = [QQ(a) - QQ(b) for a, b in zip(p, mu)]
        i = next(j for j, c in enumerate(d) if c)
        sg = 1 if d[i] > 0 else -1
        r = len(p)
        a = tuple(sg if j == i else 0 for j in range(r))
        p2 = tuple(QQ(p[j]) - a[j] for j in range(r))
        N = -int(V._form(a, p2)) - 1
        v = self._key_image(((), p2))
        if not v:
            return {}
        eps = V._eps(a, X._shift(p2))
        return _clean({y: c / eps for y, c in Y._action_raw(self._ed[(i, sg)], N, v).items()})

    def _window_defect(self, depth):
        r"""
        The homomorphism property on a window: ``f(g_(n) m) - g_(n) f(m)``
        for the basis keys ``m`` of the domain of depth ``<= depth``, the
        generators ``g`` of the vertex algebra and the ``n`` with ``g_(n) m``
        of depth ``<= depth``; one raw dict, labels ``('hom', m, i, n,
        key)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: L0 = va.Lattice(QQ, matrix([[2]])); J = L0.J(0)
            sage: L = va.Lattice(QQ, matrix([[2]]), conformal_vector=J.no(J)/4)
            sage: M = L.simple_module([1/2]); End(M).identity()._window_defect(2)
            {}
        """
        from sage.functions.other import ceil
        X, Y = self.domain(), self.codomain()
        V = X.vertex_algebra()
        data = V._weight_data()
        gens = [_clean(dict(g._monomial_coefficients)) for g in V.gens()]
        hs = []
        for g in V.gens():
            ws = {V._weight_key(k, data) for k in g.support()}
            hs.append(QQ(ws.pop()))
        base = self._base_weight()
        out = {}
        for t in _degrees(X, depth):
            for m in X.weight_space(base + t).basis_keys():
                fm = self._key_image(m)
                for i, g in enumerate(gens):
                    nlo = ceil(t + hs[i] - 1 - QQ(depth))
                    nhi = max([X._nmax_key(a, m) for a in g]
                              + [Y._nmax_key(a, y) for a in self._g[i] for y in fm])
                    for n in range(nlo, nhi + 1):
                        lhs = self._eval_dict(_clean(X._action_raw(g, n, {m: 1})))
                        rhs = _clean(Y._action_raw(self._g[i], n, fm)) if fm else {}
                        for y in set(lhs) | set(rhs):
                            c = lhs.get(y, 0) - rhs.get(y, 0)
                            if c:
                                out[('hom', m, i, n, y)] = c
        return out

    def _defect(self, check_depth=None):
        r"""
        Everything that must vanish for an induced or adjoint domain, as one
        raw dict (linear in the images): labels ``('low', u, i, n, key)``
        (lowering modes / non-negative modes on the vacuum) and ``('zero',
        u, i, key)`` (zero modes against the action on the top), and
        ``('parity', u, key)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: End(M).identity()._defect()
            {}
            sage: End(M)([L.mode(v, -1)], check=False)._defect()      # singular, weight 1
            {('zero', ((), 0), 0, (((0, -1),), 0)): 1}
            sage: End(M)([L.mode(v, -2)], check=False)._defect()
            {('low', ((), 0), 0, 2, (((0, -1),), 0)): 3,
             ('low', ((), 0), 0, 3, ((), 0)): 1/4,
             ('zero', ((), 0), 0, (((0, -2),), 0)): 2}
        """
        X, Y = self.domain(), self.codomain()
        out = {}
        if self._kind == 'lattice':
            # V_{λ+L} is simple and generated by e^λ; in a semisimple Y the
            # vectors w with J_i(n) w = 0 (n > 0) and J_i(0) w = B(x_i, λ) w
            # are the copies of e^λ in the summands V_{λ+L} of Y, and each
            # extends (Schur): these conditions are exact
            V = X.vertex_algebra()
            u = self._gens[0]
            img = self._im[u]
            p = X._parity_key(u)
            for y, c in img.items():
                if Y._parity_key(y) != p:
                    out[('parity', u, y)] = c
            lam = u[1]
            r = V.rank()
            for i in range(r):
                ji = self._jd[i]
                nmax = max((Y._nmax_key(a, y) for a in ji for y in img), default=0)
                for n in range(1, nmax + 1):
                    for y, c in _clean(Y._action_raw(ji, n, img)).items() if img else ():
                        out[('low', u, i, n, y)] = c
                xi = tuple(int(k == i) for k in range(r))
                diff = _clean(Y._action_raw(ji, 0, img)) if img else {}
                _add_scaled(diff, img, -QQ(V._form(xi, lam)))
                for y, c in diff.items():
                    if c:
                        out[('eigen', u, i, y)] = c
            if not _known_semisimple(Y, V):
                if check_depth is None:
                    raise ValueError('{} is not known to be a semisimple module over {}: give '
                                     'check_depth'.format(Y, V))
                out.update(self._window_defect(check_depth))
            return out
        if self._kind == 'higher':
            return self._higher_defect()
        for u in self._gens:
            img = self._im[u]
            p = X._parity_key(u)
            for y, c in img.items():
                if Y._parity_key(y) != p:
                    out[('parity', u, y)] = c
            if self._kind == 'induced':
                lows = [(i, floor(h - 1) + 1) for i, h in enumerate(self._h)]
            else:
                lows = [(i, 0) for i in range(len(self._g))]
            for i, nmin in lows:
                nmax = max((Y._nmax_key(a, y) for a in self._g[i] for y in img), default=nmin - 1)
                for n in range(nmin, nmax + 1):
                    for y, c in self._mode(i, n, img).items():
                        out[('low', u, i, n, y)] = c
            if self._kind != 'induced':
                continue
            U = X._U
            for i, z in X._zidx.items():
                act = U._gen_action_key(z, u[1])
                if any(((), u2) not in self._im for u2 in act):
                    continue                     # a lowering generator of a Verma top
                diff = dict(self._mode(i, self._h[i] - 1, img))
                for u2, c in act.items():
                    _add_scaled(diff, self._im[((), u2)], -c)
                for y, c in diff.items():
                    if c:
                        out[('zero', u, i, y)] = c
        return out

    def _higher_defect(self):
        r"""
        The conditions on the images ``w_j`` of ``u_j`` for a domain
        ``\bar M_n(U)``, ``U`` a module over the level-``n`` Zhu algebra
        ``A_n(V)`` (He's model; Dong--Li--Mason's adjunction ``Hom_V(\bar
        M_n(U), N) = Hom_{A_n}(U, Ω_n(N))``, exact): parities; ``('low', u,
        p, i, n, y)``: every word ``g_(n) p`` of lowering generator modes
        that lowers by more than ``n`` kills ``w_j`` (``p`` lowering by at
        most ``n``: then all longer words do); ``('word', u, w, y)``: the
        generator words ``w`` of ``A_n`` act on the ``w_j`` by ``U``'s
        matrices.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); A = V.zhu_algebra(level=1)
            sage: M = V.induced_module(A.module({'L_0': 3, 'L_{-1} L_1': 4}), max_depth=3)
            sage: End(M).identity()._higher_defect()
            {}
            sage: N = V.induced_module(A.module({'L_0': 3, 'L_{-1} L_1': 0}), max_depth=3)
            sage: Hom(M, N)([N.highest_weight_vector()], check=False)._higher_defect()
            {('word', ((), ((), 0)), ((0, -1), (0, 1)), ((), ((), 0))): -4}
        """
        X, Y = self.domain(), self.codomain()
        n = self._level
        h = self._h
        out = {}
        for u in self._gens:
            img = self._im[u]
            p = X._parity_key(u)
            for y, c in img.items():
                if Y._parity_key(y) != p:
                    out[('parity', u, y)] = c
            # the words p of lowering modes (total <= n) on w_j, breadth first
            words = {(): img}
            todo = [()]
            while todo:
                w = todo.pop()
                vec = words[w]
                if not vec:
                    continue
                tot = sum(m for _, m in w)
                for i in range(len(self._g)):
                    nmax = max((Y._nmax_key(a, y) for a in self._g[i] for y in vec),
                               default=-1)
                    for m in range(1, int(floor(nmax - h[i])) + 2):
                        r = self._mode(i, m + h[i] - 1, vec)
                        if tot + m > n:
                            for y, c in r.items():
                                out[('low', u, w, i, m + h[i] - 1, y)] = c
                        elif r:
                            w2 = ((i, m),) + w
                            words[w2] = r
                            todo.append(w2)
        # the generator words of A_n act by U's matrices
        for word, mat in self._gmat.items():
            for jj, u in enumerate(self._gens):
                vec = self._im[u]
                for i, m in reversed(word):
                    vec = self._mode(i, m + h[i] - 1, vec)
                vec = dict(vec)
                for s in range(mat.nrows()):
                    if mat[s, jj]:
                        _add_scaled(vec, self._im[self._gens[s]], -mat[s, jj])
                for y, c in vec.items():
                    if c:
                        out[('word', u, word, y)] = c
        return out

    def _quotient_defect(self, check_depth=None):
        r"""
        For a quotient domain ``M / K``: the images of the relations of
        ``K`` (generators, or the rows up to a depth), as one raw dict, and
        the depth up to which they were imposed (``None``: exact).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: Q = M / M.submodule([L.mode(v, -1)])
            sage: End(Q).identity()._quotient_defect()
            ({}, None)
        """
        from .vertex_algebra_submodule import FinitelyGeneratedSubmodule
        X = self.domain()
        K = X.defining_submodule()
        H = self.parent()
        out = {}
        base = self._base
        if getattr(K, '_is_maximal_submodule', False) and H._quotient_exact():
            return out, None
        if isinstance(K, FinitelyGeneratedSubmodule):
            for j, g in enumerate(K.gens()):
                for y, c in base._eval_dict(dict(K.lift(g)._monomial_coefficients)).items():
                    out[('gen', j, y)] = c
            return out, None
        if check_depth is None:
            check_depth = H._window()
        if check_depth is None:
            raise ValueError('the maximal submodule of {} is known only degree by degree and '
                             '{} is not known to be simple: give check_depth'
                             .format(X.ambient(), self.codomain()))
        for t in _degrees(X.ambient(), check_depth):
            for j, r in enumerate(K._rows_at_tdeg(t)):
                for y, c in base._eval_dict(r).items():
                    out[('row', t, j, y)] = c
        return out, check_depth

    def _check(self, check_depth):
        r"""
        Raise ``ValueError`` unless the images define a morphism (exactly, or
        up to ``check_depth``; recorded in :meth:`checked_up_to_depth`).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); v = M.highest_weight_vector()
            sage: End(M)([L.mode(v, -1)])
            Traceback (most recent call last):
            ...
            ValueError: the zero mode of L does not intertwine on the image of v
        """
        X = self.domain()
        if self._kind == 'quotient':
            self._base._check(check_depth)
            d, checked = self._quotient_defect(check_depth)
            if d:
                lab = next(iter(d))
                raise ValueError('the images do not kill the relations of {} ({} {})'
                                 .format(X, lab[0], lab[1]))
            self._checked = _combine(self._base._checked, checked)
            return
        if self._kind in ('twist', 'flow'):
            self._base._check(check_depth)
            self._checked = self._base._checked
            return
        if self._kind == 'sum':
            for f in self._parts:
                f._check(check_depth)
            self._checked = _combine(*[f._checked for f in self._parts])
            return
        d = self._defect(check_depth)
        if self._kind == 'lattice':
            self._checked = self._lattice_checked(check_depth)
        if d:
            lab = next(iter(d))
            u = X.monomial(lab[1])
            if lab[0] == 'hom':
                raise ValueError('the images do not define a morphism: the mode {}_({}) on '
                                 '{}'.format(self._gnames[lab[2]], lab[3], u))
            if lab[0] == 'parity':
                raise ValueError('the image of {} does not have its parity'.format(u))
            if lab[0] == 'low' and self._kind == 'higher':
                raise ValueError('the image of {} is not killed by the mode {}_({}) after the '
                                 'lowering word {} (it is not in Omega_{}(N))'.format(
                                     u, self._gnames[lab[3]], lab[4], lab[2], self._level))
            if lab[0] == 'word':
                raise ValueError('the generator word {} of the Zhu algebra does not act on the '
                                 'image of {} as on U'.format(lab[2], u))
            if lab[0] == 'low':
                raise ValueError('the image of {} is not killed by the mode {}_({}) (it is '
                                 'not in Omega(N))'.format(u, self._gnames[lab[2]], lab[3]))
            if lab[0] == 'eigen':
                lam = lab[1][1]
                xi = tuple(int(k == lab[2]) for k in range(len(lam)))
                raise ValueError('{}_(0) does not act on the image of {} by {}'.format(
                    self._gnames[lab[2]], u, X.vertex_algebra()._form(xi, lam)))
            raise ValueError('the zero mode of {} does not intertwine on the image of {}'
                             .format(self._gnames[lab[2]], u))

    def _lattice_checked(self, check_depth):
        r"""
        For a lattice domain: ``None`` (exact) if the codomain is known to be
        semisimple (:func:`_known_semisimple`), else ``check_depth``.

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); M = L.simple_module([1/2])
            sage: End(M).identity()._lattice_checked(3) is None
            True
        """
        if _known_semisimple(self.codomain(), self.domain().vertex_algebra()):
            return None
        return check_depth

