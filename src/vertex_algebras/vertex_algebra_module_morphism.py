from .vertex_algebra_submodule import VertexAlgebraSubmodule


class KernelSubmodule(VertexAlgebraSubmodule):
    r"""
    The kernel of a module morphism ``f: M -> N``, a submodule of ``M``:
    piece by piece (twisted degree), the left kernel of ``f`` on a basis of
    the piece, in reduced echelon form.  Exact per piece.

    Built by ``f.kernel()``.

    INPUT:

    - ``f`` -- a :class:`ModuleMorphism`

    EXAMPLES:

    The kernel of ``M(1/2, 1) -> M(1/2, 0)``, ``v -> L_{-1} v`` is zero, that of the
    cover of ``L(1/2, 0)`` the maximal submodule::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
        sage: M0, M1 = V.verma_module(0), V.verma_module(1)
        sage: K = Hom(M1, M0).basis()[0].kernel(); K
        Kernel of a module morphism from Verma module of highest weight {'L': 1} over ... to Verma module of highest weight {'L': 0} over ...
        sage: [K.weight_space(1 + d).dimension() for d in range(5)]
        [0, 0, 0, 0, 0]
        sage: K = M0.simple_quotient().cover().kernel()
        sage: [K.weight_space(d).dimension() for d in range(7)]
        [0, 1, 1, 2, 3, 5, 8]
        sage: TestSuite(K).run()
    """

    @staticmethod
    def __classcall_private__(cls, f):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: p = M.simple_quotient().cover(); p.kernel() is p.kernel()
            True
        """
        from .vertex_algebra_module import VertexAlgebraModule
        return VertexAlgebraModule.__classcall__(cls, f)

    def __init__(self, f):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: K = M.simple_quotient().cover().kernel()
            sage: K._ambient_module is M, K._whole, K._zero
            (True, False, False)
        """
        self._f = f
        self._J = {}
        self._whole = False
        self._zero = False
        self._init_submodule(f.domain())

    def _repr_(self):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: repr(M.simple_quotient().cover().kernel()).startswith('Kernel of')
            True
        """
        f = self._f
        return 'Kernel of a module morphism from {} to {}'.format(f.domain(), f.codomain())

    def morphism(self):
        r"""
        The morphism this is the kernel of.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: p = M.simple_quotient().cover(); p.kernel().morphism() == p
            True
        """
        return self._f

    def _echelon_piece(self, p):
        r"""
        The kernel in the piece ``p = (t, None)``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: K = M.simple_quotient().cover().kernel()
            sage: K._echelon_piece((1, None)).rows()
            [{(((0, -1),), 0): 1}]
        """
        from ._keyed_spans import KeyedSpan
        t = QQ(p[0])
        E = self._J.get(t)
        if E is not None:
            return E
        M = self._ambient_module
        R = self.base_ring()
        basis = M._tdeg_basis(t)
        imgs = [self._f._eval_dict(b) for b in basis]
        kernel = []
        for rel in left_kernel(imgs, R):
            v = {}
            for j, c in rel.items():
                _add_scaled(v, basis[j], c)
            kernel.append(_clean(v))
        E = KeyedSpan(R, key_order=M._key_order)
        if kernel:
            E.insert_many(kernel)
        self._J[t] = E
        return E

    def some_elements(self):
        r"""
        A few vectors of the kernel: the zero vector and the first rows of the
        lowest pieces (twisted degrees up to 4).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: M.simple_quotient().cover().kernel().some_elements()
            [0, L_{-1} v, L_{-1} L_{-1} v]
        """
        out = [self.zero()]
        M = self._ambient_module
        try:
            degrees = _degrees(M, 4)
        except NotImplementedError:
            degrees = []
        for t in degrees:
            for r in self._echelon_piece((t, None)).rows()[:1]:
                out.append(self._from_dict(r))
            if len(out) >= 3:
                break
        return out

    def _is_graded_submodule(self):
        r"""
        Not known to be graded (the morphism need not be).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: M.simple_quotient().cover().kernel()._is_graded_submodule()
            False
        """
        return False


