    #  Evaluation                                                      #
    # -------------------------------------------------------------- #

    def _mode(self, i, n, vec):
        r"""
        ``g_i_(n) vec`` in the codomain (``g_i`` the ``i``-th generator, raw
        dicts).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: f = End(M).identity(); f._mode(0, 0, {((), 0): 1})
            {(((0, -1),), 0): 1}
        """
        if not vec:
            return {}
        return _clean(self.codomain()._action_raw(self._g[i], int(n), vec))

    def _key_image(self, k):
        r"""
        The image of the basis key ``k`` of the domain, a raw dict
        (memoised).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: f = End(M).identity(); f._key_image((((0, -2), (0, -1)), 0))
            {(((0, -2), (0, -1)), 0): 1}
        """
        try:
            return self._memo[k]
        except KeyError:
            pass
        if self._base is not None:
            r = self._base._key_image(k)
        elif self._kind == 'sum':
            r = self._parts[k[0]]._key_image(k[1])
        elif k in self._im:
            r = self._im[k]
        elif self._kind == 'lattice':
            r = self._lattice_key(k)
        elif self._kind == 'higher':
            # (t_1 ... t_k, (l, j)) = t_1 ... t_k l u_j, outermost first
            modes, (l, j) = k
            if modes:
                (i, m), rest = modes[0], modes[1:]
                r = self._mode(i, m + self._h[i] - 1, self._key_image((rest, (l, j))))
            else:
                (i, m), rest = l[0], l[1:]
                r = self._mode(i, m + self._h[i] - 1, self._key_image(((), (rest, j))))
        elif self._kind == 'induced':
            modes, u = k
            if modes:
                (i, m), rest = modes[0], modes[1:]
                r = self._mode(i, m + self._h[i] - 1, self._key_image((rest, u)))
            else:
                # a Verma module of the Zhu algebra: u = l u', l a lowering
                # Zhu generator acting by the zero mode of its generator
                i = self._zinv[u[0]]
                r = self._mode(i, self._h[i] - 1, self._key_image(((), u[1:])))
        else:
            Y = self.codomain()
            V = self.domain().vertex_algebra()
            a = _clean(dict(Y._vertex_algebra_element(V.monomial(k))._monomial_coefficients))
            w = self._im[self._gens[0]]
            r = _clean(Y._action_raw(a, -1, w)) if w else {}
        self._memo[k] = r
        return r

    def _eval_dict(self, d):
        r"""
        The image of the raw dict ``d`` of the domain, a raw dict.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: End(M).identity()._eval_dict({((), 0): 2})
            {((), 0): 2}
        """
        out = {}
        for k, c in d.items():
            _add_scaled(out, self._key_image(k), c)
        return _clean(out)

    def _call_(self, x):
        r"""
        The image of ``x``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: M = V.verma_module(0); f = 2 * End(M).identity()
            sage: f(L.mode(M.highest_weight_vector(), -3))
            2*L_{-3} v
        """
        Y = self.codomain()
        return Y._from_dict(self._eval_dict(dict(x._monomial_coefficients)), coerce=False,
                            remove_zeros=True)

