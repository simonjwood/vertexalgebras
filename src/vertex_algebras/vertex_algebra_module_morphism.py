def _kind(M):
    r"""
    How morphisms out of ``M`` are given: ``'higher'`` (``\bar M_n(U)``
    induced from an ``A_n(V)``-module, ``n >= 1``), ``'quotient'``,
    ``'twist'``, ``'flow'``, ``'induced'``, ``'adjoint'``, ``'lattice'``,
    ``'sum'`` (direct sums of those), or ``None`` (not supported).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_module_morphism import _kind
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
        sage: [_kind(X) for X in (M, M.simple_quotient(), V.adjoint_module())]
        ['induced', 'quotient', 'adjoint']
    """
    from .higher_zhu_algebra import HigherInducedModule
    from .lattice_vertex_algebra_module import LatticeVertexAlgebraModule
    from .module_twists import PullbackModule, SpectralFlowModule
    from .vertex_algebra_module import AdjointModule, InducedModule
    from .vertex_algebra_submodule import DirectSumOfModules
    if isinstance(M, LatticeVertexAlgebraModule):
        return 'lattice'
    if isinstance(M, DirectSumOfModules):
        return 'sum' if all(_kind(N) is not None for N in M.summands()) else None
    if getattr(M, '_cover_module', None) is not None and getattr(M, '_N', None) is not None:
        if isinstance(M._cover_module, HigherInducedModule):
            return 'higher'
        return 'quotient'
    if isinstance(M, SpectralFlowModule):
        return 'flow'
    if isinstance(M, PullbackModule):
        from .module_twists import _inverse
        if _inverse(M.morphism()) is not None:
            return 'twist'
        return None
    if isinstance(M, InducedModule) and not isinstance(M, HigherInducedModule):
        return 'induced'
    if isinstance(M, AdjointModule):
        return 'adjoint'
    return None


def _generating_keys(M):
    r"""
    The basis keys of ``M`` whose images define a morphism out of ``M``: the
    top level of an induced module (the highest weight vector for an
    infinite top), the vacuum of the adjoint module, ``e^λ`` of a lattice
    module ``V_{λ+L}`` (``λ`` the canonical representative,
    :meth:`~vertex_algebras.lattice_vertex_algebra_module.LatticeVertexAlgebraModule.coset_representative`);
    quotients and twists: those of the module underneath.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_module_morphism import _generating_keys
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
        sage: _generating_keys(V.verma_module(0)), _generating_keys(V.adjoint_module())
        ([((), 0)], [()])
    """
    k = _kind(M)
    if k == 'induced':
        U = M._U
        top = U._top_keys()
        if top is None:
            return [((), U._first_key())]
        return [((), u) for u in top]
    if k == 'adjoint':
        return [M.vertex_algebra()._vacuum_key()]
    if k == 'lattice':
        return [((), M._lam)]
    if k == 'higher':
        return [((), ((), j)) for j in range(M._cover_module._U._dim)]
    if k == 'quotient':
        return _generating_keys(M.ambient())
    if k in ('twist', 'flow'):
        return _generating_keys(M.underlying_module())
    if k == 'sum':
        return [(i, g) for i, N in enumerate(M.summands()) for g in _generating_keys(N)]
    raise NotImplementedError('morphisms out of {} are not implemented yet'.format(M))


def _lowest_weight(M, k):
    r"""
    The lowest weight of the submodule generated by the generating key ``k``
    of ``M`` when known (lattice modules, also as summands), else the weight
    of ``k``.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_module_morphism import _lowest_weight
        sage: L0 = va.Lattice(QQ, matrix([[3]])); J = L0.J(0)
        sage: M = L0.with_conformal_vector(J.no(J) / 6).simple_module([2/3])
        sage: _lowest_weight(M, ((), (2/3,))), M._weight_key(((), (2/3,)))
        (1/6, 2/3)
    """
    kind = _kind(M)
    if kind == 'lattice':
        return M._weight_key(M.highest_weight_vector().leading_support())
    if kind == 'sum':
        return _lowest_weight(M.summands()[k[0]], k[1])
    return M._weight_key(k)


def _known_semisimple(Y, V):
    r"""
    Whether ``Y`` is known to be a semisimple module over the lattice vertex
    algebra ``V``, i.e. a direct sum of simple modules ``V_{ν+L}``: every
    module of an even positive definite lattice ([DLM1997]_: ``V_L`` is
    regular), and, for any lattice, the modules built from simple ones (lattice
    modules, the adjoint module, direct sums, submodules, quotients,
    spectral flows, twists by automorphisms).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_module_morphism import _known_semisimple
        sage: L = va.Lattice(QQ, matrix([[0, 1], [1, 0]]))
        sage: M = L.simple_module([0, 0])
        sage: _known_semisimple(M.direct_sum(M), L), _known_semisimple(L.adjoint_module(), L)
        (True, True)

    Hom between the simple modules of ``A_2`` is ``δ`` (exact, by Schur's
    lemma), and each identity is an isomorphism::

        sage: def lattice(B, **kw):
        ....:     L0 = va.Lattice(QQ, B); Bi = B.inverse(); r = B.nrows()
        ....:     T = sum(Bi[i, j] * L0.J(i).no(L0.J(j)) for i in range(r) for j in range(r)) / 2
        ....:     return va.Lattice(QQ, B, conformal_vector=T, **kw)
        sage: mods = lattice(matrix([[2, -1], [-1, 2]])).simple_modules()
        sage: [[Hom(X, Y).dimension() for Y in mods] for X in mods]
        [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
        sage: [End(X).checked_up_to_depth() for X in mods]
        [None, None, None]
        sage: all(End(X).basis()[0].is_isomorphism_up_to(3) for X in mods)
        True

    An indefinite lattice: Hom counts multiplicities, exactly::

        sage: L0 = va.Lattice(QQ, diagonal_matrix([2, -2])); J0, J1 = L0.J(0), L0.J(1)
        sage: LI = va.Lattice(QQ, diagonal_matrix([2, -2]), conformal_vector=J0.no(J0) / 4 - J1.no(J1) / 4,
        ....:                 horizontal_grading='lattice')
        sage: MI, NI = LI.simple_module([1/2, 1/2]), LI.simple_module([1/2, 0])
        sage: Hom(MI, NI).dimension(), End(MI).dimension(), End(MI.direct_sum(MI, NI)).dimension()
        (0, 1, 5)
        sage: End(MI).checked_up_to_depth() is None
        True

    A spectral flow of a lattice module is known to be semisimple: Hom into
    it is exact::

        sage: A1 = lattice(matrix([[2]]), horizontal_grading='lattice')
        sage: Fl = A1.simple_module([0]).spectral_flow(A1.J(0) / 2)
        sage: Hom(A1.simple_module([1/2]), Fl).checked_up_to_depth() is None
        True

    The pullback of ``V_{√3 Z}`` along ``V_{3√3 Z} -> V_{√3 Z}`` (an odd
    lattice) is not known to be semisimple, so Hom into it needs a depth.
    ``V_{√3 Z}`` is ``V_{0+L} + V_{1/3+L} + V_{2/3+L}``, and ``e^(1)`` is
    odd, so no even map comes from ``V_{1/3+L}``::

        sage: A27, C3 = lattice(matrix([[27]])), lattice(matrix([[3]]))
        sage: Y = C3.adjoint_module().pullback(A27.hom([C3.e((3,)), C3.e((-3,))], C3))
        sage: _known_semisimple(Y, A27)
        False
        sage: Hom(A27.simple_module([0]), Y).basis()
        Traceback (most recent call last):
        ...
        ValueError: Pullback of ... is not known to be a semisimple module over ...: give check_depth
        sage: [Hom(A27.simple_module([l]), Y).dimension(check_depth=2) for l in (0, 1/3, 2/3, 1/27)]
        [1, 0, 1, 0]
        sage: Hom(A27.simple_module([0]), Y).checked_up_to_depth(check_depth=2)
        2
    """
    from .lattice_vertex_algebra_module import LatticeVertexAlgebraModule
    from .module_twists import PullbackModule, _inverse
    B = V.gram_matrix()
    if all(B[i, i] % 2 == 0 for i in range(B.nrows())) and B.is_positive_definite():
        return True
    if isinstance(Y, LatticeVertexAlgebraModule):
        return True
    k = _kind(Y)
    if k == 'adjoint':
        return getattr(Y.vertex_algebra(), '_is_lattice_vertex_algebra', False)
    if k == 'sum':
        return all(_known_semisimple(N, V) for N in Y.summands())
    if k == 'flow':
        return _known_semisimple(Y.underlying_module(), V)
    if isinstance(Y, PullbackModule):
        phi = Y.morphism()
        return (phi.domain() is phi.codomain() and _inverse(phi) is not None
                and _known_semisimple(Y.underlying_module(), V))
    if hasattr(Y, '_cover_module') or hasattr(Y, '_ambient_module'):
        return _known_semisimple(Y.ambient(), V)
    return False


def _underlying_codomain(M, Y):
    r"""
    For a twisted domain ``M`` (``M = P^σ`` or the flow of ``P`` by ``h``):
    the codomain ``Y`` twisted back (``Y^{σ^{-1}}``, the flow by ``-h``), so
    that ``Hom(M, Y) = Hom(P, Y')`` with the same linear maps.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_module_morphism import _underlying_codomain
        sage: H = va.FreeBosons(QQ); J = H.gen(0); H = H.with_conformal_vector(J.no(J)/2)
        sage: J = H.gen(0); F = H.induced_module(H.zhu_algebra().module({'alpha': 0}))
        sage: S = F.spectral_flow(J); _underlying_codomain(S, S) is F
        True
    """
    k = _kind(M)
    if k == 'twist':
        sigma = M.morphism()
        if getattr(Y, '_phi', None) is not None and _kind(Y) == 'twist' and Y.morphism() == sigma:
            return Y.underlying_module()
        from .module_twists import _inverse
        inv = _inverse(sigma)
        if inv is None:
            raise NotImplementedError('the inverse of {} is not known'.format(sigma))
        return Y.twist(inv)
    h = M._h
    if _kind(Y) == 'flow' and Y._h == h:
        return Y.underlying_module()
    return Y.spectral_flow(-h)


def _clean(d):
    """The raw dict ``d`` without zero coefficients.

    TESTS::

        sage: from vertex_algebras.vertex_algebra_module_morphism import _clean
        sage: _clean({1: 0, 2: 3})
        {2: 3}
    """
    return {k: c for k, c in d.items() if c}


def _degrees(M, depth):
    r"""
    The twisted degrees ``0, 1/D, ..., depth`` of ``M`` (``D`` the common
    denominator of the weights of the generators); ``NotImplementedError``
    for modules with a twisted degree functional.

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra_module_morphism import _degrees
        sage: V = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L')
        sage: _degrees(V.verma_module(0), 1)
        [0, 1/2, 1]
    """
    if M._mu is not None:
        raise NotImplementedError('checks up to a depth of modules graded by a twisted degree '
                                  '(infinite top levels) are not implemented yet')
    V = M.vertex_algebra()
    D = getattr(M, '_D', None)
    if D is None:
        D = lcm([QQ(V._weight_key(k, V._weight_data())).denominator()
                 for g in V.gens() for k in g.support()] + [1])
    return [QQ((j, D)) for j in range(floor(QQ(depth) * D) + 1)]


