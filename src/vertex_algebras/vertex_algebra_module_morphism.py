def _make_module_morphism(X, Y, images, checked):
    r"""
    Unpickling: the morphism with these images, not checked again.

    TESTS::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
        sage: f = End(M).identity(); loads(dumps(f)) == f
        True
    """
    return Hom(X, Y).element_class(Hom(X, Y), list(images), check=False, _checked=checked)


class ModuleMorphism(Morphism):
    r"""
    A morphism of modules over a vertex algebra, given by the images of the
    generating vectors of its domain (see the module documentation for
    what is checked).

    Built by ``M.hom(images, N)`` or ``Hom(M, N)(images)``.

    INPUT:

    - ``parent`` -- a :class:`ModuleHomset`
    - ``im_gens`` -- the images of the generating vectors of the domain
      (see :meth:`ModuleHomset.generating_vectors`): a list in their
      order, a dict by generating vector, or a morphism with the same
      images (e.g. out of the cover of a quotient)
    - ``check`` -- boolean (default: ``True``); whether to check the
      relations of the domain (``ValueError`` if they fail)
    - ``check_depth`` -- (default: ``None``) the depth up to which
      relations known only degree by degree are checked
    - ``_checked`` -- (default: ``None``) internal: the depth recorded as
      :meth:`checked_up_to_depth` of a morphism built without checks

    EXAMPLES:

    The singular vector of level 2 of the Virasoro Verma module ``M(1/2,
    1/2)`` (Ising) defines a morphism from ``M(1/2, 5/2)``::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
        sage: M0, M2 = V.verma_module(1/2), V.verma_module(5/2)
        sage: v = M0.highest_weight_vector()
        sage: s = L.mode(L.mode(v, -1), -1) - 4/3*L.mode(v, -2)
        sage: f = M2.hom([s], M0); f(L.mode(M2.highest_weight_vector(), -1)) == L.mode(s, -1)
        True
        sage: M2.hom([L.mode(v, -2)], M0)
        Traceback (most recent call last):
        ...
        ValueError: the image of v is not killed by the mode L_(2) (it is not in Omega(N))
    """

    def __init__(self, parent, im_gens, check=True, check_depth=None, _checked=None):
        r"""
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: v = M.highest_weight_vector(); End(M)([v, v])
            Traceback (most recent call last):
            ...
            ValueError: expected 1 images, got 2
        """
        Morphism.__init__(self, parent)
        X, Y = parent.domain(), parent.codomain()
        self._kind = _kind(X)
        self._gens = _generating_keys(X)
        self._memo = {}
        self._checked = _checked
        self._im = self._normalize(im_gens)
        if self._kind == 'quotient':
            self._base = Hom(X.ambient(), Y).element_class(
                Hom(X.ambient(), Y), [Y._from_dict(self._im[k]) for k in self._gens], check=False)
        elif self._kind == 'sum':
            self._base = None
            self._parts = []
            for i, N in enumerate(X.summands()):
                HN = Hom(N, Y)
                self._parts.append(HN.element_class(
                    HN, [Y._from_dict(self._im[(j, g)]) for j, g in self._gens if j == i],
                    check=False))
        elif self._kind in ('twist', 'flow'):
            Y2 = _underlying_codomain(X, Y)
            H2 = Hom(X.underlying_module(), Y2)
            self._base = H2.element_class(H2, [Y2._from_dict(self._im[k]) for k in self._gens],
                                          check=False)
        else:
            self._base = None
            V = X.vertex_algebra()
            if self._kind == 'higher':
                C = X._cover_module
                self._h = C._h
                self._level = C._n
                self._gmat = C._Un._gmat
                gens = C._V.gens()
            elif self._kind == 'induced':
                W = X._V
                self._h = X._h
                self._zinv = {z: i for i, z in X._zidx.items()}
                gens = W.gens()
            elif self._kind == 'lattice':
                self._h = None
                gens = V.gens()
                conv = lambda a: _clean(dict(Y._vertex_algebra_element(a)._monomial_coefficients))
                r = V.rank()
                self._jd = [conv(V.J(i)) for i in range(r)]
                self._ed = {(i, sg): conv(V.e(tuple(sg if k == i else 0 for k in range(r))))
                            for i in range(r) for sg in (1, -1)}
            else:
                self._h = None
                gens = V.gens()
            self._g = [_clean(dict(Y._vertex_algebra_element(g)._monomial_coefficients))
                       for g in gens]
            self._gnames = [str(g) for g in gens]
        if check:
            self._check(check_depth)

    # -------------------------------------------------------------- #
    #  Input                                                           #
    # -------------------------------------------------------------- #

    def _normalize(self, im_gens):
        r"""
        The images as a dict ``{generating key: raw dict of the codomain}``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); M = V.verma_module(0)
            sage: End(M).identity()._normalize([M.highest_weight_vector()])
            {((), 0): {((), 0): 1}}
        """
        X, Y = self.domain(), self.codomain()
        gens = self._gens
        if isinstance(im_gens, ModuleMorphism):
            im_gens = list(im_gens.im_gens())
        if isinstance(im_gens, dict):
            d = {}
            for k, v in im_gens.items():
                kk = k
                if _parent(k) is not None and k in X:
                    x = X(k)
                    if len(x.support()) != 1 or x.leading_coefficient() != 1:
                        raise ValueError('{} is not a generating vector'.format(k))
                    kk = x.leading_support()
                d[kk] = v
            imgs = [d.get(k, Y.zero()) for k in gens]
            if any(k not in gens for k in d):
                raise ValueError('the images must be of the generating vectors {}'.format(
                    [X.monomial(k) for k in gens]))
        else:
            if not isinstance(im_gens, (list, tuple)):
                im_gens = [im_gens]
            imgs = list(im_gens)
            if len(imgs) != len(gens):
                raise ValueError('expected {} images, got {}'.format(len(gens), len(imgs)))
        out = {}
        for k, v in zip(gens, imgs):
            v = Y._vector(v) if v != 0 else Y.zero()
            out[k] = _clean(dict(v._monomial_coefficients))
        return out

