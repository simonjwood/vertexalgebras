def _realization(P):
    r"""
    ``P.realization()`` (unpickling).

    TESTS::

        sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
        sage: from vertex_algebras.presented_vertex_algebra import _realization
        sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]}, degrees={'J': 1})
        sage: J = H.gen('J'); P = H.subalgebra([J.no(J)/2], names=['L']).presentation()
        sage: _realization(P) == P.realization()
        True
    """
    return P.realization()


class PresentedVertexAlgebra(QuotientVertexAlgebra):
    r"""
    A presentation ``F / R`` of a vertex subalgebra ``S`` by its strong
    generators (see the module documentation and :meth:`vertex_subalgebra.VertexSubalgebra.presentation`):
    the quotient of the universal (proto) vertex algebra ``F`` on the
    strong generators by the kernel of the realization ``F -> S``.

    Users obtain it from :meth:`vertex_subalgebra.VertexSubalgebra.presentation`;
    the constructor takes the arguments of
    :class:`~quotient_vertex_algebra.QuotientVertexAlgebra`.

    INPUT:

    - ``ambient`` -- the universal (proto) vertex algebra ``F`` on the
      strong generators

    - ``ideal`` -- the kernel ``R`` of the realization (a
      :class:`~vertex_ideal.KernelIdeal`), or what
      :class:`~quotient_vertex_algebra.QuotientVertexAlgebra` accepts

    - ``horizontal_grading`` -- (default: ``None``) ``None`` or
      ``'ambient'``, as for :class:`~quotient_vertex_algebra.QuotientVertexAlgebra`

    - ``names`` -- (default: ``None``) as for
      :class:`~quotient_vertex_algebra.QuotientVertexAlgebra` (only for
      generators of an ideal)

    - ``conformal_vector`` -- (default: ``None``) ``None``, ``'ambient'``
      or an element, as for :class:`~quotient_vertex_algebra.QuotientVertexAlgebra`

    EXAMPLES:

    The Ising model as the Virasoro subalgebra of a Majorana fermion::

        sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
        sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
        sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
        sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
        ....:                              conformal_vector=psi.derivative()*psi/2)
        sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
        sage: from vertex_algebras.presented_vertex_algebra import PresentedVertexAlgebra
        sage: isinstance(P, PresentedVertexAlgebra), P.ambient()
        (True, Universal vertex algebra on generators ['L'] over Rational Field)
        sage: [P.weight_space(w).dimension() for w in range(9)]
        [1, 0, 1, 1, 2, 2, 3, 3, 5]
    """

    @staticmethod
    def __classcall_private__(cls, ambient, ideal, horizontal_grading=None, names=None,
                              conformal_vector=None):
        r"""
        Normalize the arguments as the quotient does (Sage's private
        classcall is not inherited by subclasses).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: from vertex_algebras.presented_vertex_algebra import PresentedVertexAlgebra
            sage: PresentedVertexAlgebra(P.ambient(), P.defining_ideal()) is P
            True
        """
        # (the private classcall of the quotient is not inherited)
        return QuotientVertexAlgebra.__classcall_private__(cls, ambient, ideal, horizontal_grading, names,
                                                           conformal_vector)

    @property
    def _presentation_of(self):
        r"""
        The vertex subalgebra ``S`` this presents (recorded on the ideal).

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: P._presentation_of is S
            True
        """
        return self._I._presented[0]

    def __reduce__(self):
        r"""
        Pickle as the call ``_presentation(S, names)``, which finds the
        presentation cached on ``S``.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: P.__reduce__()[1] == (S, None)
            True
            sage: loads(dumps(P)) is P
            True
        """
        return (_presentation, self._I._presented)

    def _repr_(self):
        r"""
        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: repr(P)
            "Presentation of Vertex subalgebra of ... strongly generated by ['L'] by generators ['L'] and relations"
        """
        return 'Presentation of {} by generators {} and relations'.format(
            self._presentation_of, list(self._ambient.variable_names()))

    def realization(self):
        r"""
        The realization ``P -> S``, an isomorphism of vertex algebras
        onto the vertex algebra ``S`` this presents (its inverse is
        ``P(s)``, through :meth:`~vertex_subalgebra.NormalOrderedSpans.express`).

        OUTPUT:

        A morphism of vertex algebras from ``self`` to ``S`` (evaluated
        lazily, not checked: it is a morphism by construction).

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: r = P.realization(); r.codomain() is S
            True
            sage: L = P.gen('L'); r(L.no(L)) == S.gen('L').no(S.gen('L'))
            True
            sage: r(P.relations(6)[0])
            0
            sage: loads(dumps(r)) == r
            True
        """
        from .vertex_algebra_morphism import _function_morphism
        return _function_morphism(self, self._presentation_of, self._realize,
                                  reduction=(_realization, (self,)))

    def relations(self, weight, horizontal_grade=None):
        r"""
        The relations of weight ``weight`` (and ``horizontal_grade``, if graded): the
        canonical basis of the kernel of the realization in that weight, as
        elements of the universal vertex algebra on the generators.

        INPUT:

        - ``weight`` -- a conformal weight

        - ``horizontal_grade`` -- (default: ``None``) a grade, if the
          presentation is graded, or ``None`` for all grades

        OUTPUT: a list of elements of ``self.ambient()``

        EXAMPLES:

        The Ising model: the first relation is the singular vector of weight
        6 of the universal Virasoro vertex algebra at ``c = 1/2``::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: [len(P.relations(w)) for w in range(8)]
            [0, 0, 0, 0, 0, 0, 1, 1]
            sage: r = P.relations(6)[0]; r
            :L L L: + 93/64*:dL dL: - 33/16*:d^2L L: - 9/128*d^4L
            sage: r.parent() is P.ambient(), S(P(r)) == 0
            (True, True)
        """
        return self._I.weight_space(weight, horizontal_grade).basis()

    def _realize(self, x):
        r"""
        The element of ``S`` represented by ``x``: the realization of the
        normal form of ``P(x)``, computed from the NO-monomial vectors of
        ``S`` (``S._vectors``) of its keys.

        TESTS::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: X.<psi> = NormallyOrderedExpressions(QQ, parities={'psi': 1})
            sage: Maj = UniversalVertexAlgebra(QQ, X, {('psi', 'psi'): [1]},
            ....:                              conformal_vector=psi.derivative()*psi/2)
            sage: S = Maj.subalgebra([Maj.conformal_vector()], names=['L']); P = S.presentation()
            sage: L = P.gen('L'); P._realize(L.no(L)) == S.gen('L').no(S.gen('L'))
            True
            sage: P._realize(P.relations(6)[0])
            0
        """
        S = self._presentation_of
        d = dict(self(x)._monomial_coefficients)
        keys = list(d)
        out = {}
        for k, v in zip(keys, S._vectors(keys)):
            for m, c in v.items():
                out[m] = out.get(m, 0) + d[k] * c
        return S._el({m: c for m, c in out.items() if c})


def _presentation(S, names=None):
    r"""
    The presentation ``F / R`` of the vertex subalgebra ``S`` by its strong
    generators: ``F`` the universal (proto) vertex algebra on them with
    their OPEs written in their normally ordered monomials, ``R`` the kernel
    of the realization ``F -> S`` (see the module documentation).  Also
    ``S.presentation()``.  ``names``: names of the generators (default those
    of ``S``).  The conformal weights, the grading (if ``S`` is graded) and
    the conformal vector (if ``S`` has one) carry over.

    EXAMPLES::

        sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
        sage: H = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]},
        ....:     conformal_vector={(('J', 0), ('J', 0)): 1/2, (('J', 1),): 1/3})
        sage: J = H.gen('J')
        sage: S = H.subalgebra([H.conformal_vector()], names=['T'], conformal_vector='ambient')
        sage: P = S.presentation(); P.central_charge()       # 1 - 12 (1/3)^2
        -1/3
        sage: [len(P.relations(w)) for w in range(9)]        # the universal Virasoro algebra
        [0, 0, 0, 0, 0, 0, 0, 0, 0]
    """
    from .normally_ordered_expressions import NormallyOrderedExpressions
    from .universal_vertex_algebra import UniversalVertexAlgebra
    if not getattr(S, '_is_vertex_subalgebra', False):
        raise TypeError('presentations are implemented for vertex subalgebras '
                        '(strongly generated by the closure), not for {}'.format(S))
    cache = S.__dict__.setdefault('_presentations', {})
    key = None if names is None else tuple(str(t) for t in names)
    P = cache.get(key)
    if P is not None:
        return P
    gens = S.gens()
    snames = list(key) if key is not None else list(S.variable_names())
    if len(snames) != len(gens):
        raise ValueError('{} names for {} strong generators'.format(len(snames), len(gens)))
    R = S.base_ring()
    info = S._gens
    parities = {n: 1 for n, g in zip(snames, info) if g['odd']}
    E = NormallyOrderedExpressions(R, snames, parities=parities)

    def expression(x):
        return {tuple((snames[i], n) for i, n in w): c for w, c in S.express(x).monomial_coefficients().items()}
    opes = {}
    for i in range(len(gens)):
        for j in range(i, len(gens)):
            poles = gens[i].ope(gens[j])
            if poles:
                opes[(snames[i], snames[j])] = [expression(p) for p in poles]
    weights = {n: g['h'] for n, g in zip(snames, info)}
    horizontal_grading = group = None
    graded = S._cgrading is not None
    if graded:
        A = S._cgrading['group']
        horizontal_grading = {n: A.element(G) for n, G in zip(snames, S._gen_grades)}
        group = A.group
    F = UniversalVertexAlgebra(R, E, opes, degrees=weights, horizontal_grading=horizontal_grading,
                               horizontal_grading_group=group, proto=True)

    def images(keys):
        return S._vectors(list(keys))

    def preimage(x):
        P = getattr(x, 'parent', lambda: None)()
        if not isinstance(x, VertexAlgebraElement) or P is F:
            return None
        if P is not S and P is not S._root and P is not S.ambient():
            return None
        try:
            e = S.express(x)
        except ValueError:
            return None
        return dict(F._evaluate({tuple((snames[i], n) for i, n in w): c
                                 for w, c in e.monomial_coefficients().items()})._monomial_coefficients)

    I = KernelIdeal(F, images, name='the realization in {}'.format(S), graded=graded,
                    preimage=preimage, vertex_algebra_quotient=True)
    I._presented = (S, key)
    T = S.conformal_vector()
    TF = None if T is None else F._evaluate(expression(T))
    P = PresentedVertexAlgebra(F, I, horizontal_grading='ambient' if graded else None,
                               conformal_vector=TF)
    cache[key] = P
    return P
