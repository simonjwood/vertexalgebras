    def is_known_exact(self):
        """
        Always ``False``: only known to map onto the Zhu algebra of the
        quotient vertex algebra (see the module documentation).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.is_known_exact()
            False
        """
        return False

    def _standard(self, m):
        """
        Whether the ordered monomial ``m`` is standard: divisible by no
        leading monomial (exponent vectors), and the ideal is proper.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra(); x = A.gen(0)
            sage: Z = A.quotient([x*x + 1/5*x]); Z._standard((0,)), Z._standard((0, 0))
            (True, False)
        """
        if self._zero:
            return False
        e = [0] * self._A.ngens()
        for i in m:
            e[i] += 1
        return not any(all(x <= y for x, y in zip(l, e)) for l in self._lead)

    def _nf(self, d):
        """
        The normal form of a dict over the ordered monomials of ``A`` (by
        Plural's reduction modulo the Gröbner basis).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra(); x = A.gen(0)
            sage: Z = A.quotient([x*x + 1/5*x]); Z._nf({(0, 0, 0): 1}), Z._nf({})
            ({(0,): 1/25}, {})
        """
        if not d:
            return {}
        f = self._to_P(d)
        return self._from_P(f.reduce(self._G))

    def one_basis(self):
        """
        The basis key of the unit: the empty monomial.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.one_basis()
            ()
        """
        return ()

    def one(self):
        """
        The unit (zero if the ideal is the whole algebra).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.one()
            1
            sage: x = Z.cover_ring().gen(0); Z.cover_ring().quotient([x, x - 1]).one()
            0
        """
        if self._zero:
            return self.zero()
        return self.monomial(())

    def _even_odd_on_basis(self, m):
        """
        The parity of the standard monomial ``m`` (as in the cover).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L').zhu_algebra(twist='H')
            sage: L, G = A.gens(); Z = A.quotient([L - 7/16])
            sage: Z._even_odd_on_basis((1,)), Z._even_odd_on_basis(())
            (1, 0)
        """
        return self._A._even_odd_on_basis(m)

    def product_on_basis(self, m1, m2):
        """
        The product of the standard monomials ``m1`` and ``m2``: the normal
        form of their product in :meth:`cover_ring`.

        INPUT:

        - ``m1``, ``m2`` -- standard monomials (basis keys)

        EXAMPLES:

        Lee--Yang: ``[L]^2 = -1/5 [L]``::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.product_on_basis((0,), (0,))
            -1/5*[L]
        """
        return self._from_dict(self._nf(self._A._mul(m1, m2)), coerce=False,
                               remove_zeros=True)

    def _element_constructor_(self, x):
        """
        ``Z(x)``: ``x`` an element of :meth:`cover_ring` (its normal form),
        of the universal or the quotient vertex algebra (:meth:`retract`),
        or anything a ``CombinatorialFreeModule`` converts.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)]); Z = Q.zhu_algebra_up_to(4)
            sage: Z(Z.cover_ring().gen(0)^3), Z(L), Z(Q(L)), Z(2)
            (1/25*[L], [L], [L], 2)
        """
        P = _parent(x)
        if P is self._A:
            return self._from_dict(self._nf(dict(x._monomial_coefficients)),
                                   coerce=False, remove_zeros=True)
        if P is not self:
            V = self._A.vertex_algebra()
            Q = self._Q
            if (P is V or V.has_coerce_map_from(P)
                    or (Q is not None and (P is Q or Q.has_coerce_map_from(P)))):
                return self.retract(x)
        return super()._element_constructor_(x)

    def ngens(self):
        """
        The number of generators, those of :meth:`cover_ring`.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.ngens()
            1
        """
        return self._A.ngens()

    def gen(self, i):
        """
        The image of the ``i``-th generator of :meth:`cover_ring` (``i`` an
        index or a name).

        INPUT:

        - ``i`` -- an integer or the name of a generator

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.gen(0), Z.gen('L') == Z(L)
            ([L], True)

        Generators may vanish in the quotient::

            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A.quotient([A.gen('H')]).gens()
            (0, 0, 0)
        """
        return self(self._A.gen(i))

    def gens(self):
        """
        The images of the generators of :meth:`cover_ring`.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.gens()
            ([L],)
        """
        return tuple(self.gen(i) for i in range(self.ngens()))

    def algebra_generators(self):
        """
        The algebra generators, the same as :meth:`gens`.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.algebra_generators()
            ([L],)
        """
        return self.gens()

    def some_elements(self):
        """
        Some elements (used by ``TestSuite``).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.some_elements()
            [1, [L], -1/5*[L]]
        """
        gens = list(self.gens()[:3])
        return [self.one()] + gens + ([gens[0] * gens[-1]] if gens else [])

    def retract(self, v):
        r"""
        The image of ``v``: an element of the quotient vertex algebra (the
        image of its canonical representative in the universal one), or of
        the universal vertex algebra; also ``Z(v)``.

        INPUT:

        - ``v`` -- an element of the quotient or of the universal vertex
          algebra

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.retract(L.no(L)), Z.retract(Q(L.derivative())), Z(L.no(L))
            (9/5*[L], -2*[L], 9/5*[L])
            sage: Z.retract(L.no(L) - 3/10*L.derivative(2))      # in the ideal
            0
        """
        A = self._A
        V = A.vertex_algebra()
        Q = self._Q
        if Q is not None and _parent(v) is not V:
            v = _to_root(Q(v))
        return self(A.retract(v))

    def module(self, action, parities=None, horizontal_grades=None, horizontal_grading_group=None, embedding=None):
        r"""
        The finite-dimensional module with the matrices ``action`` of the
        generators, checked against the relations of the cover ring and
        the Gröbner basis of the ideal: a
        :class:`zhu_algebra_module.ZhuAlgebraModule`.

        The arguments are as for :meth:`ZhuAlgebra.module`.

        INPUT:

        - ``action`` -- the matrices of the generators: a dict by name, a
          list in the order of :meth:`gens`, or scalars (one-dimensional)
        - ``parities`` -- (default: ``None``, all even) the parities of the
          basis vectors
        - ``horizontal_grades`` -- (default: ``None``) the grades of the basis
          vectors
        - ``horizontal_grading_group`` -- (default: ``None``) the group of the
          grades
        - ``embedding`` -- (default: ``None``) the matrix of the embedding of
          the grading group of the vertex algebra into
          ``horizontal_grading_group``

        OUTPUT:

        A :class:`zhu_algebra_module.ZhuAlgebraModule`.

        EXAMPLES:

        Lee--Yang: one-dimensional modules exist exactly for the conformal
        weights ``0`` and ``-1/5``::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.module({'L': -1/5}).dimension()
            1
            sage: Z.module({'L': 1/2})
            Traceback (most recent call last):
            ...
            ValueError: the matrices do not satisfy the relation ... = 0 of the Zhu algebra
        """
        from .zhu_algebra_module import ZhuAlgebraModule
        return ZhuAlgebraModule(self, action, parities, horizontal_grades, horizontal_grading_group, embedding)

    def groebner_basis(self):
        r"""
        The two-sided Gröbner basis of the ideal (monic), as elements of
        :meth:`cover_ring` (ordered monomials).

        OUTPUT:

        A list of elements of :meth:`cover_ring`.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1, names=['E', 'H', 'F'])
            sage: E = V.gen('E')
            sage: Z = V.quotient([E.no(E)]).zhu_algebra_up_to(2)
            sage: G = Z.groebner_basis(); all(Z(g) == 0 for g in G), len(G) > 0
            (True, True)
            sage: Z.leading_monomials() == sorted(Z.leading_monomials())
            True
        """
        A = self._A
        return [A._from_dict(self._from_P(g * ~g.lc()), coerce=False, remove_zeros=True)
                for g in self._G.gens() if g]

    def leading_monomials(self):
        """
        The leading monomials of the two-sided Gröbner basis, as basis
        keys of :meth:`cover_ring` (tuples of generator indices), sorted.

        OUTPUT:

        A sorted list of tuples of generator indices.

        EXAMPLES:

        Affine ``sl_2`` at level 1 modulo ``:EE:``::

            sage: import vertex_algebras as va
            sage: V = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']); E = V.gen('E')
            sage: Z = V.quotient([E.no(E)]).zhu_algebra_up_to(2)
            sage: Z.leading_monomials()
            [(0, 0), (0, 1), (0, 2), (1, 1, 1), (1, 2), (2, 2)]
        """
        return sorted(tuple(i for i in range(len(e)) for _ in range(e[i])) for e in self._lead)

    def dimension(self):
        r"""
        The dimension (``+Infinity`` if infinite).

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1, names=['E', 'H', 'F'])
            sage: A = V.zhu_algebra(); E, H, F = A.gens()
            sage: A.quotient([H]).dimension(), A.quotient([2*E*F + H*H/2 - H]).dimension()
            (1, +Infinity)
        """
        b = self._bounds()
        if b is None:
            return Infinity
        return len(self._enumerate(b))

    def _bounds(self):
        """
        Exponent bounds if finite dimensional (for each generator the
        smallest pure power among the leading monomials), else ``None``.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra(); x = A.gen(0)
            sage: A.quotient([x*x + 1/5*x])._bounds(), A.quotient([])._bounds()
            ([2], None)
        """
        n = self._A.ngens()
        if self._zero:
            return [0] * n
        bounds = []
        for i in range(n):
            pure = [l[i] for l in self._lead
                    if l[i] and all(not x for j, x in enumerate(l) if j != i)]
            if not pure:
                return None
            bounds.append(min(pure))
        return bounds

    def _enumerate(self, bounds):
        """
        The standard monomials with exponents below ``bounds`` (see
        :meth:`_bounds`), sorted by (degree, monomial).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra(); x = A.gen(0)
            sage: Z = A.quotient([x*x + 1/5*x]); Z._enumerate(Z._bounds())
            [(), (0,)]
        """
        if self._zero:
            return []
        out = []
        for e in _cartesian(*[range(b) for b in bounds]):
            m = tuple(i for i in range(len(e)) for _ in range(e[i]))
            if self._standard(m):
                out.append(m)
        out.sort(key=lambda m: (self._A.degree_on_basis(m), m))
        return out

    def basis(self):
        """
        The basis of standard monomials, a family indexed by them (finite
        dimension only; see :meth:`standard_monomials`).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: list(Z.basis())
            [1, [L]]
            sage: Z.cover_ring().quotient([]).basis()
            Traceback (most recent call last):
            ...
            ValueError: ... is infinite dimensional; see standard_monomials
        """
        from sage.sets.family import Family
        b = self._bounds()
        if b is None:
            raise ValueError('{} is infinite dimensional; see '
                             'standard_monomials'.format(self))
        return Family(self._enumerate(b), self.monomial)

    def _an_element_(self):
        """
        The first generator (the unit if there is none).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra(); x = A.gen(0)
            sage: A.quotient([x*x]).an_element()
            [L]
        """
        gens = self.gens()
        return gens[0] if gens else self.one()

    def standard_monomials(self, max_degree):
        """
        The standard monomials of degree (sum of the conformal weights)
        ``<= max_degree``, as keys (tuples of generator indices), by degree.

        INPUT:

        - ``max_degree`` -- a rational number

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4)
            sage: Z.standard_monomials(10)
            [(), (0,)]
            sage: A = V.zhu_algebra(); x = A.gen(0)
            sage: A.quotient([x*x*x]).standard_monomials(10)
            [(), (0,), (0, 0)]
        """
        A = self._A
        n = A.ngens()
        out = []

        def grow(m, start, d):
            out.append(m)
            for i in range(start, n):
                dd = d + A._h[i]
                if dd > max_degree or (i in A._odd and m and m[-1] == i):
                    continue
                mm = m + (i,)
                if self._standard(mm):
                    grow(mm, i, dd)
        if not self._zero:
            grow((), 0, QQ.zero())
        out.sort(key=lambda m: (A.degree_on_basis(m), m))
        return out


