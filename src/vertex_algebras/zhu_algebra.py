    #  Confluence (diamond lemma)                                         #
    # ------------------------------------------------------------------ #

    def _reduce_pair(self, a, b):
        """
        ``x_a x_b`` for an out-of-order pair (``a > b``, or ``a == b``
        odd), one rewriting step (a dict; used by :meth:`check_overlaps`).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._reduce_pair(2, 0)
            {(0, 2): 1, (1,): -1}
            sage: NA = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L').zhu_algebra(twist='H')
            sage: NA._reduce_pair(1, 1)
            {(): -7/240, (0,): 1}
        """
        if a == b:
            return self._commutator(a, a)
        r = {(b, a): self.base_ring()(self._sign(a, b))}
        return _add_to(r, self._commutator(a, b), 1)

    def check_overlaps(self, max_degree=None):
        r"""
        Bergman's diamond lemma [Ber1978]_: the overlaps ``x_k x_j x_i`` of
        two rewriting rules (``k > j > i``; with odd generators also ``x_j x_i
        x_i``, ``x_j x_j x_i``, ``x_i x_i x_i``), in increasing degree, up to
        ``max_degree`` (default: all).  Returns the list of ``((k, j, i),
        difference)`` of those that do not resolve: empty iff the ordered
        monomials are a basis of the algebra with these relations (a failure
        means a Jacobi identity of ``V`` fails, or extra relations of
        ``A(V)``).  With fewer than three generators (all even) there are no
        overlaps, so nothing is checked.

        INPUT:

        - ``max_degree`` -- (default: ``None``, all overlaps) only the
          overlaps of degree (sum of the conformal weights) at most this

        OUTPUT:

        A list of pairs ``((name_k, name_j, name_i), difference)``.

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: K.<c> = Frac(QQ['c'])
            sage: E.<L, W> = NormallyOrderedExpressions(K)
            sage: Lam = L*L - 3/10*L.derivative(2)
            sage: def w3(beta):
            ....:     return UniversalVertexAlgebra(K, E, {
            ....:         ('L', 'L'): [L.derivative(), 2*L, 0, c/2], ('L', 'W'): [W.derivative(), 3*W],
            ....:         ('W', 'W'): [beta*Lam.derivative() + L.derivative(3)/15,
            ....:                      2*beta*Lam + 3/10*L.derivative(2), L.derivative(), 2*L, 0, c/3]},
            ....:         degrees={'L': 2, 'W': 3})
            sage: A = w3(16/(22 + 5*c)).zhu_algebra()
            sage: A.relations(), A.check_overlaps()
            ({}, [])

        With two even generators there are no overlaps, so a wrong ``β``
        (the Jacobi identity fails) passes too::

            sage: w3(1).zhu_algebra().check_overlaps()
            []

        A wrong bracket of affine ``sl_2`` (``[H, E] = 3E``, violating the
        Jacobi identity) fails the only overlap, of degree 3::

            sage: E, H, F = NormallyOrderedExpressions(QQ, ['E', 'H', 'F']).gens()
            sage: V = UniversalVertexAlgebra(QQ, ['E', 'H', 'F'],
            ....:     {('H', 'E'): [3*E], ('H', 'F'): [-2*F], ('E', 'F'): [H, 1]},
            ....:     degrees={'E': 1, 'H': 1, 'F': 1})
            sage: A = V.zhu_algebra()
            sage: A.check_overlaps(max_degree=2), A.check_overlaps()
            ([], [(('F', 'H', 'E'), [H])])
        """
        n = self.ngens()
        words = []
        for k in range(n):
            for j in range(k + 1):
                for i in range(j + 1):
                    if (k > j or k in self._odd) and (j > i or j in self._odd):
                        words.append((k, j, i))
        words.sort(key=lambda w: (self.degree_on_basis(w), w))
        bad = []
        for k, j, i in words:
            if max_degree is not None and self.degree_on_basis((k, j, i)) > max_degree:
                break
            left = {}
            for m, c in self._reduce_pair(k, j).items():
                _add_to(left, self._mul(m, (i,)), c)
            right = {}
            for m, c in self._reduce_pair(j, i).items():
                _add_to(right, self._mul((k,), m), c)
            diff = _add_to(dict(left), right, -1)
            if diff:
                bad.append(((self._names[k], self._names[j], self._names[i]),
                            self._from_dict(diff, coerce=False, remove_zeros=True)))
        return bad

    def _test_overlaps(self, **options):
        """
        ``TestSuite``: :meth:`check_overlaps` finds nothing (with at most 8
        generators).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._test_overlaps()
        """
        tester = self._tester(**options)
        if self.ngens() <= 8:
            tester.assertEqual(self.check_overlaps(), [])

