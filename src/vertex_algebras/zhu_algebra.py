    @staticmethod
    def __classcall_private__(cls, V, weight=None, twist=None):
        """
        Normalise the key ``(V, weight, twist)``: ``weight`` is ``None``
        without quotient factors (required with them), the twist canonical.

        TESTS::

            sage: from vertex_algebras.zhu_algebra import TensorProductZhuAlgebra
            sage: import vertex_algebras as va
            sage: Vir = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = Vir.gen('L')
            sage: V = Vir.tensor(Vir, conformal_vector='factors'); A = V.zhu_algebra()
            sage: TensorProductZhuAlgebra(V) is A, TensorProductZhuAlgebra(V, 5, 'H') is A
            (True, True)
        """
        if any(getattr(W, '_is_quotient_vertex_algebra', False) for W in V.factors()):
            if weight is None:
                raise NotImplementedError(
                    'the Zhu algebra of a quotient is computed up to a weight: '
                    'use zhu_algebra_up_to(max_weight)')
            weight = QQ(weight)
        else:
            weight = None
        return CombinatorialFreeModule.__classcall__(cls, V, weight, _twist_of(V, twist))

    def __init__(self, V, weight, twist=None):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: Vir = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: A = Vir.tensor(Vir, conformal_vector='factors').zhu_algebra()
            sage: len(A.factors()), A.is_known_exact()
            (2, True)
        """
        R = V.base_ring()
        try:
            data = V._weight_data()['factors']
        except ValueError:
            raise ValueError('{} has no conformal weights (give conformal_weights '
                             'or a conformal vector)'.format(V))
        self._V = V
        self._twist = twist
        #: the factors with the gradings of the tensor product, their Zhu algebras
        self._vfactors = tuple(_with_weight_data(W, d, i)
                               for i, (W, d) in enumerate(zip(V.factors(), data)))
        self._factors = tuple(
            W.zhu_algebra_up_to(weight, twist=twist)
            if getattr(W, '_is_quotient_vertex_algebra', False)
            else W.zhu_algebra(twist=twist) for W in self._vfactors)
        self._super = tuple(A in Algebras(R).Super() for A in self._factors)
        self._fzeta = tuple({} for _ in self._factors)      # factor key -> {key: c}
        self._zeta = {}
        finite = [_finite_basis_keys(A) for A in self._factors]
        if any(k is None for k in finite):
            finite = None
        cat = Algebras(R).WithBasis()
        if finite is not None:
            cat = cat.FiniteDimensional()
            keys = list(_cartesian(*finite))
        else:
            keys = _ZhuTensorKeys(self._factors)
        if any(self._super):
            cat = cat.Super()
        CombinatorialFreeModule.__init__(self, R, keys, prefix='', category=cat)

