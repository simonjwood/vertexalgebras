    def _grade_data(self):
        r"""
        The product grading (the grading ``'factors'`` of the tensor
        product), if every factor's Zhu algebra is graded by the
        corresponding factor of the group; else ``None``.

        TESTS::

            sage: import vertex_algebras as va
            sage: S = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F'], conformal_vector='sugawara')
            sage: T = S.tensor(S, conformal_vector='factors', horizontal_grading='factors')
            sage: G, key = T.zhu_algebra()._grade_data(); key(((0,), (2, 2)))
            (1, -2)
            sage: Vir = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: Vir.tensor(Vir, conformal_vector='factors').zhu_algebra()._grade_data() is None
            True
        """
        gd = self._V._grading
        if gd is None or not hasattr(gd['group'], 'factors'):
            return None
        G = gd['group']
        data = [A._grade_data() for A in self._factors]
        if any(d is None for d in data) or any(
                d[0] != F for d, F in zip(data, G.factors)):
            return None
        keys = [d[1] for d in data]

        def key(m):
            return sum((k(x) for k, x in zip(keys, m)), ())
        return G, key

