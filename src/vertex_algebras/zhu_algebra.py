    def __init__(self, V):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.zhu_algebra import LatticeZhuAlgebra
            sage: L = va.Lattice(QQ, matrix([[2]])); J = L.J(0)
            sage: A = LatticeZhuAlgebra(L.with_conformal_vector(J.no(J)/4)); A.dimension()
            5
            sage: LatticeZhuAlgebra(L)
            Traceback (most recent call last):
            ...
            ValueError: ... has no conformal weights (give conformal_weights or a conformal vector)
        """
        from sage.modules.free_module_element import vector
        R = V.base_ring()
        try:
            data = V._weight_data()
        except ValueError:
            raise ValueError('{} has no conformal weights (give conformal_weights '
                             'or a conformal vector)'.format(V))
        B = V.gram_matrix()
        n = V.rank()
        beta = vector(QQ, [_to_rational(x, 'lattice weight coefficient β')
                           for x in data['beta']])
        for i in range(n):
            # Δ(-x_i) = B_ii - Δ(x_i), and Δ(q + p) = Δ(q) + Δ(p) + B(q, p)
            w = QQ(B[i, i]) / 2 + beta[i]
            if 2 * w not in ZZ:
                q = tuple(int(i == j) for j in range(n))
                raise ValueError('the conformal weight {} of {} is not an integer '
                                 'or half-integer'.format(w, V.e(q)))
        self._V = V
        self._positive = B.is_positive_definite()
        self._levels = _top_levels(B, beta) if self._positive else []
        #: μ -> (top level, row, μ - λ (an integer tuple), (B(x_i, μ))_i)
        self._where = {}
        BQ = B.change_ring(QQ)
        for t, (h, mus) in enumerate(self._levels):
            for r, mu in enumerate(mus):
                self._where[mu] = (
                    t, r, tuple(int(a - b) for a, b in zip(mu, mus[0])),
                    tuple(int(x) for x in BQ * vector(QQ, mu)))
        keys = [(nu, mu) for h, mus in self._levels for nu in mus for mu in mus]
        self._zeta = {}             # V basis key -> {matrix unit: c}
        cat = Algebras(R).FiniteDimensional().WithBasis()
        if any(self._even_odd_on_basis(m) for m in keys):
            cat = cat.Super()
        CombinatorialFreeModule.__init__(self, R, keys, prefix='', category=cat)

    def _repr_(self):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); J = L.J(0)
            sage: V = L.with_conformal_vector(J.no(J)/4); A = V.zhu_algebra()
            sage: repr(A)
            'Zhu algebra of Lattice vertex algebra of rank 1 with Gram matrix [2] over Rational Field'
        """
        if self._positive:
            return 'Zhu algebra of {}'.format(self._V)
        return ('Zhu algebra of {} (zero: the form is not positive definite)'
                .format(self._V))

    def _repr_term(self, m):
        """
        The matrix unit ``m = (ν, μ)`` as ``|ν><μ|``.

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); J = L.J(0)
            sage: V = L.with_conformal_vector(J.no(J)/4); A = V.zhu_algebra()
            sage: A._repr_term(((1/2,), (-1/2,)))
            '|1/2><-1/2|'
        """
        nu, mu = m
        return '|{}><{}|'.format(','.join(str(x) for x in nu),
                                 ','.join(str(x) for x in mu))

    def _latex_term(self, m):
        r"""
        The matrix unit ``m = (ν, μ)`` as ``|ν\rangle\langle μ|``.

        TESTS::

            sage: import vertex_algebras as va
            sage: L = va.Lattice(QQ, matrix([[2]])); J = L.J(0)
            sage: V = L.with_conformal_vector(J.no(J)/4); A = V.zhu_algebra()
            sage: A._latex_term(((1/2,), (-1/2,)))
            '|\\frac{1}{2}\\rangle\\langle -\\frac{1}{2}|'
        """
        from sage.misc.latex import latex
        nu, mu = m
        return '|{}\\rangle\\langle {}|'.format(','.join(str(latex(x)) for x in nu),
                                                 ','.join(str(latex(x)) for x in mu))

