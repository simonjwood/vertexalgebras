    def _repr_term(self, m):
        """
        The ordered monomial ``m`` as a product of the ``[g]``, with powers.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L').zhu_algebra(twist='H')
            sage: A._repr_term(()), A._repr_term((0, 0, 1))
            ('1', '[L]^2*[G]')
        """
        if not m:
            return '1'
        out = []
        i = 0
        while i < len(m):
            j = i
            while j < len(m) and m[j] == m[i]:
                j += 1
            s = '[{}]'.format(self._names[m[i]])
            out.append(s if j - i == 1 else '{}^{}'.format(s, j - i))
            i = j
        return '*'.join(out)

    def _latex_term(self, m):
        r"""
        The ordered monomial ``m`` in LaTeX: the ``[g]``, with powers.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L').zhu_algebra(twist='H')
            sage: A._latex_term(()), A._latex_term((0, 0, 1))
            ('1', '[L]^{2} [G]')
            sage: L, G = A.gens(); latex(2*L*L - G)
            2 [L]^{2} - [G]
        """
