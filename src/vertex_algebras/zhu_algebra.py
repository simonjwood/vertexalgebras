    #  The Zhu map                                                        #
    # ------------------------------------------------------------------ #

    def _key_weight(self, m):
        """
        The conformal weight of the basis monomial ``m`` of the vertex
        algebra (letters ``(generator, derivative)``).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra()
            sage: A._key_weight(((0, 1), (0, 0))), A._key_weight(())
            (5, 0)
        """
        return sum((self._hV[i] + n for i, n in m), QQ.zero())

    def _zeta_key(self, m):
        """
        The image of the basis monomial ``m`` of ``V``, as a dict (the Zhu
        map on basis keys, recursive in the first letter; memoised in
        ``_zeta``; see the module documentation for the two rules).

        TESTS:

        ``[∂L] = -2[L]``, ``[:L L:] = [L]^2 + 2[L]``; for ``N = 1`` the
        untwisted image of ``G`` (half-integer weight) is zero::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra()
            sage: A._zeta_key(((0, 1),)), A._zeta_key(((0, 0), (0, 0)))
            ({(0,): -2}, {(0,): 2, (0, 0): 1})
            sage: NS = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L')
            sage: NS.zhu_algebra()._zeta_key(((1, 0),)), NS.zhu_algebra(twist='H')._zeta_key(((1, 0),))
            ({}, {(1,): 1})

        The same images as an independent recursion, Zhu's product formula
        ``[:x B:] = [x][B] - Σ_{i>=1} C(Δ_x, i) [x_(i-1) B]``, ``[∂^k g] =
        (-1)^k Δ(Δ+1)...(Δ+k-1) [g]``, on ``W_3`` up to weight 7::

            sage: V = va.W3(QQ, 2, conformal_vector='L'); A = V.zhu_algebra(); h = V.degrees()
            sage: def z(m):
            ....:     if not m:
            ....:         return A.one()
            ....:     (g, k), x = m[0], V.monomial(m[:1])
            ....:     if len(m) == 1:
            ....:         return (-1)^k * rising_factorial(h[V.variable_names()[g]], k) * A.gen(g)
            ....:     B = V.monomial(m[1:])
            ....:     return z(m[:1]) * z(m[1:]) - sum(binomial(x.degree(), i) * zd(x.nproduct(B, i - 1))
            ....:                                      for i in range(1, x.degree() + 2))
            sage: zd = lambda v: sum((c * z(m) for m, c in v.monomial_coefficients().items()), A.zero())
            sage: all(A(V.monomial(m)) == z(m) for w in range(8) for m in V.weight_space(w).basis_keys())
            True

        The pure-Python implementation of ``W_3`` (another algebra, its own
        products) gives the same Zhu map up to weight 8::

            sage: Vp = va.W3(QQ, 2, conformal_vector='L', implementation='python'); Ap = Vp.zhu_algebra()
            sage: Vp is V
            False
            sage: all(A(V.monomial(m)).monomial_coefficients() == Ap(Vp.monomial(m)).monomial_coefficients()
            ....:     for w in range(9) for m in V.weight_space(w).basis_keys())
            True
        """
        r = self._zeta.get(m)
        if r is not None:
            return r
        R = self.base_ring()
        if not self._twist and self._key_weight(m) not in ZZ:
            r = {}
        elif not m:
            r = {(): R.one()}
        else:
            V = self._V
            (g, k), B = m[0], m[1:]
            hg = self._hV[g]
            if self._twist or hg in ZZ:
                # De Sole--Kac: [:(∂^k a) B:] = k! C(-Δ, k) ([a][B]
                #     - (Δ + k) Σ_j C(Δ - 1, j)/(k + j + 1) [a_(j) B])
                s = {}
                for j, p in enumerate(V._ope_mono(((g, 0),), B)):
                    if p:
                        _add_to(s, self._zeta_dict(p),
                                R(binomial(hg - 1, j) / (k + j + 1)))
                c = R(factorial(k) * binomial(-hg, k))
                r = {}
                _add_to(r, self._lmul(self._zidx[g], self._zeta_key(B)), c)
                _add_to(r, s, -c * (hg + k))
            else:
                # x of half-integer weight: Σ_j C(Δ_x - 1/2, j) x_(j-1) B ∈ J
                hx = hg + k
                r = {}
                for j, p in enumerate(V._ope_mono((m[0],), B), start=1):
                    if p:
                        _add_to(r, self._zeta_dict(p), R(-binomial(hx - QQ((1, 2)), j)))
        self._zeta[m] = r
        return r

    def _zeta_dict(self, d):
        """
        The Zhu map on a dict ``{basis monomial of V: coefficient}``.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Virasoro(QQ, -22/5, conformal_vector='L').zhu_algebra()
            sage: A._zeta_dict({((0, 1),): 1, (): 3})
            {(): 3, (0,): -2}
        """
        out = {}
        for m, c in d.items():
            _add_to(out, self._zeta_key(m), c)
        return out

    def _element_constructor_(self, x):
        """
        ``A(v)``: the image of an element of the vertex algebra (see
        :meth:`retract`); otherwise as for any ``CombinatorialFreeModule``
        (scalars, elements of ``A``).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); A = V.zhu_algebra()
            sage: A(V.gen('L').derivative()), A(3), A(A.gen(0))
            (-2*[L], 3, [L])
        """
        P = _parent(x)
        if self._from_higher_level(P):
            zidx = self._zidx
            return self._from_dict({tuple(zidx[i] for i, _ in w): c
                                    for w, c in x.monomial_coefficients().items()
                                    if all(m == 0 for _, m in w)},
                                   coerce=False, remove_zeros=True)
        if P is not self and _of_vertex_algebra(self._V, P):
            return self.retract(x)
        return super()._element_constructor_(x)

    def _from_higher_level(self, P):
        """
        Whether ``P`` is a higher level Zhu algebra of the same vertex
        algebra (it maps onto this one: the words in zero modes are the
        ordered monomials, the others map to zero).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L')
            sage: A, A1 = V.zhu_algebra(), V.zhu_algebra(level=1)
            sage: A._from_higher_level(A1), A.has_coerce_map_from(A1), A(A1(L.no(L))) == A(L.no(L))
            (True, True, True)
        """
        return (getattr(P, '_is_higher_zhu_algebra', False) and P._V is self._V
                and self._twist is None)

    def _coerce_map_from_(self, P):
        """
        The projections from higher level Zhu algebras.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L')
            sage: V.zhu_algebra().has_coerce_map_from(V.zhu_algebra(level=2))
            True
        """
        if self._from_higher_level(P):
            return True
        return super()._coerce_map_from_(P)

    def retract(self, v):
        r"""
        The image ``[v]`` of the element ``v`` of the vertex algebra (zero
        for elements of half-integer weight, unless twisted); also ``A(v)``.

        A conversion, not a coercion: the product of the vertex algebra
        is the normally ordered product, not Zhu's product.

        INPUT:

        - ``v`` -- an element of the vertex algebra (or anything it
          converts)

        OUTPUT:

        An element of this algebra.

        EXAMPLES::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: K.<c> = Frac(QQ['c'])
            sage: E.<L> = NormallyOrderedExpressions(K)
            sage: V = UniversalVertexAlgebra(K, E, {('L', 'L'): [L.derivative(), 2*L, 0, c/2]},
            ....:                            conformal_vector=L)
            sage: A = V.zhu_algebra(); L = V.gen('L')
            sage: A(L.derivative()), A(L.no(L)), A(V.one())
            (-2*[L], 2*[L] + [L]^2, 1)
            sage: A.retract(L.no(L)) == A(L.no(L)), A.has_coerce_map_from(V)
            (True, False)

        ``(∂ + L_0) v`` maps to zero, and ``[a * b] = [a][b]`` (``*`` the
        Zhu product)::

            sage: v = L.no(L.derivative())
            sage: A(v.derivative() + 5*v)
            0
            sage: star = sum(binomial(2, j) * L.nproduct(v, j - 1) for j in range(3))
            sage: A(star) == A(L) * A(v)
            True

        TESTS:

        Scalars map to multiples of the unit, zero to zero, and elements of
        ``A`` to themselves::

            sage: A(3) == 3 * A.one(), A(V.zero()), A(0), A(A.gen(0)) == A.gen(0)
            (True, 0, 0, True)
        """
        V = self._V
        v = V(v)
        return self._from_dict(self._zeta_dict(dict(v._monomial_coefficients)),
                               coerce=False, remove_zeros=True)

    def relations(self):
        r"""
        The defining relations: a dict ``(name_a, name_b) -> x_a x_b -
        (-1)^{|a||b|} x_b x_a`` for the generators ``x_a`` listed after
        ``x_b`` (the nonzero ones), and ``(name_a, name_a) -> x_a x_a`` for
        odd ``x_a``.

        OUTPUT:

        A dictionary ``{(name_a, name_b): element}``.

        EXAMPLES::

            sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
            sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1, names=['E', 'H', 'F'])
            sage: V.zhu_algebra().relations()
            {('F', 'E'): -[H], ('F', 'H'): 2*[F], ('H', 'E'): 2*[E]}
        """
        out = {}
        n = self.ngens()
        for a in range(n):
            for b in range(a + 1):
                if a == b and a not in self._odd:
                    continue
                d = self._commutator(a, b)
                if d:
                    out[(self._names[a], self._names[b])] = self._from_dict(
                        d, coerce=False, remove_zeros=True)
        return out

