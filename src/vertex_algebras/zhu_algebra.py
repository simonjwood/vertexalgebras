    def _sign(self, a, b):
        """
        The Koszul sign ``(-1)^{|a||b|}`` of the generators ``a``, ``b``.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L').zhu_algebra(twist='H')
            sage: A._sign(1, 1), A._sign(1, 0), A._sign(0, 0)
            (-1, 1, 1)
        """
        return -1 if (a in self._odd and b in self._odd) else 1

    def _commutator(self, a, b):
        r"""
        For ``a > b``: ``[x_a, x_b] = x_a x_b - (-1)^{|a||b|} x_b x_a`` as a
        dict (``Σ_j C(Δ_a - 1, j) ζ(g_a (j) g_b)``); for ``a == b`` odd: the
        square ``x_a x_a`` (half of that).  Memoised in ``_comm``; a relation
        needed to compute itself raises a ``RuntimeError``.

        TESTS:

        ``U(sl_2)`` and the Ramond relation ``[G]^2 = [L] - c/24``::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._commutator(2, 0), A._commutator(1, 0)
            ({(1,): -1}, {(0,): 2})
            sage: NA = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L').zhu_algebra(twist='H')
            sage: NA._commutator(1, 1)
            {(): -7/240, (0,): 1}
        """
        key = (a, b)
        r = self._comm.get(key)
        if r is not None:
            return r
        if key in self._busy:
            raise RuntimeError('the relation of {} and {} is needed to compute '
                               'itself'.format(self._names[a], self._names[b]))
        self._busy.add(key)
        try:
            V, R = self._V, self.base_ring()
            ga, gb = self._vgen[a], self._vgen[b]
            poles = V._ope_mono(((ga, 0),), ((gb, 0),))
            r = {}
            for j, p in enumerate(poles):
                if p:
                    _add_to(r, self._zeta_dict(p), R(binomial(self._h[a] - 1, j)))
            if a == b:
                r = {m: c / 2 for m, c in r.items()}
        finally:
            self._busy.discard(key)
        self._comm[key] = r
        return r

    def _lmul_mono(self, a, m):
        """
        ``x_a`` times the ordered monomial ``m``, rewritten in ordered
        monomials (a dict; memoised in ``_lmul_cache``).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._lmul_mono(0, (2,)), A._lmul_mono(2, (0,))
            ({(0, 2): 1}, {(0, 2): 1, (1,): -1})
        """
        if not m or a < m[0] or (a == m[0] and a not in self._odd):
            return {(a,) + m: self.base_ring().one()}
        key = (a, m)
        r = self._lmul_cache.get(key)
        if r is not None:
            return r
        b, rest = m[0], m[1:]
        if a == b:                    # odd: x_a x_a = (square)
            r = self._mul_dict(self._commutator(a, a), {rest: self.base_ring().one()})
        else:                         # a > b: x_a x_b = ± x_b x_a + [x_a, x_b]
            r = {}
            _add_to(r, self._lmul(b, self._lmul_mono(a, rest)), self._sign(a, b))
            _add_to(r, self._mul_dict(self._commutator(a, b),
                                      {rest: self.base_ring().one()}), 1)
        self._lmul_cache[key] = r
        return r

    def _lmul(self, a, d):
        """
        ``x_a`` times the dict ``d`` over ordered monomials, rewritten.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._lmul(2, {(0,): 1, (1,): 2}) == dict(A.gen(2) * (A.gen(0) + 2*A.gen(1)))
            True
        """
        out = {}
        for m, c in d.items():
            _add_to(out, self._lmul_mono(a, m), c)
        return out

    def _mul(self, m1, m2):
        """
        The product of the ordered monomials ``m1``, ``m2``, rewritten (a
        dict).

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._mul((2, 2), (0,))
            {(0, 2, 2): 1, (1, 2): -2, (2,): -2}
        """
        out = {m2: self.base_ring().one()}
        for a in reversed(m1):
            out = self._lmul(a, out)
        return out

    def _mul_dict(self, d1, d2):
        """
        The product of two dicts over ordered monomials, rewritten.

        TESTS::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, names=['E', 'H', 'F']).zhu_algebra()
            sage: A._mul_dict({(2,): 1}, {(0,): 3})
            {(0, 2): 3, (1,): -3}
        """
        out = {}
        for m1, c1 in d1.items():
            for m2, c2 in d2.items():
                _add_to(out, self._mul(m1, m2), c1 * c2)
        return out

