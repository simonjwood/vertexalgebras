def _zhu_algebra_up_to(Q, max_weight, twist=None, degree_bound=None, algorithm=None, level=0):
    r"""
    ``A(V)`` modulo the images of the weight spaces ``I_w``, ``w <= max_weight``,
    of the ideal of the quotient ``Q = V/I`` (``V`` universal; nested
    quotients included): an algebra mapping onto ``A(Q)``, equal to it for
    ``max_weight`` large enough.  Used by ``Q.zhu_algebra_up_to(max_weight)``.  With
    ``twist='H'`` (or ``'ramond'``) the same for the H-twisted Zhu algebras
    (``A_H(V/I) = A_H(V)/[I]``, the images of ``I_w`` for all rational
    ``w <= max_weight``).

    EXAMPLES::

        sage: from vertex_algebras.affine_vertex_algebra import UniversalAffineVertexAlgebra
        sage: V = UniversalAffineVertexAlgebra(QQ, ['A', 1], level=1, names=['E', 'H', 'F'])
        sage: E = V.gen('E')
        sage: Q = V.quotient([E.no(E)])
        sage: [Q.zhu_algebra_up_to(W).dimension() for W in (1, 2, 4)]
        [+Infinity, 5, 5]

    TESTS:

    ``L_2(sl_2)``: ``U(sl_2)/<e^3>`` of dimension ``1 + 4 + 9 = 14``; a
    nested quotient by an element that is already zero::

        sage: import vertex_algebras as va
        sage: V2 = va.Affine(QQ, ['A', 1], 2, names=['E', 'H', 'F'])
        sage: E2 = V2.gen('E'); Q2 = V2.quotient([E2.no(E2.no(E2))])
        sage: [Q2.zhu_algebra_up_to(W).dimension() for W in (2, 3)]
        [+Infinity, 14]
        sage: F = V.gen('F'); Q.quotient([Q(F.no(F))]).zhu_algebra_up_to(3).dimension()
        5

    The tricritical Ising model (``N = 1`` at ``c = 7/10``): untwisted
    dimension 2, the Ramond sector of dimension 4 with ``[L]`` of the
    Ramond weights ``3/80``, ``7/16`` and ``[G]^2 = [L] - 7/240``::

        sage: NS = va.NeveuSchwarz(QQ, 7/10, conformal_vector='L'); [v] = NS.find_singular(4)
        sage: QT = NS.quotient([v]); Z = QT.zhu_algebra_up_to(6, twist='ramond'); L, G = Z.gens()
        sage: Z.dimension(), (L - 3/80)*(L - 7/16), G*G == L - 7/240, QT.zhu_algebra_up_to(6).dimension()
        (4, 0, True, 2)
    """
    from .vertex_algebra_categories import _is_proto
    if not (level in ZZ and level >= 0):
        raise ValueError('the level must be a nonnegative integer, not {}'.format(level))
    if level:
        from .higher_zhu_algebra import HigherZhuAlgebraQuotient
        if twist is not None and _twist_of(_to_cover(Q), twist) is not None:
            raise NotImplementedError('twisted higher level Zhu algebras are not '
                                      'implemented yet')
        if algorithm is not None:
            raise ValueError('higher level Zhu algebras of quotients have no '
                             'algorithm choice')
        return HigherZhuAlgebraQuotient(Q, level, max_weight, degree_bound)
    W = QQ(max_weight)
    V = Q
    while getattr(V, '_is_quotient_vertex_algebra', False):
        V = V.ambient()
    if not getattr(V, '_is_universal_vertex_algebra', False):
        raise NotImplementedError('Zhu algebras of quotients are implemented for '
                                  'quotients of universal vertex algebras, not of {}'
                                  .format(V))
    if algorithm not in (None, 'plural', 'letterplace'):
        raise ValueError("algorithm must be None, 'plural' or 'letterplace'")
    if algorithm == 'letterplace' or (algorithm is None and _is_proto(V)):
        # the PBW algebra of a proto V need not be a G-algebra: Gröbner bases
        # in the free algebra
        return ZhuAlgebraFreeQuotient(Q, W, twist, degree_bound)
    if _is_proto(V):
        raise ValueError("{} is a proto vertex algebra: its PBW Zhu algebra need not be "
                         "a G-algebra (use algorithm='letterplace')".format(V))
    A = ZhuAlgebra(V, twist)
    step = QQ.one()
    if A.twist():
        # all weights: those of V lie in (1/D) ZZ
        step = QQ((1, lcm([QQ(h).denominator() for h in A._hV])))
    els = _ideal_elements(Q, W, step)[1]
    images = [A.retract(x) for x in els]
    return ZhuAlgebraQuotient(A, tuple(x for x in images if x), Q, W)


def _to_cover(Q):
    """
    The vertex algebra under the quotient ``Q`` (also nested).

    TESTS::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.zhu_algebra import _to_cover
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: _to_cover(V / [L.no(L) - 3/10*L.derivative(2)]) is V
        True
    """
    while getattr(Q, '_is_quotient_vertex_algebra', False):
        Q = Q.ambient()
    return Q


def _ideal_elements(Q, W, step=1):
    """
    ``(V, elements)``: the universal vertex algebra under the quotient
    ``Q`` and a spanning set of the ideal of ``V`` defining ``Q`` in the
    weights ``<= W`` in ``step ZZ`` (integer weights for ``step = 1``;
    nested quotients: the ideals of all levels, lifted to ``V``).

    TESTS::

        sage: from vertex_algebras.zhu_algebra import _ideal_elements
        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
        sage: W, els = _ideal_elements(Q, 4); W is V, els
        (True, [:L L: - 3/10*d^2L])
        sage: len(_ideal_elements(Q, 6)[1])        # weights 4, 5, 6: 1 + 1 + 2
        4
    """
    amb = Q.ambient()
    I = Q.defining_ideal()
    els = []
    w = QQ.zero()
    graded = getattr(I, '_grading', None)
    while w <= W:
        if graded is not None and not getattr(I, '_whole', False):
            # an ideal split by grades: its weight spaces grade by grade
            horizontal_grades = {amb._grade_key(k) for k in amb.weight_space(w).basis_keys()}
            for G in sorted(horizontal_grades):
                els.extend(I.weight_space(w, graded['group'].element(G)).basis())
        else:
            els.extend(I.weight_space(w).basis())
        w += step
    if getattr(amb, '_is_quotient_vertex_algebra', False):
        V, lower = _ideal_elements(amb, W, step)
        return V, lower + [_to_root(x) for x in els]
    if not getattr(amb, '_is_universal_vertex_algebra', False):
        raise NotImplementedError('Zhu algebras of quotients are implemented for '
                                  'quotients of universal vertex algebras, not of {}'
                                  .format(amb))
    return amb, els


def _to_root(x):
    """
    The canonical representative of ``x`` (an element of a quotient,
    possibly nested) in the vertex algebra at the bottom; ``x`` itself if it
    is not in a quotient.

    TESTS::

        sage: from vertex_algebras.zhu_algebra import _to_root
        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
        sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
        sage: _to_root(Q(L.no(L))), _to_root(L)
        (3/10*d^2L, L)
        sage: _to_root(Q(L.no(L))).parent() is V
        True
    """
    while getattr(x.parent(), '_is_quotient_vertex_algebra', False):
        x = x.parent().lift(x)
    return x


