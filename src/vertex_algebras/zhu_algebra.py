            A = self.parent()
            R = A.base_ring()
            mats = [matrix(R, len(mus), len(mus)) for h, mus in A._levels]
            for (nu, mu), c in self._monomial_coefficients.items():
                t, r, _, _ = A._where[nu]
                mats[t][r, A._where[mu][1]] = c
            return mats


