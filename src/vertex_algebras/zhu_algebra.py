    @staticmethod
    def __classcall_private__(cls, Q, weight, twist=None, degree_bound=None):
        """
        Normalise the key ``(Q, weight, twist, degree_bound)``: a rational
        weight, the canonical twist of the universal algebra under ``Q``, an
        integer degree bound.

        TESTS::

            sage: from vertex_algebras.zhu_algebra import ZhuAlgebraFreeQuotient
            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: ZhuAlgebraFreeQuotient(Q, 4) is Z, ZhuAlgebraFreeQuotient(Q, 4, 'ramond') is Z
            (True, True)

        The default degree bound is resolved, so giving it gives the same
        algebra::

            sage: Z.degree_bound(), ZhuAlgebraFreeQuotient(Q, 4, degree_bound=8) is Z
            (8, True)
        """
        V = Q
        while getattr(V, '_is_quotient_vertex_algebra', False):
            V = V.ambient()
        W, twist = QQ(weight), _twist_of(V, twist)
        if degree_bound is None:                  # the default: twice the top relation degree
            degree_bound = 2 * _free_quotient_relations(Q, W, twist)[1]
        return CombinatorialFreeModule.__classcall__(cls, Q, W, twist, int(degree_bound))

    def __init__(self, Q, W, twist=None, degree_bound=None):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: Z._W, Z._n, Z.dimension()
            (4, 1, 2)
        """
        V = Q
        while getattr(V, '_is_quotient_vertex_algebra', False):
            V = V.ambient()
        A0 = _RewritingZhuAlgebra(V, twist)
        R = A0.base_ring()
        self._A0 = A0
        self._Q = Q
        self._W = W
        self._twist = twist
        self._n = A0.ngens()
        self._names = A0._names
        self._odd = A0._odd
        self._vgen = A0._vgen
        self._zidx = A0._zidx
        self._h = A0._h
        D = lcm([QQ(h).denominator() for h in A0._h] + [1])
        degs = [int(D * h) for h in A0._h]
        if any(d <= 0 for d in degs):
            raise NotImplementedError('the Gröbner bases need generators of positive weight')
        self._degs = degs
        rels, top = _free_quotient_relations(Q, W, twist)
        self._relation_dicts = rels
        self._degree_bound = degree_bound if degree_bound is not None else 2 * top
        self._rules = self._groebner(rels, self._degree_bound)
        self._maxlead = max([len(w) for w in self._rules] + [0])
        self._zero = () in self._rules
        cat = Algebras(R).WithBasis()
        if self._odd:
            cat = cat.Super()
        CombinatorialFreeModule.__init__(self, R, _StandardWords(self), prefix='',
                                         category=cat)

    def _degree(self, w):
        """
        The degree of the word ``w``: the sum of the integer degrees of its
        letters (conformal weights times their common denominator).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: Z._degree((0, 0)), Z._degree(())
            (4, 0)
        """
        return sum(self._degs[i] for i in w)

    def _groebner(self, rels, bound):
        """
        The dehomogenised two-sided Gröbner basis of the relations ``rels``
        (dicts over words), computed by Letterplace to the degree ``bound``,
        as rules ``{leading word: replacement dict}`` (monic).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: Z._rules
            {(0, 0): {(0,): -1/5}}
            sage: Z._groebner([{(0, 0): 1, (0,): 1/5}], 8)
            {(0, 0): {(0,): -1/5}}
        """
        from sage.algebras.free_algebra import FreeAlgebra
        from sage.misc.misc_c import prod
        n = self._n
        R = self._A0.base_ring()            # (called before the parent is set up)
        H = FreeAlgebra(R, ['x{}'.format(i) for i in range(n)] + ['xh'],
                        implementation='letterplace', degrees=self._degs + [1])
        X = H.gens()
        h = X[n]
        weighted = True     # explicit degrees: every position has a padding variable
        H.set_degbound(bound)               # products beyond it are refused

        def homog(d):
            top = max(self._degree(w) for w in d)
            return sum((c * prod([X[i] for i in w], H.one()) * h ** (top - self._degree(w))
                        for w, c in d.items()), H.zero())
        gens = [homog(d) for d in rels] + [X[i] * h - h * X[i] for i in range(n)]
        G = (H * gens * H).groebner_basis(degbound=bound)
        rules = {}
        for g in G.gens():
            terms = _letterplace_words(g, n + 1, weighted)
            if sum((c * prod([X[i] for i in w], H.one()) for w, c in terms.items()),
                   H.zero()) != g:
                raise RuntimeError('could not decode the Letterplace element {}'.format(g))
            d = {}
            for w, c in terms.items():
                _add_to(d, {tuple(i for i in w if i != n): R.one()}, c)
            if not d:
                continue
            (lw, _), = _letterplace_words(g.lm(), n + 1, weighted).items()
            lead = tuple(i for i in lw if i != n)
            c0 = d.pop(lead)
            rules[lead] = {w: -c / c0 for w, c in d.items()}
        return rules

    def _find(self, w):
        """
        ``(position, leading word)`` of the first reducible subword of
        ``w``, or ``None``.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: Z._find((0, 0, 0)), Z._find((0,))
            ((0, (0, 0)), None)
        """
        rules = self._rules
        for i in range(len(w)):
            for L in range(1, min(self._maxlead, len(w) - i) + 1):
                u = w[i:i + L]
                if u in rules:
                    return i, u
        return None

    def _is_standard(self, w):
        """
        Whether the word ``w`` contains no leading word.

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: Z._is_standard((0,)), Z._is_standard((0, 0))
            (True, False)
        """
        return self._find(w) is None

    def _reduce(self, d):
        """
        The normal form of a dict over words (subword rewriting with the
        rules of the Gröbner basis).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])
            sage: Z = Q.zhu_algebra_up_to(4, algorithm='letterplace')
            sage: Z._reduce({(0, 0, 0): 1}), Z._reduce({(): 2, (0,): 0})
            ({(0,): 1/25}, {(): 2})
        """
        out = {}
        todo = {w: c for w, c in d.items() if c}
        while todo:
            w, c = todo.popitem()
            f = self._find(w)
            if f is None:
                _add_to(out, {w: 1}, c)
                continue
            i, u = f
            for w2, c2 in self._rules[u].items():
                _add_to(todo, {w[:i] + w2 + w[i + len(u):]: 1}, c * c2)
        return out

