    def __init__(self, V, twist=None):
        """
        TESTS::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.zhu_algebra import ZhuAlgebra
            sage: A = ZhuAlgebra(va.Virasoro(QQ, -22/5, conformal_vector='L'))
            sage: A.ngens(), A.twist(), A.is_known_exact()
            (1, None, True)
            sage: ZhuAlgebra(va.Lattice(QQ, matrix([[2]])))
            Traceback (most recent call last):
            ...
            NotImplementedError: Zhu algebras are implemented for universal vertex algebras ...
        """
        from .vertex_algebra_categories import _is_proto
        if not getattr(V, '_is_universal_vertex_algebra', False):
            raise NotImplementedError(
                'Zhu algebras are implemented for universal vertex algebras '
                '(and quotients of them: zhu_algebra_up_to), not for {}'.format(V))
        if _is_proto(V) and not self._rewriting_only:
            raise ValueError('{} is a proto vertex algebra (its Jacobi identity '
                             'is not claimed): no Zhu algebra'.format(V))
        R = V.base_ring()
        if R.characteristic() != 0:
            raise ValueError('Zhu algebras need rational conformal weights '
                             '(characteristic 0)')
        try:
            data = V._weight_data()
        except ValueError:
            raise ValueError('{} has no conformal weights (give conformal_weights '
                             'or a conformal vector)'.format(V))
        hV = []
        for x, s in zip(data['h'], V._gens):
            h = _to_rational(x, 'conformal weight of ' + s)
            if twist is None and 2 * h not in ZZ:
                raise ValueError('the conformal weight {} of {} is not an integer '
                                 "or half-integer (twist='H' takes any rational "
                                 'weights)'.format(h, s))
            if h < 0:
                raise NotImplementedError('the generator {} has negative conformal '
                                          'weight {}'.format(s, h))
            hV.append(h)
        self._V = V
        self._twist = twist
        self._hV = tuple(hV)
        #: Zhu generator index -> V generator index (the integer weights; all
        #: with the twist)
        self._vgen = tuple(i for i, h in enumerate(hV) if twist or h in ZZ)
        self._zidx = {v: z for z, v in enumerate(self._vgen)}
        self._h = tuple(hV[v] for v in self._vgen)
        self._odd = frozenset(z for z, v in enumerate(self._vgen)
                              if V._parities.get(v, 0))
        self._names = tuple(V._gens[v] for v in self._vgen)
        self._exact = (len(self._vgen) == len(hV) and all(h > 0 for h in self._h))
        self._zeta = {}             # V basis key -> {monomial: c}
        self._comm = {}             # (a, b), a >= b -> [x_a, x_b] (a == b: the square)
        self._lmul_cache = {}       # (a, monomial) -> {monomial: c}
        self._busy = set()
        self._plural_data = None
        cat = Algebras(R).WithBasis()
        cat = cat.Super() if self._odd else cat.Filtered()
        CombinatorialFreeModule.__init__(
            self, R, _OrderedMonomials(len(self._vgen), self._odd),
            prefix='', category=cat)

