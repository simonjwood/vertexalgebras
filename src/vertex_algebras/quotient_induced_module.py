    def _product_in_window(self, a, n, m):
        r"""
        Whether ``a_(n) m`` lies within the computed depths: ``a`` and
        ``m`` homogeneous, ``depth(m) + wt a - n - 1 <= max_depth``
        (the category tests skip the other products).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])       # Lee--Yang
            sage: U = Q.zhu_algebra_up_to(4).module({'L': -1/5})
            sage: M = Q.induced_module_up_to(U, 4, 3); v = M.some_elements()[0]
            sage: M._product_in_window(L, -2, v), M._product_in_window(L, -3, v)
            (True, False)
            sage: M._product_in_window(L + L.no(L), 0, v)       # not homogeneous
            False
        """
        try:
            wa = a.degree()
        except ValueError:
            return False
        if m.is_zero():
            return True
        t = max(self._tdeg(k) for k in m.support())
        return t + wa - n - 1 <= self._N._depth

    def _test_module_borcherds(self, **options):
        r"""
        The commutator formula of the strong generators of ``Q`` on the
        basis vectors of twisted degree ``<= 1``, for the modes whose
        products stay within the computed depths (the category's test needs
        larger depths).

        TESTS::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, -22/5, conformal_vector='L'); L = V.gen('L')
            sage: Q = V.quotient([L.no(L) - 3/10*L.derivative(2)])       # Lee--Yang
            sage: U = Q.zhu_algebra_up_to(4).module({'L': -1/5})
            sage: M = Q.induced_module_up_to(U, 4, 6); N = M._N
            sage: M._test_module_borcherds()
        """
        tester = self._tester(**options)
        M = self._cover_module
        N = self._N
        V = M.vertex_algebra()
        X = N._X
        one = self.base_ring().one()
        for t in (0, 1):
            if t > N._depth:
                continue
            for k in self._keys_of_tdeg(t):
                v = {k: one}
                for i, (_, xi, hi, _) in enumerate(X[:3]):
                    for j, (_, xj, hj, _) in enumerate(X[:3]):
                        s = (-1) ** (V._parity_key(((i, 0),)) * V._parity_key(((j, 0),)))
                        poles = V._ope_mono(((i, 0),), ((j, 0),))
                        for q in N._modes(hj, t):
                            for p in N._modes(hi, t + hj - q - 1):
                                if not 0 <= t + hi - p - 1 <= N._depth:
                                    continue
                                lhs = self._from_dict(self._nf(M._action_raw(
                                    xi, p, M._action_raw(xj, q, v))))
                                lhs -= s * self._from_dict(self._nf(M._action_raw(
                                    xj, q, M._action_raw(xi, p, v))))
                                rhs = self.zero()
                                for jj, d in enumerate(poles):
                                    if d and binomial(p, jj):
                                        rhs += binomial(p, jj) * self._from_dict(
                                            self._nf(M._action_raw(d, p + q - jj, v)))
                                tester.assertEqual(lhs, rhs)
