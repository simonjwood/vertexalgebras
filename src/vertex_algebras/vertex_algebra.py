        if weights is None:
            self._weights = None
            return
        data = self._conformal_weights_data(weights)
        if self._conformal is not None and data != self._conformal['data']:
            raise ValueError(
                'these conformal weights differ from those of the Virasoro '
                'vector {}'.format(self._conformal['T']))
