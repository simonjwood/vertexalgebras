def _mode_word_str(letters, vacuum, style='ascii', conformal=False):
    r"""
    The mode word ``a(n) b(m) ... |vacuum>`` in the notation ``style``.

    INPUT:

    - ``letters`` -- a list of triples ``(name, n, h)``: the mode ``n``
      of the field ``name`` of conformal weight ``h`` (the coefficient
      of `z^{-n-1}`; ``h`` is used only if ``conformal``)
    - ``vacuum`` -- ``None`` (the vacuum ``|0>``) or a tuple (the Fock
      vacuum ``|(q_1,...,q_r)>`` of momentum `q`; ``|0>`` if `q = 0`)
    - ``style`` -- ``'ascii'``, ``'unicode'`` or ``'latex'``
    - ``conformal`` -- (default: ``False``) whether to label the modes
      by the coefficient of `z^{-n-h}`: ``a_{n-h+1}`` instead of
      ``a(n)``

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _mode_word_str
        sage: w = [('L', -3, 2), ('G', -1, 3/2)]
        sage: _mode_word_str(w, None), _mode_word_str(w, None, conformal=True)
        ('L(-3)G(-1)|0>', 'L_{-4}G_{-3/2}|0>')
        sage: _mode_word_str(w, None, 'unicode')
        'L(-3)G(-1)|0⟩'
        sage: print(_mode_word_str(w, (1, -1), 'latex'))
        L_{(-3)} G_{(-1)} |(1,-1)\rangle
        sage: print(_mode_word_str(w, None, 'latex', conformal=True))
        L_{-4} G_{-\frac{3}{2}} |0\rangle
        sage: _mode_word_str([], (0, 0)), _mode_word_str([], (2,))
        ('|0>', '|(2)>')
    """
    from sage.misc.latex import latex
    parts = []
    for name, n, h in letters:
        if conformal:
            n = n - h + 1
            parts.append('{}_{{{}}}'.format(name, latex(n) if style == 'latex' else n))
        elif style == 'latex':
            parts.append('{}_{{({})}}'.format(name, latex(n)))
        else:
            parts.append('{}({})'.format(name, n))
    if vacuum is None or not any(vacuum):
        label = '0'
    else:
        label = '({})'.format(','.join(str(v) for v in vacuum))
    parts.append('|{}{}'.format(label, {'ascii': '>', 'unicode': '⟩',
                                        'latex': '\\rangle'}[style]))
    return (' ' if style == 'latex' else '').join(parts)


def _is_int_like(v):
    """
    Return True if ``v`` is an integer (Python or Sage).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _is_int_like
        sage: _is_int_like(int(3)), _is_int_like(4/2), _is_int_like(1/2), _is_int_like('a')
        (True, True, False, False)
    """
    try:
        return Integer(v) == v
    except (TypeError, ValueError):
        return False


def _add_scaled(dst, src, c):
    """
    ``dst += c * src`` over raw coefficient dicts, dropping zeros; returns
    ``dst`` (changed in place).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _add_scaled
        sage: d = {1: 2, 2: 3}
        sage: _add_scaled(d, {1: -1, 3: 1}, 2) is d, d
        (True, {2: 3, 3: 2})
        sage: _add_scaled(d, {5: 1}, 0)
        {2: 3, 3: 2}
    """
    if not c:
        return dst
    for k, v in src.items():
        w = dst.get(k)
        w = c * v if w is None else w + c * v
        if w:
            dst[k] = w
        else:
            dst.pop(k, None)
    return dst


def _trim(poles):
    """
    Drop trailing empty pole dicts (in place) and return the list.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _trim
        sage: _trim([{1: 1}, {}, {2: 1}, {}, {}]), _trim([{}])
        ([{1: 1}, {}, {2: 1}], [])
    """
    while poles and not poles[-1]:
        poles.pop()
    return poles


