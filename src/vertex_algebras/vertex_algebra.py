def _normalize_implementation(implementation, allowed=IMPLEMENTATIONS):
    r"""
    ``implementation`` if it is ``None`` or one of ``allowed``, else a
    ``ValueError``.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _normalize_implementation
        sage: _normalize_implementation('python'), _normalize_implementation(None)
        ('python', None)
        sage: _normalize_implementation('fast')
        Traceback (most recent call last):
        ...
        ValueError: implementation must be None, 'engine' or 'python' (got 'fast')
    """
    if implementation is None or (isinstance(implementation, str)
                                  and implementation in allowed):
        return implementation
    raise ValueError('implementation must be None, {} or {!r} (got {!r})'.format(
        ', '.join(repr(a) for a in allowed[:-1]), allowed[-1], implementation))


