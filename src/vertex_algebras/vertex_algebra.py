    def _install_virasoro(self, T, check=True):
        """
        Install the Virasoro vector ``T`` (constructions taking the
        Virasoro vector as constructor data call it from ``__init__``):
        checked (:meth:`_verify_virasoro`, unless ``check`` is false, then
        the central charge is unknown), weight data and Jordan chains from
        :meth:`_virasoro_data`; a :class:`LogarithmicWarning` if there are
        Jordan chains.  ``None`` removes the Virasoro vector.

        EXAMPLES:

        On a private algebra (algebras are immutable: only constructors
        call this)::

            sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
            sage: from vertex_algebras.normally_ordered_expressions import NormallyOrderedExpressions
            sage: E.<Lu> = NormallyOrderedExpressions(QQ)
            sage: U = UniversalVertexAlgebra(QQ, E, {('Lu', 'Lu'): [Lu.derivative(), 2*Lu, 0, 1/4]},
            ....:                            degrees={'Lu': 2})
            sage: x = U.gen(0)
            sage: U.conformal_vector() is None
            True
            sage: U._install_virasoro(x); U.conformal_vector(), U._conformal['c']
            (Lu, 1/2)
            sage: U._install_virasoro(x, check=False); U._conformal['c'] is None
            True
            sage: U._install_virasoro(None); U.conformal_vector() is None
            True
        """
        if T is None:
            self._conformal = None
            return
        T = self(T)
        c = self._verify_virasoro(T) if check else None
        data, chains = self._virasoro_data(T)
        if self._weights is not None and data != self._weights['data']:
            raise ValueError(
                'T induces conformal weights different from the conformal '
                'weights {} given with it'.format(self._weights['spec']))
        self._conformal = {'T': T, 'c': c, 'data': data, 'jordan': chains}
        if chains:
            parts = ', '.join('T_(1) {} = {} {} {}'.format(
                s, ch[0], *(('-', str(ch[1])[1:]) if str(ch[1]).startswith('-')
                            else ('+', ch[1])))
                for s, ch in chains.items())
            warnings.warn(
                'L_0 = T_(1) is not diagonalizable for this Virasoro vector '
                '(it has Jordan blocks): {} (Jordan chains of length up to {} '
                'on the generators); conformal weights and weight spaces '
                'refer to generalized L_0 eigenvalues'.format(
                    parts, max(len(ch) for ch in chains.values())),
                LogarithmicWarning, stacklevel=3)

    def _virasoro_data(self, T):
        """
        Check ``T_(0) = ∂`` and the triangularity of ``T_(1)`` on the
        generators (see :meth:`with_conformal_vector`); return the weight data (from
        ``_weight_data_from()``) and the Jordan chains.

        EXAMPLES:

        Affine ``sl_2`` at level 1 with ``T_sug + dE``::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: T = A.conformal_vector() + E.derivative()
            sage: data, chains = A._virasoro_data(T)
            sage: data, sorted(chains), chains['-alpha[1]']
            ({'h': [1, 1, 1]}, ['-alpha[1]', 'alphacheck[1]'], (-alpha[1], -alphacheck[1], -2*alpha[1]))
            sage: A._virasoro_data(A.conformal_vector())
            ({'h': [1, 1, 1]}, {})
            sage: A._virasoro_data(2 * A.conformal_vector())
            Traceback (most recent call last):
            ...
            ValueError: T_(0) alpha[1] = 2*dalpha[1] is not ∂alpha[1]: T does not act as the translation operator on alpha[1]
        """
        gens = self._weight_generators()
        weights, t1s = [], []
        for label, key in gens:
            x = self.monomial(key)
            t0 = T.nproduct(x, 0)
            if t0 != x.derivative():
                raise ValueError('T_(0) {} = {} is not ∂{}: T does not act as '
                                 'the translation operator on {}'
                                 .format(label, t0, label, label))
            t1 = T.nproduct(x, 1)
            weights.append(t1.coefficient(key))
            t1s.append(t1)
        data = self._weight_data_from(weights)
        chains = {}
        for (label, key), h, t1 in zip(gens, weights, t1s):
            x = self.monomial(key)
            y = t1 - h * x
            if y.is_zero():
                continue
            for m in y.support():
                w = self._weight_key(m, data)
                if w != h:
                    raise ValueError(
                        'T_(1) is not triangular: T_(1) {} = {} contains {} '
                        'of weight {}, but {} has weight {} (the diagonal '
                        'coefficient); the weight spaces are not spanned by '
                        'basis monomials'.format(label, t1, self._repr_term(m),
                                                 w, label, h))
            chains[label] = self._jordan_chain(T, x, y, h, label)
        return data, chains

    def _jordan_chain(self, T, x, y, h, label):
        """``[x, D x, D^2 x, ...]`` up to the last nonzero term, for
        ``D = T_(1) - h`` (``y = D x``); a ``ValueError`` if ``D`` is not
        nilpotent on ``x`` (a nonzero ``D^k x`` in the span of the earlier
        ones).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: T = A.conformal_vector() + E.derivative()
            sage: A._jordan_chain(T, F, T.nproduct(F, 1) - F, 1, 'F')
            (-alpha[1], -alphacheck[1], -2*alpha[1])
        """
        from sage.matrix.constructor import matrix
        R = self.base_ring()
        chain = [x]
        while not y.is_zero():
            chain.append(y)
            keys = sorted({m for v in chain for m in v.support()}, key=repr)
            M = matrix(R, [[v.coefficient(m) for m in keys] for v in chain])
            if M.rank() < len(chain):
                raise ValueError(
                    'T_(1) - {} is not nilpotent on {}: the chain {} is linearly '
                    'dependent; L_0 is diagonalizable only in a basis that mixes '
                    'basis monomials (e.g. generators of different tensor '
                    'factors): construct the vertex algebra from adapted '
                    'generators'.format(h, label, chain))
            if len(chain) > MAX_JORDAN_CHAIN:
                raise ValueError(
                    'could not verify that T_(1) - {} is nilpotent on {} (no '
                    'end after {} steps)'.format(h, label, MAX_JORDAN_CHAIN))
            y = T.nproduct(y, 1) - h * y
        return tuple(chain)

    def _check_l0_on(self, T, gens, data):
        r"""
        For constructions whose conformal weights are those of an ambient
        algebra (subalgebras, quotients): check that ``T`` induces them on
        the strong generators ``gens``, a list of ``(label, x, h)``.  For
        each, ``T_(0) x = ∂x`` and ``D x = T_(1) x - h x`` has weight ``h``
        (for the weight data ``data``) and is nilpotent under ``T_(1) - h``;
        then ``T_(0) = ∂`` and ``D`` is a locally nilpotent derivation (see
        :meth:`with_conformal_vector`).  Returns the Jordan chains of the ``x`` with
        ``D x != 0``; a ``ValueError`` names what fails.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: A = va.Affine(QQ, ['A', 1], 1, conformal_vector='sugawara')
            sage: E, F = A.gen('alpha[1]'), A.gen('-alpha[1]')
            sage: T = A.conformal_vector() + E.derivative()
            sage: gens = [('E', E, 1), ('F', F, 1)]
            sage: A._check_l0_on(T, gens, A._weight_data())
            {'F': (-alpha[1], -alphacheck[1], -2*alpha[1])}
            sage: A._check_l0_on(A.conformal_vector(), gens, A._weight_data())
            {}
            sage: A._check_l0_on(A.conformal_vector(), [('E', E, 2)], A._weight_data())
            Traceback (most recent call last):
            ...
            ValueError: T does not induce the conformal weights of the ambient algebra on ...
        """
        chains = {}
        for label, x, h in gens:
            t0 = T.nproduct(x, 0)
            if t0 != x.derivative():
                raise ValueError('T_(0) {} = {} is not ∂{}: T does not act as '
                                 'the translation operator on {}'
                                 .format(label, t0, label, label))
            y = T.nproduct(x, 1) - h * x
            if y.is_zero():
                continue
            ws = {self._weight_key(m, data) for m in y.support()}
            msg = ('T does not induce the conformal weights of the ambient '
                   'algebra on {}: T_(1) {} = {} but {} has weight {}'.format(
                       self, label, y + h * x, label, h))
            if ws != {h}:
                raise ValueError(msg)
            try:
                chains[label] = self._jordan_chain(T, x, y, h, label)
            except ValueError:
                raise ValueError(msg)
        return chains

