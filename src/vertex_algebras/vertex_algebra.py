def _format_terms(P, items, style='ascii'):
    r"""
    The string ``c1*t1 + c2*t2 + ...`` for ``(term string, coefficient)``
    pairs (term ``None``: the vacuum, printed as the bare coefficient);
    coefficients are coerced into the base ring of ``P``, zero terms
    dropped, compound coefficients get brackets.  ``style='latex'``: LaTeX
    coefficients, no ``*``.

    EXAMPLES::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra import _format_terms
        sage: K.<c> = Frac(QQ['c'])
        sage: V = va.Virasoro(K, c)
        sage: print(_format_terms(V, [('L', 2), (None, c/2), ('dL', c + 1), ('X', 0), ('Y', 1)]))
        2*L + 1/2*c + (c + 1)*dL + Y
        sage: print(_format_terms(V, [('L', c - 1), (None, 1)], 'latex'))
        \left( c - 1 \right) L + 1
        sage: _format_terms(V, [])
        '0'

    Negative coefficients follow Sage's convention::

        sage: print(_format_terms(V, [('L', -1), ('dL', -3), (None, -c), ('Y', 1 - c)]))
        -L - 3*dL - c + (-c + 1)*Y
        sage: print(_format_terms(V, [(None, 1), ('L', -2)], 'latex'))
        1 - 2 L
    """
    terms = []
    for t, c in items:
        c = P._rc(c)
        if c.is_zero():
            continue
        cs = str(c)
        compound = '+' in cs[1:] or ' - ' in cs
        if style == 'latex':
            from sage.misc.latex import latex
            cs = latex(c)
            if compound:
                cs = '\\left(' + cs + '\\right)'
        elif compound:
            cs = '(' + cs + ')'
        if t is None:
            terms.append(str(latex(c)) if style == 'latex' else str(c))
        elif c == 1:
            terms.append(t)
        elif c == -1:
            terms.append('-' + t)
        else:
            terms.append(('{} {}' if style == 'latex' else '{}*{}').format(cs, t))
    if not terms:
        return '0'
    # Sage's convention: ``a - b``, not ``a + -b``
    return terms[0] + ''.join(' - ' + s[1:] if s.startswith('-') else ' + ' + s
                              for s in terms[1:])


