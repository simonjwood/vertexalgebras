def _compiled_module(name):
    r"""
    ``(module, None)``: the compiled module ``name`` of this package (built
    when the package is installed, e.g. ``_universal_engine``), or ``(None,
    reason)`` when the developer switch ``VERTEX_ALGEBRAS_NO_ENGINE=1``
    turns the compiled modules off (the pure-Python recursions everywhere;
    ``tests/run_all.sh --fallback``).  The switch only chooses which code
    runs; results do not depend on it.  A module that is missing although
    not switched off means a broken installation: an ``ImportError`` saying
    so.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _compiled_module
        sage: import os
        sage: m, why = _compiled_module('_universal_engine')
        sage: (m is None) == bool(os.environ.get('VERTEX_ALGEBRAS_NO_ENGINE')), why is None or 'switched off' in why
        (True, True)
        sage: try:
        ....:     r = _compiled_module('_no_such_module')
        ....: except ImportError as err:
        ....:     r = str(err).split(' (')[0]
        sage: r in ('the compiled module vertex_algebras._no_such_module is missing',
        ....:       (None, 'switched off by VERTEX_ALGEBRAS_NO_ENGINE'))
        True
    """
    if os.environ.get('VERTEX_ALGEBRAS_NO_ENGINE'):
        return None, 'switched off by VERTEX_ALGEBRAS_NO_ENGINE'
    try:
        return importlib.import_module('.' + name, __package__), None
    except ImportError as err:
        raise ImportError(
            'the compiled module {}.{} is missing ({}): install the package '
            'with pip, e.g. "pip install --no-build-isolation -e ." in the '
            'repository'.format(__package__, name, err)) from err


class VertexAlgebraParallelism(Singleton, SageObject):
    r"""
    The number of threads used by the C++ engines of vertex algebra
    computations, for the whole session (default ``1``: serial).  Results
    do not depend on it (dict order included).

    This is Sage's :class:`~sage.parallel.parallelism.Parallelism` for this
    library, with the same methods for its single field: Sage's
    ``Parallelism()`` has no field for vertex algebras (its fields are
    fixed), so ``Parallelism().set(nproc=n)`` does not reach these
    computations.  Should Sage gain a ``'vertex_algebra'`` field, this
    object forwards to it.  The count is read at every call
    (``_nproc()``), so changing it affects every algebra at once.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
        sage: P = VertexAlgebraParallelism(); P
        Number of threads for vertex algebra computations: 1
        sage: P.set(nproc=2); P.get()
        2
        sage: VertexAlgebraParallelism() is P
        True
        sage: P.reset(); P.get()
        1
        sage: P.set(); P.get() == P.get_default()      # all CPUs
        True
        sage: P.reset()
        sage: TestSuite(P).run()

    TESTS:

    The pure-Python implementation has no engine and computes serially
    whatever the setting, with the same results (in the same order)::

        sage: import vertex_algebras as va
        sage: V = va.NeveuSchwarz(QQ, 7/10, implementation='python'); L, G = V.gens()
        sage: X = L.no(L).no(G) + 3*G.derivative(2); Y = G.no(L) - 5*L.derivative(3).no(L)
        sage: want = [list(p.monomial_coefficients().items()) for p in X.ope(Y)]
        sage: V.clear_caches(); P.set(2)
        sage: [list(p.monomial_coefficients().items()) for p in X.ope(Y)] == want, V._engine()
        (True, None)
        sage: P.reset()
    """
    def __init__(self):
        """
        TESTS::

            sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
            sage: VertexAlgebraParallelism()._nproc
            1
        """
        self._nproc = 1

    def _repr_(self):
        """
        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
            sage: repr(VertexAlgebraParallelism())
            'Number of threads for vertex algebra computations: 1'
        """
        return ('Number of threads for vertex algebra computations: {}'
                .format(self.get()))

    def get_default(self):
        """
        The number used by :meth:`set` without an argument: the number
        of CPUs (as for Sage's ``Parallelism()``).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
            sage: VertexAlgebraParallelism().get_default() >= 1
            True
        """
        return _cpu_count()

    def set(self, nproc=None):
        """
        Use ``nproc`` threads for the rest of the session.

        INPUT:

        - ``nproc`` -- (default: ``None``) a positive integer, or ``None``
          for all CPUs (:meth:`get_default`); more than the CPUs available
          warns

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
            sage: P = VertexAlgebraParallelism()
            sage: P.set(2); P.get()
            2
            sage: P.reset()

        TESTS::

            sage: P.set(0)
            Traceback (most recent call last):
            ...
            ValueError: nproc must be positive, got 0
        """
        n = self.get_default() if nproc is None else int(nproc)
        if n < 1:
            raise ValueError('nproc must be positive, got {}'.format(nproc))
        if n > (os.cpu_count() or 1):
            warnings.warn('{} threads requested but only {} CPU '
                          'core(s) available'.format(n, os.cpu_count() or 1),
                          RuntimeWarning, stacklevel=2)
        if _sage_has_field():
            Parallelism().set(_SAGE_FIELD, nproc=n)
        else:
            self._nproc = n

    def get(self):
        """
        The number of threads (default ``1``).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
            sage: VertexAlgebraParallelism().get()
            1
        """
        if _sage_has_field():
            return Parallelism().get(_SAGE_FIELD)
        return self._nproc

    def reset(self):
        """
        Back to the default: serial.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import VertexAlgebraParallelism
            sage: P = VertexAlgebraParallelism()
            sage: P.set(2); P.reset(); P.get()
            1
        """
        self.set(1)


#: The name of the field of Sage's ``Parallelism()`` this library would use.
_SAGE_FIELD = 'vertex_algebra'
_SAGE_HAS_FIELD = None


def _sage_has_field():
    """
    Whether Sage's ``Parallelism()`` has a field for vertex algebras
    (computed once; then :class:`VertexAlgebraParallelism` forwards to it).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _sage_has_field, _SAGE_FIELD
        sage: _sage_has_field() == (_SAGE_FIELD in Parallelism()._nproc)
        True
    """
    global _SAGE_HAS_FIELD
    if _SAGE_HAS_FIELD is None:
        try:
            Parallelism().get(_SAGE_FIELD)
            _SAGE_HAS_FIELD = True
        except KeyError:
            _SAGE_HAS_FIELD = False
    return _SAGE_HAS_FIELD


def _nproc():
    """
    The number of threads every computation uses
    (:class:`VertexAlgebraParallelism`); the one place reading it.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _nproc, VertexAlgebraParallelism
        sage: _nproc()
        1
        sage: VertexAlgebraParallelism().set(2); _nproc()
        2
        sage: VertexAlgebraParallelism().reset()
    """
    return VertexAlgebraParallelism().get()


