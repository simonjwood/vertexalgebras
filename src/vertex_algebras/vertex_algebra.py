    @_gc_paused
    def _ope_el(self, A, B):
        """
        The OPE of elements of ``self`` as the trimmed list of poles
        (behind ``A.ope(B)``).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._ope_el(L, L)
            [dL, 2*L, 0, 1/4]
            sage: V._ope_el(L, V.zero()), V._ope_el(L, V.one())
            ([], [])
        """
        self._check(A, B)
        if A.is_zero() or B.is_zero():
            return []
        out = _trim(self._ope_raw(dict(A._monomial_coefficients),
                                  dict(B._monomial_coefficients)))
        return [self._el_from_dict(d) for d in out]

    @_gc_paused
    def _nprod_el(self, A, n, B):
        """
        ``A_(n) B`` for elements of ``self`` (behind ``A.nproduct(B, n)``).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._nprod_el(L, -1, L), V._nprod_el(L, 3, L), V._nprod_el(V.zero(), 0, L)
            (:L L:, 1/4, 0)
        """
        self._check(A, B)
        if A.is_zero() or B.is_zero():
            return self.zero()
        return self._el_from_dict(
            self._nprod_raw(dict(A._monomial_coefficients), int(n),
                            dict(B._monomial_coefficients)))

    @_gc_paused
    def _deriv_el(self, A, n=1):
        """
        ``∂^n A`` (behind ``A.derivative(n)``).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._deriv_el(L, 2), V._deriv_el(L, 0), V._deriv_el(V.one())
            (d^2L, L, 0)
            sage: V._deriv_el(L, -1)
            Traceback (most recent call last):
            ...
            ValueError: the derivative order must be non-negative
        """
        n = int(n)
        if n < 0:
            raise ValueError('the derivative order must be non-negative')
        if n == 0 or A.is_zero():
            return A
        return self._el_from_dict(
            self._deriv_raw(dict(A._monomial_coefficients), n))

    def _deriv_el_serial(self, A, n):
        """
        ``∂^n A`` without parallel dispatch (for use inside kernels): from
        the key-level accessors only, not the engine's element level.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._deriv_el_serial(L.no(L), 1) == L.no(L).derivative(), V._deriv_el_serial(L, 0)
            (True, L)
        """
        if n == 0 or A.is_zero():
            return A
        res = {}
        for m, c in A._monomial_coefficients.items():
            _add_scaled(res, self._deriv_mono(m, n), c)
        return self._el_from_dict(res)

