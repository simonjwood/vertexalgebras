    def _conformal_weights_data(self, weights):
        """
        The weight data for the spec of :meth:`with_degrees`
        (a dict ``label -> weight``); constructions may accept more.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._conformal_weights_data({'L': 2})
            {'h': [2]}
            sage: V._conformal_weights_data({'X': 2})
            Traceback (most recent call last):
            ...
            ValueError: conformal weights must be given for exactly ['L'] (got ['X'])
            sage: V._conformal_weights_data(2)
            Traceback (most recent call last):
            ...
            ValueError: the conformal weights must be a dict label -> weight
        """
        if not isinstance(weights, dict):
            raise ValueError('the conformal weights must be a dict '
                             'label -> weight')
        labels = [label for label, _ in self._weight_generators()]
        if set(weights) != set(labels):
            raise ValueError(
                'conformal weights must be given for exactly {} (got {})'
                .format(labels, sorted(weights, key=str)))
        R = self.base_ring()
        return self._weight_data_from([R(weights[s]) for s in labels])

