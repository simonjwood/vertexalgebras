def _save_with_state(obj, filename, compress, loader, args):
    r"""
    Write ``obj`` with its computed state to ``filename`` (the ``save``
    method that Sage's ``save(obj, filename)`` calls): a Sage pickle whose
    unpickling (``load(filename)``) is ``loader(*args)``; ``.sobj`` is
    appended to a name without extension, the file replaced atomically.
    Ordinary pickles of ``obj`` (``dumps``, pickles of containers or
    elements) keep only the construction data.

    EXAMPLES::

        sage: from types import SimpleNamespace
        sage: from vertex_algebras.vertex_algebra import _save_with_state
        sage: o = SimpleNamespace(); fn = tmp_filename(ext='.sobj')
        sage: _save_with_state(o, fn, True, ZZ, (5,))
        sage: load(fn), o._default_filename == fn
        (5, True)
        sage: _save_with_state(o, None, True, ZZ, (6,)); load(fn)
        6
        sage: base = os.path.join(tmp_dir(), 'state')
        sage: _save_with_state(o, base, False, ZZ, (7,))
        sage: o._default_filename == base + '.sobj', load(base + '.sobj')
        (True, 7)
        sage: _save_with_state(SimpleNamespace(), None, True, ZZ, ())
        Traceback (most recent call last):
        ...
        ValueError: give a file name
    """
    from sage.misc.persist import dumps
    if filename is None:
        filename = getattr(obj, '_default_filename', None)
        if filename is None:
            raise ValueError('give a file name')
    filename = os.fspath(filename)
    if not os.path.splitext(filename)[1]:
        filename += '.sobj'
    data = dumps(_Saved(loader, args), compress)
    tmp = '{}.tmp{}'.format(filename, os.getpid())
    with open(tmp, 'wb') as f:
        f.write(data)
    os.replace(tmp, filename)
    obj._default_filename = filename


def _canonical_element(P, x, specs=()):
    """
    A conformal vector given to a construction on ``P`` (its ambient
    algebra) in canonical form: ``None``, one of the strings ``specs``
    (e.g. ``'ambient'``), or a tuple of ``(key, coefficient)`` of the
    element ``P(x)`` sorted by the repr of the key (a tuple of that form is
    taken as it is: the normalized construction arguments, pickling).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _canonical_element
        sage: from vertex_algebras.lattice_vertex_algebra import LatticeVertexAlgebra
        sage: L = LatticeVertexAlgebra(QQ, matrix([[2]])); J = L.J(0)
        sage: t = _canonical_element(L, J.no(J)/4 + J.derivative()); t
        (((((0, 0), (0, 0)), (0,)), 1/4), ((((0, 1),), (0,)), 1))
        sage: _canonical_element(L, t) == t, _canonical_element(L, 'ambient', ('ambient',))
        (True, 'ambient')
    """
    if x is None:
        return None
    if isinstance(x, str):
        if x not in specs:
            raise ValueError('the conformal vector must be an element{}{}'.format(
                ', None or ' if specs else ' or None',
                ' or '.join(repr(t) for t in specs)))
        return x
    if isinstance(x, tuple):
        return x
    d = P(x)._monomial_coefficients
    return tuple(sorted(((k, c) for k, c in d.items() if c),
                        key=lambda kc: repr(kc[0])))


def _module_of(x):
    """
    The module over a vertex algebra that ``x`` is a vector of, or
    ``None``.

    EXAMPLES::

        sage: import vertex_algebras as va
        sage: from vertex_algebras.vertex_algebra import _module_of
        sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); M = V.adjoint_module()
        sage: _module_of(L) is None, _module_of(M(L)) is M, _module_of(3) is None
        (True, True, True)
    """
    P = _parent(x)
    return P if getattr(P, '_is_vertex_algebra_module', False) else None


def _common(x, y):
    """
    ``x`` and ``y`` in a common parent (Sage's coercion model), for the
    products of elements of different parents, e.g. of an algebra and of
    the same algebra with a conformal vector (forgetful coercion).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _common
        sage: from vertex_algebras.lattice_vertex_algebra import LatticeVertexAlgebra
        sage: L = LatticeVertexAlgebra(QQ, matrix([[2]]))
        sage: LT = L.with_horizontal_grading('lattice')
        sage: a, b = _common(LT.J(0), L.e((1,))); a.parent() is b.parent() is L
        True
        sage: LT.J(0).ope(L.e((1,)))
        [2*e^(1)]
    """
    px, py = _parent(x), _parent(y)
    if px is py:
        return x, y
    from sage.structure.element import get_coercion_model
    return get_coercion_model().canonical_coercion(x, y)


