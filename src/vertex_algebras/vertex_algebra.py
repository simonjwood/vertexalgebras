    def _cache_owners(self):
        """
        The algebras whose caches the computations of ``self`` fill
        (``self`` first; for checks of the cache contract).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._cache_owners() == [V]
            True
        """
        return [self]

    def _raw_caches(self):
        """
        Names of this algebra's caches of raw dicts (the cache contract).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: VertexAlgebra._raw_caches(V)
            ['_ope_cache', '_no_cache', '_nprod_cache', '_deriv_cache']
            sage: all(isinstance(getattr(V, n), dict) for n in V._raw_caches())
            True
        """
        return ['_ope_cache', '_no_cache', '_nprod_cache', '_deriv_cache']

    def _compute_job(self, job):
        """
        Compute one job (a tuple ``('ope', a, b)``, ``('no', a, b)``,
        ``('nprod', a, n, b)`` or ``('deriv', m, n)``); custom tags go to
        :meth:`_compute_custom_job`.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._compute_job(('deriv', a, 1)), V._compute_job(('nprod', a, -2, a))
            ({((0, 1),): 1}, {((0, 1), (0, 0)): 1})
            sage: V._compute_job(('no', a, a)), V._compute_job(('ope', (), a))
            ({((0, 0), (0, 0)): 1}, ())
            sage: V._compute_job(('foo', a))
            Traceback (most recent call last):
            ...
            ValueError: unknown job tag 'foo'
        """
        tag = job[0]
        if tag == 'ope':
            return self._ope_mono(job[1], job[2])
        if tag == 'no':
            return self._no_mono(job[1], job[2])
        if tag == 'nprod':
            return self._nprod_mono(job[1], job[2], job[3])
        if tag == 'deriv':
            return self._deriv_mono(job[1], job[2])
        return self._compute_custom_job(job)

    def _compute_custom_job(self, job):
        """
        Compute a job with a construction-specific tag (subclass hook;
        e.g. the subalgebra's ``('vec', word)``); the default refuses.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: VertexAlgebra._compute_custom_job(V, ('foo', 1))
            Traceback (most recent call last):
            ...
            ValueError: unknown job tag 'foo'
        """
        raise ValueError('unknown job tag %r' % (job[0],))

    def _run_jobs(self, jobs):
        """
        Compute every job (serially; the job functions cache their results)
        and return ``{job: result}``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: from vertex_algebras.vertex_algebra import VertexAlgebra
            sage: V = va.Virasoro(QQ, 1/2, conformal_vector='L'); L = V.gen('L'); a = ((0, 0),)
            sage: V._run_jobs([('no', a, a)])
            {('no', ((0, 0),), ((0, 0),)): {((0, 0), (0, 0)): 1}}
            sage: V._run_jobs([])
            {}
        """
        return {job: self._compute_job(job) for job in jobs}
