r"""
Vertex algebras: the common base class.

:class:`VertexAlgebra` is the abstract parent of every vertex algebra in this
project.  Concrete constructions are
subclasses:

- :class:`universal_vertex_algebra.UniversalVertexAlgebra` -- strong
  generators and OPE relations (the OPEdefs port, [Thi1991]_);
- :class:`lattice_vertex_algebra.LatticeVertexAlgebra` -- the lattice
  vertex (super)algebra of an integral non-degenerate form;
- :class:`tensor_product_vertex_algebra.TensorProductVertexAlgebra` -- the
  (super) tensor product of any vertex algebras, also available as
  ``V.tensor(W)``.
- :class:`vertex_subalgebra.VertexSubalgebra` -- the vertex subalgebra
  generated by finitely many elements, ``V.subalgebra(A)``;
- :class:`quotient_vertex_algebra.QuotientVertexAlgebra` -- the quotient by
  an ideal (:mod:`vertex_ideal`), ``V.quotient(I)`` or ``V / I``.

The base class owns everything that does not depend on the construction:

- the element API: ``ope``, ``no``, ``pole``, ``nproduct``, ``derivative``,
  ``parity``, ``is_one``, ``*`` (normal ordered product) and scalars;
- linearity: element operations are expanded over basis keys;
- the key-level caches ``_ope_cache``, ``_no_cache``, ``_nprod_cache`` and
  ``_deriv_cache`` (raw dicts ``{key: coeff}`` only, never elements);
- the generic ``n``-th product for ``n < -1``,
  ``a_(-1-k) b = (∂^k a)_(-1) b / k!``;
- parallel evaluation in the threads of the C++ engines, their number a
  setting of the session (:class:`VertexAlgebraParallelism`, default
  serial); everything else is serial.

A subclass implements the construction on basis keys; each hook is called
only when the result is not cached yet:

- ``_vacuum_key()``, ``_parity_key(m)``, ``_repr_term(m)``;
- ``_ope_key(a, b)``: the tuple of pole dicts ``(a_(0) b, a_(1) b, ...)``;
- ``_no_key(a, b)``: ``a_(-1) b``;
- ``_deriv_key(m, n)``: ``∂^n m`` for ``n >= 1``;
- optionally ``_nprod_key(a, n, b)`` for ``n < -1``, ``_nmax_key(a, b)``,
  ``_acc`` (fast accumulation), ``_ope_raw``/``_nprod_raw``/``_deriv_raw``
  (joint evaluation of many keys) and custom parallel jobs.

Optional structure (all subclasses; see :meth:`VertexAlgebra.with_conformal_vector`,
:meth:`VertexAlgebra.with_horizontal_grading`, :meth:`~vertex_algebra_categories.ProtoVertexAlgebras.Graded.ParentMethods.weight_space`): a
chosen Virasoro vector, which makes the generators homogeneous of some
conformal weight (checked), an additional grading by a finitely generated
abelian group (checked against the algebra; see ``_grading_groups``), and the resulting weight spaces, simultaneously of a
given conformal weight and grade, with their bases of basis keys.  The
subclass hooks are ``_weight_generators``, ``_weight_data_from``,
``_weight_key``, ``_grading_data``, ``_grade_key``,
``_weight_space_enumeration`` and ``_weight_bounds``.

Conventions shared by all subclasses: ``a.ope(b)`` is the list of poles
whose entry ``k`` is ``a_(k) b``, the coefficient of ``(z-w)^(-k-1)``;
``a.no(b)`` is ``a_(-1) b``.  No conformal vector is built in anywhere.

EXAMPLES::

    sage: from vertex_algebras import vertex_algebra
    sage: from vertex_algebras.universal_vertex_algebra import UniversalVertexAlgebra
    sage: V = UniversalVertexAlgebra(QQ, ['J'], {('J', 'J'): [0, 1]})
    sage: isinstance(V, vertex_algebra.VertexAlgebra)
    True
    sage: J = V.gen('J')
    sage: J.nproduct(J, -2) == J.derivative().no(J)
    True
    sage: J.nproduct(J, -3) == J.derivative(2).no(J) / 2
    True

AUTHORS:

- Christopher Raymond, Simon Wood (2026): initial version
"""

