def _number_field(K):
    """
    True if ``K`` is a number field other than ``QQ`` (absolute or
    relative, i.e. given as a tower).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _number_field
        sage: K.<s> = QuadraticField(5)
        sage: [_number_field(F) for F in (QQ, K, K.extension(x^2 + 1, 't'), GF(5), QQbar)]
        [False, True, True, False, False]
    """
    from sage.rings.number_field.number_field_base import NumberField
    from sage.rings.rational_field import QQ
    return K is not QQ and isinstance(K, NumberField)


def _absolute_presentation(K):
    """
    ``(M, to_abs, from_abs)``: the absolute field ``M`` of the number
    field ``K`` and the isomorphisms ``K -> M -> K``; ``to_abs`` and
    ``from_abs`` are ``None`` if ``K`` is absolute (``M = K``).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _absolute_presentation
        sage: K.<s> = QuadraticField(5)
        sage: _absolute_presentation(K) == (K, None, None)
        True
        sage: L.<i> = K.extension(x^2 + 1)
        sage: M, to_abs, from_abs = _absolute_presentation(L)
        sage: M.degree(), M.is_absolute(), from_abs(to_abs(s + i)) == s + i
        (4, True, True)
    """
    if K.is_absolute():
        return K, None, None
    M = K.absolute_field('t')
    from_abs, to_abs = M.structure()
    return M, to_abs, from_abs


class _AlgebraicCoefficients:
    r"""
    Coefficients in ``F = QQbar`` or ``AA`` for a C++ engine, which computes
    in a number field ``K`` (or ``QQ``) containing the given algebraic
    numbers (Sage's ``number_field_elements_from_algebraics``, with its
    embedding ``hom: K -> F``).  ``up`` maps an element of ``F`` lying in
    ``K`` to ``K`` (cached; the minimal polynomial's roots in ``K`` are
    compared exactly), else records it in ``outside`` and raises
    ``ValueError``: the algebra then rebuilds its engine over a field
    containing it (:meth:`VertexAlgebra._engine_call`).  ``down`` maps back
    and remembers the pair, so results fed back in convert at once.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _AlgebraicCoefficients
        sage: a = QQbar(2).sqrt()
        sage: A = _AlgebraicCoefficients(QQbar, [a, QQbar(1/3)])
        sage: A.K.degree(), A.down(A.up(a / 5 + 1)) == a / 5 + 1
        (2, True)
        sage: A.up(QQbar(3).sqrt())
        Traceback (most recent call last):
        ...
        ValueError: 1.732050807568878? is not in the engine's number field ...
        sage: A.outside
        [1.732050807568878?]
    """

    def __init__(self, F, numbers):
        """
        TESTS::

            sage: from vertex_algebras.vertex_algebra import _AlgebraicCoefficients
            sage: A = _AlgebraicCoefficients(AA, [AA(1/2), 3])
            sage: A.F is AA, A.K is QQ, A.hom, A.outside
            (True, True, None, [])
            sage: _AlgebraicCoefficients(QQbar, [QQbar(5).sqrt()]).K.degree()
            2
        """
        from sage.rings.qqbar import number_field_elements_from_algebraics
        from sage.rings.rational_field import QQ
        self.F = F
        nums, seen = [], set()
        for x in numbers:
            x = F(x)
            if x not in seen:
                seen.add(x)
                if x.minpoly().degree() > 1:
                    nums.append(x)
        if nums:
            K, els, hom = number_field_elements_from_algebraics(
                nums, minimal=True, embedded=True)
        else:
            K, els, hom = QQ, [], None
        self.K, self.hom = K, hom
        self._to = dict(zip(nums, els))
        self.outside = []

    def up(self, x):
        """
        The element ``x`` of ``F`` as an element of ``K`` (cached); a
        ``ValueError`` (and ``x`` recorded in ``outside``) if it is not in
        ``K``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _AlgebraicCoefficients
            sage: r = QQbar(2).sqrt()
            sage: A = _AlgebraicCoefficients(QQbar, [r])
            sage: y = A.up(r + 1); y.parent() is A.K, A.hom(y) == r + 1, A.up(r + 1) is y
            (True, True, True)
        """
        y = self._to.get(x)
        if y is None:
            y = self._to[x] = self._find(x)
        return y

    def _find(self, x):
        """
        The element of ``K`` mapped to ``x`` by ``hom``, found among the
        roots in ``K`` of the minimal polynomial of ``x`` (rationals
        directly); else ``x`` is appended to ``outside`` and a
        ``ValueError`` raised.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _AlgebraicCoefficients
            sage: A = _AlgebraicCoefficients(AA, [AA(2).sqrt()])
            sage: A._find(AA(1/2)), A.hom(A._find(-AA(2).sqrt())) == -AA(2).sqrt()
            (1/2, True)
            sage: A._find(AA(3).sqrt())
            Traceback (most recent call last):
            ...
            ValueError: 1.732050807568878? is not in the engine's number field ...
            sage: A.outside
            [1.732050807568878?]
        """
        f = self.F(x).minpoly()
        K = self.K
        if f.degree() == 1:
            return K(-f[0])
        if self.hom is not None and K.degree() % f.degree() == 0:
            for r in f.roots(K, multiplicities=False):
                if self.hom(r) == x:
                    return r
        self.outside.append(x)
        raise ValueError('%s is not in the engine\'s number field %s' % (x, K))

    def down(self, y):
        """
        The element ``y`` of ``K`` as an element of ``F`` (the pair is
        remembered for :meth:`up`).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _AlgebraicCoefficients
            sage: r = QQbar(2).sqrt()
            sage: A = _AlgebraicCoefficients(QQbar, [r])
            sage: A.down(A.up(r) / 3) == r / 3
            True
            sage: B = _AlgebraicCoefficients(AA, [1/2])
            sage: B.K, B.down(QQ(3)), B.down(QQ(3)).parent()
            (Rational Field, 3, Algebraic Real Field)
        """
        x = self.F(y if self.hom is None else self.hom(y))
        self._to.setdefault(x, y)
        return x


class _SingularNumberFieldElements:
    r"""
    Elements of a polynomial ring ``R`` implemented by Singular over an
    absolute number field ``M``, built from rational power-basis coordinates
    by Singular arithmetic only.

    Why: Sage 10.9 and earlier convert every coefficient that enters such a
    ring (``sa2si_NF``, also for rationals and integers: ``R(dict)``, ``3 *
    f``) by creating and completing a new Singular ring, which is never freed
    (about 2 KB per coefficient) and on macOS costs milliseconds (Singular
    looks up its routines through the dynamic loader); Sage 10.10 reuses one
    ring.  The C++ engines return thousands of such coefficients per product
    (the lattice algebra of ``A_2`` over ``Q(sqrt 5)[c, d]``: 72679
    coefficients in one test run, 1270 s per run on macOS).  Here the
    generator of ``M`` is the only number converted; integers are sums of
    ``1`` (digits in base 256, Horner's scheme), a coefficient ``Σ_k n_k
    a^k / D`` uses Singular's division by a constant, monomials are products
    of the generators.  Integers, coefficients and monomials met before are
    cached (each cache is emptied once it holds ``CACHE_MAX`` entries).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
        sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
        sage: B = _SingularNumberFieldElements(R, K)
        sage: f = B.polynomial({(1, 0): [(0, 3, 4), (1, -1, 6)], (0, 2): [(0, 123456789, 1)]})
        sage: f == R({(1, 0): 3/4 - s/6, (0, 2): 123456789})
        True
        sage: B.number(((1, 2**100 + 1, 7),)) == (2**100 + 1) * s / 7, B.integer(-300)
        (True, -300)

    TESTS:

    A cubic field, negative and large numbers, denominators, and caches
    emptied on the way::

        sage: L.<z> = NumberField(x^3 - 2); S.<a, b, e> = L[]
        sage: B = _SingularNumberFieldElements(S, L); B.CACHE_MAX = 3
        sage: data = [((0, -7, 3), (2, 5, 2)), ((1, 3**60, 11),), ((0, 1, 1),),
        ....:         ((0, -2**70, 1), (1, 1, 2**40), (2, -9, 4))] * 2
        sage: all(B.number(v) == S(sum(QQ((p, q)) * z^k for k, p, q in v)) for v in data)
        True
        sage: f = B.polynomial({(2, 0, 1): [(2, -1, 3)], (0, 0, 0): [(0, 5, 1), (1, 1, 5)]})
        sage: f == -z^2/3 * a^2 * e + 5 + z/5, B.polynomial({}) == 0
        (True, True)
    """
    CACHE_MAX = 1 << 16

    def __init__(self, R, M):
        """
        TESTS::

            sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
            sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
            sage: B = _SingularNumberFieldElements(R, K)
            sage: len(B._digits), B._radix == 256, B._pow == [1, R(s)], B._gens == (c, d)
            (256, True, True, True)
        """
        self._R = R
        one, zero = R.one(), R.zero()
        digits = [zero]
        for _ in range(255):
            digits.append(digits[-1] + one)
        self._digits = digits
        self._radix = digits[-1] + one
        a = R(M.gen())                    # the only number converted by Sage
        self._pow = [one]
        for _ in range(1, M.degree()):
            self._pow.append(self._pow[-1] * a)
        self._gens = R.gens()
        self._zero, self._one = zero, one
        self._ints, self._nums, self._monos = {}, {}, {}

    def _store(self, cache, key, value):
        """
        ``cache[key] = value`` (the cache emptied first if it holds
        ``CACHE_MAX`` entries); returns ``value``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
            sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
            sage: B = _SingularNumberFieldElements(R, K)
            sage: B.CACHE_MAX = 2; cache = {0: 0, 1: 1}
            sage: B._store(cache, 2, 5), cache
            (5, {2: 5})
        """
        if len(cache) >= self.CACHE_MAX:
            cache.clear()
        cache[key] = value
        return value

    def integer(self, n):
        """
        The integer ``n`` as a constant of the ring.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
            sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
            sage: B = _SingularNumberFieldElements(R, K)
            sage: B.integer(1000) == 1000, B.integer(-2^80) == -2^80, B.integer(0)
            (True, True, 0)
        """
        r = self._ints.get(n)
        if r is not None:
            return r
        m, ds = abs(int(n)), []
        while m:
            ds.append(m & 255)
            m >>= 8
        r = self._zero
        for x in reversed(ds):
            r = r * self._radix + self._digits[x]
        return self._store(self._ints, n, -r if n < 0 else r)

    def number(self, coords):
        """
        The constant ``Σ_k (a_k / b_k) θ^k`` for ``coords`` a tuple of
        ``(k, a_k, b_k)`` (``θ`` the generator of the number field).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
            sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
            sage: B = _SingularNumberFieldElements(R, K)
            sage: B.number(((0, 1, 2), (1, -3, 4))) == 1/2 - 3*s/4
            True
        """
        r = self._nums.get(coords)
        if r is not None:
            return r
        D = 1
        for _, _, b in coords:
            D = D * b // gcd(D, b)
        r = self._zero
        for k, a, b in coords:
            r += self.integer(a * (D // b)) * self._pow[k]
        if D != 1:
            r = r / self.integer(D)       # Singular's division by a constant
        return self._store(self._nums, coords, r)

    def monomial(self, e):
        """
        The monomial with exponent vector ``e``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
            sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
            sage: B = _SingularNumberFieldElements(R, K)
            sage: B.monomial((2, 1)) == c^2*d, B.monomial((0, 0))
            (True, 1)
        """
        r = self._monos.get(e)
        if r is not None:
            return r
        r = self._one
        for g, k in zip(self._gens, e):
            if k:
                r = r * g ** k
        return self._store(self._monos, e, r)

    def polynomial(self, terms):
        """
        The polynomial ``{exponents: [(k, a, b), ...]}`` (coordinates as
        for :meth:`number`).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _SingularNumberFieldElements
            sage: K.<s> = QuadraticField(5); R.<c, d> = K[]
            sage: B = _SingularNumberFieldElements(R, K)
            sage: B.polynomial({(1, 0): [(1, 1, 1)], (0, 0): [(0, -1, 3)]}) == s*c - 1/3
            True
        """
        r = self._zero
        for e, coords in terms.items():
            r += self.number(tuple(sorted(coords))) * self.monomial(e)
        return r


def _engine_ring(F):
    """
    The coefficient kind of a C++ engine (``_engine_base.hpp``)
    computing over the ring ``F`` itself: ``'q'`` for ``QQ``, ``'nmod'`` for a
    prime field ``GF(p)``, ``2 < p < 2^63``, ``'qpoly'`` / ``'qmpoly'`` for a
    univariate / multivariate polynomial ring over ``QQ``, ``'nf'`` for a
    number field, ``'nfmpoly'`` for a (univariate or multivariate)
    polynomial ring over one; else ``None``.  A relative number field (a
    tower) is computed over its absolute field (``_EngineKernel``
    converts).  (Fraction fields need a lift to a polynomial ring first,
    chosen by the algebra, e.g. ``universal_vertex_algebra._LiftedKernel``.)

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _engine_ring
        sage: [_engine_ring(R) for R in (QQ, GF(7), QQ['c'], QQ['a, b'], GF(2),
        ....:                           Frac(QQ['c']), QQ['c']['d'])]
        ['q', 'nmod', 'qpoly', 'qmpoly', None, None, None]
        sage: K.<s> = QuadraticField(5)
        sage: L.<z> = NumberField(x^3 - 2)
        sage: M.<t> = K.extension(x^2 + 1)
        sage: [_engine_ring(R) for R in (K, L, CyclotomicField(7), K['c'], L['a, b'],
        ....:                           M, Frac(K['c']), QQbar)]
        ['nf', 'nf', 'nf', 'nfmpoly', 'nfmpoly', 'nf', None, None]
    """
    from sage.rings.polynomial.multi_polynomial_ring_base import MPolynomialRing_base
    from sage.rings.polynomial.polynomial_ring import PolynomialRing_generic
    from sage.rings.rational_field import QQ
    try:
        if F is QQ:
            return 'q'
        if _number_field(F):
            return 'nf'
        if F.is_field() and F.is_finite() and F.is_prime_field():
            return 'nmod' if 2 < int(F.characteristic()) < 2**63 else None
        if isinstance(F, (PolynomialRing_generic, MPolynomialRing_base)):
            B = F.base_ring()
            if B is QQ:
                return 'qpoly' if isinstance(F, PolynomialRing_generic) else 'qmpoly'
            if _number_field(B):
                return 'nfmpoly'
    except (AttributeError, TypeError, ValueError, NotImplementedError):
        pass
    return None


class _EngineKernel:
    r"""
    The Python side of an algebra's C++ engine: the engine computes over a
    ring ``Rk`` (kind ``'q'``, ``'nmod'``, ``'qpoly'``, ``'qmpoly'``,
    ``'nf'`` or ``'nfmpoly'``, see :func:`_engine_ring`); coefficients of the algebra (in its base ring
    ``F``) go up to ``Rk`` by ``up`` (default: ``Rk``'s coercion), results
    come down by ``down`` (default: none, ``Rk = F``).  The algebra builds
    the engine object (``attach``) in its ``_build_engine`` hook;
    :class:`VertexAlgebra` dispatches to the methods here (key level: results
    for its caches; element level: ``nthreads`` threads, ``None`` if a
    coefficient cannot be lifted, then the caller takes the generic path).

    The engine object (Cython) takes and returns elements as lists of
    ``(key, terms)``, ``terms`` a list of ``(exponents, numerator,
    denominator)``, and poles as lists of elements; its methods:
    ``ope_mono``, ``no_mono``, ``deriv_mono``, ``ope_el``, ``ope_el_many``,
    ``nprod_el``, ``deriv_el``, ``nprod_el_many``, ``cache_sizes``.  Examples:
    ``universal_vertex_algebra._engine_kernel``.

    EXAMPLES:

    The coefficient conversions need no engine object::

        sage: from vertex_algebras.vertex_algebra import _EngineKernel
        sage: K = _EngineKernel(QQ, 'q', QQ)
        sage: K.coef_in(3/4), K.coef_from_engine(K.coef_in(3/4))
        ([((), 3, 4)], 3/4)
        sage: _EngineKernel(QQ, 'z', QQ)
        Traceback (most recent call last):
        ...
        ValueError: unknown engine coefficient kind 'z'

    The kernel of an algebra computes its products::

        sage: import vertex_algebras as va
        sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); d = dict(L._monomial_coefficients)
        sage: E = V._engine()
        sage: E is None or (isinstance(E, _EngineKernel) and E.kind() == 'q'
        ....:               and E.ope(d, d, 1) == [dict(p._monomial_coefficients) for p in L.ope(L)])
        True
    """

    def __init__(self, F, kind, Rk, up=None, down=None):
        """
        TESTS::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: R.<c> = QQ[]
            sage: K = _EngineKernel(R, 'qpoly', R)
            sage: K.kind(), K._E is None, K.coef_in(c^2/3 + 1)
            ('qpoly', True, [((0,), 1, 1), ((2,), 1, 3)])
            sage: K.coef_from_engine(K.coef_in(c^2/3 + 1))
            1/3*c^2 + 1
        """
        from sage.rings.rational_field import QQ
        self._F = F
        self._Rk = Rk
        self._kind = kind
        self._E = None
        if kind == 'q':
            self._cin = lambda x: [((), int(x.numerator()),
                                    int(x.denominator()))]
            self._cout = lambda t: QQ((t[0][1], t[0][2]))
        elif kind == 'nmod':
            self._cin = lambda x: [((), int(x), 1)]
            self._cout = lambda t: F(t[0][1])
        elif kind == 'qpoly':
            self._cin = lambda x: [((e,), int(c.numerator()),
                                    int(c.denominator()))
                                   for e, c in x.dict().items()]
            self._cout = lambda t: Rk({e[0]: QQ((a, b)) for e, a, b in t})
        elif kind == 'qmpoly':
            self._cin = lambda x: [(tuple(e), int(c.numerator()),
                                    int(c.denominator()))
                                   for e, c in x.dict().items()]
            self._cout = lambda t: Rk({e: QQ((a, b)) for e, a, b in t})
        elif kind in ('nf', 'nfmpoly'):
            # power-basis coordinates in the ABSOLUTE field M of the number
            # field K (a tower K is converted by its structure maps); for
            # polynomial rings the exponents are the variables of Rk, then
            # the generator of M
            K = Rk if kind == 'nf' else Rk.base_ring()
            M, to_abs, from_abs = _absolute_presentation(K)
            self._field = M
            deg = M.degree()
            ca = (lambda c: c) if to_abs is None else to_abs
            cb = (lambda m: m) if from_abs is None else from_abs

            def coords(e, c):
                return [(e + (k,), int(q.numerator()), int(q.denominator()))
                        for k, q in enumerate(ca(c).list()) if q]

            def field_out(t):
                v = [QQ.zero()] * deg
                for e, a, b in t:
                    v[e[-1]] = QQ((a, b))
                return v
            if kind == 'nf':
                self._cin = lambda x: coords((), x)
                self._cout = lambda t: cb(M(field_out(t)))
            else:
                from sage.rings.polynomial.polynomial_ring import PolynomialRing_generic
                uni = isinstance(Rk, PolynomialRing_generic)

                def cin(x):
                    out = []
                    for e, c in x.dict().items():
                        out.extend(coords((int(e),) if uni else tuple(e), c))
                    return out

                from sage.rings.polynomial.multi_polynomial_libsingular import (
                    MPolynomialRing_libsingular,
                )
                if isinstance(Rk, MPolynomialRing_libsingular) and to_abs is None:
                    # never Rk(dict): see _SingularNumberFieldElements
                    build = _SingularNumberFieldElements(Rk, M)

                    def cout(t):
                        d = {}
                        for e, a, b in t:
                            d.setdefault(e[:-1], []).append((e[-1], a, b))
                        return build.polynomial(d)
                else:
                    def cout(t):
                        d = {}
                        for e, a, b in t:
                            d.setdefault(e[:-1], []).append((e, a, b))
                        return Rk({(e[0] if uni else e): cb(M(field_out(ts)))
                                   for e, ts in d.items()})
                self._cin, self._cout = cin, cout
        else:
            raise ValueError('unknown engine coefficient kind %r' % (kind,))
        self._up = Rk if up is None else up
        self._down = down
        self._one = self._cin(Rk.one())
        self._scalars = {}       # scalar -> engine terms, see _lift_scalar
        self._alg = None        # _AlgebraicCoefficients (QQbar / AA)
        self._lift_factors = ()  # p_j of a lift A[u_j] (u_j = 1/p_j), see span_field

    def attach(self, engine):
        """
        Use ``engine`` (the algebra's Cython engine object).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ); K._E is None
            True
            sage: K.attach('engine'); K._E
            'engine'
        """
        self._E = engine

    def kind(self):
        """
        ``'q'``, ``'nmod'``, ``'qpoly'``, ``'qmpoly'``, ``'nf'`` or
        ``'nfmpoly'``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: _EngineKernel(QQ, 'q', QQ).kind(), _EngineKernel(GF(7), 'nmod', GF(7)).kind()
            ('q', 'nmod')
        """
        return self._kind

    def ring(self):
        """
        The ring the engine computes over.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K.<c> = Frac(QQ['c'])
            sage: _EngineKernel(K, 'qpoly', QQ['c']).ring()
            Univariate Polynomial Ring in c over Rational Field
        """
        return self._Rk

    def nvars(self):
        """
        Number of variables of the engine's ring (``'qmpoly'``,
        ``'nfmpoly'``), else 0.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: R = QQ['a, b']
            sage: _EngineKernel(R, 'qmpoly', R).nvars(), _EngineKernel(QQ, 'q', QQ).nvars()
            (2, 0)
        """
        return self._Rk.ngens() if self._kind in ('qmpoly', 'nfmpoly') else 0

    def minpoly(self):
        """
        The defining polynomial of the number field (``'nf'``,
        ``'nfmpoly'``) as engine terms, else ``[]``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: F.<s> = QuadraticField(5)
            sage: _EngineKernel(F, 'nf', F).minpoly(), _EngineKernel(QQ, 'q', QQ).minpoly()
            ([((0,), -5, 1), ((2,), 1, 1)], [])
        """
        if self._kind not in ('nf', 'nfmpoly'):
            return []
        return [((k,), int(c.numerator()), int(c.denominator()))
                for k, c in enumerate(self._field.absolute_polynomial().list()) if c]

    def modulus(self):
        """
        The characteristic for ``'nmod'``, else 0.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: _EngineKernel(GF(7), 'nmod', GF(7)).modulus(), _EngineKernel(QQ, 'q', QQ).modulus()
            (7, 0)
        """
        return int(self._F.characteristic()) if self._kind == 'nmod' else 0

    def coef_in(self, x):
        """
        An element of the engine's ring as engine terms (a list of
        ``(exponents, numerator, denominator)``).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: F.<s> = QuadraticField(5)
            sage: _EngineKernel(QQ, 'q', QQ).coef_in(-3/4)
            [((), -3, 4)]
            sage: _EngineKernel(F, 'nf', F).coef_in(s/2 + 1)
            [((0,), 1, 1), ((1,), 1, 2)]
            sage: R.<a, b> = QQ[]
            sage: _EngineKernel(R, 'qmpoly', R).coef_in(a^2*b/3)
            [((2, 1), 1, 3)]
        """
        return self._cin(x)

    def cache_sizes(self):
        """
        Entries of the engine's caches and its scheduler statistics.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); x = L.no(L).ope(L)
            sage: E = V._engine()
            sage: E is None or ('ope' in E.cache_sizes() and E.cache_sizes()['ope'] > 0)
            True
        """
        return self._E.cache_sizes()

    def _lift_scalar(self, x):
        """``x`` (a scalar, e.g. a cocycle value) lifted and in engine terms,
        cached: few distinct values occur, and lifting into a Singular ring
        over a number field is slow before Sage 10.10 (see
        :class:`_SingularNumberFieldElements`).  May raise.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ)
            sage: K._lift_scalar(-1), K._scalars
            ([((), -1, 1)], {-1: [((), -1, 1)]})
        """
        try:
            r = self._scalars.get(x)
        except TypeError:               # not hashable
            return self._cin(self._up(x))
        if r is None:
            r = self._scalars[x] = self._cin(self._up(x))
        return r

    def _el_up(self, d):
        """
        A raw dict over ``F`` as an engine element (may raise); zero
        coefficients are dropped.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ)
            sage: K._el_up({'m': 1/2, 'z': QQ(0)})
            [('m', [((), 1, 2)])]
        """
        up, cin = self._up, self._cin
        return [(m, cin(up(c))) for m, c in d.items() if c]

    def _el_down(self, el):
        """
        An engine element as a raw dict over ``F`` (zeros dropped).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ)
            sage: K._el_down([('m', [((), 1, 2)])])
            {'m': 1/2}
            sage: K2 = _EngineKernel(QQ, 'q', QQ, down=lambda x: 2*x)
            sage: K2._el_down([('m', [((), 1, 2)]), ('n', [((), 0, 1)])])
            {'m': 1}
        """
        cout, down = self._cout, self._down
        out = {}
        if down is None:
            for m, t in el:
                out[m] = cout(t)
        else:
            for m, t in el:
                x = down(cout(t))
                if x:
                    out[m] = x
        return out

    def _lift_all(self, *ds):
        """
        The raw dicts ``ds`` as engine elements, or ``None`` if a
        coefficient cannot be lifted (over ``QQbar`` / ``AA`` every number
        outside the engine's field is recorded first, see
        :class:`_AlgebraicCoefficients`).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ)
            sage: K._lift_all({'m': QQ(1)}, {})
            [[('m', [((), 1, 1)])], []]
            sage: c = Frac(QQ['c']).gen()
            sage: K._lift_all({'m': 1/c}) is None
            True
        """
        try:
            return [self._el_up(d) for d in ds]
        except (ValueError, ArithmeticError, TypeError, AttributeError):
            if self._alg is not None:   # QQbar / AA: record EVERY number outside
                for d in ds:            # the field (one rebuild for all of them)
                    for c in d.values():
                        try:
                            self._alg.up(c)
                        except ValueError:
                            pass
            return None

    # key level (for the cached accessors of the algebra)

    def ope_mono(self, a, b):
        """
        The OPE of the basis keys ``a``, ``b``: a trimmed tuple of pole
        dicts (for :meth:`VertexAlgebra._ope_mono`).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: E is None or E.ope_mono(a, a) == tuple(dict(p._monomial_coefficients) for p in L.ope(L))
            True
        """
        out = [self._el_down(el) for el in self._E.ope_mono(a, b)]
        while out and not out[-1]:
            out.pop()
        return tuple(out)

    def no_mono(self, a, b):
        """
        ``a_(-1) b`` of basis keys as a raw dict.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: E is None or E.no_mono(a, a) == dict(L.no(L)._monomial_coefficients)
            True
        """
        return self._el_down(self._E.no_mono(a, b))

    def deriv_mono(self, m, n):
        """
        ``∂^n m`` of a basis key as a raw dict.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: E is None or E.deriv_mono(a, 2) == {((0, 2),): 1}
            True
        """
        return self._el_down(self._E.deriv_mono(m, int(n)))

    def nprod_mono(self, a, n, b):
        """
        ``a_(n) b`` of basis keys as a raw dict, any ``n``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: E is None or E.nprod_mono(a, -3, a) == dict(L.nproduct(L, -3)._monomial_coefficients)
            True
        """
        return self._el_down(self._E.nprod_el([(a, self._one)], int(n),
                                              [(b, self._one)], 1))

    # element level: None if a coefficient cannot be lifted

    def ope(self, dA, dB, nthreads):
        """
        The pole dicts of the OPE of the raw dicts ``dA``, ``dB``
        (``nthreads`` threads), or ``None`` if a coefficient cannot be
        lifted.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: d = dict(L._monomial_coefficients)
            sage: E is None or E.ope(d, d, 1) == [dict(p._monomial_coefficients) for p in L.ope(L)]
            True
            sage: E is None or E.ope({a: 1/polygen(QQ)}, d, 1) is None
            True
        """
        lifted = self._lift_all(dA, dB)
        if lifted is None:
            return None
        return [self._el_down(el)
                for el in self._E.ope_el(lifted[0], lifted[1], nthreads)]

    def ope_many(self, dA, dBs, nthreads):
        """
        ``[self.ope(dA, dB, nthreads) for dB in dBs]`` in one engine call,
        or ``None``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: d = dict(L._monomial_coefficients)
            sage: E is None or E.ope_many(d, [d, {(): QQ(1)}], 1) == [E.ope(d, d, 1), []]
            True
        """
        lifted = self._lift_all(dA, *dBs)
        if lifted is None:
            return None
        return [[self._el_down(el) for el in P]
                for P in self._E.ope_el_many(lifted[0], lifted[1:], nthreads)]

    def nprod(self, dA, n, dB, nthreads):
        """
        ``dA_(n) dB`` as a raw dict, or ``None``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: d = dict(L._monomial_coefficients)
            sage: E is None or E.nprod(d, -2, d, 1) == dict(L.nproduct(L, -2)._monomial_coefficients)
            True
        """
        lifted = self._lift_all(dA, dB)
        if lifted is None:
            return None
        return self._el_down(self._E.nprod_el(lifted[0], int(n), lifted[1],
                                              nthreads))

    def deriv(self, d, n, nthreads):
        """
        ``∂^n d`` as a raw dict, or ``None``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: d = dict(L._monomial_coefficients)
            sage: E is None or E.deriv(d, 2, 1) == {((0, 2),): 1}
            True
        """
        lifted = self._lift_all(d)
        if lifted is None:
            return None
        return self._el_down(self._E.deriv_el(lifted[0], int(n), nthreads))

    def nprod_many(self, els, tasks, nthreads):
        """
        ``[els[i]_(n) els[j] for (i, n, j) in tasks]`` (raw dicts) in one
        engine call, or ``None``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: d = dict(L._monomial_coefficients)
            sage: E is None or E.nprod_many([d], [(0, 1, 0), (0, -1, 0)], 1) == [{a: 2}, E.no_mono(a, a)]
            True
        """
        lifted = self._lift_all(*els)
        if lifted is None:
            return None
        return [self._el_down(el) for el in self._E.nprod_el_many(
            lifted, [(int(i), int(n), int(j)) for i, n, j in tasks], nthreads)]

    # engine form (lists of (key, terms) over the engine's ring): vectors that
    # stay in it, e.g. the normally ordered monomials of subalgebra spans
    # (_keyed_spans._EngineSpan), never become Sage elements

    def to_engine(self, d):
        """
        A raw dict over ``F`` in engine form (``ValueError`` if a
        coefficient cannot be lifted).

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ)
            sage: K.to_engine({'m': QQ(2)})
            [('m', [((), 2, 1)])]
        """
        return self._el_up(d)

    def from_engine(self, el):
        """
        An engine-form element as a raw dict over ``F``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: K = _EngineKernel(QQ, 'q', QQ)
            sage: K.from_engine(K.to_engine({'m': 2/3}))
            {'m': 2/3}
        """
        return self._el_down(el)

    def coef_from_engine(self, terms):
        """
        One engine coefficient as an element of ``F``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: F.<s> = QuadraticField(5)
            sage: K = _EngineKernel(F, 'nf', F)
            sage: K.coef_from_engine([((0,), 1, 1), ((1,), 1, 2)])
            1/2*s + 1
        """
        x = self._cout(terms)
        return x if self._down is None else self._down(x)

    def nprod_many_engine(self, els, tasks, nthreads):
        """
        :meth:`nprod_many` on engine-form elements, results in engine
        form (no conversions).

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.Virasoro(QQ, 1/2); L = V.gen('L'); a = ((0, 0),)
            sage: E = V._engine()
            sage: d = dict(L._monomial_coefficients)
            sage: E is None or E.nprod_many_engine([E.to_engine(d)], [(0, 1, 0)], 1) == [E.to_engine({a: QQ(2)})]
            True
        """
        return self._E.nprod_el_many(
            els, [(int(i), int(n), int(j)) for i, n, j in tasks], nthreads)

    def span_field(self):
        """How spans of engine-form vectors are eliminated in C++
        (``_keyed_spans._EngineSpan``): ``('nf', minpoly)`` over a
        number field (kind ``'nf'``: also towers, QQbar, AA), ``('frac',
        n, polys)`` over ``F = Frac(QQ[x_1, ..., x_n])`` computed over
        ``QQ[x..., u_1, ...]`` with ``u_j = 1/polys[j]``; else ``None``.

        EXAMPLES::

            sage: from vertex_algebras.vertex_algebra import _EngineKernel
            sage: F.<s> = QuadraticField(5); K.<c> = Frac(QQ['c'])
            sage: _EngineKernel(QQ, 'q', QQ).span_field() is None
            True
            sage: _EngineKernel(F, 'nf', F).span_field()
            ('nf', [((0,), -5, 1), ((2,), 1, 1)])
            sage: _EngineKernel(K, 'qpoly', QQ['c']).span_field()
            ('frac', 1, [])
            sage: _EngineKernel(QQ['c'], 'qpoly', QQ['c']).span_field() is None
            True
        """
        from sage.rings.rational_field import QQ
        if self._kind == 'nf':
            return ('nf', self.minpoly())
        if self._kind in ('qpoly', 'qmpoly'):
            F = self._F
            try:
                A = F.ring()
                if A is F or F is not A.fraction_field() or A.base_ring() is not QQ:
                    return None
            except (AttributeError, TypeError, ValueError, NotImplementedError):
                return None
            n = A.ngens()
            if self._Rk.ngens() != n + len(self._lift_factors):
                return None
            from sage.rings.polynomial.polynomial_ring import PolynomialRing_generic
            uni = isinstance(A, PolynomialRing_generic)
            polys = []
            for p in self._lift_factors:
                p = A(p)
                polys.append([((int(e),) if uni else tuple(e), int(c.numerator()),
                               int(c.denominator())) for e, c in p.dict().items()])
            return ('frac', n, polys)
        return None


def _gc_paused(f):
    """
    Decorator: run ``f`` with Python's cyclic garbage collector paused
    (re-enabled afterwards, nesting-safe).  The heavy kernels build millions
    of dicts and tuples without reference cycles; collector passes over them
    cost about a quarter of the run time of large computations.

    EXAMPLES::

        sage: import gc
        sage: from vertex_algebras.vertex_algebra import _gc_paused
        sage: f = _gc_paused(lambda: gc.isenabled())
        sage: g = _gc_paused(lambda: (f(), gc.isenabled()))
        sage: gc.isenabled(), f(), g(), gc.isenabled()
        (True, False, (False, False), True)
    """
    @functools.wraps(f)
    def wrapper(*args, **kwds):
        if not gc.isenabled():
            return f(*args, **kwds)
        gc.disable()
        try:
            return f(*args, **kwds)
        finally:
            gc.enable()
    return wrapper


