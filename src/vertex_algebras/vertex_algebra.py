    def hom(self, im_gens, codomain=None, check=True, check_weight=None):
        r"""
        The morphism of vertex algebras ``self -> codomain`` sending the
        generators to ``im_gens``.  ``check`` verifies that the images
        define a morphism (exactly, or up to ``check_weight`` for presented
        algebras); see :mod:`vertex_algebra_morphism`.

        INPUT:

        - ``im_gens`` -- the images of the generators: a list in the order
          of :meth:`gens` (lattice algebras: also just the images of the
          ``e^{±x_i}``), a dict by generator name, or (tensor products) a
          list of factor morphisms
        - ``codomain`` -- (default: ``None``) a vertex algebra; ``None``: the
          parent of the first image that is a vertex algebra element, or
          the codomain of the first factor morphism (a ``ValueError`` if
          there is none)
        - ``check`` -- (default: ``True``) whether to verify that the images
          define a morphism
        - ``check_weight`` -- (default: ``None``) for presented algebras
          (and subalgebras), the weight up to which the check runs

        OUTPUT:

        A morphism in ``Hom(self, codomain)``.

        EXAMPLES::

            sage: import vertex_algebras as va
            sage: V = va.FermionicGhosts(QQ); b, c = V.gens()
            sage: phi = V.hom([c, b]); phi(b.no(c))
            -:b c:
            sage: phi.domain() is phi.codomain() is V
            True
        """
        if codomain is None:
            from sage.categories.morphism import Morphism
            vals = list(im_gens.values()) if isinstance(im_gens, dict) else list(im_gens)
            for v in vals:
                if isinstance(v, Morphism):
                    codomain = v.codomain()
                    break
                P = v.parent() if hasattr(v, 'parent') else None
                if getattr(P, '_is_vertex_algebra', False):
                    codomain = P
                    break
            if codomain is None:
                raise ValueError('give the codomain')
        from sage.categories.homset import Hom
        return Hom(self, codomain)(im_gens, check=check, check_weight=check_weight)

