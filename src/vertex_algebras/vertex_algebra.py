_SUPERSCRIPT = str.maketrans('0123456789', '⁰¹²³⁴'
                                          '⁵⁶⁷⁸⁹')


def _sup(n):
    """
    The integer ``n`` as a superscript string, e.g. ``2`` -> ``'²'``.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _sup
        sage: _sup(2), _sup(10)
        ('²', '¹⁰')
    """
    return str(int(n)).translate(_SUPERSCRIPT)


def _derivative_str(name, n, style='ascii'):
    r"""
    ``∂^n`` of the field ``name`` in the notation ``style``: ``'ascii'``
    (``dL``, ``d^2L``: the default repr), ``'unicode'`` (``∂ L``, ``∂² L``:
    ``unicode_art``) or ``'latex'``.

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _derivative_str
        sage: [_derivative_str('L', n, s) for s in ('ascii', 'unicode', 'latex') for n in (0, 1, 2)]
        ['L', 'dL', 'd^2L', 'L', '∂ L', '∂² L', 'L', '\\partial L', '\\partial^{2} L']
    """
    if not n:
        return name
    if style == 'unicode':
        return ('∂ ' if n == 1 else '∂{} '.format(_sup(n))) + name
    if style == 'latex':
        return ('\\partial ' if n == 1 else '\\partial^{%d} ' % n) + name
    return ('d' if n == 1 else 'd^{}'.format(n)) + name


def _word_str(parts, style='ascii'):
    r"""
    The normally ordered product ``:a b c:`` of the factor strings
    ``parts`` (``'1'`` for none, the factor itself for one).

    EXAMPLES::

        sage: from vertex_algebras.vertex_algebra import _word_str
        sage: _word_str([]), _word_str(['L']), _word_str(['dL', 'L'])
        ('1', 'L', ':dL L:')
        sage: print(_word_str(['a', 'b'], 'latex'))
        :a\, b:
    """
    if not parts:
        return '1'
    if len(parts) == 1:
        return parts[0]
    return ':{}:'.format(('\\, ' if style == 'latex' else ' ').join(parts))


