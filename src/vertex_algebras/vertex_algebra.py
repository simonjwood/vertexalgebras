    def horizontal_grading(self):
        """
        The horizontal grading as given to the constructor or to
        :meth:`with_horizontal_grading` (``None`` if none was chosen): a dict
        name -> grade, or a named choice such as ``'lattice'``,
        ``'factors'`` or ``'ambient'``; the group is
        :meth:`horizontal_grading_group`.

        EXAMPLES::

            sage: from vertex_algebras import BosonicGhosts
            sage: B = BosonicGhosts(QQ, horizontal_grading='charge')
            sage: B.horizontal_grading(), B.horizontal_grading_group()
            ({'beta': 1, 'gamma': -1}, Integer Ring)
            sage: BosonicGhosts(QQ).horizontal_grading() is None
            True
        """
        if self._grading is None:
            return None
        try:
            d = self._conformal_key().get('horizontal_grading')
        except NotImplementedError:
            return None
        spec = d[0] if isinstance(d, tuple) and len(d) == 2 else d
        if (isinstance(spec, tuple) and spec
                and all(isinstance(p, tuple) and len(p) == 2 and isinstance(p[0], str)
                        for p in spec)):
            return dict(spec)
        return spec

