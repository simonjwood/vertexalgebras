    def commutant(self, A=None, horizontal_grading=None, max_weight=None,
                  conformal_vector=None):
        r"""
        The commutant (coset) ``Com(A, self)`` of a vertex subalgebra ``A``,
        as a :class:`commutant_vertex_algebra.CommutantVertexAlgebra`: the
        elements ``v`` with ``a_(n) v = 0`` for all ``a`` in ``A`` and
        ``n >= 0`` (also :meth:`coset`).  ``A`` is a vertex subalgebra of
        ``self`` (its given generators are used) or a finite list of elements
        of ``self`` (generators of ``A``, homogeneous for the conformal weight
        and the parity).  Without ``A``, ``self`` must be a vertex subalgebra
        (or commutant), and the result is its commutant in its ambient
        algebra.  For a commutant ``A`` (whose strong generators are only
        known up to a weight) give ``max_weight``: the result is the
        commutant of the subalgebra generated by the weight spaces of ``A``
        up to ``max_weight`` (that of ``A`` iff they generate ``A``).  Needs
        the conformal weights of ``self``; ``horizontal_grading='ambient'`` grades the
        commutant by the grading of ``self``.  ``conformal_vector``:
        ``'coset'`` (``T_self - T_A``, ``A`` given as a subalgebra with a
        Virasoro vector) or an element (none by default).

        INPUT:

        - ``A`` -- (default: ``None``) a vertex subalgebra of ``self``, a
          list of elements of ``self`` or a commutant
        - ``horizontal_grading`` -- (default: ``None``) ``'ambient'``: grade
          the commutant by the horizontal grading of ``self``
        - ``max_weight`` -- (default: ``None``) required when ``A`` is a
          commutant
        - ``conformal_vector`` -- (default: ``None``) ``'coset'`` or an element

        EXAMPLES:

        The commutant of one free boson in two is the other one (partition
        numbers)::

            sage: import vertex_algebras as va
            sage: H = va.FreeBosons(QQ, 1)
            sage: P = H.tensor(H, degrees='factors')
            sage: J1, J2 = P.embed(0, H.gen(0)), P.embed(1, H.gen(0))
            sage: C = P.commutant([J1])
            sage: [C.weight_space(n).dimension() for n in range(6)]
            [1, 1, 2, 3, 5, 7]
            sage: J2 in C, J1 in C
            (True, False)
        """
        from .commutant_vertex_algebra import _commutant
        return _commutant(self, A, horizontal_grading=horizontal_grading, max_weight=max_weight,
                         conformal_vector=conformal_vector)

